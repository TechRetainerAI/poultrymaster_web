#!/usr/bin/env node
// Generates the IAM catalog migration from lib/iam/page-catalog.ts.
//
//   node scripts/iam/gen-page-catalog-sql.mjs 506 Gyimah
//
// Writes poultrycore_Backend/PoultryFarmAPI/Migrations/<NNN>_<Branch>_PageAccessCatalog.postgres.sql.
// The migration is idempotent: re-running it (or a later one generated after
// adding pages) only inserts keys that are missing and refreshes the metadata.
//
// Needs Node 23.6+ (type stripping) to load the .ts catalog directly.

import { writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"
import { PAGE_CATALOG, NAV_SECTIONS } from "../../lib/iam/page-catalog.ts"

const here = dirname(fileURLToPath(import.meta.url))
const num = process.argv[2]
const branch = process.argv[3] ?? "Gyimah"
if (!/^\d{3}$/.test(num ?? "")) {
  console.error("usage: node scripts/iam/gen-page-catalog-sql.mjs NNN [Branch]")
  process.exit(1)
}

const q = (v) => (v === null || v === undefined ? "NULL" : `'${String(v).replace(/'/g, "''")}'`)
const COMPANY = { poultry: "Poultry", water: "Water", generic: "Generic", hotel: "Hotel", restaurant: "Restaurant", livestock: "Livestock", office: null }

const rows = PAGE_CATALOG.map((p, i) => {
  const actions = ["view", ...(p.actions ?? [])]
  return `    (${[
    q(p.module), q(p.resource), q(p.label), q(p.section), q(p.group),
    q(p.routes[0] ?? null), `ARRAY[${actions.map(q).join(",")}]::text[]`,
    p.sensitive ? "TRUE" : "FALSE", q(p.dependsOn ? `${p.dependsOn}.view` : null),
    q(p.carry ?? null), q(p.description ?? null), q(COMPANY[p.module]),
    String(NAV_SECTIONS.indexOf(p.section) * 1000 + i),
  ].join(", ")})`
})

const file = `${num}_${branch}_PageAccessCatalog.postgres.sql`
const sql = `-- =============================================================================
-- ${file}
--
-- GENERATED by scripts/iam/gen-page-catalog-sql.mjs from lib/iam/page-catalog.ts.
-- Do not edit by hand: change the catalog and regenerate.
--
-- Makes the IAM permission catalog the page registry for Staff Page Access:
--   1. iampermissions gets navsection / route / defaultgrant / dependson /
--      isdeprecated, so the editor can group pages the way the menus do and
--      know which ones are sensitive.
--   2. Every page in every company type gets a <module>.<resource>.view key
--      plus its action keys (create/edit/delete/approve/reverse/export).
--      Hotel and Restaurant get catalog modules for the first time.
--   3. Built-in roles that held the key a new page was split from receive the
--      new key ("Carried over from X by migration ${num}"), so no role loses a
--      page it reached before. User overrides are carried the same way.
--   4. spiam_getcatalog returns the new columns.
--
-- Changes no business data. Safe to re-run.
-- =============================================================================

BEGIN;

DO $iam$
BEGIN
    IF to_regclass('public.iampermissions') IS NULL THEN
        RAISE EXCEPTION '${num}: iampermissions is missing — apply the IAM migrations (199-203) first.';
    END IF;
END
$iam$;

ALTER TABLE iampermissions ADD COLUMN IF NOT EXISTS navsection   varchar(40);
ALTER TABLE iampermissions ADD COLUMN IF NOT EXISTS route        varchar(200);
ALTER TABLE iampermissions ADD COLUMN IF NOT EXISTS defaultgrant varchar(12) NOT NULL DEFAULT 'ordinary';
ALTER TABLE iampermissions ADD COLUMN IF NOT EXISTS dependson    varchar(120);
ALTER TABLE iampermissions ADD COLUMN IF NOT EXISTS isdeprecated boolean NOT NULL DEFAULT FALSE;

DO $chk$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_iampermissions_defaultgrant') THEN
        ALTER TABLE iampermissions ADD CONSTRAINT ck_iampermissions_defaultgrant
            CHECK (defaultgrant IN ('ordinary', 'sensitive'));
    END IF;
END
$chk$;

CREATE TEMP TABLE _pages (
    module text, resource text, label text, navsection text, grp text, route text,
    actions text[], sensitive boolean, dependson text, carry text, description text,
    companytype text, sortorder int
) ON COMMIT DROP;

INSERT INTO _pages VALUES
${rows.join(",\n")};

-- Every key the catalog defines, with the policy that applies to it.
CREATE TEMP TABLE _keys ON COMMIT DROP AS
SELECT p.module || '.' || p.resource || '.' || a.action AS permissionkey,
       p.module, p.resource, a.action, p.label, p.navsection, p.grp, p.route,
       p.dependson, p.carry, p.description, p.companytype, p.sortorder,
       -- A ticked page is not permission to perform privileged operations:
       -- approving, reversing and deleting are always opt-in.
       CASE WHEN p.sensitive OR a.action IN ('approve', 'reverse', 'delete') THEN 'sensitive' ELSE 'ordinary' END AS defaultgrant,
       (a.action IN ('approve', 'reverse', 'delete') OR (p.sensitive AND a.action <> 'view')) AS isdangerous
FROM _pages p
CROSS JOIN LATERAL unnest(p.actions) AS a(action);

CREATE TEMP TABLE _new ON COMMIT DROP AS
SELECT k.* FROM _keys k
WHERE NOT EXISTS (SELECT 1 FROM iampermissions x WHERE x.permissionkey = k.permissionkey);

INSERT INTO iampermissions (permissionkey, module, resource, action, permissiongroup, resourcelabel,
                            description, companytype, isdangerous, sortorder,
                            navsection, route, defaultgrant, dependson)
SELECT permissionkey, module, resource, action, grp, label, description, companytype, isdangerous, sortorder,
       navsection, route, defaultgrant, dependson
FROM _new
ON CONFLICT (permissionkey) DO NOTHING;

-- Refresh the page metadata on every catalog key (new and existing). Labels
-- become the menu labels owners recognise; an existing key keeps its group.
UPDATE iampermissions x
SET    navsection   = k.navsection,
       route        = k.route,
       defaultgrant = k.defaultgrant,
       dependson    = k.dependson,
       resourcelabel = k.label,
       description  = COALESCE(k.description, x.description),
       sortorder    = k.sortorder,
       isdeprecated = FALSE
FROM   _keys k
WHERE  x.permissionkey = k.permissionkey;

-- Keys outside the page catalog (finer actions such as
-- poultry.customer-payments.create) are left alone: code still checks them and
-- the editor lists them under "More actions" for their module.

-- ---- carry grants to the new keys ------------------------------------------
-- Which existing keys "imply" a new one:
--   view of a new page      <- the page's carry key
--   an action on any page   <- the same page's equal-or-stronger existing action,
--                              or the carry page's same action
CREATE TEMP TABLE _carry ON COMMIT DROP AS
SELECT n.permissionkey AS new_key, src.old_key
FROM _new n
CROSS JOIN LATERAL (
    SELECT n.carry AS old_key WHERE n.action = 'view' AND n.carry IS NOT NULL
    UNION
    SELECT n.module || '.' || n.resource || '.' || s.a
    FROM unnest(CASE n.action
                    WHEN 'create'  THEN ARRAY['create', 'edit']
                    WHEN 'edit'    THEN ARRAY['edit']
                    WHEN 'export'  THEN ARRAY['export']
                    WHEN 'delete'  THEN ARRAY['delete']
                    WHEN 'approve' THEN ARRAY['approve', 'delete']
                    WHEN 'reverse' THEN ARRAY['reverse', 'approve', 'delete']
                    ELSE ARRAY[]::text[] END) AS s(a)
    WHERE n.action <> 'view'
    UNION
    SELECT regexp_replace(n.carry, '\\.[a-z]+$', '') || '.' || n.action
    WHERE n.action <> 'view' AND n.carry IS NOT NULL
) src
WHERE src.old_key IS NOT NULL AND src.old_key <> n.permissionkey;

DO $carry$
DECLARE
    v_keys  int;
    v_roles int := 0;
    v_users int := 0;
BEGIN
    SELECT count(*) INTO v_keys FROM _new;

    IF to_regclass('public.iamrolepermissions') IS NOT NULL THEN
        INSERT INTO iamrolepermissions (roleid, permissionkey)
        SELECT DISTINCT rp.roleid, c.new_key
        FROM   _carry c
        JOIN   iamrolepermissions rp ON rp.permissionkey = c.old_key
        ON CONFLICT (roleid, permissionkey) DO NOTHING;
        GET DIAGNOSTICS v_roles = ROW_COUNT;

        -- Admins saw every page before this upgrade (isAdmin bypassed the
        -- menu rules), so the two admin roles get every new key outright.
        INSERT INTO iamrolepermissions (roleid, permissionkey)
        SELECT r.roleid, n.permissionkey
        FROM   iamroles r CROSS JOIN _new n
        WHERE  r.rolekey IN ('sys-org-admin', 'sys-company-admin')
        ON CONFLICT (roleid, permissionkey) DO NOTHING;
    END IF;

    IF to_regclass('public.iamuserpermissions') IS NOT NULL THEN
        INSERT INTO iamuserpermissions (userid, farmid, permissionkey, effect, reason, grantedby, grantedat)
        SELECT DISTINCT ON (up.userid, up.farmid, c.new_key)
               up.userid, up.farmid, c.new_key, up.effect,
               'Carried over from ' || up.permissionkey || ' by migration ${num}',
               up.grantedby, (now() at time zone 'utc')
        FROM   _carry c
        JOIN   iamuserpermissions up ON up.permissionkey = c.old_key
        WHERE  up.expiresat IS NULL OR up.expiresat > (now() at time zone 'utc')
        -- A Deny on the source wins over an Allow if both exist.
        ORDER BY up.userid, up.farmid, c.new_key, (up.effect = 'Deny') DESC
        ON CONFLICT (userid, farmid, permissionkey) DO NOTHING;
        GET DIAGNOSTICS v_users = ROW_COUNT;
    END IF;

    RAISE NOTICE '${num}: % new catalog key(s), % role grant(s), % user grant(s) carried over.', v_keys, v_roles, v_users;
END
$carry$;

-- ---- spiam_getcatalog: the new columns -------------------------------------
DROP FUNCTION IF EXISTS spiam_getcatalog();
CREATE FUNCTION spiam_getcatalog()
RETURNS TABLE(permissionkey text, module text, resource text, action text, permissiongroup text,
              resourcelabel text, description text, companytype text, isdangerous boolean, sortorder integer,
              navsection text, route text, defaultgrant text, dependson text, isdeprecated boolean)
LANGUAGE plpgsql
AS $function$
BEGIN
    RETURN QUERY
    SELECT p.permissionkey::text, p.module::text, p.resource::text, p.action::text, p.permissiongroup::text,
           p.resourcelabel::text, p.description::text, p.companytype::text, p.isdangerous, p.sortorder,
           p.navsection::text, p.route::text, p.defaultgrant::text, p.dependson::text, p.isdeprecated
    FROM iampermissions p
    ORDER BY p.module, p.sortorder, p.resource, p.action;
END;
$function$;

-- ---- self-test ---------------------------------------------------------------
DO $test$
DECLARE
    v_missing int;
    v_badsens int;
BEGIN
    SELECT count(*) INTO v_missing FROM _keys k
    WHERE NOT EXISTS (SELECT 1 FROM iampermissions x WHERE x.permissionkey = k.permissionkey);
    IF v_missing > 0 THEN
        RAISE EXCEPTION '${num} self-test: % catalog key(s) were not created.', v_missing;
    END IF;

    -- Payroll, owner money and cash accounts must never be default-granted.
    SELECT count(*) INTO v_badsens FROM iampermissions
    WHERE permissionkey ~ '\\.(payroll|owner-money|cash|profit-loss|employee-loans)\\.view$'
      AND navsection IS NOT NULL AND defaultgrant <> 'sensitive';
    IF v_badsens > 0 THEN
        RAISE EXCEPTION '${num} self-test: % sensitive page(s) are marked ordinary.', v_badsens;
    END IF;

    IF NOT EXISTS (SELECT 1 FROM iampermissions WHERE permissionkey = 'hotel.bookings.view')
       OR NOT EXISTS (SELECT 1 FROM iampermissions WHERE permissionkey = 'restaurant.pos.view') THEN
        RAISE EXCEPTION '${num} self-test: hotel/restaurant modules were not seeded.';
    END IF;

    RAISE NOTICE '${num} self-test passed: % page key(s) in the catalog.', (SELECT count(*) FROM _keys);
END
$test$;

COMMIT;
`

const out = join(here, "..", "..", "..", "poultrycore_Backend", "PoultryFarmAPI", "Migrations", file)
writeFileSync(out, sql)
console.log(`wrote ${out} (${PAGE_CATALOG.length} pages)`)

// The backend route-map test checks every Farm API route against these keys,
// so an API permission can never name a page the editor does not show.
const keysOut = join(here, "..", "..", "..", "poultrycore_Backend", "Tests", "Iam.Tests", "page-keys.json")
const pageKeys = PAGE_CATALOG.flatMap((p) => ["view", ...(p.actions ?? [])].map((a) => `${p.module}.${p.resource}.${a}`))
writeFileSync(keysOut, JSON.stringify(pageKeys.sort(), null, 1) + "\n")
console.log(`wrote ${keysOut} (${pageKeys.length} keys)`)
