/// One lot's share of a draw (`lib/water-lot-draw.ts` LotTake).
class WaterLotTake {
  const WaterLotTake(this.lot, this.productionQuantity, this.purchaseQuantity, this.cost);
  final Map lot;
  final num productionQuantity, purchaseQuantity, cost;
}

/// What a typed quantity will draw, walked down the item's lots in their own
/// FIFO/LIFO/HIFO order (`lib/water-lot-draw.ts` DrawPlan).
class WaterDrawPlan {
  const WaterDrawPlan(this.takes, this.available, this.drawn, this.shortfall, this.totalCost, this.unitCost);
  final List<WaterLotTake> takes;
  final num available, drawn, shortfall, totalCost, unitCost;
}

const _epsilon = 0.0005;

WaterDrawPlan planWaterDraw(List<Map> lots, num needed) {
  final available = lots.fold<num>(0, (s, l) => s + tNum(l['remainingProductionQuantity']));
  if (needed <= 0) return WaterDrawPlan(const [], available, 0, 0, 0, 0);
  final takes = <WaterLotTake>[];
  var remaining = needed;
  for (final lot in lots) {
    if (remaining <= _epsilon) break;
    final lotProd = tNum(lot['remainingProductionQuantity']);
    if (lotProd <= 0) continue;
    final q = math.min(lotProd, remaining);
    final mult = tNum(lot['productionUnitsPerPurchaseUnit']) == 0 ? 1 : tNum(lot['productionUnitsPerPurchaseUnit']);
    takes.add(WaterLotTake(lot, q, q / mult, q * tNum(lot['productionUnitCost'])));
    remaining -= q;
  }
  final drawn = takes.fold<num>(0, (s, t) => s + t.productionQuantity);
  final total = takes.fold<num>(0, (s, t) => s + t.cost);
  return WaterDrawPlan(takes, available, drawn, math.max(0, needed - drawn), total, drawn > 0 ? total / drawn : 0);
}

List<Map> waterLotsForItem(List<Map> lots, int itemId) => [for (final l in lots) if (tIntOrNull(l['waterRawMaterialItemId']) == itemId) l];

/// A "Raw materials & supplies used" row.
class WaterMaterialRow {
  WaterMaterialRow({
    required this.itemId,
    required this.expected,
    required this.actual,
    required this.unitCost,
    required this.unit,
    required this.stock,
    required this.name,
  });
  int itemId;
  num expected, actual, unitCost, stock;
  String unit, name;
}

/// Expected = bags × qty-per-bag × (1 + waste%), from a recipe item.
WaterMaterialRow waterRecipeRow(Map it, num bags, List<Map> rawMaterials) {
  final id = tIntOrNull(it['waterRawMaterialItemId']) ?? 0;
  final mat = rawMaterials.where((m) => tIntOrNull(m['waterRawMaterialItemId']) == id).firstOrNull;
  final expected = _round3(bags * tNum(it['quantityPerOutputUnit']) * (1 + tNum(it['wasteAllowancePercent']) / 100));
  return WaterMaterialRow(
    itemId: id,
    expected: expected,
    actual: expected,
    unitCost: tNum(it['latestUnitCost']),
    unit: tStr(it['rawMaterialUnit']).isNotEmpty ? tStr(it['rawMaterialUnit']) : tStr(mat?['unitOfMeasure']),
    stock: it['rawMaterialStock'] != null ? tNum(it['rawMaterialStock']) : tNum(mat?['currentQuantity']),
    name: tStr(it['rawMaterialName']).isNotEmpty ? tStr(it['rawMaterialName']) : (tStr(mat?['itemName']).isNotEmpty ? tStr(mat?['itemName']) : 'Material #$id'),
  );
}

