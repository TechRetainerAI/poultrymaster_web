/// Water → Operations → Production → Water Production, as
/// `app/water-production-batches/page.tsx`: production records (Draft →
/// Approved, Cancel, Reopen), the Record / Edit form with its raw materials
/// and the lot-by-lot cost preview, and the record's Details page
/// (`app/water-production-batches/[id]/page.tsx`).

const waterShifts = ['Morning', 'Afternoon', 'Night', 'FullDay'];

num _round3(num n) => (n * 1000).round() / 1000;
String _day(Object? v) => tStr(v).split('T').first;

/// A record generated by a Batch Production allocation (migration 193): it is
/// managed from its parent day, never edited or reopened on its own.
bool isDailyProductionChild(Map b) => tStr(b['sourceType']) == 'DailyProductionAllocation' || tIntOrNull(b['waterDailyProductionId']) != null;

/// goodBags, or Produced − Damaged.
num waterGoodBags(Map b) => b['goodBags'] != null ? tNum(b['goodBags']) : tNum(b['bagsProduced']) - tNum(b['damagedBags']);

/// allInCost, or production costs + raw materials.
num waterAllInCost(Map b) => b['allInCost'] != null ? tNum(b['allInCost']) : tNum(b['totalProductionCost']) + tNum(b['rawMaterialCost']);

String waterMachineLabel(Map b, {String all = 'All Machines'}) =>
    tStr(b['machineScope']) == 'AllMachines' ? all : (tStr(b['machineName']).isEmpty ? '—' : tStr(b['machineName']));

/// makeBatchNumber: B-YYYYMMDD-HHMMSS in local time.
String makeWaterBatchNumber([DateTime? now]) {
  final d = now ?? DateTime.now();
  String p(int n) => n.toString().padLeft(2, '0');
  return 'B-${d.year}${p(d.month)}${p(d.day)}-${p(d.hour)}${p(d.minute)}${p(d.second)}';
}

/// The score cards: today's and this month's good bags from Approved records,
/// and the Draft count. [today] is the web's `new Date().toISOString()` day.
({num todayBags, num monthBags, int draftCount}) waterProductionTotals(List<Map> batches, String today) {
  final month = today.substring(0, 7);
  final approved = [for (final b in batches) if (tStr(b['status']) == 'Approved') b];
  num sum(String prefix) => approved.where((b) => tStr(b['productionDate']).startsWith(prefix)).fold<num>(0, (s, b) => s + waterGoodBags(b));
  return (todayBags: sum(today), monthBags: sum(month), draftCount: batches.where((b) => tStr(b['status']) == 'Draft').length);
}

/// filterByDateAndSearch on productionDate, searching batch number, status and notes.
List<Map> filterWaterBatches(List<Map> rows, {String search = '', String from = '', String to = ''}) {
  final q = search.trim().toLowerCase();
  return rows.where((r) {
    final day = RegExp(r'^(\d{4}-\d{2}-\d{2})').firstMatch(tStr(r['productionDate']))?[1];
    if (day != null) {
      if (from.isNotEmpty && day.compareTo(from) < 0) return false;
      if (to.isNotEmpty && day.compareTo(to) > 0) return false;
    }
    if (q.isNotEmpty && !['batchNumber', 'status', 'notes'].any((k) => r[k] != null && '${r[k]}'.toLowerCase().contains(q))) return false;
    return true;
  }).toList();
}

