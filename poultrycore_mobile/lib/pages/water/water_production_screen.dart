  Future<void> _loadRecipe(int productId, num bags) async {
    setState(() {
      _recipeLoading = true;
      _hasRecipe = false;
    });
    try {
      final recipe = await _api.get('/api/Water/products/$productId/recipe', query: {'farmId': _farmId});
      final items = recipe is Map ? rowsOf(recipe['items']) : const <Map>[];
      if (mounted) {
        setState(() {
          _hasRecipe = items.isNotEmpty;
          _setRows([for (final it in items) waterRecipeRow(it, bags, widget.rawMaterials)]);
        });
      }
    } on ApiException {
      // Leave the section empty: the batch can still be recorded without a recipe.
      if (mounted) setState(() => _setRows([]));
    }
    if (mounted) setState(() => _recipeLoading = false);
  }

  /// Prefer the rows this Draft already recorded over a fresh recipe.
  Future<void> _loadUsed() async {
    try {
      final used = rowsOf(await _api.get('/api/Water/production-batches/${tStr(e!['waterProductionBatchId'])}/materials', query: {'farmId': _farmId}));
      if (used.isNotEmpty) {
        if (!mounted) return;
        setState(() {
          _hasRecipe = true;
          _setRows([
            for (final u in used)
              () {
                final id = tIntOrNull(u['waterRawMaterialItemId']) ?? 0;
                final mat = widget.rawMaterials.where((m) => tIntOrNull(m['waterRawMaterialItemId']) == id).firstOrNull;
                return WaterMaterialRow(
                  itemId: id,
                  expected: tNum(u['expectedQuantityUsed'] ?? u['quantityUsed']),
                  actual: tNum(u['quantityUsed']),
                  unitCost: tNum(u['unitCost']),
                  unit: tStr(u['unitOfMeasure']).isNotEmpty ? tStr(u['unitOfMeasure']) : tStr(mat?['unitOfMeasure']),
                  stock: u['currentStock'] != null ? tNum(u['currentStock']) : tNum(mat?['currentQuantity']),
                  name: tStr(u['itemName']).isNotEmpty ? tStr(u['itemName']) : (tStr(mat?['itemName']).isNotEmpty ? tStr(mat?['itemName']) : 'Material #$id'),
                );
              }(),
          ]);
        });
      } else if (tIntOrNull(e!['waterProductId']) != null) {
        await _loadRecipe(tIntOrNull(e!['waterProductId'])!, tNum(e!['bagsProduced']));
      }
    } on ApiException {
      // As the web: the dialog stays usable without the earlier rows.
    }
  }

