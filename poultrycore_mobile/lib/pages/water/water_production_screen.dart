class WaterProductionScreen extends StatefulWidget {
  const WaterProductionScreen({super.key, required this.session, required this.company});
  final Session session;
  final Company company;

  @override
  State<WaterProductionScreen> createState() => _WaterProductionScreenState();
}

class _WaterProductionScreenState extends State<WaterProductionScreen> {
  List<Map> _batches = [], _machines = [], _products = [], _rawMaterials = [], _lots = [];
  bool _loading = true;
  final _search = TextEditingController();
  String _from = '', _to = '';
  int _page = 1, _pageSize = 10, _lastTotal = -1;
  FarmMoney _gh = const FarmMoney();
  Duration _offset = DateTime.now().timeZoneOffset;

  ApiClient get _api => widget.session.farmClient;
  String get _farmId => widget.company.farmId;

  @override
  void initState() {
    super.initState();
    FarmMoney.load(widget.session, widget.company).then((m) {
      if (mounted) setState(() => _gh = m);
    });
    CompanyClock.load(widget.session, widget.company).then((c) {
      if (mounted) setState(() => _offset = c.offset);
    });
    _load();
  }

  @override
  void dispose() {
    _search.dispose();
    super.dispose();
  }

  Future<void> _load() async {
    setState(() => _loading = true);
    final q = {'farmId': _farmId};
    try {
      final r = await Future.wait([
        _api.get('/api/Water/production-batches', query: q),
        _api.get('/api/Water/machines', query: q),
        _api.get('/api/Water/products', query: q),
        _api.get('/api/Water/raw-material-items', query: q),
        // Tolerated failure: without lots the form falls back to headline
        // stock and the latest-purchase price.
        _api.get('/api/Water/raw-material-items/open-lots', query: q).catchError((_) => const <Map>[]),
      ]);
      if (!mounted) return;
      setState(() {
        _batches = rowsOf(r[0]);
        _machines = rowsOf(r[1]);
        _products = rowsOf(r[2]);
        _rawMaterials = rowsOf(r[3]);
        _lots = rowsOf(r[4]);
      });
    } on ApiException catch (e) {
      if (mounted) trackerToast(context, 'Could not load production records', description: e.message, error: true);
    }
    if (mounted) setState(() => _loading = false);
  }

  int _id(Map b) => tIntOrNull(b['waterProductionBatchId']) ?? 0;

  Future<void> _openForm([Map? editing]) async {
    final saved = await Navigator.of(context).push<bool>(MaterialPageRoute(
      builder: (_) => WaterProductionFormScreen(
        session: widget.session,
        company: widget.company,
        editing: editing,
        machines: _machines,
        products: _products,
        rawMaterials: _rawMaterials,
        lots: _lots,
      ),
    ));
    if (saved == true) await _load();
  }

  Future<void> _view(Map b) async {
    await Navigator.of(context).push(MaterialPageRoute(
      builder: (_) => WaterProductionDetailScreen(session: widget.session, company: widget.company, batchId: _id(b)),
    ));
  }

  Future<void> _post(String leaf, Map<String, String> extra, String ok, String fail) async {
    try {
      // The web sends these as query parameters on a bodiless POST.
      await _api.post('/api/Water/production-batches/$leaf', query: {'farmId': _farmId, ...extra});
      if (mounted) trackerToast(context, ok);
      await _load();
    } on ApiException catch (e) {
      if (mounted) trackerToast(context, fail, description: e.message, error: true);
    }
  }

  Future<void> _approve(Map b) =>
      _post('${_id(b)}/approve', {'approvedBy': widget.session.tokens.userId ?? ''}, 'Batch approved — bags added to inventory', 'Approve failed');

  Future<void> _cancel(Map b) => _post('${_id(b)}/cancel', const {}, 'Batch cancelled', 'Cancel failed');

  Future<void> _reopen(Map b) async {
    final good = tNum(b['bagsProduced']) - tNum(b['damagedBags']);
    final ok = await confirmDelete(
      context,
      title: 'Reopen this approved production record?',
      description:
          'Reversing "${tStr(b['batchNumber'])}" will subtract its ${qtyFmt(good)} good bags from stock and flip it back to Draft. If those bags have already been sold this will fail — cancel the sales first.',
      confirmLabel: 'Reopen',
    );
    if (!ok) return;
    await _post('${_id(b)}/reopen', {'reopenedBy': widget.session.tokens.userId ?? ''}, 'Production record reopened — back to Draft', 'Reopen failed');
  }

  void _openDay(Map b) => openAppHref(context, widget.session, widget.company, '/water-daily-production/${tStr(b['waterDailyProductionId'])}',
      label: 'Batch Production');

  List<Widget> _actions(Map b) {
    final st = tStr(b['status']);
    return [
      OutlinedButton.icon(onPressed: () => _view(b), icon: const Icon(Icons.visibility_outlined, size: 16), label: const Text('View')),
      if (isDailyProductionChild(b))
        OutlinedButton.icon(
          onPressed: () => _openDay(b),
          style: OutlinedButton.styleFrom(foregroundColor: const Color(0xFF0369A1), side: const BorderSide(color: Color(0xFFBAE6FD))),
          icon: const Icon(Icons.calendar_month_outlined, size: 16),
          label: const Text('Open batch production'),
        )
      else ...[
        if (st == 'Draft') OutlinedButton.icon(onPressed: () => _openForm(b), icon: const Icon(Icons.edit_outlined, size: 16), label: const Text('Edit')),
        if (st == 'Draft')
          OutlinedButton.icon(
            onPressed: () => _approve(b),
            style: OutlinedButton.styleFrom(foregroundColor: const Color(0xFF15803D), side: const BorderSide(color: Color(0xFFBBF7D0))),
            icon: const Icon(Icons.check_circle_outline, size: 16),
            label: const Text('Approve'),
          ),
        if (st != 'Cancelled' && st != 'Approved')
          OutlinedButton.icon(
            onPressed: () => _cancel(b),
            style: OutlinedButton.styleFrom(foregroundColor: TColors.red600, side: const BorderSide(color: Color(0xFFFECACA))),
            icon: const Icon(Icons.cancel_outlined, size: 16),
            label: const Text('Cancel'),
          ),
        if (st == 'Approved')
          OutlinedButton.icon(
            onPressed: () => _reopen(b),
            style: OutlinedButton.styleFrom(foregroundColor: TColors.amber700, side: const BorderSide(color: Color(0xFFFDE68A))),
            icon: const Icon(Icons.undo, size: 16),
            label: const Text('Reopen'),
          ),
      ],
    ];
  }

  Widget _score(String label, String value) => Container(
        padding: const EdgeInsets.all(10),
        decoration: BoxDecoration(color: Colors.white, border: Border.all(color: TColors.slate200), borderRadius: BorderRadius.circular(10)),
        child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
          Text(label, style: const TextStyle(fontSize: 11, color: TColors.slate500)),
          Text(value, style: const TextStyle(fontSize: 16, fontWeight: FontWeight.w600, color: TColors.slate900)),
        ]),
      );

  Widget _table(List<Map> items) => TrackerTable(
        columns: const [
          TCol('Date', width: 140), TCol('Shift', width: 90), TCol('Machine', width: 140), TCol('Produced', right: true, width: 90),
          TCol('Good', right: true, width: 80), TCol('Damaged', right: true, width: 80), TCol('Total cost', right: true, width: 120),
          TCol('Cost/bag', right: true, width: 100), TCol('Status', width: 100), TCol('Actions', right: true, width: 200),
        ],
        rows: [
          for (final b in items)
            [
              cellText(tStr(b['productionDate']).isEmpty ? '—' : fmtDateTime(b['productionDate'], b, _offset)),
              cellText(tStr(b['shift']).isEmpty ? '—' : tStr(b['shift'])),
              tStr(b['machineScope']) == 'AllMachines'
                  ? const Text('All / Combined', style: TextStyle(fontStyle: FontStyle.italic, color: TColors.slate600))
                  : cellText(waterMachineLabel(b)),
              Align(alignment: Alignment.centerRight, child: cellText(qtyFmt(b['bagsProduced']))),
              Align(alignment: Alignment.centerRight, child: cellText(qtyFmt(waterGoodBags(b)), bold: true)),
              Align(alignment: Alignment.centerRight, child: cellText('${tNum(b['damagedBags'])}')),
              Align(alignment: Alignment.centerRight, child: cellText(_gh(waterAllInCost(b)))),
              Align(alignment: Alignment.centerRight, child: cellText(_gh(tNum(b['costPerBag'])))),
              Align(alignment: Alignment.centerLeft, child: waterBatchStatusBadge(b['status'])),
              Wrap(alignment: WrapAlignment.end, children: [
                IconButton(tooltip: 'View details', onPressed: () => _view(b), icon: const Icon(Icons.visibility_outlined, size: 18)),
                if (isDailyProductionChild(b))
                  IconButton(
                    tooltip: 'Open the batch production that created this record',
                    onPressed: () => _openDay(b),
                    icon: const Icon(Icons.calendar_month_outlined, size: 18, color: Color(0xFF0284C7)),
                  )
                else ...[
                  if (tStr(b['status']) == 'Draft') IconButton(tooltip: 'Edit', onPressed: () => _openForm(b), icon: const Icon(Icons.edit_outlined, size: 18)),
                  if (tStr(b['status']) == 'Draft')
                    IconButton(tooltip: 'Approve', onPressed: () => _approve(b), icon: const Icon(Icons.check_circle_outline, size: 18, color: Color(0xFF16A34A))),
                  if (tStr(b['status']) != 'Cancelled' && tStr(b['status']) != 'Approved')
                    IconButton(tooltip: 'Cancel', onPressed: () => _cancel(b), icon: const Icon(Icons.cancel_outlined, size: 18, color: Color(0xFFF43F5E))),
                  if (tStr(b['status']) == 'Approved')
                    IconButton(tooltip: 'Reopen for edit', onPressed: () => _reopen(b), icon: const Icon(Icons.undo, size: 18, color: TColors.amber600)),
                ],
              ]),
            ],
        ],
      );

  @override
  Widget build(BuildContext context) {
    final lead = sidebarLeading(context, widget.session, widget.company, href: '/water-production-batches');
    final totals = waterProductionTotals(_batches, DateTime.now().toUtc().toIso8601String().substring(0, 10));
    final visible = filterWaterBatches(_batches, search: _search.text, from: _from, to: _to);
    if (visible.length != _lastTotal) {
      _lastTotal = visible.length;
      _page = 1;
    }
    final pageRows = pageSlice(visible, _page, _pageSize);
    final n = _batches.length;
    return Scaffold(
      appBar: AppBar(leading: lead.leading, leadingWidth: lead.width, title: const Text('Production')),
      body: RefreshIndicator(
        onRefresh: _load,
        child: ListView(
          padding: const EdgeInsets.fromLTRB(14, 12, 14, 28),
          children: [
            Row(children: [
              Container(
                width: 40,
                height: 40,
                decoration: BoxDecoration(color: const Color(0xFFE0F2FE), borderRadius: BorderRadius.circular(8)),
                child: const Icon(Icons.factory_outlined, color: Color(0xFF0284C7)),
              ),
              const SizedBox(width: 10),
              Expanded(
                child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
                  const Text('Production', style: TextStyle(fontSize: 20, fontWeight: FontWeight.w600, color: TColors.slate900)),
                  Text('$n production record${n == 1 ? '' : 's'} on file.', style: const TextStyle(fontSize: 12, color: TColors.slate500)),
                ]),
              ),
            ]),
            const SizedBox(height: 10),
            FilledButton.icon(
              onPressed: () => _openForm(),
              style: FilledButton.styleFrom(minimumSize: const Size.fromHeight(44)),
              icon: const Icon(Icons.add, size: 16),
              label: const Text('Record production'),
            ),
            const SizedBox(height: 12),
            ListFiltersCard(
              search: _search,
              searchPlaceholder: 'Search batch number, status or notes',
              onSearch: () => setState(() {}),
              from: _from,
              to: _to,
              onDates: (f, t) => setState(() {
                _from = f;
                _to = t;
              }),
              onClear: () => setState(() {
                _search.clear();
                _from = '';
                _to = '';
              }),
            ),
            const SizedBox(height: 12),
            twoUp([
              _score("Today's bags (good)", qtyFmt(totals.todayBags)),
              _score("Month's bags (good)", qtyFmt(totals.monthBags)),
              _score('Pending approval', '${totals.draftCount}'),
              _score('Active machines', '${_machines.where((m) => tStr(m['status']) == 'Active').length}'),
            ]),
            const SizedBox(height: 12),
            if (_loading)
              const Padding(padding: EdgeInsets.all(16), child: LoadingLine('Loading…'))
            else if (_batches.isEmpty)
              Container(
                padding: const EdgeInsets.all(32),
                decoration: BoxDecoration(color: Colors.white, border: Border.all(color: TColors.slate200), borderRadius: BorderRadius.circular(12)),
                child: const Text('No production records yet.', textAlign: TextAlign.center, style: TextStyle(color: TColors.slate500)),
              )
            else
              MobileCardList<Map>(
                striped: true,
                items: pageRows,
                keyOf: (b) => '${_id(b)}',
                primary: (b) => '${tStr(b['batchNumber']).isEmpty ? '#${_id(b)}' : tStr(b['batchNumber'])} · ${qtyFmt(waterGoodBags(b))} good bags',
                secondaryBuilder: (b) => Wrap(spacing: 6, runSpacing: 4, crossAxisAlignment: WrapCrossAlignment.center, children: [
                  Text(tStr(b['productionDate']).isEmpty ? '—' : fmtDateTime(b['productionDate'], b, _offset)),
                  _outlineBadge(waterMachineLabel(b)),
                  waterBatchStatusBadge(b['status']),
                ]),
                highlights: (b) => [
                  Highlight('Produced bags', qtyFmt(b['bagsProduced']), accent: Accent.blue),
                  Highlight('Good bags', qtyFmt(waterGoodBags(b)), accent: Accent.emerald),
                  Highlight('Total cost', _gh(waterAllInCost(b)), accent: Accent.violet, wide: true),
                ],
                details: (b) => [
                  ('Date', tStr(b['productionDate']).isEmpty ? '—' : fmtDateTime(b['productionDate'], b, _offset)),
                  ('Shift', tStr(b['shift']).isEmpty ? '—' : tStr(b['shift'])),
                  ('Machine', waterMachineLabel(b, all: 'All Machines / Combined')),
                  ('Damaged', '${tNum(b['damagedBags'])}'),
                  ('Cost/bag', _gh(tNum(b['costPerBag']))),
                ],
                actions: _actions,
                table: _table,
                pager: CompactPager(
                  total: visible.length,
                  page: _page,
                  pageSize: _pageSize,
                  onPage: (p) => setState(() => _page = p),
                  onPageSize: (v) => setState(() {
                    _pageSize = v;
                    _page = 1;
                  }),
                ),
              ),
          ],
        ),
      ),
    );
  }
}

