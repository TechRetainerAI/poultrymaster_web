  Future<void> _save({bool approve = false}) async {
    if (_batchNo.text.trim().isEmpty) return trackerToast(context, 'Batch number is required', error: true);
    if (_productId == 0) return trackerToast(context, 'Pick a product first', error: true);
    if (_v(_bags) <= 0) return trackerToast(context, 'Bags produced must be greater than zero', error: true);
    if ((num.tryParse(_perBag.text) ?? 30) <= 0) return trackerToast(context, 'Sachets per bag must be greater than zero', error: true);
    for (final r in _rows) {
      if (r.actual < 0) return trackerToast(context, 'Negative quantity not allowed', description: '${r.name}: actual cannot be negative.', error: true);
    }
    if (_hasRecipe && _rows.any((r) => r.actual <= 0) && !_override) {
      return trackerToast(context, 'Some materials are missing',
          description: 'Tick "Save anyway (override)" below the Raw Materials section if you want to record this production without them.', error: true);
    }
    setState(() => _saving = true);
    final payload = <String, Object?>{
      'batchNumber': _batchNo.text,
      'productionDate': _date,
      'shift': _shift,
      // "All Machines / Combined" → NULL machine id.
      'waterMachineId': _scope == 'AllMachines' || _machineId == 0 ? null : _machineId,
      'machineScope': _scope,
      'waterProductId': _productId == 0 ? null : _productId,
      'bagsProduced': _v(_bags),
      'sachetsPerBag': (num.tryParse(_perBag.text) ?? 0) == 0 ? 30 : num.parse(_perBag.text),
      'rejectedSachets': _v(_rejected),
      'damagedBags': _v(_damaged),
      'electricityCost': _v(_electricity),
      'fuelCost': _v(_fuel),
      'laborCost': _v(_labor),
      'otherProductionCost': _v(_other),
      'notes': _notes.text,
      'materialsUsed': [
        for (final r in _rows)
          {'waterRawMaterialItemId': r.itemId, 'quantityUsed': r.actual, 'expectedQuantityUsed': r.expected, 'unitCost': r.unitCost},
      ],
      'farmId': _farmId,
    };
    try {
      int? approveId = tIntOrNull(e?['waterProductionBatchId']);
      if (_editing) {
        await _api.put('/api/Water/production-batches/$approveId', body: {...payload, 'waterProductionBatchId': approveId});
        if (!approve && mounted) trackerToast(context, 'Production record updated');
      } else {
        final created = await _api.post('/api/Water/production-batches', body: {...payload, 'createdBy': widget.session.tokens.userId});
        approveId = created is Map ? tIntOrNull(created['waterProductionBatchId']) : null;
        if (!approve && mounted) trackerToast(context, 'Production record saved as Draft', description: 'Approve to add to inventory.');
      }
      if (approve && approveId != null) {
        await _api.post('/api/Water/production-batches/$approveId/approve',
            query: {'farmId': _farmId, 'approvedBy': widget.session.tokens.userId ?? ''});
        if (mounted) trackerToast(context, 'Production saved & approved — bags added to inventory');
      }
      if (mounted) Navigator.pop(context, true);
    } on ApiException catch (x) {
      if (!mounted) return;
      setState(() => _saving = false);
      trackerToast(context, approve ? 'Save & approve failed' : (_editing ? 'Update failed' : 'Save failed'), description: x.message, error: true);
    }
  }

