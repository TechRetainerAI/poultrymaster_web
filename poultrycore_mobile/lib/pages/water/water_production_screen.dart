/// Production Record Details (`app/water-production-batches/[id]/page.tsx`):
/// read-only, every field, the materials, and the linked stock, expense and
/// loss records. Each part loads on its own so a missing one doesn't blank the page.
class WaterProductionDetailScreen extends StatefulWidget {
  const WaterProductionDetailScreen({super.key, required this.session, required this.company, required this.batchId});
  final Session session;
  final Company company;
  final int batchId;

  @override
  State<WaterProductionDetailScreen> createState() => _WaterProductionDetailScreenState();
}

class _WaterProductionDetailScreenState extends State<WaterProductionDetailScreen> {
  Map? _batch;
  List<Map> _materials = [], _losses = [], _expenses = [], _txns = [];
  bool _busy = true;
  FarmMoney _gh = const FarmMoney();
  Duration _offset = DateTime.now().timeZoneOffset;

  ApiClient get _api => widget.session.farmClient;

  @override
  void initState() {
    super.initState();
    FarmMoney.load(widget.session, widget.company).then((m) {
      if (mounted) setState(() => _gh = m);
    });
    CompanyClock.load(widget.session, widget.company).then((c) {
      if (mounted) setState(() => _offset = c.offset);
    });
    _load();
  }

  Future<void> _load() async {
    setState(() => _busy = true);
    final base = '/api/Water/production-batches/${widget.batchId}';
    final q = {'farmId': widget.company.farmId};
    Future<List<Map>> soft(String leaf) async {
      try {
        return rowsOf(await _api.get('$base/$leaf', query: q));
      } on ApiException {
        return const [];
      }
    }

    Future<Map?> batch() async {
      try {
        final r = await _api.get(base, query: q);
        return r is Map ? r : null;
      } on ApiException catch (e) {
        if (mounted) trackerToast(context, 'Could not load batch', description: e.message, error: true);
        return null;
      }
    }

    final r = await Future.wait<Object?>([batch(), soft('materials'), soft('linked-losses'), soft('linked-expenses'), soft('linked-stock-txns')]);
    if (!mounted) return;
    setState(() {
      _batch = r[0] as Map?;
      _materials = r[1] as List<Map>;
      _losses = r[2] as List<Map>;
      _expenses = r[3] as List<Map>;
      _txns = r[4] as List<Map>;
      _busy = false;
    });
  }

  void _back() {
    final nav = Navigator.of(context);
    if (nav.canPop()) {
      nav.pop();
    } else {
      nav.pushReplacement(MaterialPageRoute(builder: (_) => WaterProductionScreen(session: widget.session, company: widget.company)));
    }
  }

  Widget _sum(String label, String value, {Color? color}) => Container(
        padding: const EdgeInsets.all(12),
        decoration: BoxDecoration(color: Colors.white, border: Border.all(color: TColors.slate200), borderRadius: BorderRadius.circular(10)),
        child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
          Text(label.toUpperCase(), style: const TextStyle(fontSize: 11, letterSpacing: .6, color: TColors.slate500)),
          const SizedBox(height: 4),
          Text(value, maxLines: 1, overflow: TextOverflow.ellipsis, style: TextStyle(fontSize: 18, fontWeight: FontWeight.w600, color: color)),
        ]),
      );

  Widget _fields(List<(String, String, Color?)> items) => twoUp([
        for (final (k, v, c) in items)
          Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
            Text(k, style: const TextStyle(fontSize: 12, color: TColors.slate500)),
            Text(v, style: TextStyle(fontWeight: c != null ? FontWeight.w600 : FontWeight.w500, color: c)),
          ]),
      ]);

  Widget _card(List<Widget> children) => Container(
        padding: const EdgeInsets.all(12),
        decoration: BoxDecoration(color: Colors.white, border: Border.all(color: TColors.slate200), borderRadius: BorderRadius.circular(6)),
        child: Column(crossAxisAlignment: CrossAxisAlignment.stretch, children: children),
      );

  Widget _kv(String k, String v, {Color? color, bool bold = false}) => Text.rich(TextSpan(children: [
        TextSpan(text: '$k: ', style: const TextStyle(color: TColors.slate500)),
        TextSpan(text: v, style: TextStyle(color: color, fontWeight: bold ? FontWeight.w600 : null)),
      ]), style: const TextStyle(fontSize: 12));

  Widget _empty(String t) => Text(t, style: const TextStyle(fontSize: 13, color: TColors.slate500));

  List<Widget> _spaced(List<Widget> w) => [for (var i = 0; i < w.length; i++) ...[if (i > 0) const SizedBox(height: 8), w[i]]];

  @override
  Widget build(BuildContext context) {
    final lead = sidebarLeading(context, widget.session, widget.company, href: '/water-production-batches');
    final b = _batch;
    final sub = [
      b != null && tStr(b['productionDate']).isNotEmpty ? 'Produced ${_day(b['productionDate'])}' : '—',
      if (tStr(b?['shift']).isNotEmpty) ' · ${tStr(b?['shift'])}',
      if (tStr(b?['productName']).isNotEmpty) ' · ${tStr(b?['productName'])}',
    ].join();
    return Scaffold(
      appBar: AppBar(
        leading: lead.leading,
        leadingWidth: lead.width,
        title: Text(tStr(b?['batchNumber']).isNotEmpty ? tStr(b?['batchNumber']) : 'Production #${widget.batchId}'),
      ),
      body: RefreshIndicator(
        onRefresh: _load,
        child: ListView(
          padding: const EdgeInsets.fromLTRB(14, 12, 14, 28),
          children: [
            Row(crossAxisAlignment: CrossAxisAlignment.start, children: [
              Container(
                width: 40,
                height: 40,
                decoration: BoxDecoration(color: const Color(0xFFE0F2FE), borderRadius: BorderRadius.circular(8)),
                child: const Icon(Icons.factory_outlined, color: Color(0xFF0284C7)),
              ),
              const SizedBox(width: 10),
              Expanded(
                child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
                  Text(tStr(b?['batchNumber']).isNotEmpty ? tStr(b?['batchNumber']) : 'Production #${widget.batchId}',
                      style: const TextStyle(fontSize: 20, fontWeight: FontWeight.w600, color: TColors.slate900)),
                  Text(sub, style: const TextStyle(fontSize: 12, color: TColors.slate500)),
                ]),
              ),
            ]),
            const SizedBox(height: 8),
            Align(
              alignment: Alignment.centerLeft,
              child: OutlinedButton.icon(onPressed: _back, icon: const Icon(Icons.arrow_back, size: 16), label: const Text('Back to production')),
            ),
            const SizedBox(height: 12),
            if (_busy)
              const LoadingLine('Loading details…')
            else if (b == null)
              _card([const Text('Production record not found.', style: TextStyle(color: TColors.slate500))])
            else
              ..._spaced(_details(b)).expand((w) => [w]),
          ],
        ),
      ),
    );
  }

  List<Widget> _details(Map b) {
    final totalSachets = tNum(b['bagsProduced']) * tNum(b['sachetsPerBag']);
    final all = waterAllInCost(b);
    return [
      Wrap(spacing: 8, runSpacing: 4, crossAxisAlignment: WrapCrossAlignment.center, children: [
        waterBatchStatusBadge(b['status']),
        if (tStr(b['machineScope']) == 'AllMachines')
          const TBadge('All Machines / Combined', bg: TColors.violet100, fg: Color(0xFF5B21B6)),
        if (tStr(b['approvedBy']).isNotEmpty)
          Text('Approved by ${tStr(b['approvedBy'])}${tStr(b['approvedAt']).isNotEmpty ? ' · ${_day(b['approvedAt'])}' : ''}',
              style: const TextStyle(fontSize: 12, color: TColors.slate500)),
        if (tStr(b['createdBy']).isNotEmpty)
          Text('Created by ${tStr(b['createdBy'])}${tStr(b['createdAt']).isNotEmpty ? ' · ${_day(b['createdAt'])}' : ''}',
              style: const TextStyle(fontSize: 12, color: TColors.slate500)),
      ]),
      twoUp([
        _sum('Produced bags', qtyFmt(b['bagsProduced'])),
        _sum('Good bags', qtyFmt(waterGoodBags(b)), color: TColors.emerald700),
        _sum('Damaged bags', '${tNum(b['damagedBags'])}', color: tNum(b['damagedBags']) != 0 ? TColors.amber700 : null),
        _sum('Rejected sachets', '${tNum(b['rejectedSachets'])}', color: tNum(b['rejectedSachets']) != 0 ? TColors.amber700 : null),
        _sum('Total cost', _gh(all), color: const Color(0xFF4338CA)),
        _sum('Cost per (good) bag', _gh(tNum(b['costPerBag']))),
        _sum('Total sachets', qtyFmt(totalSachets)),
        _sum('Efficiency', '${tNum(b['productionEfficiencyPercent']).toStringAsFixed(1)}%'),
      ]),
      formSection('Batch information', const Color(0xFF4F46E5), [
        _fields([
          ('Batch number', tStr(b['batchNumber']).isEmpty ? '—' : tStr(b['batchNumber']), null),
          ('Production date', tStr(b['productionDate']).isEmpty ? '—' : _day(b['productionDate']), null),
          ('Shift', tStr(b['shift']).isEmpty ? '—' : tStr(b['shift']), null),
          ('Machine', waterMachineLabel(b, all: 'All Machines / Combined'), null),
          ('Borehole', tStr(b['boreholeName']).isEmpty ? '—' : tStr(b['boreholeName']), null),
          ('Product', tStr(b['productName']).isEmpty ? '—' : tStr(b['productName']), null),
          ('Sachets per bag', tStr(b['sachetsPerBag']), null),
          ('Status', tStr(b['status']), null),
        ]),
      ]),
      formSection('Costs', const Color(0xFF16A34A), [
        _fields([
          ('Electricity', _gh(tNum(b['electricityCost'])), null),
          ('Fuel', _gh(tNum(b['fuelCost'])), null),
          ('Labor', _gh(tNum(b['laborCost'])), null),
          ('Other', _gh(tNum(b['otherProductionCost'])), null),
          ('Raw materials & supplies', _gh(tNum(b['rawMaterialCost'])), null),
          ('Total cost', _gh(all), TColors.emerald700),
        ]),
      ]),
      formSection('Raw materials & supplies used', TColors.amber600, [
        if (_materials.isEmpty)
          _empty('No raw materials & supplies recorded for this batch.')
        else
          ..._spaced([
            for (final m in _materials)
              _card([
                Text(tStr(m['itemName']).isEmpty ? '—' : tStr(m['itemName']), style: const TextStyle(fontWeight: FontWeight.w500)),
                const SizedBox(height: 4),
                twoUp([
                  _kv('Expected', '${qtyFmt(m['expectedQuantityUsed'])} ${tStr(m['unitOfMeasure'])}'),
                  _kv('Actual', '${qtyFmt(m['quantityUsed'])} ${tStr(m['unitOfMeasure'])}'),
                  _kv('Variance', qtyFmt(m['variance']), color: tNum(m['variance']).abs() > 0 ? TColors.amber700 : null),
                  _kv('Unit cost', tNum(m['unitCost']) != 0 ? _gh(tNum(m['unitCost'])) : '—'),
                ]),
                Align(alignment: Alignment.centerRight, child: _kv('Cost', tNum(m['totalCost']) != 0 ? _gh(tNum(m['totalCost'])) : '—', bold: true)),
              ]),
          ]),
      ]),
      formSection('Related inventory transactions', const Color(0xFF0284C7), [
        if (_txns.isEmpty)
          _empty('None yet — batch is not Approved or stock impact has been reversed.')
        else
          ..._spaced([
            for (final t in _txns)
              _card([
                Row(children: [
                  Expanded(
                    child: Text(tStr(t['productName']).isNotEmpty ? tStr(t['productName']) : '#${tStr(t['waterProductId'])}',
                        overflow: TextOverflow.ellipsis, style: const TextStyle(fontWeight: FontWeight.w500)),
                  ),
                  _outlineBadge(tStr(t['txnType']).isEmpty ? '—' : tStr(t['txnType'])),
                ]),
                const SizedBox(height: 4),
                twoUp([
                  _kv('Quantity', qtyFmt(t['quantity'])),
                  _kv('Unit cost', t['unitCost'] != null ? _gh(tNum(t['unitCost'])) : '—'),
                ]),
                _kv('Date', fmtInstant(t['createdAt'], _offset)),
                if (tStr(t['note']).isNotEmpty) Text(tStr(t['note']), style: const TextStyle(fontSize: 12, color: TColors.slate600)),
              ]),
          ]),
      ]),
      formSection('Related expense records', const Color(0xFF9333EA), [
        if (_expenses.isEmpty)
          _empty('No production-linked expenses for this batch.')
        else
          ..._spaced([
            for (final x in _expenses)
              _card([
                Row(children: [
                  Expanded(
                    child: Text(tStr(x['categoryName']).isEmpty ? '—' : tStr(x['categoryName']),
                        overflow: TextOverflow.ellipsis, style: const TextStyle(fontWeight: FontWeight.w500)),
                  ),
                  Text(_gh(tNum(x['amount'])), style: const TextStyle(fontWeight: FontWeight.w600)),
                ]),
                const SizedBox(height: 4),
                twoUp([
                  _kv('Payment',
                      '${tStr(x['paymentMethod']).isEmpty ? '—' : tStr(x['paymentMethod'])}${tStr(x['cashAccountName']).isNotEmpty ? ' · ${tStr(x['cashAccountName'])}' : ''}'),
                  _kv('Status', tStr(x['status']).isEmpty ? '—' : tStr(x['status'])),
                ]),
                _kv('Date', fmtDateTime(x['expenseDate'], x, _offset)),
                if (tStr(x['description']).isNotEmpty) Text(tStr(x['description']), style: const TextStyle(fontSize: 12, color: TColors.slate600)),
              ]),
          ]),
      ]),
      formSection('Related loss records', const Color(0xFFE11D48), [
        if (_losses.isEmpty)
          _empty('No damage / rejected loss records for this batch.')
        else
          ..._spaced([
            for (final l in _losses)
              _card([
                Row(children: [
                  Expanded(child: Text(tStr(l['lossType']), style: const TextStyle(fontWeight: FontWeight.w500))),
                  Text(_gh(tNum(l['totalValue'])), style: const TextStyle(fontWeight: FontWeight.w600)),
                ]),
                const SizedBox(height: 4),
                twoUp([
                  _kv('Date', fmtDateTime(l['lossDate'], l, _offset)),
                  _kv('Status', tStr(l['status'])),
                  _kv('Bags', '${qtyFmt(l['bagsLost'])} (${_gh(tNum(l['bagsLossValue']))})'),
                  _kv('Sachets', '${qtyFmt(l['sachetsLost'])} (${_gh(tNum(l['sachetsLossValue']))})'),
                ]),
              ]),
          ]),
      ]),
      if (tStr(b['notes']).isNotEmpty)
        formSection('Notes', TColors.slate600, [Text(tStr(b['notes']), style: const TextStyle(fontSize: 13, color: TColors.slate700))]),
    ];
  }
