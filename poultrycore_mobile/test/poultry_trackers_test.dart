      final l = buildEggStockLedger(eggProductions, sales, flocks, eggAdjustments, [], 225);
      expect([for (final r in l.rows) r.type], ['Production', 'Broken eggs', 'Sale', 'Adjustment']);
      expect(l.rows.first.description, 'Layers A — Medium — collected', reason: 'legacy grade P2 is Medium');
      expect(l.currentEggsAtHand, 225);
