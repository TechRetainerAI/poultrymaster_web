      final moves = buildFeedItemMovements(items, purchases, usages, []);
      final p = buildFeedItemPositions(items, moves, '2026-10-01', '2026-10-31');
      final mash = p.firstWhere((x) => x.itemName == 'Layer mash');
      expect((mash.opening, mash.inQty, mash.outQty, mash.closing), (500, 0, 80, 420));
      expect(mash.drift, 0);
      final maize = p.firstWhere((x) => x.itemName == 'Maize');
      expect((maize.derivedNow, maize.onRecord, maize.drift), (900, 900, 0));
      final drifted = buildFeedItemPositions(
          [{...items[1], 'currentQuantity': 950}], moves, '', '');
      expect(drifted.single.drift, -50);
    });

