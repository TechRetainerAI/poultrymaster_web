      final ingredients = buildFeedStockLedger(kind: FeedKind.ingredient, items: items, purchases: purchases, usages: usages, adjustments: []);
      expect(ingredients.atHand, 900);
      expect(ingredients.rows.last.description, 'Maize — feed production FB-4 (100 kg)');
