      expect(off.rows.last.type, 'Unmatched');
      expect(off.rows.last.outQty, 25);
      expect(off.currentEggsAtHand, 200);
    });

    test('egg stock moves: a post and its reversal cancel; manual rows are kept', () {
      final moves = [
