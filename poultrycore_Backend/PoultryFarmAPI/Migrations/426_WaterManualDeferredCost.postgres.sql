-- =============================================================================
-- 426_WaterManualDeferredCost.postgres.sql   (Water credits programme W5; requires 277-279)
--
-- Purpose
-- -------
-- Poultry 371 for Water. Record cost for stock the company already holds that
-- NO purchase lot covers -- e.g. opening stock carried into the system. The
-- batch draw (spwaterrawmaterialitem_consumebatches) refuses stock no lot
-- holds ("Not enough tracked batch stock"); a manual cost IS such a lot, so
-- production can draw from it and its cost is recognised as it is used --
-- exactly like a purchase whose cost is expensed when consumed.
--
-- It is a LOT in waterrawmaterialpurchases, lotsource = 'ManualDeferredCost':
--   quantity / remaining   the stock it covers, in the item's stock unit (mult 1)
--   deferred total / left  the amount, recognised by the existing draws
--   amountpaid = totalcost nothing is owed: no supplier, no cash
-- A side record (watermanualdeferredcosts, MDC-00001) holds the entry type,
-- reason, reference, who / when and the reversal.
--
-- ONLY for uncovered stock: quantity <= the item's stock less what its lots
-- already hold. Physical stock does not change.
--
-- REVERSAL takes back only what is not yet recognised. The quantity stays (the
-- stock is real); recognised history is never touched.
--
-- WATER-SPECIFIC: water's P&L and Daily Closing count raw materials by a
-- purchase's AMOUNTPAID. A manual lot is not a purchase -- its cost reaches the
-- P&L only as it is consumed -- so it is excluded from: periodpnl raw
-- materials, pllines / pldirectcostdetail, the closing's raw spend, payables,
-- the purchases list, the balance audit and recalculatestock (which rebuilds
-- stock from purchases and would otherwise count the opening stock twice).
-- Purchase edit / delete / pay-balance refuse it.
--
-- Deploy order: this migration, then the Farm API, then the web app.
-- =============================================================================
\set ON_ERROR_STOP on

BEGIN;

ALTER TABLE public.waterrawmaterialpurchases ADD COLUMN IF NOT EXISTS lotsource text;
CREATE INDEX IF NOT EXISTS ix_waterrmpurchases_manualdeferred
    ON public.waterrawmaterialpurchases (farmid, waterrawmaterialitemid) WHERE lotsource = 'ManualDeferredCost';

CREATE TABLE IF NOT EXISTS public.watermanualdeferredcosts (
    entryid                     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmid                      text          NOT NULL,
    entrynumber                 text          NOT NULL,
    waterrawmaterialpurchaseid  integer       NOT NULL REFERENCES public.waterrawmaterialpurchases (waterrawmaterialpurchaseid),
    waterrawmaterialitemid      integer       NOT NULL,
    entrytype                   text          NOT NULL CHECK (entrytype IN
                                    ('OpeningDeferredCost', 'HistoricalDeferredCost', 'CostAdjustment', 'Migration', 'Other')),
    amount                      numeric(14,2) NOT NULL CHECK (amount > 0),
    quantity                    numeric(14,3) NOT NULL CHECK (quantity > 0),
    effectivedate               date          NOT NULL,
    reason                      text          NOT NULL,
    reference                   text,
    notes                       text,
    status                      text          NOT NULL DEFAULT 'Posted' CHECK (status IN ('Posted', 'Reversed')),
    createdby                   text,
    createdat                   timestamp     NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    reversedby                  text,
    reversedat                  timestamp,
    reversalreason              text,
    reversedamount              numeric(14,2)
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_watermanualdeferredcosts_number ON public.watermanualdeferredcosts (farmid, entrynumber);
CREATE UNIQUE INDEX IF NOT EXISTS ux_watermanualdeferredcosts_lot ON public.watermanualdeferredcosts (waterrawmaterialpurchaseid);

-- The item's stock less what its lots still hold (the lots usage draws from).
CREATE OR REPLACE FUNCTION public.fnwaterrawmaterial_uncoveredstock(p_farmid text, p_itemid integer)
RETURNS numeric LANGUAGE sql STABLE AS $f$
    SELECT GREATEST(COALESCE(i.currentquantity, 0)
             - COALESCE((SELECT SUM(p.remainingquantity * COALESCE(NULLIF(p.productionunitsperpurchaseunit, 0), 1))
                         FROM waterrawmaterialpurchases p
                         WHERE p.farmid = i.farmid AND p.waterrawmaterialitemid = i.waterrawmaterialitemid
                           AND p.remainingquantity > 0), 0), 0)::numeric(14,3)
    FROM   waterrawmaterialitems i
    WHERE  i.waterrawmaterialitemid = p_itemid AND i.farmid = p_farmid;
$f$;

CREATE OR REPLACE FUNCTION public.spwatermanualdeferredcost_create(p_farmid text, p_itemid integer, p_amount numeric,
    p_quantity numeric, p_effectivedate date, p_entrytype text, p_reason text, p_reference text DEFAULT NULL,
    p_notes text DEFAULT NULL, p_by text DEFAULT NULL)
RETURNS jsonb LANGUAGE plpgsql AS $f$
DECLARE
    v_item      record;
    v_amt       numeric(14,2) := round(p_amount, 2);
    v_qty       numeric(14,3) := round(p_quantity, 3);
    v_uncovered numeric(14,3);
    v_lot       integer;
    v_id        integer;
    v_number    text;
BEGIN
    IF v_amt IS NULL OR v_amt <= 0 THEN
        RAISE EXCEPTION 'Enter the cost, greater than 0.' USING ERRCODE = 'P0001';
    END IF;
    IF v_qty IS NULL OR v_qty <= 0 THEN
        RAISE EXCEPTION 'Enter the quantity of stock this cost is for, greater than 0.' USING ERRCODE = 'P0001';
    END IF;
    IF p_entrytype IS NULL OR p_entrytype NOT IN ('OpeningDeferredCost', 'HistoricalDeferredCost', 'CostAdjustment', 'Migration', 'Other') THEN
        RAISE EXCEPTION 'Choose what this cost is.' USING ERRCODE = 'P0001';
    END IF;
    IF NULLIF(btrim(COALESCE(p_reason, '')), '') IS NULL THEN
        RAISE EXCEPTION 'Give a reason.' USING ERRCODE = 'P0001';
    END IF;
    IF p_effectivedate IS NULL THEN
        RAISE EXCEPTION 'Give the date the cost applies from.' USING ERRCODE = 'P0001';
    END IF;
    IF p_effectivedate > (now() AT TIME ZONE 'utc')::date + 1 THEN
        RAISE EXCEPTION 'The date is in the future.' USING ERRCODE = 'P0001';
    END IF;
    SELECT i.* INTO v_item FROM waterrawmaterialitems i
    WHERE  i.waterrawmaterialitemid = p_itemid AND i.farmid = p_farmid FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'That item does not belong to this company.' USING ERRCODE = 'P0001';
    END IF;
    v_uncovered := public.fnwaterrawmaterial_uncoveredstock(p_farmid, p_itemid);
    IF v_qty > v_uncovered THEN
        RAISE EXCEPTION 'Only % % of "%" is not already covered by a purchase. A manual cost can only cover stock no purchase covers.',
            v_uncovered, COALESCE(v_item.unitofmeasure, ''), v_item.itemname USING ERRCODE = 'P0001';
    END IF;

    INSERT INTO waterrawmaterialpurchases
        (farmid, waterrawmaterialitemid, suppliername, supplierid, purchasedate, quantity, unitcost, totalcost,
         productionunit, productionunitsperpurchaseunit, paymentmethod, amountpaid, notes, createdby, createdat,
         remainingquantity, costrecognitionmethod, deferredtotalcost, deferredremainingcost, lotsource)
    VALUES
        (p_farmid, p_itemid, NULL, NULL, p_effectivedate::timestamp, v_qty, round(v_amt / v_qty, 4), v_amt,
         v_item.unitofmeasure, 1, 'NonCash', v_amt, left('Manual deferred cost: ' || btrim(p_reason), 500),
         p_by, (now() AT TIME ZONE 'utc'),
         v_qty, 'EXPENSE_WHEN_CONSUMED', v_amt, v_amt, 'ManualDeferredCost')
    RETURNING waterrawmaterialpurchaseid INTO v_lot;

    PERFORM pg_advisory_xact_lock(hashtext('water-manualdeferred-no:' || p_farmid));
    SELECT 'MDC-' || lpad((COALESCE(MAX(NULLIF(regexp_replace(m.entrynumber, '\D', '', 'g'), '')::int), 0) + 1)::text, 5, '0')
    INTO   v_number FROM watermanualdeferredcosts m WHERE m.farmid = p_farmid;

    INSERT INTO watermanualdeferredcosts
        (farmid, entrynumber, waterrawmaterialpurchaseid, waterrawmaterialitemid, entrytype, amount, quantity,
         effectivedate, reason, reference, notes, createdby)
    VALUES
        (p_farmid, v_number, v_lot, p_itemid, p_entrytype, v_amt, v_qty, p_effectivedate, btrim(p_reason),
         NULLIF(btrim(COALESCE(p_reference, '')), ''), NULLIF(btrim(COALESCE(p_notes, '')), ''), p_by)
    RETURNING entryid INTO v_id;

    RETURN jsonb_build_object('entryId', v_id, 'entryNumber', v_number, 'lotId', v_lot);
END
$f$;

CREATE OR REPLACE FUNCTION public.spwatermanualdeferredcost_reverse(p_farmid text, p_entryid integer, p_reason text, p_by text DEFAULT NULL)
RETURNS numeric LANGUAGE plpgsql AS $f$
DECLARE v_m record; v_lot record; v_rev numeric(14,2);
BEGIN
    IF NULLIF(btrim(COALESCE(p_reason, '')), '') IS NULL THEN
        RAISE EXCEPTION 'Give a reason for reversing.' USING ERRCODE = 'P0001';
    END IF;
    SELECT m.* INTO v_m FROM watermanualdeferredcosts m WHERE m.entryid = p_entryid AND m.farmid = p_farmid FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'Entry not found for this company.' USING ERRCODE = 'P0001'; END IF;
    IF v_m.status <> 'Posted' THEN RAISE EXCEPTION '% has already been reversed.', v_m.entrynumber USING ERRCODE = 'P0001'; END IF;
    SELECT p.* INTO v_lot FROM waterrawmaterialpurchases p
    WHERE  p.waterrawmaterialpurchaseid = v_m.waterrawmaterialpurchaseid AND p.farmid = p_farmid FOR UPDATE;
    v_rev := v_lot.deferredremainingcost;
    -- Only what is not yet recognised comes off; the stock is real, so its quantity stays.
    UPDATE waterrawmaterialpurchases p
    SET    deferredtotalcost     = GREATEST(p.deferredtotalcost - p.deferredremainingcost, 0),
           deferredremainingcost = 0,
           updatedat             = (now() AT TIME ZONE 'utc')
    WHERE  p.waterrawmaterialpurchaseid = v_lot.waterrawmaterialpurchaseid;
    UPDATE watermanualdeferredcosts m
    SET    status = 'Reversed', reversedby = p_by, reversedat = (now() AT TIME ZONE 'utc'),
           reversalreason = btrim(p_reason), reversedamount = v_rev
    WHERE  m.entryid = p_entryid;
    RETURN v_rev;
END
$f$;

CREATE OR REPLACE FUNCTION public.spwatermanualdeferredcost_list(p_farmid text)
RETURNS TABLE(entryid integer, entrynumber text, waterrawmaterialpurchaseid integer, waterrawmaterialitemid integer,
              itemname text, unitofmeasure text, entrytype text, amount numeric, quantity numeric, effectivedate date,
              recognised numeric, remaining numeric, remainingquantity numeric, reason text, reference text, notes text,
              status text, createdby text, createdat timestamp, reversedby text, reversedat timestamp,
              reversalreason text, reversedamount numeric)
LANGUAGE sql STABLE AS $f$
    SELECT m.entryid, m.entrynumber, m.waterrawmaterialpurchaseid, m.waterrawmaterialitemid,
           i.itemname::text, i.unitofmeasure::text, m.entrytype, m.amount, m.quantity, m.effectivedate,
           GREATEST(p.deferredtotalcost - p.deferredremainingcost, 0)::numeric(14,2),
           p.deferredremainingcost, p.remainingquantity,
           m.reason, m.reference, m.notes, m.status, m.createdby, m.createdat,
           m.reversedby, m.reversedat, m.reversalreason, m.reversedamount
    FROM   watermanualdeferredcosts m
    JOIN   waterrawmaterialpurchases p ON p.waterrawmaterialpurchaseid = m.waterrawmaterialpurchaseid
    LEFT   JOIN waterrawmaterialitems i ON i.waterrawmaterialitemid = m.waterrawmaterialitemid
    WHERE  m.farmid = p_farmid
    ORDER  BY m.effectivedate DESC, m.entryid DESC;
$f$;

-- Items with stock no purchase covers (what a manual cost may be entered for).
CREATE OR REPLACE FUNCTION public.spwaterrawmaterial_uncoveredstock(p_farmid text)
RETURNS TABLE(waterrawmaterialitemid integer, itemname text, unitofmeasure text, currentquantity numeric, uncoveredquantity numeric)
LANGUAGE sql STABLE AS $f$
    SELECT i.waterrawmaterialitemid, i.itemname::text, i.unitofmeasure::text, i.currentquantity,
           public.fnwaterrawmaterial_uncoveredstock(p_farmid, i.waterrawmaterialitemid)
    FROM   waterrawmaterialitems i
    WHERE  i.farmid = p_farmid
      AND  public.fnwaterrawmaterial_uncoveredstock(p_farmid, i.waterrawmaterialitemid) > 0
    ORDER  BY i.itemname;
$f$;

CREATE OR REPLACE FUNCTION public.fnwaterpayables(p_farmid text)
 RETURNS TABLE(documenttype text, documentid integer, supplierid integer, docdate date, label text, reference text, totalcost numeric, amountpaid numeric, balance numeric, cashaccountid integer, duedate date)
 LANGUAGE sql
 STABLE
AS $function$
    SELECT 'RawMaterialPurchase'::text, pu.waterrawmaterialpurchaseid, pu.supplierid,
           pu.purchasedate::date,
           COALESCE(i.itemname, pu.suppliername, 'Raw material')::text,
           ('P' || pu.waterrawmaterialpurchaseid::text)::text,
           pu.totalcost, pu.amountpaid,
           GREATEST(pu.totalcost - pu.amountpaid, 0)::numeric(14,2),
           -- Always NULL: unlike poultryrawmaterialpurchases, the water table
           -- has no cash account column -- WaterRawMaterialPurchaseModel
           -- exposes one, but it is a projection, not storage.
           NULL::integer,
           NULL::date
    FROM   waterrawmaterialpurchases pu
    LEFT   JOIN waterrawmaterialitems i
           ON i.waterrawmaterialitemid = pu.waterrawmaterialitemid
    WHERE  pu.farmid = p_farmid
      AND  COALESCE(pu.lotsource, '') <> 'ManualDeferredCost'   -- 426: nothing is owed on it
    UNION ALL
    SELECT 'Expense'::text, e.waterexpenseid, e.supplierid,
           e.expensedate::date,
           COALESCE(NULLIF(btrim(e.description), ''), c.name, 'Expense')::text,
           ('E' || e.waterexpenseid::text)::text,
           COALESCE(e.amount, 0)::numeric(14,2),
           COALESCE(e.amountpaid,
                    CASE WHEN COALESCE(e.paymentmethod, '') = 'Credit'
                         THEN 0 ELSE e.amount END)::numeric(14,2),
           GREATEST(COALESCE(e.amount, 0)
                    - COALESCE(e.amountpaid,
                               CASE WHEN COALESCE(e.paymentmethod, '') = 'Credit'
                                    THEN 0 ELSE e.amount END), 0)::numeric(14,2),
           e.watercashaccountid,
           e.duedate
    FROM   waterexpenses e
    LEFT   JOIN waterexpensecategories c
           ON c.waterexpensecategoryid = e.waterexpensecategoryid
    WHERE  lower(e.farmid::text) = lower(p_farmid)
      AND  e.supplierid IS NOT NULL
      AND  COALESCE(e.isdeleted, FALSE) = FALSE
      -- 047: only an approved expense has been recognised at all. A Draft is
      -- not yet a debt.
      AND  COALESCE(e.status, '') = 'Approved'
      -- 240: only bills a person typed in are payable; anything with a
      -- sourcetype is another document's shadow. 283 adds the one real
      -- exception -- a capital asset bought on credit is a debt to a supplier,
      -- not the shadow of another document, and neither of these two
      -- sourcetypes is ever generated BY a payment, so the recursion 240 was
      -- guarding against cannot return through here.
      AND  (e.sourcetype IS NULL
            OR e.sourcetype IN ('CapitalAsset', 'CapitalAssetCost'))
    UNION ALL
    -- 424: what the business owes a supplier without a purchase here
    SELECT 'SupplierDebt'::text, d.debtid, d.supplierid, d.debtdate,
           ('Debt ' || d.debtnumber || COALESCE(' - ' || NULLIF(btrim(d.description), ''), ''))::text,
           d.debtnumber::text, d.amount, d.amountpaid,
           GREATEST(d.amount - d.amountpaid, 0)::numeric(14,2),
           NULL::integer, NULL::date
    FROM   watersupplierdebts d
    WHERE  d.farmid = p_farmid AND d.status = 'Posted';
$function$;

CREATE OR REPLACE FUNCTION public.fnwaterdailyclosing_livetotals(p_farmid text, p_closingdate date)
 RETURNS TABLE(bagsproduced numeric, totalproductioncost numeric, bagssold numeric, totalincome numeric, creditsales numeric, customercollections numeric, bagsreturned numeric, bagsdamaged numeric, drivershortagestotal numeric, momobalance numeric, bankbalance numeric, rawmaterialspendtoday numeric, closingstockbags numeric, totalexpenses numeric, cashathand numeric)
 LANGUAGE sql
AS $function$
    WITH
    prod AS (
        SELECT
            COALESCE(SUM((pb.bagsproduced - COALESCE(pb.damagedbags, 0))::numeric(14,3)), 0) AS bagsproduced,
            COALESCE(SUM(pb.totalproductioncost), 0) AS totalproductioncost
        FROM waterproductionbatches pb
        WHERE pb.farmid = p_farmid AND pb.isdeleted = FALSE AND pb.status = 'Approved'
          AND pb.productiondate = p_closingdate
    ),
    sale_items AS (
        SELECT COALESCE(SUM(si.quantity::numeric(14,3)), 0) AS bagssold
        FROM   watersales s
        INNER  JOIN watersaleitems si ON si.watersaleid = s.watersaleid
        WHERE  s.farmid = p_farmid AND s.status NOT IN ('Cancelled')
           AND COALESCE(s.sourcetype, '') <> 'DeliveryRun'
           AND s.saledate >= p_closingdate::timestamp
           AND s.saledate <  p_closingdate::timestamp + interval '1 day'
    ),
    sale_money AS (
        SELECT
            COALESCE(SUM(s2.totalamount), 0) AS totalincome,
            -- 421: what was still OWED at the end of the day (364's rule), not
            -- what is owed now -- a payment made later must not rewrite a past day.
            COALESCE(SUM(public.fnwatersale_owedasof(p_farmid, s2.watersaleid, p_closingdate)), 0) AS creditsales
        FROM   watersales s2
        WHERE  s2.farmid = p_farmid AND s2.status NOT IN ('Cancelled')
           AND COALESCE(s2.sourcetype, '') <> 'DeliveryRun'
           AND s2.saledate >= p_closingdate::timestamp
           AND s2.saledate <  p_closingdate::timestamp + interval '1 day'
    ),
    payments AS (
        SELECT
            COALESCE(SUM(pay.amount), 0) AS customercollections,
            COALESCE(SUM(CASE WHEN pay.paymentmethod IN ('Mobile Money', 'MoMo', 'Momo') THEN pay.amount ELSE 0 END), 0) AS momopayments,
            COALESCE(SUM(CASE WHEN pay.paymentmethod IN ('Bank', 'Bank Transfer', 'Transfer') THEN pay.amount ELSE 0 END), 0) AS bankpayments
        FROM   waterpayments pay
        LEFT   JOIN watersales ps ON ps.watersaleid = pay.watersaleid AND ps.farmid = pay.farmid
        WHERE  pay.farmid = p_farmid
           AND COALESCE(pay.sourcetype, '') <> 'DeliveryRun'
           -- 421: a reversed payment collected nothing.
           AND COALESCE(pay.status, 'Posted') = 'Posted'
           -- 422: a customer advance went straight into its account; opening
           -- credit and credit notes are not money. None of it is in the drawer.
           AND NOT public.fnwater_ismanualcredit(pay.sourcetype)
           -- 421: a payment on a sale made the SAME day is already in that sale's
           -- paid part (income less credit); counting it here too doubled it.
           AND NOT (ps.watersaleid IS NOT NULL
                    AND COALESCE(ps.sourcetype, '') <> 'DeliveryRun'
                    AND ps.saledate >= p_closingdate::timestamp
                    AND ps.saledate <  p_closingdate::timestamp + interval '1 day')
           AND pay.paymentdate >= p_closingdate::timestamp
           AND pay.paymentdate <  p_closingdate::timestamp + interval '1 day'
    ),
    ranked_returns AS (
        SELECT
            dr.waterdriverreturnid, dr.watervehicleloadingid,
            dr.bagsreturned, dr.bagsdamaged, dr.bagssold,
            dr.cashcollected, dr.momocollected, dr.bankcollected, dr.creditsalesamount, dr.shortageamount,
            ROW_NUMBER() OVER (PARTITION BY dr.watervehicleloadingid ORDER BY dr.waterdriverreturnid DESC) AS rn
        FROM   waterdriverreturns dr
        WHERE  dr.farmid = p_farmid AND dr.status = 'Approved'
           AND dr.returndate >= p_closingdate::timestamp
           AND dr.returndate <  p_closingdate::timestamp + interval '1 day'
    ),
    driver_returns AS (
        SELECT
            COALESCE(SUM(rr.bagsreturned::numeric(14,3)), 0) AS bagsreturned,
            COALESCE(SUM(rr.bagsdamaged::numeric(14,3)), 0)  AS bagsdamaged,
            COALESCE(SUM(rr.bagssold::numeric(14,3)), 0)     AS driverbagssold,
            COALESCE(SUM(rr.cashcollected + rr.momocollected + rr.bankcollected + rr.creditsalesamount), 0) AS drivertotalincome,
            COALESCE(SUM(rr.creditsalesamount), 0) AS drivercreditsales,
            COALESCE(SUM(rr.momocollected), 0) AS drivermomo,
            COALESCE(SUM(rr.bankcollected), 0) AS driverbank,
            COALESCE(SUM(rr.shortageamount), 0) AS drivershortages
        FROM   ranked_returns rr
        WHERE  rr.rn = 1
    ),
    raw_spend AS (
        SELECT COALESCE(SUM(rp.amountpaid), 0) AS rawmaterialspendtoday
        FROM   waterrawmaterialpurchases rp
        WHERE  rp.farmid = p_farmid
           AND COALESCE(rp.lotsource, '') <> 'ManualDeferredCost'   -- 426: not money spent today
           AND rp.purchasedate >= p_closingdate::timestamp
           AND rp.purchasedate <  p_closingdate::timestamp + interval '1 day'
    ),
    gen_exp AS (
        SELECT COALESCE(SUM(e.amount), 0) AS generalexpenses
        FROM   waterexpenses e
        WHERE  e.farmid = p_farmid AND e.isdeleted = FALSE AND e.status = 'Approved'
           AND COALESCE(e.sourcetype, '') NOT IN ('RawMaterialPurchase', 'WaterInternalUsage')
           AND e.expensedate >= p_closingdate::timestamp
           AND e.expensedate <  p_closingdate::timestamp + interval '1 day'
    ),
    delivery_exp AS (
        SELECT COALESCE(SUM(de.amount), 0) AS deliveryexpenses
        FROM   waterdeliveryexpenses de
        INNER  JOIN ranked_returns rr2 ON rr2.waterdriverreturnid = de.waterdriverreturnid AND rr2.rn = 1
        WHERE  de.isapproved = TRUE
    ),
    closing_stock AS (
        SELECT COALESCE(SUM(st.quantity::numeric(14,3)), 0) AS closingstockbags
        FROM   waterstocktransactions st WHERE st.farmid = p_farmid
    )
    SELECT
        prod.bagsproduced,
        prod.totalproductioncost,
        sale_items.bagssold + driver_returns.driverbagssold          AS bagssold,
        sale_money.totalincome + driver_returns.drivertotalincome    AS totalincome,
        sale_money.creditsales + driver_returns.drivercreditsales    AS creditsales,
        payments.customercollections,
        driver_returns.bagsreturned,
        driver_returns.bagsdamaged,
        driver_returns.drivershortages                               AS drivershortagestotal,
        driver_returns.drivermomo + payments.momopayments            AS momobalance,
        driver_returns.driverbank + payments.bankpayments            AS bankbalance,
        raw_spend.rawmaterialspendtoday,
        closing_stock.closingstockbags,
        prod.totalproductioncost + raw_spend.rawmaterialspendtoday
            + gen_exp.generalexpenses + delivery_exp.deliveryexpenses AS totalexpenses,
        (sale_money.totalincome + driver_returns.drivertotalincome)
            - (sale_money.creditsales + driver_returns.drivercreditsales)
            + payments.customercollections
            - (prod.totalproductioncost + raw_spend.rawmaterialspendtoday
               + gen_exp.generalexpenses + delivery_exp.deliveryexpenses) AS cashathand
    FROM   prod
    CROSS  JOIN sale_items
    CROSS  JOIN sale_money
    CROSS  JOIN payments
    CROSS  JOIN driver_returns
    CROSS  JOIN raw_spend
    CROSS  JOIN gen_exp
    CROSS  JOIN delivery_exp
    CROSS  JOIN closing_stock
$function$;

CREATE OR REPLACE FUNCTION public.spwaterreport_periodpnl(p_farmid text, p_fromdate date, p_todate date)
 RETURNS TABLE(periodstart date, periodend date, totalincome numeric, totalexpenses numeric, rawmaterialcost numeric, productioncost numeric, totallosses numeric, netprofit numeric, profitmarginpct numeric, bagsproduced integer, bagssold integer, avgprofitperbag numeric)
 LANGUAGE plpgsql
AS $function$
DECLARE
    v_start             timestamp;
    v_end               timestamp;
    v_storefrontincome  numeric;
    v_driverincome      numeric;
    v_totalincome       numeric;
    v_rawmaterialcost   numeric;
    v_productioncost    numeric;
    v_generalexpenses   numeric;
    v_deliveryexpenses  numeric;
    v_operatingexpenses numeric;
    v_productionlosses  numeric;
    v_shortagelosses    numeric;
    v_totallosses       numeric;
    v_netprofit         numeric;
    v_bagsproduced      integer;
    v_storefrontbagssold numeric;
    v_driverbagssold    numeric;
    v_bagssold          integer;
    v_profitmargin      numeric;
    v_avgprofitperbag   numeric;
BEGIN
    v_start := p_fromdate::timestamp;
    v_end   := p_todate::timestamp + make_interval(days => 1);

    -- Storefront sales only (exclude DeliveryRun - that income is on the return).
    v_storefrontincome := COALESCE((
        SELECT SUM(s.totalamount) FROM watersales s
        WHERE s.farmid = p_farmid AND s.status NOT IN ('Cancelled')
          AND COALESCE(s.sourcetype, '') <> 'DeliveryRun'
          AND s.saledate >= v_start AND s.saledate < v_end), 0);

    -- Driver-return income for the day (cash + momo + bank + credit sold).
    v_driverincome := COALESCE((
        SELECT SUM(dr.cashcollected + dr.momocollected + dr.bankcollected + dr.creditsalesamount)
        FROM waterdriverreturns dr
        WHERE dr.farmid = p_farmid AND dr.status IN ('Draft','Approved')
          AND dr.returndate >= v_start AND dr.returndate < v_end), 0);

    -- 422: a credit note is an allowance given -- revenue the business gave up.
    v_totalincome := (v_storefrontincome + v_driverincome
                      - COALESCE((SELECT SUM(cn.amount) FROM waterpayments cn
                                  WHERE cn.farmid = p_farmid AND cn.sourcetype = 'CreditNote'
                                    AND COALESCE(cn.status, 'Posted') = 'Posted'
                                    AND cn.paymentdate >= v_start AND cn.paymentdate < v_end), 0)
                      -- 423 (382): money paid on debts recorded by hand is revenue
                      + (SELECT dc.total FROM public.fnwaterpl_debtcollections(p_farmid, v_start, v_end) dc))::numeric(14,2);

    -- Cash paid for raw materials (matches the closing's AmountPaid basis).
    v_rawmaterialcost := COALESCE((
        SELECT SUM(p.amountpaid) FROM waterrawmaterialpurchases p
        WHERE p.farmid = p_farmid AND p.purchasedate >= v_start AND p.purchasedate < v_end
          -- 426: a manual cost reaches the P&L only as its stock is consumed
          AND COALESCE(p.lotsource, '') <> 'ManualDeferredCost'), 0);

    v_productioncost := COALESCE((
        SELECT SUM(b.totalproductioncost) FROM waterproductionbatches b
        WHERE b.farmid = p_farmid AND b.isdeleted = FALSE AND b.status = 'Approved'
          AND b.productiondate >= p_fromdate AND b.productiondate <= p_todate), 0);

    -- Operating expenses: general approved WaterExpenses (excl. the auto
    -- raw-material-purchase expense, already in RawMaterialCost) + delivery expenses.
    v_generalexpenses := COALESCE((
        SELECT SUM(e.amount) FROM waterexpenses e
        WHERE e.farmid = p_farmid AND e.isdeleted = FALSE AND e.status = 'Approved'
          AND COALESCE(e.sourcetype, '') <> 'RawMaterialPurchase'
          AND e.expensedate >= v_start AND e.expensedate < v_end), 0);

    v_deliveryexpenses := COALESCE((
        SELECT SUM(de.amount) FROM waterdeliveryexpenses de
        INNER JOIN waterdriverreturns dr ON dr.waterdriverreturnid = de.waterdriverreturnid
        WHERE dr.farmid = p_farmid AND dr.status IN ('Draft','Approved') AND de.isapproved = TRUE
          AND dr.returndate >= v_start AND dr.returndate < v_end), 0);

    -- 425 (382): money paid on supplier debts recorded by hand is an operating expense
    v_operatingexpenses := (v_generalexpenses + v_deliveryexpenses
                            + (SELECT x.total FROM public.fnwaterpl_supplierdebtpayments(p_farmid, v_start, v_end) x))::numeric(14,2);

    -- Losses: production losses (damaged/rejected) + driver cash shortages.
    v_productionlosses := COALESCE((
        SELECT SUM(l.totalvalue) FROM waterproductionlosses l
        WHERE l.farmid = p_farmid AND l.lossdate >= v_start AND l.lossdate < v_end), 0);

    v_shortagelosses := COALESCE((
        SELECT SUM(dr.shortageamount) FROM waterdriverreturns dr
        WHERE dr.farmid = p_farmid AND dr.status IN ('Draft','Approved')
          AND dr.returndate >= v_start AND dr.returndate < v_end), 0);

    v_totallosses := (v_productionlosses + v_shortagelosses)::numeric(14,2);

    v_netprofit := (v_totalincome - v_rawmaterialcost - v_productioncost
                    - v_operatingexpenses - v_totallosses)::numeric(14,2);

    v_bagsproduced := COALESCE((
        SELECT SUM(b.bagsproduced - b.damagedbags)::int FROM waterproductionbatches b
        WHERE b.farmid = p_farmid AND b.isdeleted = FALSE AND b.status = 'Approved'
          AND b.productiondate >= p_fromdate AND b.productiondate <= p_todate), 0);

    -- Bags sold = storefront sale items (excl. DeliveryRun) + driver-return bags sold.
    v_storefrontbagssold := COALESCE((
        SELECT SUM(si.quantity) FROM watersales s
        INNER JOIN watersaleitems si ON si.watersaleid = s.watersaleid
        WHERE s.farmid = p_farmid AND s.status NOT IN ('Cancelled')
          AND COALESCE(s.sourcetype, '') <> 'DeliveryRun'
          AND s.saledate >= v_start AND s.saledate < v_end), 0);

    v_driverbagssold := COALESCE((
        SELECT SUM(dr.bagssold) FROM waterdriverreturns dr
        WHERE dr.farmid = p_farmid AND dr.status IN ('Draft','Approved')
          AND dr.returndate >= v_start AND dr.returndate < v_end), 0);

    -- T-SQL CAST(decimal AS INT) truncates toward zero; trunc() keeps that.
    v_bagssold := trunc(v_storefrontbagssold + v_driverbagssold)::int;

    v_profitmargin := (CASE WHEN v_totalincome > 0 THEN (v_netprofit / v_totalincome) * 100 ELSE 0 END)::numeric(8,2);
    v_avgprofitperbag := (CASE WHEN v_bagssold > 0 THEN v_netprofit / v_bagssold ELSE 0 END)::numeric(14,2);

    RETURN QUERY
    SELECT p_fromdate, p_todate,
           v_totalincome,
           v_operatingexpenses,   -- operating only
           v_rawmaterialcost,
           v_productioncost,
           v_totallosses,
           v_netprofit,
           v_profitmargin,
           v_bagsproduced,
           v_bagssold,
           v_avgprofitperbag;
END;
$function$;

CREATE OR REPLACE FUNCTION public.spwaterreport_pllines(p_farmid text, p_startdate date, p_enddate date)
 RETURNS TABLE(section text, linekey text, linelabel text, amount numeric, sortorder integer, isinformational boolean, entrycount integer)
 LANGUAGE sql
 STABLE
AS $function$
    -- periodpnl's own window, copied: half-open on the timestamp columns.
    WITH bounds AS (
        SELECT p_startdate::timestamp                              AS s,
               p_enddate::timestamp + make_interval(days => 1)     AS e
    ),
    -- ---- Revenue -----------------------------------------------------------
    rev AS (
        SELECT 'StorefrontSales'::text AS k, 'Storefront sales'::text AS lbl,
               COALESCE(SUM(s.totalamount), 0) AS amt, COUNT(*)::integer AS n, 1 AS ord
        FROM   watersales s, bounds b
        WHERE  s.farmid = p_farmid AND s.status NOT IN ('Cancelled')
          AND  COALESCE(s.sourcetype, '') <> 'DeliveryRun'
          AND  s.saledate >= b.s AND s.saledate < b.e
        UNION ALL
        -- Collections, not sales. periodpnl takes the driver's money rather than
        -- the DeliveryRun sale rows so the two cannot double-count, and the
        -- drilldown shows the returns for the same reason.
        SELECT 'DeliveryCollections', 'Delivery-run collections',
               COALESCE(SUM(dr.cashcollected + dr.momocollected
                          + dr.bankcollected + dr.creditsalesamount), 0),
               COUNT(*)::integer, 2
        FROM   waterdriverreturns dr, bounds b
        WHERE  dr.farmid = p_farmid AND dr.status IN ('Draft', 'Approved')
          AND  dr.returndate >= b.s AND dr.returndate < b.e
        UNION ALL
        -- 423 (382): money paid on customer debts recorded by hand
        SELECT 'DebtCollections', 'Customer debt collections', dc.total, dc.n, 4
        FROM   bounds b CROSS JOIN LATERAL public.fnwaterpl_debtcollections(p_farmid, b.s, b.e) dc
        UNION ALL
        -- 422: credit notes -- allowances given, negative revenue
        SELECT 'CreditNotes', 'Credit notes & allowances',
               -COALESCE(SUM(cn.amount), 0), COUNT(*)::integer, 3
        FROM   waterpayments cn, bounds b
        WHERE  cn.farmid = p_farmid AND cn.sourcetype = 'CreditNote'
          AND  COALESCE(cn.status, 'Posted') = 'Posted'
          AND  cn.paymentdate >= b.s AND cn.paymentdate < b.e
    ),
    -- ---- Direct cost -------------------------------------------------------
    direct AS (
        SELECT 'RawMaterials'::text AS k, 'Raw materials (paid)'::text AS lbl,
               COALESCE(SUM(p.amountpaid), 0) AS amt, COUNT(*)::integer AS n, 11 AS ord
        FROM   waterrawmaterialpurchases p, bounds b
        WHERE  p.farmid = p_farmid
          AND  COALESCE(p.lotsource, '') <> 'ManualDeferredCost'   -- 426
          AND  p.purchasedate >= b.s AND p.purchasedate < b.e
        UNION ALL
        -- DATE comparison, inclusive both ends. periodpnl's own shape; see header.
        SELECT 'ProductionCost', 'Production cost',
               COALESCE(SUM(pb.totalproductioncost), 0), COUNT(*)::integer, 12
        FROM   waterproductionbatches pb
        WHERE  pb.farmid = p_farmid AND pb.isdeleted = FALSE AND pb.status = 'Approved'
          AND  pb.productiondate >= p_startdate AND pb.productiondate <= p_enddate
    ),
    -- ---- Operating / other cost -------------------------------------------
    -- The general expense pool periodpnl counts, itemised by 282's own P&L line
    -- so the P&L, the Expenses page and Financial Activity agree on the wording.
    exp AS (
        SELECT fnwaterexpense_plsection(l.line) AS sec,
               l.line                           AS k,
               fnwaterexpense_pllinelabel(l.line) AS lbl,
               COALESCE(SUM(e.amount), 0)       AS amt,
               COUNT(*)::integer                AS n
        FROM   waterexpenses e
        INNER  JOIN waterexpensecategories ec ON ec.waterexpensecategoryid = e.waterexpensecategoryid,
               bounds b
        -- Same four arguments fnwaterexpenserows passes, including the category
        -- NAME and the item category. Anything less and a legacy row lands on a
        -- different line here than it does on the Expenses page.
        CROSS  JOIN LATERAL (SELECT fnwaterexpense_costtype(
                                        e.financialcosttype::text, e.sourcetype::text,
                                        ec.name::text, e.paymentmethod::text) AS ct) c
        CROSS  JOIN LATERAL (SELECT fnwaterexpense_plline(
                                        c.ct, e.sourcetype::text, ec.name::text,
                                        fnwaterexpense_itemcategory(e.sourcetype::text, e.sourceid)) AS line) l
        WHERE  e.farmid = p_farmid
          AND  COALESCE(e.isdeleted, FALSE) = FALSE AND e.status = 'Approved'
          AND  COALESCE(e.sourcetype, '') <> 'RawMaterialPurchase'
          AND  e.expensedate >= b.s AND e.expensedate < b.e
        GROUP  BY 1, 2, 3
    ),
    deliv AS (
        SELECT 'DeliveryExpenses'::text AS k, 'Delivery expenses'::text AS lbl,
               COALESCE(SUM(de.amount), 0) AS amt, COUNT(*)::integer AS n
        FROM   waterdeliveryexpenses de
        JOIN   waterdriverreturns dr ON dr.waterdriverreturnid = de.waterdriverreturnid, bounds b
        WHERE  dr.farmid = p_farmid AND dr.status IN ('Draft', 'Approved')
          AND  de.isapproved = TRUE
          AND  dr.returndate >= b.s AND dr.returndate < b.e
    ),
    -- ---- Losses ------------------------------------------------------------
    loss AS (
        SELECT 'ProductionLosses'::text AS k, 'Production losses'::text AS lbl,
               COALESCE(SUM(pl.totalvalue), 0) AS amt, COUNT(*)::integer AS n, 61 AS ord
        FROM   waterproductionlosses pl, bounds b
        WHERE  pl.farmid = p_farmid
          AND  pl.lossdate >= b.s AND pl.lossdate < b.e
        UNION ALL
        SELECT 'DriverShortages', 'Driver cash shortages',
               COALESCE(SUM(dr.shortageamount), 0), COUNT(*) FILTER (WHERE dr.shortageamount <> 0)::integer, 62
        FROM   waterdriverreturns dr, bounds b
        WHERE  dr.farmid = p_farmid AND dr.status IN ('Draft', 'Approved')
          AND  dr.returndate >= b.s AND dr.returndate < b.e
    ),
    -- ---- Informational: cash moved, profit did not -------------------------
    fin AS (
        SELECT 'OwnerContributions'::text AS k, 'Owner Contributions'::text AS lbl,
               COALESCE(SUM(o.amount), 0) AS amt, COUNT(*)::integer AS n, 71 AS ord
        FROM   waterownermoney o, bounds b
        WHERE  o.farmid = p_farmid AND o.status = 'Posted'
          AND  o.transactiontype = 'Contribution'
          AND  o.transactiondate >= b.s AND o.transactiondate < b.e
        UNION ALL
        SELECT 'OwnerDraws', 'Owner Draws', COALESCE(SUM(o.amount), 0), COUNT(*)::integer, 72
        FROM   waterownermoney o, bounds b
        WHERE  o.farmid = p_farmid AND o.status = 'Posted'
          AND  o.transactiontype = 'Draw'
          AND  o.transactiondate >= b.s AND o.transactiondate < b.e
        UNION ALL
        SELECT 'LoansReceived', 'Loans Received', COALESCE(SUM(l.amountreceived), 0), COUNT(*)::integer, 73
        FROM   waterloans l, bounds b
        WHERE  l.farmid = p_farmid AND l.status NOT IN ('Reversed', 'Cancelled', 'Draft')
          AND  l.loandate >= b.s AND l.loandate < b.e
        UNION ALL
        SELECT 'LoanPrincipalRepaid', 'Loan Principal Repaid',
               COALESCE(SUM(pm.principalamount), 0), COUNT(*)::integer, 74
        FROM   waterloanpayments pm, bounds b
        WHERE  pm.farmid = p_farmid AND pm.status = 'Posted'
          AND  pm.paymentdate >= b.s AND pm.paymentdate < b.e
    ),
    cap AS (
        SELECT COALESCE(cat.categoryname, 'Other Assets')::text AS k,
               COALESCE(SUM(cc.amount), 0) AS amt, COUNT(*)::integer AS n
        FROM   watercapitalassetcosts cc
        JOIN   watercapitalassets a ON a.watercapitalassetid = cc.watercapitalassetid
        LEFT   JOIN waterassetcategories cat ON cat.waterassetcategoryid = a.waterassetcategoryid
        WHERE  cc.farmid = p_farmid AND cc.status = 'Posted'
          AND  cc.costdate >= p_startdate AND cc.costdate <= p_enddate
        GROUP  BY COALESCE(cat.categoryname, 'Other Assets')
    )
    SELECT 'Revenue', rev.k, rev.lbl, rev.amt::numeric(14,2), rev.ord, FALSE, rev.n
    FROM   rev WHERE rev.amt <> 0 OR rev.n > 0
    UNION ALL
    SELECT 'DirectCost', direct.k, direct.lbl, direct.amt::numeric(14,2), direct.ord, FALSE, direct.n
    FROM   direct WHERE direct.amt <> 0 OR direct.n > 0
    UNION ALL
    -- 282's own section decides which band an expense line sits in, so a
    -- depreciation or loan-interest row drops below Operating Profit rather
    -- than inflating it. Both bands together still equal periodpnl's
    -- totalexpenses, which is what keeps the statement reconciled.
    SELECT exp.sec, exp.k, exp.lbl, exp.amt::numeric(14,2),
           CASE exp.sec WHEN 'OperatingExpense' THEN 30 ELSE 50 END
             + CASE exp.k WHEN 'Payroll' THEN 1 WHEN 'Utilities' THEN 2
                          WHEN 'Transport' THEN 3 WHEN 'RepairsMaintenance' THEN 4
                          WHEN 'Depreciation' THEN 1 WHEN 'LoanInterest' THEN 2
                          WHEN 'LoanFees' THEN 3 ELSE 9 END,
           FALSE, exp.n
    FROM   exp WHERE exp.amt <> 0
    UNION ALL
    SELECT 'OperatingExpense', deliv.k, deliv.lbl, deliv.amt::numeric(14,2), 40, FALSE, deliv.n
    FROM   deliv WHERE deliv.amt <> 0 OR deliv.n > 0
    UNION ALL
    -- 425 (382): money paid on supplier debts recorded by hand
    SELECT 'OperatingExpense', 'SupplierDebtPayments', 'Supplier debt payments', x.total, 41, FALSE, x.n
    FROM   bounds b CROSS JOIN LATERAL public.fnwaterpl_supplierdebtpayments(p_farmid, b.s, b.e) x
    WHERE  x.total <> 0
    UNION ALL
    SELECT 'Loss', loss.k, loss.lbl, loss.amt::numeric(14,2), loss.ord, FALSE, loss.n
    FROM   loss WHERE loss.amt <> 0
    UNION ALL
    SELECT 'Financing', fin.k, fin.lbl, fin.amt::numeric(14,2), fin.ord, TRUE, fin.n
    FROM   fin WHERE fin.amt <> 0
    UNION ALL
    SELECT 'CapitalInvestment', cap.k, cap.k, cap.amt::numeric(14,2), 81, TRUE, cap.n
    FROM   cap WHERE cap.amt <> 0
    ORDER  BY 5, 2;
$function$;

CREATE OR REPLACE FUNCTION public.spwaterreport_pldirectcostdetail(p_farmid text, p_startdate date, p_enddate date, p_linekey text DEFAULT NULL::text)
 RETURNS TABLE(entrydate timestamp without time zone, reference text, party text, detail text, amount numeric)
 LANGUAGE sql
 STABLE
AS $function$
    -- amountpaid, not totalcost: periodpnl counts raw materials on a CASH basis
    -- and a drilldown that showed the invoice value would not add up to its line.
    SELECT p.purchasedate, ('Purchase #' || p.waterrawmaterialpurchaseid)::text,
           COALESCE(NULLIF(btrim(p.suppliername), ''), 'Supplier')::text,
           COALESCE(i.itemname, 'Raw material')::text,
           COALESCE(p.amountpaid, 0)::numeric(14,2)
    FROM   waterrawmaterialpurchases p
    LEFT   JOIN waterrawmaterialitems i ON i.waterrawmaterialitemid = p.waterrawmaterialitemid
    WHERE  p.farmid = p_farmid
      AND  COALESCE(p.lotsource, '') <> 'ManualDeferredCost'   -- 426
      AND  p.purchasedate >= p_startdate::timestamp
      AND  p.purchasedate <  p_enddate::timestamp + make_interval(days => 1)
      AND  (p_linekey IS NULL OR p_linekey = 'RawMaterials')
    UNION ALL
    SELECT pb.productiondate::timestamp, COALESCE(NULLIF(btrim(pb.batchnumber), ''),
           'Batch #' || pb.waterproductionbatchid)::text,
           'Production'::text,
           (pb.bagsproduced::text || ' bag(s)')::text,
           COALESCE(pb.totalproductioncost, 0)::numeric(14,2)
    FROM   waterproductionbatches pb
    WHERE  pb.farmid = p_farmid AND pb.isdeleted = FALSE AND pb.status = 'Approved'
      AND  pb.productiondate >= p_startdate AND pb.productiondate <= p_enddate
      AND  (p_linekey IS NULL OR p_linekey = 'ProductionCost')
    ORDER  BY 1 DESC, 2;
$function$;

CREATE OR REPLACE FUNCTION public.spwaterrawmaterialitem_recalculatestock(p_farmid text, p_waterrawmaterialitemid integer DEFAULT NULL::integer)
 RETURNS TABLE(waterrawmaterialitemid integer, itemname text, category text, unitofmeasure text, oldquantity numeric, newquantity numeric, delta numeric)
 LANGUAGE plpgsql
AS $function$
BEGIN
    RETURN QUERY
    WITH expected AS (
        SELECT i.waterrawmaterialitemid AS itemid,
               i.currentquantity        AS oldqty,
               (
                   COALESCE((SELECT SUM(p.quantity * COALESCE(NULLIF(p.productionunitsperpurchaseunit, 0), 1))
                             FROM   waterrawmaterialpurchases p
                             WHERE  p.waterrawmaterialitemid = i.waterrawmaterialitemid
                               AND  p.farmid = i.farmid
                               -- 426: a manual cost covers stock already counted; it adds none
                               AND  COALESCE(p.lotsource, '') <> 'ManualDeferredCost'), 0)
                 - COALESCE((SELECT SUM(u.quantityused)
                             FROM   waterrawmaterialusage u
                             WHERE  u.waterrawmaterialitemid = i.waterrawmaterialitemid
                               AND  u.farmid = i.farmid
                               AND  u.isreversed = FALSE), 0)
                 + COALESCE((SELECT SUM(a.quantity)
                             FROM   waterrawmaterialadjustments a
                             WHERE  a.waterrawmaterialitemid = i.waterrawmaterialitemid
                               AND  a.farmid = i.farmid), 0)
               )::numeric(14,3) AS rawexpected
        FROM   waterrawmaterialitems i
        WHERE  i.farmid = p_farmid
          AND  (p_waterrawmaterialitemid IS NULL OR i.waterrawmaterialitemid = p_waterrawmaterialitemid)
    ),
    calc AS (
        SELECT e.itemid,
               e.oldqty,
               CASE WHEN e.rawexpected < 0 THEN 0::numeric(14,3) ELSE e.rawexpected END AS newqty
        FROM   expected e
    ),
    upd AS (
        UPDATE waterrawmaterialitems i2
        SET    currentquantity = c.newqty,
               updatedat       = (now() at time zone 'utc')
        FROM   calc c
        WHERE  c.itemid = i2.waterrawmaterialitemid
          AND  i2.farmid = p_farmid
          AND  i2.currentquantity <> c.newqty
        RETURNING i2.waterrawmaterialitemid AS updatedid
    )
    SELECT c.itemid,
           i.itemname::text,
           i.category::text,
           i.unitofmeasure::text,
           c.oldqty,
           c.newqty,
           (c.newqty - c.oldqty)::numeric(14,3)
    FROM   calc c
    INNER  JOIN waterrawmaterialitems i ON i.waterrawmaterialitemid = c.itemid
    ORDER  BY i.itemname;
END;
$function$;

CREATE OR REPLACE FUNCTION public.spwaterrawmaterialpurchase_getall(p_farmid text, p_fromdate date DEFAULT NULL::date, p_todate date DEFAULT NULL::date)
 RETURNS TABLE(waterrawmaterialpurchaseid integer, farmid text, waterrawmaterialitemid integer, suppliername text, purchasedate timestamp without time zone, quantity numeric, unitcost numeric, paymentmethod text, amountpaid numeric, receipturl text, receivedbystaffid integer, notes text, createdby text, createdat timestamp without time zone, updatedat timestamp without time zone, linkedwaterexpenseid integer, supplierid integer, totalcost numeric, productionunit text, productionunitsperpurchaseunit numeric, remainingquantity numeric, itemname text, category text, unitofmeasure text, balance numeric, productionquantity numeric, productionunitcost numeric)
 LANGUAGE plpgsql
AS $function$
BEGIN
    RETURN QUERY
    SELECT p.waterrawmaterialpurchaseid,
           p.farmid::text,
           p.waterrawmaterialitemid,
           p.suppliername::text,
           p.purchasedate,
           p.quantity,
           p.unitcost,
           p.paymentmethod::text,
           p.amountpaid,
           p.receipturl::text,
           p.receivedbystaffid,
           p.notes::text,
           p.createdby::text,
           p.createdat,
           p.updatedat,
           p.linkedwaterexpenseid,
           p.supplierid,
           p.totalcost,
           p.productionunit::text,
           p.productionunitsperpurchaseunit,
           p.remainingquantity,
           i.itemname::text,
           i.category::text,
           i.unitofmeasure::text,
           (p.totalcost - p.amountpaid)::numeric(14,2),
           (p.quantity * COALESCE(p.productionunitsperpurchaseunit, 1))::numeric(18,3),
           (CASE WHEN COALESCE(p.productionunitsperpurchaseunit, 0) > 0
                 THEN p.totalcost / NULLIF(p.quantity * p.productionunitsperpurchaseunit, 0)
                 ELSE NULL END)::numeric(18,4)
    FROM   waterrawmaterialpurchases p
    INNER  JOIN waterrawmaterialitems i ON i.waterrawmaterialitemid = p.waterrawmaterialitemid
    WHERE  p.farmid = p_farmid
      AND  COALESCE(p.lotsource, '') <> 'ManualDeferredCost'   -- 426: shown on Deferred costs, not as a purchase
      AND  (p_fromdate IS NULL OR p.purchasedate::date >= p_fromdate)
      AND  (p_todate   IS NULL OR p.purchasedate::date <= p_todate)
    ORDER  BY p.purchasedate DESC, p.waterrawmaterialpurchaseid DESC;
END;
$function$;

CREATE OR REPLACE FUNCTION public.fnwaterbalanceaudit(p_farmid text)
 RETURNS TABLE(side text, documenttype text, documentid integer, amountpaid numeric, allocated numeric, difference numeric)
 LANGUAGE sql
 STABLE
AS $function$
    SELECT 'customer'::text, 'WaterSale'::text, s.watersaleid,
           s.amountpaid,
           COALESCE(a.allocated, 0)::numeric(14,2),
           (s.amountpaid - COALESCE(a.allocated, 0))::numeric(14,2)
    FROM   watersales s
    LEFT   JOIN LATERAL (
               SELECT SUM(ca.amountapplied) AS allocated
               FROM   customerpaymentallocation ca
               WHERE  ca.farmid = s.farmid AND ca.module = 'water'
                 AND  ca.saleid = s.watersaleid AND ca.status = 'Posted'
           ) a ON TRUE
    WHERE  s.farmid = p_farmid
      AND  (s.amountpaid - COALESCE(a.allocated, 0)) <> 0
    UNION ALL
    SELECT 'supplier'::text, 'RawMaterialPurchase'::text, pu.waterrawmaterialpurchaseid,
           pu.amountpaid,
           COALESCE(a.allocated, 0)::numeric(14,2),
           (pu.amountpaid - COALESCE(a.allocated, 0))::numeric(14,2)
    FROM   waterrawmaterialpurchases pu
    LEFT   JOIN LATERAL (
               SELECT SUM(sa.amountapplied) AS allocated
               FROM   supplierpaymentallocation sa
               WHERE  sa.farmid = pu.farmid AND sa.module = 'water'
                 AND  sa.documenttype = 'RawMaterialPurchase'
                 AND  sa.documentid = pu.waterrawmaterialpurchaseid
                 AND  sa.status = 'Posted'
           ) a ON TRUE
    WHERE  pu.farmid = p_farmid
      AND  COALESCE(pu.lotsource, '') <> 'ManualDeferredCost'   -- 426
      AND  (pu.amountpaid - COALESCE(a.allocated, 0)) <> 0
    UNION ALL
    SELECT 'supplier'::text, 'Expense'::text, e.waterexpenseid,
           COALESCE(e.amountpaid,
                    CASE WHEN COALESCE(e.paymentmethod, '') = 'Credit'
                         THEN 0 ELSE e.amount END)::numeric(14,2),
           COALESCE(a.allocated, 0)::numeric(14,2),
           (COALESCE(e.amountpaid,
                     CASE WHEN COALESCE(e.paymentmethod, '') = 'Credit'
                          THEN 0 ELSE e.amount END) - COALESCE(a.allocated, 0))::numeric(14,2)
    FROM   waterexpenses e
    LEFT   JOIN LATERAL (
               SELECT SUM(sa.amountapplied) AS allocated
               FROM   supplierpaymentallocation sa
               WHERE  sa.farmid = e.farmid AND sa.module = 'water'
                 AND  sa.documenttype = 'Expense'
                 AND  sa.documentid = e.waterexpenseid
                 AND  sa.status = 'Posted'
           ) a ON TRUE
    WHERE  lower(e.farmid::text) = lower(p_farmid)
      AND  COALESCE(a.allocated, 0) > COALESCE(e.amountpaid,
               CASE WHEN COALESCE(e.paymentmethod, '') = 'Credit' THEN 0 ELSE e.amount END);
$function$;

CREATE OR REPLACE FUNCTION public.spwaterrawmaterialpurchase_update(p_waterrawmaterialpurchaseid integer, p_farmid text, p_suppliername text DEFAULT NULL::text, p_purchasedate timestamp without time zone DEFAULT NULL::timestamp without time zone, p_quantity numeric DEFAULT NULL::numeric, p_unitcost numeric DEFAULT NULL::numeric, p_paymentmethod text DEFAULT NULL::text, p_amountpaid numeric DEFAULT 0, p_receipturl text DEFAULT NULL::text, p_notes text DEFAULT NULL::text, p_supplierid integer DEFAULT NULL::integer, p_totalcost numeric DEFAULT NULL::numeric, p_watercashaccountid integer DEFAULT NULL::integer, p_productionunit text DEFAULT NULL::text, p_productionunitsperpurchaseunit numeric DEFAULT NULL::numeric)
 RETURNS void
 LANGUAGE plpgsql
AS $function$
DECLARE
    v_totalcost       numeric := p_totalcost;
    v_suppliername    text    := p_suppliername;
    v_oldqty          numeric;
    v_itemid          integer;
    v_linkedexpenseid integer;
    v_oldmult         numeric;
    v_newmult         numeric;
    v_delta           numeric;
    v_currentstock    numeric;
    v_msg1            text;
    v_updcashaccountid integer := NULL;
BEGIN
    -- 426: a manual cost is not a purchase -- reverse it on Deferred costs.
    IF EXISTS (SELECT 1 FROM waterrawmaterialpurchases g WHERE g.waterrawmaterialpurchaseid = p_waterrawmaterialpurchaseid
               AND g.farmid = p_farmid AND g.lotsource = 'ManualDeferredCost') THEN
        RAISE EXCEPTION 'This is a manual deferred cost, not a purchase. Reverse it on Deferred costs.' USING ERRCODE = 'P0001';
    END IF;
    -- A lot that an approved production batch has already drawn from can't be
    -- re-quantified underneath it - the draw records and remaining balances
    -- would stop agreeing. Reopen that batch first.
    IF EXISTS (SELECT 1 FROM waterrawmaterialusagebatch ub
               WHERE ub.waterrawmaterialpurchaseid = p_waterrawmaterialpurchaseid) THEN
        RAISE EXCEPTION 'This purchase batch has already been drawn from by an approved production batch. Reopen that batch first.';
    END IF;

    IF (p_quantity <= 0) THEN
        RAISE EXCEPTION 'Quantity must be > 0.';
    END IF;
    IF (p_unitcost < 0) THEN
        RAISE EXCEPTION 'UnitCost cannot be negative.';
    END IF;

    IF (v_totalcost IS NULL OR v_totalcost <= 0) THEN
        v_totalcost := p_quantity::numeric(14,2) * p_unitcost;
    END IF;

    SELECT p.quantity, p.waterrawmaterialitemid, p.linkedwaterexpenseid,
           COALESCE(NULLIF(p.productionunitsperpurchaseunit, 0), 1)
      INTO v_oldqty, v_itemid, v_linkedexpenseid, v_oldmult
    FROM waterrawmaterialpurchases p
    WHERE p.waterrawmaterialpurchaseid = p_waterrawmaterialpurchaseid AND p.farmid = p_farmid;

    IF v_oldqty IS NULL THEN
        RAISE EXCEPTION 'Purchase % not found.', p_waterrawmaterialpurchaseid;
    END IF;

    -- Stock delta measured in PRODUCTION units (new prod qty - old prod qty).
    v_newmult := COALESCE(NULLIF(p_productionunitsperpurchaseunit, 0), 1);
    v_delta   := ((p_quantity * v_newmult) - (v_oldqty * v_oldmult))::numeric(18,4);

    IF (v_delta < 0) THEN
        SELECT mi.currentquantity::numeric(18,4) INTO v_currentstock
        FROM waterrawmaterialitems mi
        WHERE mi.waterrawmaterialitemid = v_itemid AND mi.farmid = p_farmid;

        IF (v_currentstock + v_delta < 0) THEN
            v_msg1 := 'Cannot reduce quantity: only ' || v_currentstock::text
                      || ' production units of this item remain in stock. Reverse usages first.';
            RAISE EXCEPTION '%', v_msg1;
        END IF;
    END IF;

    IF (p_supplierid IS NOT NULL AND (v_suppliername IS NULL OR v_suppliername = '')) THEN
        SELECT s.suppliername::text INTO v_suppliername FROM watersuppliers s
        WHERE s.watersupplierid = p_supplierid AND s.farmid = p_farmid;
    END IF;

    IF (p_watercashaccountid IS NOT NULL AND p_paymentmethod <> 'Credit') THEN
        SELECT ca.watercashaccountid INTO v_updcashaccountid FROM watercashaccounts ca
        WHERE ca.watercashaccountid = p_watercashaccountid AND ca.farmid = p_farmid AND ca.isactive = TRUE;
    END IF;

    UPDATE waterrawmaterialpurchases p
    SET suppliername  = v_suppliername,
        supplierid    = p_supplierid,
        purchasedate  = COALESCE(p_purchasedate, p.purchasedate),
        quantity      = p_quantity,
        unitcost      = p_unitcost,
        totalcost     = v_totalcost,
        paymentmethod = p_paymentmethod,
        amountpaid    = p_amountpaid,
        receipturl    = p_receipturl,
        notes         = p_notes,
        productionunit = p_productionunit,
        productionunitsperpurchaseunit = p_productionunitsperpurchaseunit,
        updatedat     = (now() at time zone 'utc'),
        remainingquantity = p_quantity,
        -- 278. The deferred balance follows the cost. Safe to rewrite outright
        -- rather than rescale, because the guard at the top of this function has
        -- already refused any lot that has been drawn from: nothing downstream
        -- can have recognised part of this balance yet, so there is no reported
        -- expense to contradict.
        --
        -- Keyed on the lot's OWN snapshot, never on today's setting. A company
        -- that switched deferral off last week must not have last month's
        -- deferred purchase silently zeroed by an unrelated edit to its notes.
        deferredtotalcost     = CASE WHEN fnwatercostrecognition_expenseatconsumption(p.costrecognitionmethod)
                                     THEN v_totalcost ELSE 0 END,
        deferredremainingcost = CASE WHEN fnwatercostrecognition_expenseatconsumption(p.costrecognitionmethod)
                                     THEN v_totalcost ELSE 0 END
    WHERE p.waterrawmaterialpurchaseid = p_waterrawmaterialpurchaseid AND p.farmid = p_farmid;

    IF (v_delta <> 0) THEN
        UPDATE waterrawmaterialitems mi
        SET currentquantity = mi.currentquantity + v_delta,   -- production-level delta
            updatedat = (now() at time zone 'utc')
        WHERE mi.waterrawmaterialitemid = v_itemid AND mi.farmid = p_farmid;
    END IF;

    IF (v_linkedexpenseid IS NOT NULL) THEN
        UPDATE waterexpenses e
        SET amount     = p_amountpaid,
            paidto     = v_suppliername,
            supplierid = p_supplierid,
            expensedate = COALESCE(p_purchasedate, e.expensedate),
            watercashaccountid = CASE WHEN p_watercashaccountid IS NOT NULL THEN v_updcashaccountid ELSE e.watercashaccountid END,
            updatedat  = (now() at time zone 'utc')
        WHERE e.waterexpenseid = v_linkedexpenseid AND e.farmid = p_farmid
          AND e.isdeleted = FALSE AND e.status IN ('Draft','Submitted','Approved');
    END IF;
END;
$function$;

CREATE OR REPLACE FUNCTION public.spwaterrawmaterialpurchase_delete(p_waterrawmaterialpurchaseid integer, p_farmid text)
 RETURNS void
 LANGUAGE plpgsql
AS $function$
DECLARE
    v_qty             numeric;
    v_itemid          integer;
    v_linkedexpenseid integer;
    v_mult            numeric;
    v_prodqty         numeric;
    v_currentstock    numeric;
    v_msg2            text;
BEGIN
    -- 426: a manual cost is not a purchase -- reverse it on Deferred costs.
    IF EXISTS (SELECT 1 FROM waterrawmaterialpurchases g WHERE g.waterrawmaterialpurchaseid = p_waterrawmaterialpurchaseid
               AND g.farmid = p_farmid AND g.lotsource = 'ManualDeferredCost') THEN
        RAISE EXCEPTION 'This is a manual deferred cost, not a purchase. Reverse it on Deferred costs.' USING ERRCODE = 'P0001';
    END IF;
    -- Deleting a drawn lot would strand its WaterRawMaterialUsageBatch rows
    -- against a purchase that no longer exists.
    IF EXISTS (SELECT 1 FROM waterrawmaterialusagebatch ub
               WHERE ub.waterrawmaterialpurchaseid = p_waterrawmaterialpurchaseid) THEN
        RAISE EXCEPTION 'This purchase batch has already been drawn from by an approved production batch. Reopen that batch first.';
    END IF;

    SELECT p.quantity, p.waterrawmaterialitemid, p.linkedwaterexpenseid,
           COALESCE(NULLIF(p.productionunitsperpurchaseunit, 0), 1)
      INTO v_qty, v_itemid, v_linkedexpenseid, v_mult
    FROM waterrawmaterialpurchases p
    WHERE p.waterrawmaterialpurchaseid = p_waterrawmaterialpurchaseid AND p.farmid = p_farmid;

    IF v_qty IS NULL THEN
        RAISE EXCEPTION 'Purchase % not found.', p_waterrawmaterialpurchaseid;
    END IF;

    v_prodqty := (v_qty * v_mult)::numeric(18,4);
    SELECT mi.currentquantity::numeric(18,4) INTO v_currentstock
    FROM waterrawmaterialitems mi
    WHERE mi.waterrawmaterialitemid = v_itemid AND mi.farmid = p_farmid;

    IF (v_currentstock < v_prodqty) THEN
        v_msg2 := 'Cannot delete: only ' || v_currentstock::text
                  || ' production units remain in stock but this purchase added '
                  || v_prodqty::text
                  || '. Reverse usages first.';
        RAISE EXCEPTION '%', v_msg2;
    END IF;

    IF v_linkedexpenseid IS NOT NULL THEN
        PERFORM spwaterrawmaterialpurchase_cancellinkedexpense(
            p_waterrawmaterialpurchaseid => p_waterrawmaterialpurchaseid,
            p_farmid                     => p_farmid,
            p_cancelledby                => NULL);
    END IF;

    UPDATE waterrawmaterialitems mi
    SET currentquantity = mi.currentquantity - v_prodqty,   -- production-level qty
        updatedat       = (now() at time zone 'utc')
    WHERE mi.waterrawmaterialitemid = v_itemid AND mi.farmid = p_farmid;

    DELETE FROM waterrawmaterialpurchases p
    WHERE p.waterrawmaterialpurchaseid = p_waterrawmaterialpurchaseid AND p.farmid = p_farmid;
END;
$function$;

CREATE OR REPLACE FUNCTION public.spwaterrawmaterialpurchase_paybalance(p_waterrawmaterialpurchaseid integer, p_farmid text, p_amount numeric, p_paymentmethod text DEFAULT NULL::text, p_paymentdate timestamp without time zone DEFAULT NULL::timestamp without time zone, p_createdby text DEFAULT NULL::text)
 RETURNS TABLE(balance numeric)
 LANGUAGE plpgsql
AS $function$
DECLARE
    v_doc    record;
    v_amount numeric(14,2);
BEGIN
    -- 426: a manual cost is not a purchase -- reverse it on Deferred costs.
    IF EXISTS (SELECT 1 FROM waterrawmaterialpurchases g WHERE g.waterrawmaterialpurchaseid = p_waterrawmaterialpurchaseid
               AND g.farmid = p_farmid AND g.lotsource = 'ManualDeferredCost') THEN
        RAISE EXCEPTION 'This is a manual deferred cost, not a purchase. Reverse it on Deferred costs.' USING ERRCODE = 'P0001';
    END IF;
    SELECT d.documentid, d.supplierid, d.balance, d.cashaccountid
    INTO   v_doc
    FROM   fnwaterpayables(p_farmid) d
    WHERE  d.documenttype = 'RawMaterialPurchase'
      AND  d.documentid = p_waterrawmaterialpurchaseid;

    IF v_doc.documentid IS NULL THEN
        RAISE EXCEPTION 'Purchase not found for this company.';
    END IF;
    IF v_doc.balance <= 0 THEN
        RAISE EXCEPTION 'This purchase has no outstanding balance.';
    END IF;
    IF p_amount IS NULL OR p_amount <= 0 THEN
        RAISE EXCEPTION 'Payment amount must be greater than 0.';
    END IF;

    -- Never overpay -- 091 clamped rather than erroring, and the Purchases page
    -- relies on that when the user types the full total on a part-paid row.
    v_amount := LEAST(p_amount, v_doc.balance)::numeric(14,2);

    PERFORM spwatersupplierpayment_record(
        p_farmid        => p_farmid,
        p_supplierid    => v_doc.supplierid,
        p_amount        => v_amount,
        p_allocations   => jsonb_build_array(jsonb_build_object(
                               'documenttype', 'RawMaterialPurchase',
                               'documentid',   p_waterrawmaterialpurchaseid,
                               'amount',       v_amount)),
        p_paymentmethod => p_paymentmethod,
        p_paymentdate   => p_paymentdate,
        p_cashaccountid => v_doc.cashaccountid,
        p_reference     => NULL,
        p_note          => NULL,
        p_sourcetype    => 'PurchaseEntry',
        p_createdby     => p_createdby);

    RETURN QUERY
    SELECT GREATEST(pu.totalcost - pu.amountpaid, 0)::numeric(14,2)
    FROM   waterrawmaterialpurchases pu
    WHERE  pu.waterrawmaterialpurchaseid = p_waterrawmaterialpurchaseid
      AND  pu.farmid = p_farmid;
END;
$function$;

