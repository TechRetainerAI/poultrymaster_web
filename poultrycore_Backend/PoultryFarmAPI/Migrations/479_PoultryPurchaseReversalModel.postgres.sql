-- =============================================================================
-- 479  Poultry: purchase reversal on the sale reversal model
-- =============================================================================
--
-- 418 gave Poultry a "Reverse purchase" (free-text reason; supplier payments
-- that paid only this purchase reversed, money back; a payment that also paid
-- other things BLOCKED the reversal). This brings it to the sale reversal
-- model (351/354), as 478 did for Water:
--
--   * a numbered reversal record (poultrypurchasereversals, PPR-00001) with a
--     snapshot, the purchase stamped with purchasereversalid;
--   * reason code from the list, "Other" needs a note;
--   * a server-side preview (sppoultrypurchase_reversalpreview) with blockers,
--     money lines and a fingerprint; stale preview refused (HINT
--     'stale-preview'); idempotency key;
--   * per money line the user chooses:
--       Refund        the supplier gave it back. A supplier payment that paid
--                     only this purchase is reversed (376: its CashOut stays,
--                     a reversal CashIn today); money paid before supplier
--                     payments existed comes back as 418's CashIn.
--       KeepAsCredit  the supplier keeps it. The payment's allocation to this
--                     purchase is released (Reversed), so that part of the
--                     payment is unapplied = supplier credit, exactly as a
--                     poultry sale's KeepAsCredit releases the customer
--                     allocation (351). Cash does not move: a poultry supplier
--                     payment's cash is its whole amount whatever it paid, and
--                     Cash Flow arm 3e shows the unapplied part on its day.
--     A payment that also paid other things can only be kept as credit (it
--     used to block the reversal).
--
-- Unchanged from 418: supplier credit applied to the purchase goes back to the
-- supplier, the purchase's expense rows are removed, stock comes back out with
-- a 'PurchaseReversal' adjustment, the lot is emptied and the row kept. All of
-- 418's other blockers stand (used stock, feed production, receipt lots,
-- manual costs, stock short).
--
-- The old 4-argument sppoultryrawmaterialpurchase_reverse stays for old
-- clients: it reverses with every line refunded where it can be (418's
-- behaviour).
--
-- Idempotent.
-- =============================================================================

BEGIN;

CREATE TABLE IF NOT EXISTS public.poultrypurchasereversals (
    purchasereversalid     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmid                 text        NOT NULL,
    reversalnumber         text        NOT NULL,
    poultryrawmaterialpurchaseid integer NOT NULL,
    poultryrawmaterialitemid integer,
    itemname               text,
    supplierid             integer,
    suppliername           text,
    purchasedate           timestamp,
    reasoncode             text,
    reason                 text        NOT NULL DEFAULT '',
    businessdate           date        NOT NULL,
    occurredat             timestamp   NOT NULL,
    reversedby             text,
    quantity               numeric(18,4),
    stockremoved           numeric(18,4),
    totalcost              numeric(14,2) NOT NULL DEFAULT 0,
    paidamount             numeric(14,2) NOT NULL DEFAULT 0,
    outstandingamount      numeric(14,2) NOT NULL DEFAULT 0,
    creditreleased         numeric(14,2) NOT NULL DEFAULT 0,
    creditcreated          numeric(14,2) NOT NULL DEFAULT 0,
    refunded               numeric(14,2) NOT NULL DEFAULT 0,
    paymenthandling        text        NOT NULL DEFAULT 'None',
    idempotencykey         text,
    snapshot               jsonb,
    createdat              timestamp   NOT NULL DEFAULT (now() AT TIME ZONE 'utc')
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_poultrypurchasereversals_number ON public.poultrypurchasereversals (farmid, reversalnumber);
CREATE UNIQUE INDEX IF NOT EXISTS ux_poultrypurchasereversals_purchase ON public.poultrypurchasereversals (farmid, poultryrawmaterialpurchaseid);
CREATE UNIQUE INDEX IF NOT EXISTS ux_poultrypurchasereversals_idem ON public.poultrypurchasereversals (farmid, idempotencykey)
    WHERE idempotencykey IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.poultrypurchasereversalpayments (
    purchasereversalpaymentid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchasereversalid     integer     NOT NULL REFERENCES public.poultrypurchasereversals (purchasereversalid),
    farmid                 text        NOT NULL,
    linekey                text        NOT NULL,
    source                 text        NOT NULL,          -- 'SupplierPayment' | 'PaidAtEntry'
    poultrysupplierpaymentid integer,
    poultrycashaccountid   integer,
    amount                 numeric(14,2) NOT NULL,
    action                 text        NOT NULL CHECK (action IN ('Refund', 'KeepAsCredit'))
);

ALTER TABLE public.poultryrawmaterialpurchases ADD COLUMN IF NOT EXISTS purchasereversalid integer;

-- ---------------------------------------------------------------------------
-- State: blockers (418's, minus SharedPayment), money lines, fingerprint.
-- Same JSON shape as Water's fnwaterpurchase_reversalstate (one web dialog).
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.fnpoultrypurchase_reversalstate(p_farmid text, p_purchaseid integer)
RETURNS jsonb LANGUAGE plpgsql STABLE AS $f$
DECLARE
    v_p        record;
    v_blockers jsonb;
    v_money    jsonb := '[]'::jsonb;
    v_credit   numeric(14,2);
    v_fp       text;
BEGIN
    SELECT pu.*, i.itemname::text AS itemnm, i.unitofmeasure::text AS uom,
           COALESCE(NULLIF(btrim(s.name), ''), NULLIF(btrim(pu.suppliername), ''))::text AS suppnm
    INTO   v_p
    FROM   poultryrawmaterialpurchases pu
    LEFT   JOIN poultryrawmaterialitems i ON i.poultryrawmaterialitemid = pu.poultryrawmaterialitemid
    LEFT   JOIN supplier s ON s.supplierid = pu.supplierid AND s.farmid = pu.farmid
    WHERE  pu.poultryrawmaterialpurchaseid = p_purchaseid AND pu.farmid = p_farmid;
    IF NOT FOUND THEN
        RETURN jsonb_build_object('found', false, 'payments', '[]'::jsonb,
               'blockers', jsonb_build_array(jsonb_build_object('code', 'NotFound',
                           'message', 'This purchase was not found for this company.')));
    END IF;

    -- 418's blockers, except SharedPayment: a shared payment is now kept as credit.
    SELECT COALESCE(jsonb_agg(jsonb_build_object('code', b.code, 'message', b.message)), '[]'::jsonb)
    INTO   v_blockers
    FROM   public.sppoultryrawmaterialpurchase_reversalblockers(p_farmid, p_purchaseid) b
    WHERE  b.code <> 'SharedPayment';

    SELECT COALESCE(SUM(sa.amountapplied), 0) INTO v_credit
    FROM   supplierpaymentallocation sa
    WHERE  sa.farmid = p_farmid AND sa.module = 'poultry' AND sa.status = 'Posted'
      AND  sa.documenttype = 'RawMaterialPurchase' AND sa.documentid = p_purchaseid AND sa.fromcredit;

    -- Supplier payments that paid this purchase (credit applications excluded).
    SELECT COALESCE(jsonb_agg(jsonb_build_object(
               'key', 'sp:' || x.paymentid, 'source', 'SupplierPayment', 'paymentId', x.paymentid,
               'paymentNumbers', 'Supplier payment #' || x.paymentid,
               'allocated', x.amt, 'paymentDate', x.paymentdate, 'paymentMethod', x.paymentmethod,
               'cashAccountId', x.poultrycashaccountid, 'cashAccountName', x.accountname,
               'allowed', CASE WHEN x.onlythis THEN '["KeepAsCredit","Refund"]'::jsonb ELSE '["KeepAsCredit"]'::jsonb END,
               'default', 'KeepAsCredit',
               'keepUnavailableReason', NULL,
               'refundUnavailableReason', CASE WHEN NOT x.onlythis THEN
                   'This payment also paid other items, so only this purchase''s part is released -- as supplier credit. '
                   || 'To get the money back, refund it from Supplier Credits afterwards.' END,
               'noCashNote', CASE WHEN x.poultrycashaccountid IS NULL THEN
                   'This payment was not recorded in a cash account, so a refund puts nothing back into one.' END)
             ORDER BY x.paymentdate, x.paymentid), '[]'::jsonb)
    INTO   v_money
    FROM  (SELECT sp.poultrysupplierpaymentid AS paymentid, sp.paymentdate, sp.paymentmethod,
                  sp.poultrycashaccountid, a.accountname::text AS accountname,
                  SUM(sa.amountapplied)::numeric(14,2) AS amt,
                  -- 418's rule for a payment that can be reversed with the purchase
                  (NOT EXISTS (SELECT 1 FROM supplierpaymentallocation o
                               WHERE o.farmid = p_farmid AND o.module = 'poultry' AND o.status = 'Posted'
                                 AND o.paymentid = sp.poultrysupplierpaymentid
                                 AND NOT (o.documenttype = 'RawMaterialPurchase' AND o.documentid = p_purchaseid AND NOT o.fromcredit))
                   AND public.fnpoultrysupplierpayment_unapplied(p_farmid, sp.poultrysupplierpaymentid) <= 0.005) AS onlythis
           FROM   supplierpaymentallocation sa
           JOIN   poultrysupplierpayments sp ON sp.poultrysupplierpaymentid = sa.paymentid AND sp.farmid = sa.farmid
           LEFT   JOIN poultrycashaccounts a ON a.poultrycashaccountid = sp.poultrycashaccountid
           WHERE  sa.farmid = p_farmid AND sa.module = 'poultry' AND sa.status = 'Posted'
             AND  sa.documenttype = 'RawMaterialPurchase' AND sa.documentid = p_purchaseid
             AND  NOT sa.fromcredit
           GROUP  BY sp.poultrysupplierpaymentid, sp.paymentdate, sp.paymentmethod, sp.poultrycashaccountid, a.accountname) x;

    -- Money paid up front before supplier payments existed (legacy _insert):
    -- its net 'RawMaterialPurchase' cash, per account. Only a refund fits --
    -- there is no payment to hold it as credit.
    SELECT v_money || COALESCE(jsonb_agg(jsonb_build_object(
               'key', 'cash:' || c.poultrycashaccountid, 'source', 'PaidAtEntry', 'paymentId', NULL,
               'paymentNumbers', 'Paid when the purchase was entered',
               'allocated', -c.net, 'paymentDate', v_p.purchasedate, 'paymentMethod', v_p.paymentmethod,
               'cashAccountId', c.poultrycashaccountid, 'cashAccountName', c.accountname,
               'allowed', '["Refund"]'::jsonb, 'default', 'Refund',
               'keepUnavailableReason', 'This money was paid before supplier payments were recorded, so it can only be recorded as refunded.',
               'refundUnavailableReason', NULL, 'noCashNote', NULL)), '[]'::jsonb)
    INTO   v_money
    FROM  (SELECT ct.poultrycashaccountid, a.accountname::text AS accountname, SUM(ct.amount)::numeric(14,2) AS net
           FROM   poultrycashtransactions ct
           LEFT   JOIN poultrycashaccounts a ON a.poultrycashaccountid = ct.poultrycashaccountid
           WHERE  ct.farmid = p_farmid AND ct.sourcetype = 'RawMaterialPurchase' AND ct.sourceid = p_purchaseid
           GROUP  BY ct.poultrycashaccountid, a.accountname
           HAVING SUM(ct.amount) < -0.005) c;

    SELECT md5(COALESCE(string_agg(t, '|' ORDER BY t), '')) INTO v_fp
    FROM (
        SELECT 'p' || pu.poultryrawmaterialpurchaseid || ':' || pu.quantity || ':' || pu.remainingquantity || ':'
               || pu.totalcost || ':' || COALESCE(pu.amountpaid, 0) || ':' || COALESCE(pu.reversedat::text, '') AS t
        FROM   poultryrawmaterialpurchases pu WHERE pu.farmid = p_farmid AND pu.poultryrawmaterialpurchaseid = p_purchaseid
        UNION ALL
        SELECT 'a' || sa.allocationid || ':' || sa.status || ':' || sa.amountapplied
        FROM   supplierpaymentallocation sa
        WHERE  sa.farmid = p_farmid AND sa.module = 'poultry'
          AND  sa.documenttype = 'RawMaterialPurchase' AND sa.documentid = p_purchaseid
        UNION ALL
        SELECT 'i' || i.poultryrawmaterialitemid || ':' || i.currentquantity
        FROM   poultryrawmaterialitems i WHERE i.poultryrawmaterialitemid = v_p.poultryrawmaterialitemid
    ) z;

    RETURN jsonb_build_object(
        'found', true,
        'purchaseId', p_purchaseid,
        'purchaseDate', v_p.purchasedate,
        'itemId', v_p.poultryrawmaterialitemid,
        'itemName', COALESCE(v_p.itemnm, 'Item'),
        'unit', v_p.uom,
        'quantity', v_p.quantity,
        'stockToRemove', (v_p.quantity * COALESCE(NULLIF(v_p.productionunitsperpurchaseunit, 0), 1))::numeric(18,4),
        'supplierId', v_p.supplierid,
        'supplierName', COALESCE(v_p.suppnm, 'No supplier'),
        'total', v_p.totalcost,
        'paid', COALESCE(v_p.amountpaid, 0),
        'creditApplied', v_credit,
        'outstanding', GREATEST(v_p.totalcost - COALESCE(v_p.amountpaid, 0), 0),
        'deferred', COALESCE(v_p.deferredtotalcost, 0) > 0,
        'payments', v_money,
        'supplierCreditNow', CASE WHEN v_p.supplierid IS NULL THEN 0
                                  ELSE public.fnpoultrysupplier_credit(p_farmid, v_p.supplierid) END,
        'blockers', v_blockers,
        'fingerprint', v_fp);
END $f$;

CREATE OR REPLACE FUNCTION public.sppoultrypurchase_reversalpreview(p_farmid text, p_purchaseid integer)
RETURNS jsonb LANGUAGE sql STABLE AS $f$
    SELECT public.fnpoultrypurchase_reversalstate(p_farmid, p_purchaseid);
$f$;

-- ---------------------------------------------------------------------------
-- Reverse
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.sppoultrypurchase_reverse(
    p_farmid text, p_purchaseid integer, p_reasoncode text, p_reason text,
    p_handling jsonb DEFAULT '{}'::jsonb, p_expectedfingerprint text DEFAULT NULL,
    p_idempotencykey text DEFAULT NULL, p_reversedby text DEFAULT NULL)
RETURNS integer LANGUAGE plpgsql AS $f$
DECLARE
    v_now      timestamp := (now() AT TIME ZONE 'utc');
    v_state    jsonb;
    v_item     jsonb;
    v_action   text;
    v_reason   text;
    v_note     text;
    v_id       integer;
    v_existing integer;
    v_number   text;
    v_p        record;
    v_amt      numeric(14,2);
    v_acct     integer;
    v_bal      numeric(14,2);
    v_gid      uuid;
    v_credit   numeric(14,2) := 0;
    v_refund   numeric(14,2) := 0;
    v_kinds    text[] := ARRAY[]::text[];
    c          record;
BEGIN
    IF NULLIF(btrim(COALESCE(p_reasoncode, '')), '') IS NULL AND NULLIF(btrim(COALESCE(p_reason, '')), '') IS NULL THEN
        RAISE EXCEPTION 'Give a reason for reversing this purchase.' USING ERRCODE = 'P0001';
    END IF;
    IF lower(btrim(COALESCE(p_reasoncode, ''))) = 'other' AND NULLIF(btrim(COALESCE(p_reason, '')), '') IS NULL THEN
        RAISE EXCEPTION 'Say in a few words what happened (the reason is "Other").' USING ERRCODE = 'P0001';
    END IF;
    v_reason := concat_ws(': ', NULLIF(btrim(COALESCE(p_reasoncode, '')), ''), NULLIF(btrim(COALESCE(p_reason, '')), ''));

    PERFORM pg_advisory_xact_lock(hashtext('poultry-purchasereversal:' || p_farmid || ':' || p_purchaseid::text));
    SELECT pu.*, i.itemname::text AS itemnm INTO v_p
    FROM   poultryrawmaterialpurchases pu
    LEFT   JOIN poultryrawmaterialitems i ON i.poultryrawmaterialitemid = pu.poultryrawmaterialitemid
    WHERE  pu.poultryrawmaterialpurchaseid = p_purchaseid AND pu.farmid = p_farmid
    FOR UPDATE OF pu;

    IF p_idempotencykey IS NOT NULL THEN
        SELECT r.purchasereversalid INTO v_existing FROM poultrypurchasereversals r
        WHERE  r.farmid = p_farmid AND r.idempotencykey = p_idempotencykey;
        IF FOUND THEN RETURN v_existing; END IF;
    END IF;

    v_state := fnpoultrypurchase_reversalstate(p_farmid, p_purchaseid);
    IF jsonb_array_length(v_state->'blockers') > 0 THEN
        RAISE EXCEPTION '%', v_state->'blockers'->0->>'message' USING ERRCODE = 'P0001';
    END IF;
    IF p_expectedfingerprint IS NOT NULL AND p_expectedfingerprint <> v_state->>'fingerprint' THEN
        RAISE EXCEPTION 'This purchase changed after the reversal preview was generated. Please review the updated impact before continuing.'
            USING ERRCODE = 'P0001', HINT = 'stale-preview';
    END IF;

    FOR v_item IN SELECT * FROM jsonb_array_elements(v_state->'payments') LOOP
        v_action := COALESCE(p_handling->>(v_item->>'key'), v_item->>'default');
        IF NOT (v_item->'allowed') ? v_action THEN
            RAISE EXCEPTION '%', COALESCE(
                CASE WHEN v_action = 'Refund' THEN v_item->>'refundUnavailableReason' ELSE v_item->>'keepUnavailableReason' END,
                'Choose whether the supplier refunded ' || (v_item->>'paymentNumbers') || ' or it is kept as supplier credit.')
                USING ERRCODE = 'P0001';
        END IF;
    END LOOP;

    PERFORM pg_advisory_xact_lock(hashtext('poultry-purchasereversal-no:' || p_farmid));
    SELECT 'PPR-' || lpad((COALESCE(MAX(NULLIF(regexp_replace(r.reversalnumber, '\D', '', 'g'), '')::int), 0) + 1)::text, 5, '0')
    INTO   v_number
    FROM   poultrypurchasereversals r WHERE r.farmid = p_farmid;
    v_note := left('Purchase #' || p_purchaseid || ' reversed (' || v_number || '): ' || v_reason, 500);

    INSERT INTO poultrypurchasereversals
        (farmid, reversalnumber, poultryrawmaterialpurchaseid, poultryrawmaterialitemid, itemname, supplierid, suppliername,
         purchasedate, reasoncode, reason, businessdate, occurredat, reversedby, quantity, stockremoved,
         totalcost, paidamount, outstandingamount, creditreleased, idempotencykey, snapshot)
    VALUES
        (p_farmid, v_number, p_purchaseid, v_p.poultryrawmaterialitemid, v_state->>'itemName', v_p.supplierid,
         v_state->>'supplierName', v_p.purchasedate, NULLIF(btrim(p_reasoncode), ''), btrim(COALESCE(p_reason, '')),
         fncompany_businessdate(p_farmid), v_now, p_reversedby, v_p.quantity, (v_state->>'stockToRemove')::numeric,
         (v_state->>'total')::numeric, (v_state->>'paid')::numeric, (v_state->>'outstanding')::numeric,
         (v_state->>'creditApplied')::numeric, p_idempotencykey, v_state)
    RETURNING purchasereversalid INTO v_id;

    -- 1. Supplier credit applied to it goes back to the supplier (418).
    FOR c IN SELECT sa.allocationid FROM supplierpaymentallocation sa
             WHERE  sa.farmid = p_farmid AND sa.module = 'poultry' AND sa.status = 'Posted'
               AND  sa.documenttype = 'RawMaterialPurchase' AND sa.documentid = p_purchaseid
               AND  sa.fromcredit LOOP
        PERFORM public.sppoultrysuppliercredit_unapply(p_farmid, c.allocationid, v_note, p_reversedby);
    END LOOP;

    -- 2. The money, line by line.
    FOR v_item IN SELECT * FROM jsonb_array_elements(v_state->'payments') LOOP
        v_action := COALESCE(p_handling->>(v_item->>'key'), v_item->>'default');
        v_amt    := (v_item->>'allocated')::numeric;
        v_acct   := NULLIF(v_item->>'cashAccountId', '')::int;

        IF v_item->>'source' = 'SupplierPayment' AND v_action = 'Refund' THEN
            -- Paid only this purchase: the payment is reversed (376: CashOut kept,
            -- reversal CashIn today).
            PERFORM public.sppoultrysupplierpayment_reverse(p_farmid, (v_item->>'paymentId')::int, v_note, p_reversedby);
        ELSIF v_item->>'source' = 'SupplierPayment' THEN
            -- Kept: release what the payment paid on this purchase. The payment
            -- stays Posted with that part unapplied -- supplier credit. No cash moves.
            UPDATE supplierpaymentallocation sa
            SET    status = 'Reversed', reversedby = p_reversedby, reversedat = v_now, reversalreason = v_note
            WHERE  sa.farmid = p_farmid AND sa.module = 'poultry' AND sa.status = 'Posted'
              AND  sa.paymentid = (v_item->>'paymentId')::int
              AND  sa.documenttype = 'RawMaterialPurchase' AND sa.documentid = p_purchaseid AND NOT sa.fromcredit;
            UPDATE poultryrawmaterialpurchases pu
            SET    amountpaid = GREATEST(COALESCE(pu.amountpaid, 0) - v_amt, 0), updatedat = v_now
            WHERE  pu.poultryrawmaterialpurchaseid = p_purchaseid AND pu.farmid = p_farmid;
        ELSE
            -- Paid at entry before supplier payments (418 step 3): back in today.
            UPDATE poultrycashaccounts a
            SET    currentbalance = a.currentbalance + v_amt, updatedat = v_now
            WHERE  a.poultrycashaccountid = v_acct AND a.farmid = p_farmid
            RETURNING a.currentbalance INTO v_bal;
            INSERT INTO poultrycashtransactions
                (farmid, poultrycashaccountid, transactiondate, transactiontype, sourcetype, sourceid,
                 amount, balanceaftertransaction, description, createdby, approvedby, approvedat)
            VALUES
                (p_farmid, v_acct, v_now, 'CashIn', 'RawMaterialPurchaseReversal', p_purchaseid,
                 v_amt, v_bal, left('Reversal of purchase: ' || COALESCE(v_p.itemnm, 'item') || ' (' || v_number || ')', 500),
                 p_reversedby, p_reversedby, v_now);
        END IF;

        IF v_action = 'Refund' THEN v_refund := v_refund + v_amt; ELSE v_credit := v_credit + v_amt; END IF;
        v_kinds := v_kinds || v_action;

        INSERT INTO poultrypurchasereversalpayments
            (purchasereversalid, farmid, linekey, source, poultrysupplierpaymentid, poultrycashaccountid, amount, action)
        VALUES
            (v_id, p_farmid, v_item->>'key', v_item->>'source', NULLIF(v_item->>'paymentId', '')::int, v_acct, v_amt, v_action);
    END LOOP;

    -- 3. The purchase's expense rows stop counting as spend (418).
    BEGIN v_gid := p_farmid::uuid; EXCEPTION WHEN OTHERS THEN v_gid := NULL; END;
    IF v_gid IS NOT NULL THEN
        DELETE FROM expense e
        WHERE  e.farmid = v_gid AND e.sourcetype = 'PoultryRawMaterialPurchase' AND e.sourceid = p_purchaseid;
    END IF;

    -- 4. Stock out, lot emptied, row kept and marked Reversed (418).
    PERFORM public.sppoultryrawmaterialitem_adjust(
        p_farmid, v_p.poultryrawmaterialitemid, -((v_state->>'stockToRemove')::numeric),
        v_p.unitcost, 'PurchaseReversal', v_note, p_reversedby);

    UPDATE poultryrawmaterialpurchases pu
    SET    remainingquantity = 0, deferredremainingcost = 0,
           reversedat = v_now, reversedby = p_reversedby, reversalreason = v_reason,
           purchasereversalid = v_id, updatedat = v_now
    WHERE  pu.poultryrawmaterialpurchaseid = p_purchaseid AND pu.farmid = p_farmid;

    UPDATE poultrypurchasereversals r
    SET    creditcreated = v_credit, refunded = v_refund,
           paymenthandling = CASE
               WHEN array_length(v_kinds, 1) IS NULL THEN 'None'
               WHEN 'KeepAsCredit' = ALL (v_kinds) THEN 'KeepAsCredit'
               WHEN 'Refund' = ALL (v_kinds) THEN 'Refund'
               ELSE 'Mixed' END
    WHERE  r.purchasereversalid = v_id;

    RETURN v_id;
END $f$;

CREATE OR REPLACE FUNCTION public.sppoultrypurchase_reversalget(p_farmid text, p_purchaseid integer)
RETURNS jsonb LANGUAGE sql STABLE AS $f$
    SELECT jsonb_build_object(
             'purchaseReversalId', r.purchasereversalid, 'reversalNumber', r.reversalnumber,
             'purchaseId', r.poultryrawmaterialpurchaseid, 'itemName', r.itemname, 'supplierName', r.suppliername,
             'reasonCode', r.reasoncode, 'reason', r.reason,
             'businessDate', r.businessdate, 'occurredAt', r.occurredat, 'reversedBy', r.reversedby,
             'paymentHandling', r.paymenthandling, 'total', r.totalcost, 'paid', r.paidamount,
             'outstanding', r.outstandingamount, 'creditCreated', r.creditcreated,
             'creditReleased', r.creditreleased, 'refunded', r.refunded, 'stockRemoved', r.stockremoved,
             'payments', COALESCE((SELECT jsonb_agg(jsonb_build_object(
                             'source', p.source, 'paymentId', p.poultrysupplierpaymentid,
                             'amount', p.amount, 'action', p.action, 'cashAccountId', p.poultrycashaccountid)
                             ORDER BY p.purchasereversalpaymentid)
                           FROM poultrypurchasereversalpayments p WHERE p.purchasereversalid = r.purchasereversalid), '[]'::jsonb))
    FROM   poultrypurchasereversals r
    WHERE  r.farmid = p_farmid AND r.poultryrawmaterialpurchaseid = p_purchaseid
    ORDER  BY r.purchasereversalid DESC
    LIMIT  1;
$f$;

-- ---------------------------------------------------------------------------
-- 418's entry point, kept for old clients: every line refunded where it can
-- be, otherwise its default. (418 refused shared payments outright.)
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.sppoultryrawmaterialpurchase_reverse(p_farmid text, p_purchaseid integer, p_reason text, p_reversedby text DEFAULT NULL::text)
 RETURNS void
 LANGUAGE plpgsql
AS $function$
DECLARE v_h jsonb;
BEGIN
    IF COALESCE(btrim(p_reason), '') = '' THEN
        RAISE EXCEPTION 'Give a reason for reversing this purchase.';
    END IF;
    SELECT COALESCE(jsonb_object_agg(m->>'key',
                    CASE WHEN (m->'allowed') ? 'Refund' THEN 'Refund' ELSE m->>'default' END), '{}'::jsonb)
    INTO   v_h
    FROM   jsonb_array_elements(public.fnpoultrypurchase_reversalstate(p_farmid, p_purchaseid)->'payments') m;
    PERFORM public.sppoultrypurchase_reverse(p_farmid, p_purchaseid, NULL, btrim(p_reason), v_h, NULL, NULL, p_reversedby);
END $function$;

COMMIT;
