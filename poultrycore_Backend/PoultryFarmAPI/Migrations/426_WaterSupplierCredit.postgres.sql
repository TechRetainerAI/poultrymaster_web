CREATE UNIQUE INDEX IF NOT EXISTS ux_watersupplierdebts_number ON public.watersupplierdebts (farmid, debtnumber);

-- ===================================================== 2. credit, derived ===
-- Credit added by hand: no money moved, no account.
CREATE OR REPLACE FUNCTION public.fnwatersupplier_iscreditkind(p_sourcetype text)
RETURNS boolean LANGUAGE sql IMMUTABLE AS $f$
    SELECT COALESCE(p_sourcetype, '') IN ('SupplierCreditNote', 'SupplierOpeningCredit', 'SupplierManualCredit');
$f$;

-- Credit on a supplier payment = amount - posted allocations (its own and later
-- ones from credit) - posted refund lines.
CREATE OR REPLACE FUNCTION public.fnwatersupplierpayment_unapplied(p_farmid text, p_paymentid integer)
RETURNS numeric LANGUAGE sql STABLE AS $f$
    SELECT CASE WHEN COALESCE(sp.status, 'Posted') <> 'Posted' THEN 0
                ELSE GREATEST(sp.totalamount
                     - COALESCE((SELECT SUM(sa.amountapplied) FROM supplierpaymentallocation sa
                                 WHERE sa.farmid = sp.farmid AND sa.module = 'water'
                                   AND sa.paymentid = sp.watersupplierpaymentid AND sa.status = 'Posted'), 0)
                     - COALESCE((SELECT SUM(rl.amount) FROM watersupplierrefundlines rl
                                 JOIN watersupplierrefunds r ON r.refundid = rl.refundid AND r.status = 'Posted'
                                 WHERE rl.farmid = sp.farmid AND rl.watersupplierpaymentid = sp.watersupplierpaymentid), 0), 0)
           END::numeric(14,2)
    FROM   watersupplierpayments sp
    WHERE  sp.watersupplierpaymentid = p_paymentid AND sp.farmid = p_farmid;
$f$;

CREATE OR REPLACE FUNCTION public.fnwatersupplier_credit(p_farmid text, p_supplierid integer)
RETURNS numeric LANGUAGE sql STABLE AS $f$
    SELECT COALESCE(SUM(public.fnwatersupplierpayment_unapplied(p_farmid, sp.watersupplierpaymentid)), 0)::numeric(14,2)
    FROM   watersupplierpayments sp
    WHERE  sp.farmid = p_farmid AND sp.supplierid = p_supplierid AND COALESCE(sp.status, 'Posted') = 'Posted';
$f$;

CREATE OR REPLACE FUNCTION public.spwatersuppliercredit_events(p_farmid text, p_supplierid integer DEFAULT NULL)
RETURNS TABLE(watersupplierpaymentid integer, creditnumber text, creditdate timestamp, supplierid integer,
              suppliername text, source text, sourcetype text, reference text, notes text, originalamount numeric,
              applied numeric, refunded numeric, available numeric, status text, ismanual boolean,
              watercashaccountid integer, accountname text)
LANGUAGE sql STABLE AS $f$
    WITH x AS (
        SELECT sp.*,
               COALESCE((SELECT SUM(sa.amountapplied) FROM supplierpaymentallocation sa
                         WHERE sa.farmid = sp.farmid AND sa.module = 'water' AND sa.paymentid = sp.watersupplierpaymentid
                           AND sa.status = 'Posted' AND NOT sa.fromcredit), 0) AS paidnow,
               COALESCE((SELECT SUM(sa.amountapplied) FROM supplierpaymentallocation sa
                         WHERE sa.farmid = sp.farmid AND sa.module = 'water' AND sa.paymentid = sp.watersupplierpaymentid
                           AND sa.status = 'Posted' AND sa.fromcredit), 0) AS appliedlater,
               COALESCE((SELECT SUM(rl.amount) FROM watersupplierrefundlines rl
                         JOIN watersupplierrefunds r ON r.refundid = rl.refundid AND r.status = 'Posted'
                         WHERE rl.farmid = sp.farmid AND rl.watersupplierpaymentid = sp.watersupplierpaymentid), 0) AS refundedamt,
               EXISTS (SELECT 1 FROM supplierpaymentallocation sa
                       WHERE sa.farmid = sp.farmid AND sa.module = 'water' AND sa.paymentid = sp.watersupplierpaymentid
                         AND NOT sa.fromcredit) AS hadallocations
        FROM   watersupplierpayments sp
        WHERE  sp.farmid = p_farmid AND COALESCE(sp.status, 'Posted') = 'Posted' AND sp.supplierid IS NOT NULL
          AND  (p_supplierid IS NULL OR sp.supplierid = p_supplierid)
    )
    SELECT x.watersupplierpaymentid, ('SP-' || lpad(x.watersupplierpaymentid::text, 5, '0'))::text, x.paymentdate,
           x.supplierid, s.suppliername::text,
           CASE x.sourcetype
                WHEN 'SupplierCreditNote'    THEN 'Credit note'
                WHEN 'SupplierOpeningCredit' THEN 'Opening credit'
                WHEN 'SupplierManualCredit'  THEN 'Manual credit'
                ELSE CASE WHEN x.hadallocations THEN 'Overpayment' ELSE 'Supplier advance' END
           END::text,
           x.sourcetype::text, x.referenceno::text, x.notes::text,
           (x.totalamount - x.paidnow)::numeric(14,2), x.appliedlater::numeric(14,2), x.refundedamt::numeric(14,2),
           public.fnwatersupplierpayment_unapplied(p_farmid, x.watersupplierpaymentid),
           CASE WHEN public.fnwatersupplierpayment_unapplied(p_farmid, x.watersupplierpaymentid) <= 0
                     AND x.refundedamt > 0 AND x.appliedlater = 0 THEN 'Refunded'
                WHEN public.fnwatersupplierpayment_unapplied(p_farmid, x.watersupplierpaymentid) <= 0 THEN 'Used'
                WHEN x.appliedlater > 0 OR x.refundedamt > 0 THEN 'Partly used'
                ELSE 'Available' END::text,
           (public.fnwatersupplier_iscreditkind(x.sourcetype) OR NOT x.hadallocations),
           x.watercashaccountid, a.accountname::text
    FROM   x
    LEFT   JOIN watersuppliers s ON s.watersupplierid = x.supplierid AND s.farmid = x.farmid
    LEFT   JOIN watercashaccounts a ON a.watercashaccountid = x.watercashaccountid AND a.farmid = x.farmid
    WHERE  (x.totalamount - x.paidnow) > 0
    ORDER  BY x.paymentdate DESC, x.watersupplierpaymentid DESC;
$f$;

CREATE OR REPLACE FUNCTION public.spwatersuppliercredit_summary(p_farmid text)
RETURNS TABLE(supplierid integer, suppliername text, availablecredit numeric, creditcount integer, owed numeric)
LANGUAGE sql STABLE AS $f$
    SELECT e.supplierid, MIN(e.suppliername)::text, SUM(e.available)::numeric(14,2),
           COUNT(*) FILTER (WHERE e.available > 0)::integer,
           COALESCE((SELECT SUM(d.balance) FROM fnwaterpayables(p_farmid) d WHERE d.supplierid = e.supplierid), 0)::numeric(14,2)
    FROM   public.spwatersuppliercredit_events(p_farmid, NULL) e
    GROUP  BY e.supplierid
    HAVING SUM(e.available) > 0
    ORDER  BY SUM(e.available) DESC;
$f$;

CREATE OR REPLACE FUNCTION public.spwatersuppliercredit_applications(p_farmid text, p_supplierid integer DEFAULT NULL)
RETURNS TABLE(allocationid integer, watersupplierpaymentid integer, creditnumber text, supplierid integer,
              suppliername text, documenttype text, documentid integer, reference text, label text, amount numeric,
              applieddate timestamp, status text, createdby text, reversedat timestamp, reversalreason text)
LANGUAGE sql STABLE AS $f$
    SELECT sa.allocationid, sp.watersupplierpaymentid, ('SP-' || lpad(sp.watersupplierpaymentid::text, 5, '0'))::text,
           sp.supplierid, s.suppliername::text, sa.documenttype, sa.documentid, d.reference, d.label,
           sa.amountapplied, sa.createdat, sa.status, sa.createdby, sa.reversedat, sa.reversalreason
    FROM   supplierpaymentallocation sa
    JOIN   watersupplierpayments sp ON sp.watersupplierpaymentid = sa.paymentid AND sp.farmid = sa.farmid
    LEFT   JOIN watersuppliers s ON s.watersupplierid = sp.supplierid AND s.farmid = sp.farmid
    LEFT   JOIN fnwaterpayables(p_farmid) d ON d.documenttype = sa.documenttype AND d.documentid = sa.documentid
    WHERE  sa.farmid = p_farmid AND sa.module = 'water' AND sa.fromcredit
      AND  (p_supplierid IS NULL OR sp.supplierid = p_supplierid)
    ORDER  BY sa.createdat DESC, sa.allocationid DESC;
$f$;

-- ================================================= 3. writers: credit ======
-- Credit added by hand: no cash, no account.
CREATE OR REPLACE FUNCTION public.spwatersuppliercredit_create(p_farmid text, p_supplierid integer, p_kind text,
    p_amount numeric, p_date timestamp DEFAULT NULL, p_reference text DEFAULT NULL, p_reason text DEFAULT NULL,
    p_by text DEFAULT NULL)
RETURNS integer LANGUAGE plpgsql AS $f$
DECLARE v_id integer; v_date timestamp := COALESCE(p_date, (now() AT TIME ZONE 'utc'));
BEGIN
    IF p_kind NOT IN ('SupplierCreditNote', 'SupplierOpeningCredit', 'SupplierManualCredit') THEN
        RAISE EXCEPTION 'Choose what the credit is: a credit note, an opening credit or a manual credit.' USING ERRCODE = 'P0001';
    END IF;
    IF p_amount IS NULL OR round(p_amount, 2) <= 0 THEN
        RAISE EXCEPTION 'Enter an amount greater than 0.' USING ERRCODE = 'P0001';
    END IF;
    IF NULLIF(btrim(COALESCE(p_reason, '')), '') IS NULL THEN
        RAISE EXCEPTION 'Give a reason for the credit.' USING ERRCODE = 'P0001';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM watersuppliers s WHERE s.watersupplierid = p_supplierid AND s.farmid = p_farmid) THEN
        RAISE EXCEPTION 'Supplier does not belong to this company.' USING ERRCODE = 'P0001';
    END IF;
    IF v_date > (now() AT TIME ZONE 'utc') + interval '1 day' THEN
        RAISE EXCEPTION 'The credit date is in the future.' USING ERRCODE = 'P0001';
    END IF;
    INSERT INTO watersupplierpayments
        (farmid, supplierid, paymentdate, totalamount, paymentmethod, watercashaccountid, referenceno, notes,
         sourcetype, status, createdby, createdat)
    VALUES (p_farmid, p_supplierid, v_date, round(p_amount, 2), 'NonCash', NULL, NULLIF(btrim(p_reference), ''),
            btrim(p_reason), p_kind, 'Posted', p_by, (now() AT TIME ZONE 'utc'))
    RETURNING watersupplierpaymentid INTO v_id;
    RETURN v_id;
END
$f$;

-- Reverse a credit: refused while any of it is applied or refunded. A credit
-- added by hand simply goes; an advance / overpayment is a payment, reversed
-- with its cash (spwatersupplierpayment_reverse).
CREATE OR REPLACE FUNCTION public.spwatersuppliercredit_reverse(p_farmid text, p_paymentid integer, p_reason text,
                                                                p_by text DEFAULT NULL)
RETURNS integer LANGUAGE plpgsql AS $f$
DECLARE v_sp watersupplierpayments%ROWTYPE;
BEGIN
    IF NULLIF(btrim(COALESCE(p_reason, '')), '') IS NULL THEN
        RAISE EXCEPTION 'Give a reason for reversing the credit.' USING ERRCODE = 'P0001';
    END IF;
    SELECT * INTO v_sp FROM watersupplierpayments sp
    WHERE  sp.watersupplierpaymentid = p_paymentid AND sp.farmid = p_farmid FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'That credit does not belong to this company.' USING ERRCODE = 'P0001'; END IF;
    IF COALESCE(v_sp.status, 'Posted') <> 'Posted' THEN
        RAISE EXCEPTION 'This credit has already been reversed.' USING ERRCODE = 'P0001';
    END IF;
    IF EXISTS (SELECT 1 FROM supplierpaymentallocation sa WHERE sa.farmid = p_farmid AND sa.module = 'water'
               AND sa.paymentid = p_paymentid AND sa.status = 'Posted' AND sa.fromcredit) THEN
        RAISE EXCEPTION 'Part of this credit has been applied. Undo those applications first.' USING ERRCODE = 'P0001';
    END IF;
    IF EXISTS (SELECT 1 FROM watersupplierrefundlines rl JOIN watersupplierrefunds r ON r.refundid = rl.refundid
               WHERE rl.farmid = p_farmid AND rl.watersupplierpaymentid = p_paymentid AND r.status = 'Posted') THEN
        RAISE EXCEPTION 'Part of this credit has been refunded. Reverse the refund first.' USING ERRCODE = 'P0001';
    END IF;
    IF NOT public.fnwatersupplier_iscreditkind(v_sp.sourcetype) THEN
        RETURN public.spwatersupplierpayment_reverse(p_farmid, p_paymentid, btrim(p_reason), p_by);
    END IF;
    UPDATE watersupplierpayments SET status = 'Reversed', reversedby = p_by, reversedat = (now() AT TIME ZONE 'utc'),
           reversalreason = btrim(p_reason)
    WHERE  watersupplierpaymentid = p_paymentid AND farmid = p_farmid;
    RETURN 1;
END
$f$;

-- Bump / drop what a payable document shows as paid.
CREATE OR REPLACE FUNCTION public.fnwaterpayable_addpaid(p_farmid text, p_documenttype text, p_documentid integer, p_delta numeric)
RETURNS void LANGUAGE plpgsql AS $f$
BEGIN
    IF p_documenttype = 'Expense' THEN
        UPDATE waterexpenses
        SET    amountpaid = LEAST(GREATEST(COALESCE(amountpaid, CASE WHEN COALESCE(paymentmethod, '') = 'Credit'
                                                                    THEN 0 ELSE amount END) + p_delta, 0), amount),
               updatedat  = (now() AT TIME ZONE 'utc')
        WHERE  waterexpenseid = p_documentid AND lower(farmid::text) = lower(p_farmid);
    ELSIF p_documenttype = 'SupplierDebt' THEN
        UPDATE watersupplierdebts SET amountpaid = GREATEST(amountpaid + p_delta, 0)
        WHERE  debtid = p_documentid AND farmid = p_farmid;
    ELSE
        UPDATE waterrawmaterialpurchases
        SET    amountpaid = GREATEST(amountpaid + p_delta, 0), updatedat = (now() AT TIME ZONE 'utc')
        WHERE  waterrawmaterialpurchaseid = p_documentid AND farmid = p_farmid;
    END IF;
END
$f$;

-- Apply credit to a purchase / bill / supplier debt: an allocation on the
-- CREDIT's payment, marked fromcredit, dated now. No cash (it left with the
-- advance, or never existed). The document's amountpaid goes up as for a
-- payment, so a raw-material purchase reaches the P&L on water's paid basis.
CREATE OR REPLACE FUNCTION public.spwatersuppliercredit_apply(p_farmid text, p_paymentid integer,
    p_documenttype text, p_documentid integer, p_amount numeric, p_by text DEFAULT NULL)
RETURNS integer LANGUAGE plpgsql AS $f$
DECLARE
    v_sp     watersupplierpayments%ROWTYPE;
    v_doc    record;
    v_amt    numeric(14,2) := round(p_amount, 2);
    v_avail  numeric(14,2);
    v_before numeric(14,2);
    v_id     integer;
BEGIN
    IF v_amt IS NULL OR v_amt <= 0 THEN
        RAISE EXCEPTION 'Enter an amount greater than 0.' USING ERRCODE = 'P0001';
    END IF;
    SELECT * INTO v_sp FROM watersupplierpayments sp
    WHERE  sp.watersupplierpaymentid = p_paymentid AND sp.farmid = p_farmid FOR UPDATE;
    IF NOT FOUND OR v_sp.supplierid IS NULL THEN
        RAISE EXCEPTION 'That credit does not belong to this company.' USING ERRCODE = 'P0001';
    END IF;
    v_avail := public.fnwatersupplierpayment_unapplied(p_farmid, p_paymentid);
    IF v_amt > v_avail THEN
        RAISE EXCEPTION 'That credit only has % available.', v_avail USING ERRCODE = 'P0001';
    END IF;
    SELECT * INTO v_doc FROM fnwaterpayables(p_farmid) d
    WHERE  d.documenttype = COALESCE(p_documenttype, 'RawMaterialPurchase') AND d.documentid = p_documentid;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'That item is not an open payable of this company.' USING ERRCODE = 'P0001';
    END IF;
    IF v_doc.supplierid IS DISTINCT FROM v_sp.supplierid THEN
        RAISE EXCEPTION 'That item is owed to a different supplier.' USING ERRCODE = 'P0001';
    END IF;
    v_before := v_doc.balance;
    IF v_before <= 0 THEN RAISE EXCEPTION '% is already fully paid.', v_doc.reference USING ERRCODE = 'P0001'; END IF;
    IF v_amt > v_before THEN RAISE EXCEPTION 'Only % is owed on %.', v_before, v_doc.reference USING ERRCODE = 'P0001'; END IF;
    IF EXISTS (SELECT 1 FROM supplierpaymentallocation sa
               WHERE sa.module = 'water' AND sa.paymentid = p_paymentid
                 AND sa.documenttype = v_doc.documenttype AND sa.documentid = p_documentid) THEN
        RAISE EXCEPTION 'This credit has already been applied to % once. Use another credit, or pay it.', v_doc.reference
            USING ERRCODE = 'P0001';
    END IF;
    PERFORM public.fnwaterpayable_addpaid(p_farmid, v_doc.documenttype, p_documentid, v_amt);
    INSERT INTO supplierpaymentallocation
        (farmid, module, paymentid, documenttype, documentid, amountapplied,
         documentbalancebefore, documentbalanceafter, status, createdby, createdat, fromcredit)
    VALUES (p_farmid, 'water', p_paymentid, v_doc.documenttype, p_documentid, v_amt,
            v_before, v_before - v_amt, 'Posted', p_by, (now() AT TIME ZONE 'utc'), TRUE)
    RETURNING allocationid INTO v_id;
    RETURN v_id;
END
$f$;

CREATE OR REPLACE FUNCTION public.spwatersuppliercredit_unapply(p_farmid text, p_allocationid integer,
    p_reason text, p_by text DEFAULT NULL)
RETURNS integer LANGUAGE plpgsql AS $f$
DECLARE v_a supplierpaymentallocation%ROWTYPE;
BEGIN
    IF NULLIF(btrim(COALESCE(p_reason, '')), '') IS NULL THEN
        RAISE EXCEPTION 'Give a reason.' USING ERRCODE = 'P0001';
    END IF;
    SELECT * INTO v_a FROM supplierpaymentallocation sa
    WHERE  sa.allocationid = p_allocationid AND sa.farmid = p_farmid AND sa.module = 'water' FOR UPDATE;
    IF NOT FOUND OR NOT v_a.fromcredit THEN
        RAISE EXCEPTION 'That is not an application of supplier credit in this company.' USING ERRCODE = 'P0001';
    END IF;
    IF v_a.status <> 'Posted' THEN
        RAISE EXCEPTION 'That application has already been reversed.' USING ERRCODE = 'P0001';
    END IF;
    PERFORM public.fnwaterpayable_addpaid(p_farmid, v_a.documenttype, v_a.documentid, -v_a.amountapplied);
    UPDATE supplierpaymentallocation
    SET    status = 'Reversed', reversedby = p_by, reversedat = (now() AT TIME ZONE 'utc'), reversalreason = btrim(p_reason)
    WHERE  allocationid = p_allocationid;
    RETURN p_allocationid;
END
$f$;

-- ================================================= 4. writers: refunds =====
-- The supplier sends money back out of credit: money IN to the account chosen.
CREATE OR REPLACE FUNCTION public.spwatersupplierrefund_record(p_farmid text, p_paymentid integer, p_amount numeric,
    p_cashaccountid integer, p_paymentmethod text, p_refunddate date, p_reason text, p_by text DEFAULT NULL)
RETURNS integer LANGUAGE plpgsql AS $f$
DECLARE
    v_sp    watersupplierpayments%ROWTYPE;
    v_amt   numeric(14,2) := round(p_amount, 2);
    v_avail numeric(14,2);
    v_id    integer;
    v_no    text;
    v_date  date := COALESCE(p_refunddate, (now() AT TIME ZONE 'utc')::date);
BEGIN
    IF v_amt IS NULL OR v_amt <= 0 THEN RAISE EXCEPTION 'Enter an amount greater than 0.' USING ERRCODE = 'P0001'; END IF;
    IF NULLIF(btrim(COALESCE(p_reason, '')), '') IS NULL THEN RAISE EXCEPTION 'Give a reason.' USING ERRCODE = 'P0001'; END IF;
    SELECT * INTO v_sp FROM watersupplierpayments sp
    WHERE  sp.watersupplierpaymentid = p_paymentid AND sp.farmid = p_farmid FOR UPDATE;
    IF NOT FOUND OR v_sp.supplierid IS NULL OR COALESCE(v_sp.status, 'Posted') <> 'Posted' THEN
        RAISE EXCEPTION 'That credit does not belong to this company.' USING ERRCODE = 'P0001';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM watercashaccounts a WHERE a.watercashaccountid = p_cashaccountid AND a.farmid = p_farmid) THEN
        RAISE EXCEPTION 'Choose the cash account the money came into.' USING ERRCODE = 'P0001';
    END IF;
    v_avail := public.fnwatersupplierpayment_unapplied(p_farmid, p_paymentid);
    IF v_amt > v_avail THEN RAISE EXCEPTION 'That credit only has % available.', v_avail USING ERRCODE = 'P0001'; END IF;
    PERFORM pg_advisory_xact_lock(hashtext('water-supplierrefundnumber:' || p_farmid));
    SELECT 'SR-' || lpad((COALESCE(MAX(NULLIF(regexp_replace(r.refundnumber, '\D', '', 'g'), '')::int), 0) + 1)::text, 4, '0')
    INTO   v_no FROM watersupplierrefunds r WHERE r.farmid = p_farmid;
    INSERT INTO watersupplierrefunds
        (farmid, refundnumber, supplierid, amount, refunddate, watercashaccountid, paymentmethod, reason, createdby)
    VALUES (p_farmid, v_no, v_sp.supplierid, v_amt, v_date, p_cashaccountid,
            COALESCE(NULLIF(btrim(p_paymentmethod), ''), 'Cash'), btrim(p_reason), p_by)
    RETURNING refundid INTO v_id;
    INSERT INTO watersupplierrefundlines (refundid, farmid, watersupplierpaymentid, amount)
    VALUES (v_id, p_farmid, p_paymentid, v_amt);
    INSERT INTO watercashtransactions
        (farmid, watercashaccountid, transactiondate, transactiontype, sourcetype, sourceid,
         amount, description, createdby, approvedby, approvedat)
    VALUES (p_farmid, p_cashaccountid, v_date::timestamp, 'CashIn', 'WaterSupplierRefund', v_id, v_amt,
            'Supplier refund ' || v_no, p_by, p_by, (now() AT TIME ZONE 'utc'));
    UPDATE watercashaccounts SET currentbalance = currentbalance + v_amt, updatedat = (now() AT TIME ZONE 'utc')
    WHERE  watercashaccountid = p_cashaccountid AND farmid = p_farmid;
    RETURN v_id;
END
$f$;

-- The refund stays (Reversed); its money goes back out; the credit comes back.
CREATE OR REPLACE FUNCTION public.spwatersupplierrefund_reverse(p_farmid text, p_refundid integer, p_reason text,
                                                                p_by text DEFAULT NULL)
RETURNS integer LANGUAGE plpgsql AS $f$
DECLARE v_r watersupplierrefunds%ROWTYPE; v_now timestamp := (now() AT TIME ZONE 'utc');
BEGIN
    IF NULLIF(btrim(COALESCE(p_reason, '')), '') IS NULL THEN RAISE EXCEPTION 'Give a reason.' USING ERRCODE = 'P0001'; END IF;
    SELECT * INTO v_r FROM watersupplierrefunds r WHERE r.refundid = p_refundid AND r.farmid = p_farmid FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'Refund not found for this company.' USING ERRCODE = 'P0001'; END IF;
    IF v_r.status <> 'Posted' THEN RAISE EXCEPTION 'This refund has already been reversed.' USING ERRCODE = 'P0001'; END IF;
    UPDATE watersupplierrefunds
    SET    status = 'Reversed', reversedby = p_by, reversedat = v_now, reversalreason = btrim(p_reason), reversaldate = v_now::date
    WHERE  refundid = p_refundid;
    INSERT INTO watercashtransactions
        (farmid, watercashaccountid, transactiondate, transactiontype, sourcetype, sourceid,
         amount, description, createdby, approvedby, approvedat)
    VALUES (p_farmid, v_r.watercashaccountid, v_now, 'CashOut', 'WaterSupplierRefund', p_refundid, -v_r.amount,
            'Reversal of supplier refund ' || v_r.refundnumber, p_by, p_by, v_now);
    UPDATE watercashaccounts SET currentbalance = currentbalance - v_r.amount, updatedat = v_now
    WHERE  watercashaccountid = v_r.watercashaccountid AND farmid = p_farmid;
    RETURN p_refundid;
END
$f$;

