CREATE OR REPLACE FUNCTION public.fnwaterpayables(p_farmid text)
 RETURNS TABLE(documenttype text, documentid integer, supplierid integer, docdate date, label text, reference text, totalcost numeric, amountpaid numeric, balance numeric, cashaccountid integer, duedate date)
 LANGUAGE sql
 STABLE
AS $function$
    SELECT 'RawMaterialPurchase'::text, pu.waterrawmaterialpurchaseid, pu.supplierid,
           pu.purchasedate::date,
           COALESCE(i.itemname, pu.suppliername, 'Raw material')::text,
           ('P' || pu.waterrawmaterialpurchaseid::text)::text,
           pu.totalcost, pu.amountpaid,
           GREATEST(pu.totalcost - pu.amountpaid, 0)::numeric(14,2),
           -- Always NULL: unlike poultryrawmaterialpurchases, the water table
           -- has no cash account column -- WaterRawMaterialPurchaseModel
           -- exposes one, but it is a projection, not storage.
           NULL::integer,
           NULL::date
    FROM   waterrawmaterialpurchases pu
    LEFT   JOIN waterrawmaterialitems i
           ON i.waterrawmaterialitemid = pu.waterrawmaterialitemid
    WHERE  pu.farmid = p_farmid
    UNION ALL
    SELECT 'Expense'::text, e.waterexpenseid, e.supplierid,
           e.expensedate::date,
           COALESCE(NULLIF(btrim(e.description), ''), c.name, 'Expense')::text,
           ('E' || e.waterexpenseid::text)::text,
           COALESCE(e.amount, 0)::numeric(14,2),
           COALESCE(e.amountpaid,
                    CASE WHEN COALESCE(e.paymentmethod, '') = 'Credit'
                         THEN 0 ELSE e.amount END)::numeric(14,2),
           GREATEST(COALESCE(e.amount, 0)
                    - COALESCE(e.amountpaid,
                               CASE WHEN COALESCE(e.paymentmethod, '') = 'Credit'
                                    THEN 0 ELSE e.amount END), 0)::numeric(14,2),
           e.watercashaccountid,
           e.duedate
    FROM   waterexpenses e
    LEFT   JOIN waterexpensecategories c
           ON c.waterexpensecategoryid = e.waterexpensecategoryid
    WHERE  lower(e.farmid::text) = lower(p_farmid)
      AND  e.supplierid IS NOT NULL
      AND  COALESCE(e.isdeleted, FALSE) = FALSE
      -- 047: only an approved expense has been recognised at all. A Draft is
      -- not yet a debt.
      AND  COALESCE(e.status, '') = 'Approved'
      -- 240: only bills a person typed in are payable; anything with a
      -- sourcetype is another document's shadow. 283 adds the one real
      -- exception -- a capital asset bought on credit is a debt to a supplier,
      -- not the shadow of another document, and neither of these two
      -- sourcetypes is ever generated BY a payment, so the recursion 240 was
      -- guarding against cannot return through here.
      AND  (e.sourcetype IS NULL
            OR e.sourcetype IN ('CapitalAsset', 'CapitalAssetCost'))
    UNION ALL
    -- 426: what the business owes a supplier without a purchase here
    SELECT 'SupplierDebt'::text, d.debtid, d.supplierid, d.debtdate,
           ('Debt ' || d.debtnumber || COALESCE(' - ' || NULLIF(btrim(d.description), ''), ''))::text,
           d.debtnumber::text, d.amount, d.amountpaid,
           GREATEST(d.amount - d.amountpaid, 0)::numeric(14,2),
           NULL::integer, NULL::date
    FROM   watersupplierdebts d
    WHERE  d.farmid = p_farmid AND d.status = 'Posted';
$function$;

CREATE OR REPLACE FUNCTION public.spwatersupplierpayment_record(p_farmid text, p_supplierid integer, p_amount numeric, p_allocations jsonb, p_paymentmethod text DEFAULT NULL::text, p_paymentdate timestamp without time zone DEFAULT NULL::timestamp without time zone, p_cashaccountid integer DEFAULT NULL::integer, p_reference text DEFAULT NULL::text, p_note text DEFAULT NULL::text, p_sourcetype text DEFAULT 'SupplierBalances'::text, p_createdby text DEFAULT NULL::text)
 RETURNS integer
 LANGUAGE plpgsql
AS $function$
DECLARE
    v_date      timestamp := COALESCE(p_paymentdate, (now() at time zone 'utc'));
    v_allocated numeric(14,2);
    v_count     integer;
    v_distinct  integer;
    v_minamount numeric(14,2);
    v_missing   integer;
    v_paymentid integer;
    v_row       record;
BEGIN
    IF p_amount IS NULL OR p_amount <= 0 THEN
        RAISE EXCEPTION 'Payment amount must be greater than 0.';
    END IF;
    IF p_supplierid IS NOT NULL
       AND NOT EXISTS (SELECT 1 FROM watersuppliers s
                       WHERE s.watersupplierid = p_supplierid AND s.farmid = p_farmid) THEN
        RAISE EXCEPTION 'Supplier does not belong to this company.';
    END IF;
    IF p_cashaccountid IS NOT NULL
       AND NOT EXISTS (SELECT 1 FROM watercashaccounts a
                       WHERE a.watercashaccountid = p_cashaccountid AND a.farmid = p_farmid) THEN
        RAISE EXCEPTION 'Cash account does not belong to this company.';
    END IF;

    SELECT COUNT(*), COUNT(DISTINCT (a.documenttype, a.documentid)),
           COALESCE(SUM(a.amount), 0), COALESCE(MIN(a.amount), 0)
    INTO   v_count, v_distinct, v_allocated, v_minamount
    FROM   jsonb_to_recordset(COALESCE(p_allocations, '[]'::jsonb))
           AS a(documenttype text, documentid integer, amount numeric)
    WHERE  a.documentid IS NOT NULL AND COALESCE(a.amount, 0) <> 0;

    IF v_distinct <> v_count THEN
        RAISE EXCEPTION 'The same item appears more than once in this payment.';
    END IF;
    IF v_count > 0 AND v_minamount <= 0 THEN
        RAISE EXCEPTION 'Each allocation must be greater than 0.';
    END IF;
    -- 426: what is not applied is the supplier's credit (an advance when nothing is).
    IF v_allocated::numeric(14,2) > p_amount::numeric(14,2) THEN
        RAISE EXCEPTION 'Allocated total (%) is more than the payment amount (%).',
              v_allocated::numeric(14,2), p_amount::numeric(14,2);
    END IF;
    IF v_allocated::numeric(14,2) < p_amount::numeric(14,2) AND p_supplierid IS NULL THEN
        RAISE EXCEPTION 'Choose the supplier -- money not applied to anything is kept as their credit.';
    END IF;

    SELECT COUNT(*) INTO v_missing
    FROM   jsonb_to_recordset(COALESCE(p_allocations, '[]'::jsonb))
           AS a(documenttype text, documentid integer, amount numeric)
    WHERE  a.documentid IS NOT NULL AND COALESCE(a.amount, 0) <> 0
      AND  NOT EXISTS (SELECT 1 FROM fnwaterpayables(p_farmid) d
                       WHERE d.documenttype = COALESCE(a.documenttype, 'RawMaterialPurchase')
                         AND d.documentid = a.documentid);
    IF v_missing > 0 THEN
        RAISE EXCEPTION '% of the selected items do not belong to this company.', v_missing;
    END IF;

    INSERT INTO watersupplierpayments
        (farmid, supplierid, paymentdate, totalamount, paymentmethod,
         watercashaccountid, referenceno, notes, sourcetype, status, createdby, createdat)
    VALUES
        (p_farmid, p_supplierid, v_date, p_amount::numeric(14,2), p_paymentmethod,
         p_cashaccountid, p_reference, p_note,
         COALESCE(p_sourcetype, 'SupplierBalances'), 'Posted', p_createdby,
         (now() at time zone 'utc'))
    RETURNING watersupplierpaymentid INTO v_paymentid;

    FOR v_row IN
        SELECT COALESCE(a.documenttype, 'RawMaterialPurchase') AS documenttype,
               a.documentid,
               a.amount::numeric(14,2) AS amount,
               d.balance, d.supplierid, d.docdate
        FROM   jsonb_to_recordset(COALESCE(p_allocations, '[]'::jsonb))
               AS a(documenttype text, documentid integer, amount numeric)
        JOIN   fnwaterpayables(p_farmid) d
               ON d.documenttype = COALESCE(a.documenttype, 'RawMaterialPurchase')
              AND d.documentid = a.documentid
        WHERE  a.documentid IS NOT NULL AND COALESCE(a.amount, 0) <> 0
        ORDER  BY d.docdate, a.documentid
    LOOP
        IF p_supplierid IS NOT NULL AND v_row.supplierid IS DISTINCT FROM p_supplierid THEN
            RAISE EXCEPTION '% #% does not belong to this supplier.',
                  v_row.documenttype, v_row.documentid;
        END IF;
        IF v_row.balance <= 0 THEN
            RAISE EXCEPTION '% #% is already fully paid.', v_row.documenttype, v_row.documentid;
        END IF;
        IF v_row.amount > v_row.balance THEN
            RAISE EXCEPTION 'Cannot apply % to % #% -- its balance is only %.',
                  v_row.amount, v_row.documenttype, v_row.documentid, v_row.balance;
        END IF;

        INSERT INTO supplierpaymentallocation
            (farmid, module, paymentid, documenttype, documentid, amountapplied,
             documentbalancebefore, documentbalanceafter, status, createdby, createdat)
        VALUES
            (p_farmid, 'water', v_paymentid, v_row.documenttype, v_row.documentid,
             v_row.amount, v_row.balance, v_row.balance - v_row.amount,
             'Posted', p_createdby, v_date);

        -- 426: purchases, bills and supplier debts
        PERFORM public.fnwaterpayable_addpaid(p_farmid, v_row.documenttype, v_row.documentid, v_row.amount);
    END LOOP;

    -- One expense for the purchase portion, cash for the whole payment.
    PERFORM spwatersupplierpaymentcash_sync(p_farmid, v_paymentid);

    RETURN v_paymentid;
END;
$function$;

CREATE OR REPLACE FUNCTION public.spwatersupplierpayment_reverse(p_farmid text, p_paymentid integer, p_reason text DEFAULT NULL::text, p_reversedby text DEFAULT NULL::text)
 RETURNS integer
 LANGUAGE plpgsql
AS $function$
DECLARE
    v_now   timestamp := (now() at time zone 'utc');
    v_count integer := 0;
    v_row   record;
BEGIN
    IF NOT EXISTS (SELECT 1 FROM watersupplierpayments sp
                   WHERE sp.watersupplierpaymentid = p_paymentid AND sp.farmid = p_farmid) THEN
        RAISE EXCEPTION 'Payment not found for this company.';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM watersupplierpayments sp
                   WHERE sp.watersupplierpaymentid = p_paymentid AND sp.farmid = p_farmid
                     AND COALESCE(sp.status, 'Posted') = 'Posted') THEN
        RAISE EXCEPTION 'This payment has already been reversed.';
    END IF;
    -- 426
    IF EXISTS (SELECT 1 FROM watersupplierpayments sp WHERE sp.watersupplierpaymentid = p_paymentid
               AND sp.farmid = p_farmid AND public.fnwatersupplier_iscreditkind(sp.sourcetype)) THEN
        RAISE EXCEPTION 'This is supplier credit added by hand -- reverse it on Supplier Credits.';
    END IF;
    IF EXISTS (SELECT 1 FROM supplierpaymentallocation sa WHERE sa.farmid = p_farmid AND sa.module = 'water'
               AND sa.paymentid = p_paymentid AND sa.status = 'Posted' AND sa.fromcredit) THEN
        RAISE EXCEPTION 'Credit from this payment has been applied since. Undo those applications first.';
    END IF;
    IF EXISTS (SELECT 1 FROM watersupplierrefundlines rl JOIN watersupplierrefunds r ON r.refundid = rl.refundid
               WHERE rl.farmid = p_farmid AND rl.watersupplierpaymentid = p_paymentid AND r.status = 'Posted') THEN
        RAISE EXCEPTION 'The supplier refunded part of this payment. Reverse the refund first.';
    END IF;

    FOR v_row IN
        SELECT sa.documenttype, sa.documentid, sa.amountapplied
        FROM   supplierpaymentallocation sa
        WHERE  sa.farmid = p_farmid AND sa.module = 'water'
          AND  sa.paymentid = p_paymentid AND sa.status = 'Posted'
    LOOP
        PERFORM public.fnwaterpayable_addpaid(p_farmid, v_row.documenttype, v_row.documentid, -v_row.amountapplied);   -- 426
        v_count := v_count + 1;
    END LOOP;

    UPDATE supplierpaymentallocation
    SET    status = 'Reversed', reversedby = p_reversedby, reversedat = v_now,
           reversalreason = p_reason
    WHERE  farmid = p_farmid AND module = 'water'
      AND  paymentid = p_paymentid AND status = 'Posted';

    -- Cash before the header flips, since the sync reads a Posted header.
    PERFORM spwatersupplierpaymentcash_unsync(p_farmid, p_paymentid, p_reversedby);

    UPDATE watersupplierpayments
    SET    status = 'Reversed', reversedby = p_reversedby, reversedat = v_now,
           reversalreason = p_reason
    WHERE  watersupplierpaymentid = p_paymentid AND farmid = p_farmid;

    RETURN v_count;
END;
$function$;

CREATE OR REPLACE FUNCTION public.spwatersupplierpaymentcash_sync(p_farmid text, p_paymentid integer)
 RETURNS void
 LANGUAGE plpgsql
AS $function$
DECLARE
    v_pay      record;
    v_catid    integer;
    v_acct     integer;
    v_docs     text;
    v_expense  integer;
    v_party    text;
    v_purchase numeric(14,2);
    v_bills    numeric(14,2);
    v_purchaseexpensed numeric(14,2);        -- 275
    v_alldocs  text;                         -- 275
BEGIN
    SELECT sp.watersupplierpaymentid, sp.supplierid, sp.paymentdate, sp.totalamount,
           sp.paymentmethod, sp.watercashaccountid, sp.createdby, sp.notes
    INTO   v_pay
    FROM   watersupplierpayments sp
    WHERE  sp.watersupplierpaymentid = p_paymentid AND sp.farmid = p_farmid
      AND  COALESCE(sp.status, 'Posted') = 'Posted';

    IF v_pay.watersupplierpaymentid IS NULL THEN RETURN; END IF;
    -- 426: credit added by hand moves no money.
    IF EXISTS (SELECT 1 FROM watersupplierpayments sp WHERE sp.watersupplierpaymentid = p_paymentid
               AND sp.farmid = p_farmid AND public.fnwatersupplier_iscreditkind(sp.sourcetype)) THEN
        RETURN;
    END IF;

    SELECT COALESCE(SUM(sa.amountapplied) FILTER (WHERE sa.documenttype NOT IN ('Expense', 'SupplierDebt')), 0),
           COALESCE(SUM(sa.amountapplied) FILTER (WHERE sa.documenttype = 'Expense'), 0),
           -- 275. The deferred split.
           COALESCE(SUM(sa.amountapplied) FILTER (
               WHERE sa.documenttype NOT IN ('Expense', 'SupplierDebt')
                 AND fnwatercostrecognition_expenseatpurchase(
                         COALESCE(pu.costrecognitionmethod, 'EXPENSE_WHEN_PURCHASED'))
           ), 0)
    INTO   v_purchase, v_bills, v_purchaseexpensed
    FROM   supplierpaymentallocation sa
    LEFT   JOIN waterrawmaterialpurchases pu                                  -- 275
           ON  pu.waterrawmaterialpurchaseid = sa.documentid
           AND pu.farmid = sa.farmid
           AND sa.documenttype NOT IN ('Expense', 'SupplierDebt')
    WHERE  sa.farmid = p_farmid AND sa.module = 'water'
      AND  sa.paymentid = p_paymentid AND sa.status = 'Posted';

    -- 275. Every purchase document this payment settled, deferred or not. The
    -- CASH row is described with this, because the supplier was paid for all of
    -- them. v_docs below is the narrower list -- only the ones whose cost
    -- actually reached the P&L -- and describes the EXPENSE row.
    --
    -- For a payment with nothing deferred the two lists are identical, which is
    -- what keeps an unchanged payment's cash description byte-for-byte what it
    -- was.
    SELECT string_agg('#' || sa.documentid::text, ', ' ORDER BY sa.documentid)
    INTO   v_alldocs
    FROM   supplierpaymentallocation sa
    WHERE  sa.farmid = p_farmid AND sa.module = 'water'
      AND  sa.paymentid = p_paymentid AND sa.status = 'Posted'
      AND  sa.documenttype NOT IN ('Expense', 'SupplierDebt');

    -- The account the user chose, else the farm's first active one -- the same
    -- fallback 091 used, so behaviour is unchanged when no account is passed.
    v_acct := v_pay.watercashaccountid;
    IF v_acct IS NULL THEN
        SELECT a.watercashaccountid INTO v_acct
        FROM   watercashaccounts a
        WHERE  a.farmid = p_farmid AND a.isactive = TRUE
        ORDER  BY a.watercashaccountid
        LIMIT  1;
    END IF;

    SELECT s.suppliername INTO v_party
    FROM   watersuppliers s
    WHERE  s.watersupplierid = v_pay.supplierid AND s.farmid = p_farmid;

    -- ---- the purchase portion: expense row + its cash, exactly as before ----
    -- 275. Gated on the EXPENSED portion, not the whole. When every allocation
    -- on this payment is deferred, v_purchaseexpensed is 0, no expense row is
    -- written, and the cash for the payment still moves in the block below --
    -- which is now keyed to v_purchase, the full amount, as it always was.
    IF v_purchaseexpensed > 0 THEN
        -- Ensure the category exists, inline rather than through
        -- spwaterexpensecategory_ensurerawmaterialpurchase (068). Same category
        -- name, so an expense booked here lands where every other raw-material
        -- purchase expense already does.
        SELECT ec.waterexpensecategoryid INTO v_catid
        FROM   waterexpensecategories ec
        WHERE  ec.farmid = p_farmid
          AND  ec.name = 'Raw Materials / Inventory Purchase'
          AND  COALESCE(ec.isdeleted, FALSE) = FALSE
        LIMIT  1;

        IF v_catid IS NULL THEN
            INSERT INTO waterexpensecategories (farmid, name, isactive, isdeleted)
            VALUES (p_farmid, 'Raw Materials / Inventory Purchase', TRUE, FALSE)
            RETURNING waterexpensecategoryid INTO v_catid;
        END IF;

        -- 275. Only the documents this expense actually covers. Listing a
        -- deferred purchase in the description of an expense that excludes its
        -- value is how a reconciliation goes wrong at 11pm.
        SELECT string_agg('#' || sa.documentid::text, ', ' ORDER BY sa.documentid)
        INTO   v_docs
        FROM   supplierpaymentallocation sa
        LEFT   JOIN waterrawmaterialpurchases pu
               ON  pu.waterrawmaterialpurchaseid = sa.documentid
               AND pu.farmid = sa.farmid
        WHERE  sa.farmid = p_farmid AND sa.module = 'water'
          AND  sa.paymentid = p_paymentid AND sa.status = 'Posted'
          AND  sa.documenttype NOT IN ('Expense', 'SupplierDebt')
          AND  fnwatercostrecognition_expenseatpurchase(
                   COALESCE(pu.costrecognitionmethod, 'EXPENSE_WHEN_PURCHASED'));

        INSERT INTO waterexpenses
            (farmid, expensedate, waterexpensecategoryid, description, amount, paidto,
             paymentmethod, watercashaccountid, linkedwaterproductionbatchid,
             status, notes, createdby, approvedby, approvedat,
             supplierid, sourcetype, sourceid)
        VALUES
            (p_farmid, v_pay.paymentdate, v_catid,
             'Supplier payment for raw material purchase ' || COALESCE(v_docs, ''),
             v_purchaseexpensed, v_party,                                     -- 275
             COALESCE(NULLIF(btrim(v_pay.paymentmethod), ''), 'Cash'),
             v_acct, NULL,
             'Approved',
             'Auto-created from a supplier payment.',
             v_pay.createdby, v_pay.createdby, (now() at time zone 'utc'),
             v_pay.supplierid, 'WaterSupplierPayment', p_paymentid)
        RETURNING waterexpenseid INTO v_expense;
    END IF;

    -- ---- the cash for the purchase portion: the FULL amount ----------------
    -- 275. Lifted out of the expense block above and keyed to v_purchase, not
    -- v_purchaseexpensed. The supplier was paid every cedi of it whether or not
    -- the cost has reached the P&L, so the cash account and the cash-flow
    -- statement must show every cedi.
    --
    -- sourcetype/sourceid stay 'Expense'/v_expense when there IS an expense, so
    -- an unchanged payment produces a byte-identical cash row. When the whole
    -- portion is deferred there is no expense to hang it off, and the row is
    -- keyed to the payment itself -- the same shape the bill portion below has
    -- always used.
    IF v_purchase > 0 AND v_acct IS NOT NULL THEN
        INSERT INTO watercashtransactions
            (farmid, watercashaccountid, transactiondate, transactiontype,
             sourcetype, sourceid, amount, description, createdby, approvedby, approvedat)
        VALUES
            (p_farmid, v_acct, v_pay.paymentdate, 'CashOut',
             CASE WHEN v_expense IS NOT NULL THEN 'Expense' ELSE 'WaterSupplierPayment' END,
             COALESCE(v_expense, p_paymentid), -v_purchase,
             'Supplier payment — raw material purchase ' || COALESCE(v_alldocs, ''),
             v_pay.createdby, v_pay.createdby, (now() at time zone 'utc'));

        UPDATE watercashaccounts
        SET    currentbalance = currentbalance - v_purchase,
               updatedat = (now() at time zone 'utc')
        WHERE  watercashaccountid = v_acct AND farmid = p_farmid;
    END IF;

    -- ---- 426: supplier debts and the part applied to nothing (an advance) --
    -- Money out on the payment date, keyed to the payment like the bill part,
    -- so the reversal (_unsync's bill half) gives it back too.
    IF v_pay.totalamount - v_purchase - v_bills > 0 AND v_acct IS NOT NULL THEN
        INSERT INTO watercashtransactions
            (farmid, watercashaccountid, transactiondate, transactiontype,
             sourcetype, sourceid, amount, description, createdby, approvedby, approvedat)
        VALUES
            (p_farmid, v_acct, v_pay.paymentdate, 'CashOut',
             'WaterSupplierPayment', p_paymentid, -(v_pay.totalamount - v_purchase - v_bills),
             'Supplier payment - debts / advance', v_pay.createdby, v_pay.createdby,
             (now() at time zone 'utc'));
        UPDATE watercashaccounts
        SET    currentbalance = currentbalance - (v_pay.totalamount - v_purchase - v_bills),
               updatedat = (now() at time zone 'utc')
        WHERE  watercashaccountid = v_acct AND farmid = p_farmid;
    END IF;

    -- ---- the bill portion: cash only, keyed to the payment ------------------
    IF v_bills > 0 AND v_acct IS NOT NULL THEN
        INSERT INTO watercashtransactions
            (farmid, watercashaccountid, transactiondate, transactiontype,
             sourcetype, sourceid, amount, description, createdby, approvedby, approvedat)
        VALUES
            (p_farmid, v_acct, v_pay.paymentdate, 'CashOut',
             'WaterSupplierPayment', p_paymentid, -v_bills,
             'Supplier payment — expenses', v_pay.createdby, v_pay.createdby,
             (now() at time zone 'utc'));

        UPDATE watercashaccounts
        SET    currentbalance = currentbalance - v_bills,
               updatedat = (now() at time zone 'utc')
        WHERE  watercashaccountid = v_acct AND farmid = p_farmid;
    END IF;
END;
$function$;

CREATE OR REPLACE FUNCTION public.spwatercashflow_rows(p_farmid text, p_fromdate timestamp without time zone DEFAULT NULL::timestamp without time zone, p_todate timestamp without time zone DEFAULT NULL::timestamp without time zone)
 RETURNS TABLE(rowsource text, offledger boolean, sourcerowid integer, cashaccountid integer, accountname text, transactiondate timestamp without time zone, transactiontype text, sourcetype text, sourceid integer, istransfer boolean, amount numeric, description text, flowgroup text, createdat timestamp without time zone)
 LANGUAGE plpgsql
 STABLE
AS $function$

DECLARE

    v_tbl  text;
    v_createdcol text;               -- 302: 'ca.createddate' or NULL

    v_from timestamp := COALESCE(p_fromdate, '-infinity'::timestamp);

    v_to   timestamp := COALESCE(p_todate,   'infinity'::timestamp);

BEGIN

    -- ---- 1. customer receipts, dated when the money arrived -----------------

    RETURN QUERY

    SELECT 'Receipt'::text,

           FALSE,

           p.waterpaymentid,

           NULL::integer,

           NULL::text,

           p.paymentdate,

           'CashIn'::text,

           'CustomerPayment'::text,

           p.watersaleid,

           FALSE,

           COALESCE(p.amount, 0)::numeric,

           COALESCE(NULLIF(btrim(p.note), ''),

                    NULLIF(btrim(p.reference), ''),

                    'Payment for sale #' || p.watersaleid::text)::text,

           'OperatingIn'::text

           , p.createddate   -- 302: the entry time
    FROM   waterpayments p

    WHERE  lower(p.farmid::text) = lower(p_farmid)

      AND  COALESCE(p.amount, 0) <> 0

      -- A REVERSED payment is money that came back. 227 added this column and

      -- flips it on reversal rather than deleting the row, so without this filter

      -- the report counts a refunded receipt as income for ever.

      AND  COALESCE(p.status, 'Posted') = 'Posted'

      -- 424: opening credit and credit notes are credit, not money received.
      AND  NOT public.fnwater_isnocashcredit(p.sourcetype)

      AND  p.paymentdate >= v_from

      AND  p.paymentdate <= v_to;



    -- ---- 1b. 424: customer refunds -----------------------------------------
    -- Money out on the refund date, and it stays there when the refund is
    -- reversed (the money did leave); the reversal is money back in on its date.
    RETURN QUERY
    SELECT 'CustomerRefund'::text, FALSE, r.refundid, r.watercashaccountid, NULL::text,
           r.refunddate::timestamp, 'CashOut'::text, 'WaterCustomerRefund'::text, r.refundid, FALSE,
           -r.amount, ('Customer refund ' || r.refundnumber ||
                       COALESCE(' - ' || NULLIF(btrim(c.name), ''), ''))::text,
           'OperatingOut'::text, r.createdat
    FROM   watercustomerrefunds r
    LEFT   JOIN watercustomers c ON c.watercustomerid = r.watercustomerid AND c.farmid = r.farmid
    WHERE  r.farmid = p_farmid AND r.status IN ('Posted', 'Reversed')
      AND  r.refunddate::timestamp >= v_from AND r.refunddate::timestamp <= v_to;

    RETURN QUERY
    SELECT 'CustomerRefundReversal'::text, FALSE, r.refundid, r.watercashaccountid, NULL::text,
           r.reversedat, 'CashIn'::text, 'WaterCustomerRefund'::text, r.refundid, FALSE,
           r.amount, ('Reversal of customer refund ' || r.refundnumber)::text,
           'OperatingIn'::text, r.reversedat
    FROM   watercustomerrefunds r
    WHERE  r.farmid = p_farmid AND r.status = 'Reversed' AND r.reversedat IS NOT NULL
      AND  r.reversedat >= v_from AND r.reversedat <= v_to;

    -- ---- 2. the part paid at the point of sale -----------------------------

    -- Same reasoning as 235: a sale settled on the spot may never create a

    -- payment row, and the difference is what picks those up.

    RETURN QUERY

    SELECT 'SaleResidual'::text,

           FALSE,

           s.watersaleid,

           NULL::integer,

           NULL::text,

           s.saledate,

           'CashIn'::text,

           'Sale'::text,

           s.watersaleid,

           FALSE,

           v.residual,

           ('Sale #' || s.watersaleid::text)::text,

           'OperatingIn'::text

           , s.createddate   -- 302: the entry time
    FROM   watersales s

    CROSS  JOIN LATERAL (

        SELECT ROUND(

                   CASE WHEN COALESCE(s.status, '') = 'Paid'

                        THEN COALESCE(s.totalamount, 0)

                        ELSE LEAST(GREATEST(COALESCE(s.amountpaid, 0), 0),

                                   COALESCE(s.totalamount, 0))

                   END

                 - COALESCE((SELECT SUM(wp.amount)

                             FROM   waterpayments wp

                             WHERE  wp.watersaleid = s.watersaleid

                               AND  lower(wp.farmid::text) = lower(p_farmid)

                               -- Same reason: a reversed payment never covered

                               -- anything, so it must not reduce the residual.

                               AND  COALESCE(wp.status, 'Posted') = 'Posted'), 0)
                 -- 424: credit applied to the sale is not money taken at the till
                 - public.fnwatersale_creditapplied(p_farmid, s.watersaleid)

               , 2) AS residual

    ) v

    WHERE  lower(s.farmid::text) = lower(p_farmid)

      -- A cancelled sale is not income, whatever it once recorded as paid.

      AND  COALESCE(s.status, '') <> 'Cancelled'

      AND  v.residual > 0

      AND  s.saledate >= v_from

      AND  s.saledate <= v_to;



    -- ---- 3. money paid out when the bill was recorded -----------------------

    -- 236's gates are kept verbatim -- Approved, not deleted -- with two

    -- changes:

    --

    --   * the AMOUNT is what was actually paid at entry, not the whole bill:

    --     the resolved amountpaid, less anything a supplier payment has since

    --     covered (which the next arm reports on its own, later, date);

    --   * the `paymentmethod <> 'Credit'` filter is GONE, because the resolution

    --     subsumes it. A Credit bill resolves to 0 paid and drops out on

    --     `paidatentry > 0` instead -- same rows excluded, and a Credit bill

    --     that has since been part-paid is no longer wrongly invisible.

    RETURN QUERY

    SELECT 'Expense'::text,

           FALSE,

           e.waterexpenseid,

           e.watercashaccountid,

           NULL::text,

           e.expensedate,

           'CashOut'::text,

           'Expense'::text,

           e.waterexpenseid,

           FALSE,

           -v.paidatentry,

           COALESCE(NULLIF(btrim(e.description), ''),

                    NULLIF(btrim(e.paidto), ''),

                    'Expense #' || e.waterexpenseid::text)::text,

           'OperatingOut'::text

           , e.createdat   -- 302: the entry time
    FROM   waterexpenses e

    CROSS  JOIN LATERAL (

        SELECT GREATEST(

                   COALESCE(e.amountpaid,

                            CASE WHEN COALESCE(e.paymentmethod, '') = 'Credit'

                                 THEN 0 ELSE e.amount END)

                 - COALESCE((SELECT SUM(sa.amountapplied)

                             FROM   supplierpaymentallocation sa

                             WHERE  sa.farmid = p_farmid

                               AND  sa.module = 'water'

                               AND  sa.status = 'Posted'

                               AND  sa.documenttype = 'Expense'

                               AND  sa.documentid = e.waterexpenseid), 0)

               , 0)::numeric AS paidatentry

    ) v

    WHERE  lower(e.farmid::text) = lower(p_farmid)

      AND  COALESCE(e.isdeleted, false) = false

      AND  v.paidatentry > 0

      -- 047's rule: only an approved expense has been recognised at all.

      AND  COALESCE(e.status, '') = 'Approved'

      -- 259. 'NonCash' means "a cost recorded, but the money moved elsewhere".

      -- Loan interest and fees are written this way: the repayment's own arm

      -- below reports the FULL amount that left the account, so counting these

      -- rows here as well would take 12,500 out of the bank and 15,000 off the

      -- cash flow. Expense reports do not filter NonCash, so the cost still

      -- counts where it should.

      --

      -- No-op on today's data: there are zero water expenses with this marker.

      AND  COALESCE(e.paymentmethod, '') <> 'NonCash'

      -- 423: a supplier payment's own aggregated expense row is not read here.
      -- It holds only the part expensed at purchase and is Cancelled on
      -- reversal; the payment's cash is reported from the payment below (3c).
      AND  COALESCE(e.sourcetype, '') <> 'WaterSupplierPayment'

      AND  e.expensedate >= v_from

      AND  e.expensedate <= v_to;



    -- ---- 3b. money paid out later, against a bill already recorded ----------

    -- A supplier payment settling a bill. It belongs to the day the money moved,

    -- not the day the bill was entered.

    --

    -- Only documenttype='Expense'. A payment against a raw-material purchase

    -- books its own aggregated expense row dated the payment date (240) and is

    -- already counted by arm 3; adding it here would double it.

    RETURN QUERY

    SELECT 'ExpensePayment'::text,

           FALSE,

           sa.allocationid,

           sp.watercashaccountid,

           NULL::text,

           sp.paymentdate,

           'CashOut'::text,

           'ExpensePayment'::text,

           sa.documentid,

           FALSE,

           -sa.amountapplied::numeric,

           ('Payment for expense #' || sa.documentid::text ||

            COALESCE(' - ' || NULLIF(btrim(s.suppliername), ''), ''))::text,

           'OperatingOut'::text

           , sa.createdat   -- 302: the entry time
    FROM   supplierpaymentallocation sa

    JOIN   watersupplierpayments sp

           ON  sp.watersupplierpaymentid = sa.paymentid

           AND sp.farmid = sa.farmid

    LEFT   JOIN watersuppliers s

           ON  s.watersupplierid = sp.supplierid AND s.farmid = sp.farmid

    WHERE  sa.farmid = p_farmid

      AND  sa.module = 'water'

      -- 423: a reversed payment's money still LEFT on its date (376's rule);
      -- the reversal brings it back on its own date (3d). Allocations are only
      -- ever reversed together with their payment.
      AND  (sa.status = 'Posted' OR (sa.status = 'Reversed' AND sp.status = 'Reversed'))

      AND  NOT sa.fromcredit                                -- 426

      AND  sa.documenttype = 'Expense'

      AND  COALESCE(sp.status, 'Posted') IN ('Posted', 'Reversed')

      AND  sa.amountapplied <> 0

      AND  sp.paymentdate >= v_from

      AND  sp.paymentdate <= v_to;



    -- ---- 3c. 423: supplier payments for raw-material purchases ------------
    --
    -- The FULL purchase portion, on the payment date -- deferred lots included,
    -- because the supplier was paid for them whether or not their cost has
    -- reached the P&L (275). Reversed payments stay: the money did leave.
    RETURN QUERY
    SELECT 'SupplierPurchasePayment'::text,
           FALSE,
           sp.watersupplierpaymentid,
           sp.watercashaccountid,
           NULL::text,
           sp.paymentdate,
           'CashOut'::text,
           'WaterSupplierPayment'::text,
           sp.watersupplierpaymentid,
           FALSE,
           -x.amount,
           ('Supplier payment - raw material purchase' ||
            COALESCE(' - ' || NULLIF(btrim(s.suppliername), ''), ''))::text,
           'OperatingOut'::text,
           sp.createdat
    FROM   watersupplierpayments sp
    CROSS  JOIN LATERAL (
        SELECT COALESCE(SUM(sa.amountapplied), 0)::numeric AS amount
        FROM   supplierpaymentallocation sa
        WHERE  sa.farmid = sp.farmid AND sa.module = 'water'
          AND  sa.paymentid = sp.watersupplierpaymentid
          AND  sa.documenttype NOT IN ('Expense', 'SupplierDebt')     -- 426
          AND  NOT sa.fromcredit                                     -- 426
          AND  (sa.status = 'Posted' OR (sa.status = 'Reversed' AND sp.status = 'Reversed'))
    ) x
    LEFT   JOIN watersuppliers s
           ON  s.watersupplierid = sp.supplierid AND s.farmid = sp.farmid
    WHERE  sp.farmid = p_farmid
      AND  COALESCE(sp.status, 'Posted') IN ('Posted', 'Reversed')
      AND  x.amount <> 0
      AND  sp.paymentdate >= v_from
      AND  sp.paymentdate <= v_to;

    -- ---- 3d. 423: a reversed supplier payment's money coming back ---------
    --
    -- Everything the payment paid out (purchases and bills), back in on the
    -- day it was reversed.
    RETURN QUERY
    SELECT 'SupplierPaymentReversal'::text,
           FALSE,
           sp.watersupplierpaymentid,
           sp.watercashaccountid,
           NULL::text,
           sp.reversedat,
           'CashIn'::text,
           'WaterSupplierPayment'::text,
           sp.watersupplierpaymentid,
           FALSE,
           x.amount,
           ('Reversal of supplier payment #' || sp.watersupplierpaymentid::text ||
            COALESCE(' - ' || NULLIF(btrim(s.suppliername), ''), ''))::text,
           'OperatingIn'::text,
           sp.reversedat
    FROM   watersupplierpayments sp
    CROSS  JOIN LATERAL (
        -- 426: the whole payment (an advance has no allocations at all)
        SELECT sp.totalamount::numeric AS amount
    ) x
    LEFT   JOIN watersuppliers s
           ON  s.watersupplierid = sp.supplierid AND s.farmid = sp.farmid
    WHERE  sp.farmid = p_farmid
      AND  sp.status = 'Reversed'
      AND  NOT public.fnwatersupplier_iscreditkind(sp.sourcetype)   -- 426
      AND  sp.reversedat IS NOT NULL
      AND  x.amount <> 0
      AND  sp.reversedat >= v_from
      AND  sp.reversedat <= v_to;

    -- ---- 3e. 426: supplier debts and advances --------------------------------
    -- The part of a payment no other row shows: what it paid on supplier debts
    -- and what it applied to nothing (an advance / overpayment), on the
    -- payment's own day. With 3b and 3c a payment always totals its amount.
    RETURN QUERY
    SELECT 'SupplierAdvanceOrDebt'::text, FALSE, sp.watersupplierpaymentid, sp.watercashaccountid, NULL::text,
           sp.paymentdate, 'CashOut'::text, 'WaterSupplierPayment'::text, sp.watersupplierpaymentid, FALSE,
           -x.amount,
           ('Supplier payment - debts / advance' || COALESCE(' - ' || NULLIF(btrim(s.suppliername), ''), ''))::text,
           'OperatingOut'::text, sp.createdat
    FROM   watersupplierpayments sp
    CROSS  JOIN LATERAL (
        SELECT sp.totalamount - COALESCE(SUM(sa.amountapplied), 0)::numeric AS amount
        FROM   supplierpaymentallocation sa
        WHERE  sa.farmid = sp.farmid AND sa.module = 'water'
          AND  sa.paymentid = sp.watersupplierpaymentid
          AND  sa.documenttype IN ('RawMaterialPurchase', 'Expense')
          AND  NOT sa.fromcredit
          AND  (sa.status = 'Posted' OR (sa.status = 'Reversed' AND sp.status = 'Reversed'))
    ) x
    LEFT   JOIN watersuppliers s ON s.watersupplierid = sp.supplierid AND s.farmid = sp.farmid
    WHERE  sp.farmid = p_farmid
      AND  COALESCE(sp.status, 'Posted') IN ('Posted', 'Reversed')
      AND  NOT public.fnwatersupplier_iscreditkind(sp.sourcetype)
      AND  x.amount > 0
      AND  sp.paymentdate >= v_from AND sp.paymentdate <= v_to;

    -- ---- 3g / 3h. 426: supplier refunds ---------------------------------------
    RETURN QUERY
    SELECT 'SupplierRefund'::text, FALSE, r.refundid, r.watercashaccountid, NULL::text,
           r.refunddate::timestamp, 'CashIn'::text, 'WaterSupplierRefund'::text, r.refundid, FALSE,
           r.amount, ('Supplier refund ' || r.refundnumber || COALESCE(' - ' || NULLIF(btrim(s.suppliername), ''), ''))::text,
           'OperatingIn'::text, r.createdat
    FROM   watersupplierrefunds r
    LEFT   JOIN watersuppliers s ON s.watersupplierid = r.supplierid AND s.farmid = r.farmid
    WHERE  r.farmid = p_farmid AND r.status IN ('Posted', 'Reversed')
      AND  r.refunddate::timestamp >= v_from AND r.refunddate::timestamp <= v_to;

    RETURN QUERY
    SELECT 'SupplierRefundReversal'::text, FALSE, r.refundid, r.watercashaccountid, NULL::text,
           r.reversedat, 'CashOut'::text, 'WaterSupplierRefund'::text, r.refundid, FALSE,
           -r.amount, ('Reversal of supplier refund ' || r.refundnumber)::text,
           'OperatingOut'::text, r.reversedat
    FROM   watersupplierrefunds r
    WHERE  r.farmid = p_farmid AND r.status = 'Reversed' AND r.reversedat IS NOT NULL
      AND  r.reversedat >= v_from AND r.reversedat <= v_to;

    -- ---- 4. owner money (258) ----------------------------------------------

    -- Contributions and draws recorded through the Owner Money module.

    -- FINANCING, not operating: the owner funded the business or took funding

    -- back. Never revenue, never expense.

    --

    -- Reversed records are dropped entirely rather than netted to zero with a

    -- second row -- a contribution that was put in and taken back out is not

    -- funding, and showing both legs would put money the business never kept

    -- into Money In and Money Out.

    --

    -- Placed ABOVE the legacy capital arm on purpose: that arm RETURNs early

    -- when cashadjustment is absent, so anything below it is skipped on a

    -- company with no capital records.

    RETURN QUERY

    SELECT 'OwnerMoney'::text,

           FALSE,

           o.waterownermoneyid,

           o.watercashaccountid,

           a.accountname::text,

           o.transactiondate,

           CASE WHEN o.transactiontype = 'Contribution' THEN 'CashIn' ELSE 'CashOut' END::text,

           CASE WHEN o.transactiontype = 'Contribution' THEN 'OwnerContribution' ELSE 'OwnerDraw' END::text,

           o.waterownermoneyid,

           FALSE,

           -- Stored positive; the sign is applied here, once.

           (CASE WHEN o.transactiontype = 'Contribution' THEN o.amount ELSE -o.amount END)::numeric,

           COALESCE(NULLIF(btrim(o.notes), ''),

                    NULLIF(btrim(o.ownername), ''),

                    CASE WHEN o.transactiontype = 'Contribution'

                         THEN 'Owner contribution' ELSE 'Owner draw' END)::text,

           CASE WHEN o.transactiontype = 'Contribution' THEN 'FinancingIn' ELSE 'FinancingOut' END::text

           , o.createdat   -- 302: the entry time
    FROM   waterownermoney o

    LEFT   JOIN watercashaccounts a

           ON a.watercashaccountid = o.watercashaccountid

    WHERE  o.farmid = p_farmid

      AND  o.status = 'Posted'
      -- 297. A record backfilled from a Cash Flow adjustment has NO cash
      -- row of its own: the ADJUSTMENT is still the cash event, and the
      -- legacy adjustment arm below already reports it. Without this the
      -- same money is counted twice -- the trap 292 hit for loans.
      AND  o.sourceadjustmentid IS NULL

      AND  o.transactiondate >= v_from

      AND  o.transactiondate <= v_to;



    -- ---- 5. loans received (259) -------------------------------------------

    -- Borrowed money arriving. FINANCING: the business received it, it did not

    -- earn it, so it is money in and never revenue.

    --

    -- The AMOUNT RECEIVED, not the principal. A lender that withholds a fee

    -- pays out less than it lends, and only what arrived is cash in.

    --

    -- The timestamp carries 256's rule, baked in from the start rather than

    -- patched afterwards as it had to be on poultry: loandate is a DATE, so a

    -- plain cast gives midnight and a loan recorded this afternoon sorts below

    -- everything else recorded today. A loan dated TODAY reports the moment it

    -- was recorded; a BACK-DATED one keeps midnight, because using createdat

    -- unconditionally would drag last Tuesday's loan into today, above rows

    -- that really did happen after it.

    RETURN QUERY

    SELECT 'Loan'::text,

           FALSE,

           l.waterloanid,

           l.watercashaccountid,

           a.accountname::text,

           CASE WHEN l.loandate = l.createdat::date THEN l.createdat

                ELSE l.loandate::timestamp END,

           'CashIn'::text,

           'LoanReceived'::text,

           l.waterloanid,

           FALSE,

           l.amountreceived::numeric,

           ('Loan received from ' || l.lendername)::text,

           'FinancingIn'::text

           , l.createdat   -- 302: the entry time
    FROM   waterloans l

    LEFT   JOIN watercashaccounts a ON a.watercashaccountid = l.watercashaccountid

    WHERE  l.farmid = p_farmid

      AND  l.amountreceived > 0

      -- 293. A loan converted from a Cash Flow adjustment has NO cash row of

      -- its own: the ADJUSTMENT is the cash event, and the legacy adjustment arm

      -- already reports it. Without this the same borrowing is money-in twice --

      -- which is precisely what 292's stage check caught on the poultry side.

      AND  l.sourceadjustmentid IS NULL

      AND  l.status NOT IN ('Cancelled', 'Reversed', 'Draft')

      AND  (CASE WHEN l.loandate = l.createdat::date THEN l.createdat

                 ELSE l.loandate::timestamp END) >= v_from

      AND  (CASE WHEN l.loandate = l.createdat::date THEN l.createdat

                 ELSE l.loandate::timestamp END) <= v_to;



    -- ---- 6. loan repayments (259) ------------------------------------------

    -- The FULL payment leaves the account, so the full payment is money out --

    -- principal, interest and fees together.

    --

    -- This does NOT double count the interest and fee expenses those payments

    -- create: they are written paymentmethod = 'NonCash', and arm 3 above now

    -- skips NonCash. Expense reports read the expense table directly and still

    -- count them, which is the whole point -- cash out is 12,500, cost is 2,500.

    RETURN QUERY

    SELECT 'LoanPayment'::text,

           FALSE,

           p.waterloanpaymentid,

           p.watercashaccountid,

           a.accountname::text,

           p.paymentdate,

           'CashOut'::text,

           'LoanRepayment'::text,

           p.waterloanid,

           FALSE,

           -p.totalamount::numeric,

           ('Loan repayment to ' || l.lendername)::text,

           'FinancingOut'::text

           , p.createdat   -- 302: the entry time
    FROM   waterloanpayments p

    JOIN   waterloans l ON l.waterloanid = p.waterloanid

    LEFT   JOIN watercashaccounts a ON a.watercashaccountid = p.watercashaccountid

    WHERE  p.farmid = p_farmid

      AND  p.status = 'Posted'

      AND  p.paymentdate >= v_from

      AND  p.paymentdate <= v_to;



    -- ---- 7. capital in and out (legacy cash adjustments) --------------------

    -- Expected to return nothing on Water today -- see 236's header note.

    --

    -- MUST STAY LAST: it RETURNs early when the table is absent, and anything

    -- below it would be silently skipped.

    v_tbl := COALESCE(to_regclass('public.cashadjustment')::text,

                      to_regclass('public.cashadjustments')::text);



    -- 302: only reference the creation column if the resolved table has one.
    SELECT CASE WHEN EXISTS (
               SELECT 1 FROM information_schema.columns c
               WHERE  c.table_schema = 'public'
                 AND  c.table_name = replace(v_tbl, 'public.', '')
                 AND  c.column_name = 'createddate')
           THEN 'ca.createddate' ELSE 'NULL::timestamp' END
      INTO v_createdcol;

    IF v_tbl IS NULL THEN

        RETURN;

    END IF;



    RETURN QUERY EXECUTE format($sql$

        SELECT 'Adjustment'::text,

               FALSE,

               ca.adjustmentid,

               NULL::integer,

               NULL::text,

               ca.adjustmentdate,

               CASE WHEN ca.amount >= 0 THEN 'CashIn' ELSE 'CashOut' END::text,

               COALESCE(NULLIF(btrim(ca.adjustmenttype), ''), 'Adjustment')::text,

               ca.adjustmentid,

               FALSE,

               ca.amount::numeric,

               COALESCE(NULLIF(btrim(ca.description), ''), ca.adjustmenttype)::text,

               CASE WHEN ca.amount >= 0 THEN 'FinancingIn' ELSE 'FinancingOut' END::text,
               %s                       -- 302: the entry time

        FROM   %s ca

        WHERE  lower(ca.farmid::text) = lower($1)

          AND  ca.amount <> 0

          AND  ca.adjustmentdate >= $2

          AND  ca.adjustmentdate <= $3

    $sql$, v_createdcol, v_tbl)

    USING p_farmid, v_from, v_to;
    -- ---- 8. employee advances (313/315) ------------------------------------

    -- Disbursements out, manual repayments in, payroll deductions NOWHERE:

    -- a deduction moves no money, so it is not a cash event. The arms live in

    -- their own function, so this body is touched once and never again.

    RETURN QUERY

    SELECT * FROM public.spwateremployeeloan_cashflowrows(p_farmid, v_from, v_to);


END;

$function$;

CREATE OR REPLACE FUNCTION public.spwatercashflow_detail(p_farmid text, p_fromdate timestamp without time zone DEFAULT NULL::timestamp without time zone, p_todate timestamp without time zone DEFAULT NULL::timestamp without time zone)
 RETURNS TABLE(rowsource text, offledger boolean, sourcerowid integer, cashaccountid integer, accountname text, transactiondate timestamp without time zone, transactiontype text, sourcetype text, sourceid integer, istransfer boolean, amount numeric, description text, flowgroup text, category text, createdat timestamp without time zone)
 LANGUAGE sql
 STABLE
AS $function$
    SELECT r.rowsource, r.offledger, r.sourcerowid, r.cashaccountid, r.accountname,
           r.transactiondate, r.transactiontype, r.sourcetype, r.sourceid,
           r.istransfer, r.amount, r.description, r.flowgroup,
           CASE
               WHEN r.rowsource IN ('Expense', 'ExpensePayment')
                   THEN COALESCE(NULLIF(btrim(c.name), ''), 'Uncategorised')
               WHEN r.rowsource IN ('Receipt', 'SaleResidual') THEN 'Sales'
               -- 424
               WHEN r.rowsource IN ('CustomerRefund', 'CustomerRefundReversal') THEN 'Customer refunds'
               -- 426
               WHEN r.rowsource = 'SupplierAdvanceOrDebt' THEN 'Supplier advances & debts'
               WHEN r.rowsource IN ('SupplierRefund', 'SupplierRefundReversal') THEN 'Supplier refunds'
               -- 423
               WHEN r.rowsource IN ('SupplierPurchasePayment', 'SupplierPaymentReversal')
                   THEN 'Raw Materials / Inventory Purchase'
               ELSE COALESCE(NULLIF(btrim(r.sourcetype), ''), 'Other')
           END::text,
           r.createdat              -- 302: the entry time
    FROM   public.spwatercashflow_rows(p_farmid, p_fromdate, p_todate) r
    LEFT   JOIN waterexpenses e
           ON  r.rowsource IN ('Expense', 'ExpensePayment')
           AND e.waterexpenseid = r.sourceid
           AND lower(e.farmid::text) = lower(p_farmid)
    LEFT   JOIN waterexpensecategories c
           ON  c.waterexpensecategoryid = e.waterexpensecategoryid;
$function$;

CREATE OR REPLACE FUNCTION public.spwatersupplierstatement(p_farmid text, p_supplierid integer, p_from date DEFAULT NULL::date, p_to date DEFAULT NULL::date)
 RETURNS TABLE(entrydate date, entrytype text, reference text, description text, debit numeric, credit numeric, runningbalance numeric, documenttype text, documentid integer, sortkey integer)
 LANGUAGE sql
 STABLE
AS $function$
    -- Only the FIRST arm of a UNION names the columns, so every alias the outer
    -- query needs has to be declared here.
    WITH lines AS (
        SELECT CASE WHEN p_from IS NULL THEN NULL::date ELSE p_from END AS entrydate,
               'OpeningBalance'::text  AS entrytype,
               NULL::text              AS reference,
               'Opening balance'::text AS description,
               CASE WHEN p_from IS NULL THEN 0::numeric(14,2) ELSE COALESCE((
                   SELECT SUM(d.balance) FROM fnwaterpayables(p_farmid) d
                   WHERE  d.supplierid = p_supplierid AND d.docdate < p_from), 0)::numeric(14,2) END AS debit,
               0::numeric(14,2) AS credit,
               NULL::text       AS documenttype,
               NULL::integer    AS documentid,
               0                AS sortkey,
               0                AS pin

        UNION ALL

        -- A purchase or a bill INCREASES what we owe, so it is the debit here --
        -- the mirror of the customer statement, where a sale is the debit.
        SELECT d.docdate,
               CASE WHEN d.documenttype = 'Expense' THEN 'Expense' ELSE 'Purchase' END::text,
               d.reference, d.label,
               d.totalcost::numeric(14,2), 0::numeric(14,2),
               d.documenttype, d.documentid, 1, 1
        FROM   fnwaterpayables(p_farmid) d
        WHERE  d.supplierid = p_supplierid
          AND  (p_from IS NULL OR d.docdate >= p_from)
          AND  (p_to   IS NULL OR d.docdate <= p_to)

        UNION ALL

        -- Paid when it was recorded: amountpaid with no allocation behind it.
        SELECT d.docdate, 'Payment'::text, d.reference,
               CASE WHEN d.documenttype = 'Expense'
                    THEN 'Paid when recorded'
                    ELSE 'Paid at time of purchase' END::text,
               0::numeric(14,2),
               GREATEST(d.amountpaid - COALESCE((
                   SELECT SUM(sa.amountapplied) FROM supplierpaymentallocation sa
                   WHERE  sa.farmid = p_farmid AND sa.module = 'water' AND sa.status = 'Posted'
                     AND  sa.documenttype = d.documenttype AND sa.documentid = d.documentid), 0),
                   0)::numeric(14,2),
               d.documenttype, d.documentid, 2, 1
        FROM   fnwaterpayables(p_farmid) d
        WHERE  d.supplierid = p_supplierid
          AND  (p_from IS NULL OR d.docdate >= p_from)
          AND  (p_to   IS NULL OR d.docdate <= p_to)
          AND  d.amountpaid > COALESCE((
                   SELECT SUM(sa.amountapplied) FROM supplierpaymentallocation sa
                   WHERE  sa.farmid = p_farmid AND sa.module = 'water' AND sa.status = 'Posted'
                     AND  sa.documenttype = d.documenttype AND sa.documentid = d.documentid), 0)

        UNION ALL

        SELECT sp.paymentdate::date, 'Payment'::text,
               COALESCE(NULLIF(btrim(sp.referenceno), ''), 'PMT' || sp.watersupplierpaymentid::text)::text,
               ('Payment' || COALESCE(' — ' || NULLIF(btrim(sp.paymentmethod), ''), ''))::text,
               0::numeric(14,2), sp.totalamount::numeric(14,2),
               NULL::text, NULL::integer, 2, 1
        FROM   watersupplierpayments sp
        WHERE  sp.farmid = p_farmid AND sp.supplierid = p_supplierid
          AND  COALESCE(sp.status, 'Posted') = 'Posted'
          AND  (p_from IS NULL OR sp.paymentdate::date >= p_from)
          AND  (p_to   IS NULL OR sp.paymentdate::date <= p_to)

        UNION ALL
        -- 426: money the supplier sent back out of credit
        SELECT r.refunddate, 'Refund'::text, r.refundnumber::text,
               ('Refund from supplier' || COALESCE(' - ' || NULLIF(btrim(r.reason), ''), ''))::text,
               r.amount::numeric(14,2), 0::numeric(14,2),
               NULL::text, NULL::integer, 2, 1
        FROM   watersupplierrefunds r
        WHERE  r.farmid = p_farmid AND r.supplierid = p_supplierid AND r.status = 'Posted'
          AND  (p_from IS NULL OR r.refunddate >= p_from)
          AND  (p_to   IS NULL OR r.refunddate <= p_to)
    ),
    ordered AS (
        SELECT l.*,
               ROW_NUMBER() OVER (ORDER BY l.pin, l.entrydate NULLS FIRST, l.sortkey, l.documentid) AS rn
        FROM   lines l
    )
    SELECT o.entrydate, o.entrytype, o.reference, o.description,
           o.debit, o.credit,
           SUM(o.debit - o.credit) OVER (ORDER BY o.rn
               ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW)::numeric(14,2),
           o.documenttype, o.documentid, o.sortkey
    FROM   ordered o
    ORDER  BY o.rn;
$function$;

CREATE OR REPLACE FUNCTION public.spwatersupplierbalancesummary(p_farmid text)
 RETURNS TABLE(totalbalance numeric, partycount integer, overduebalance numeric, paymentstoday numeric, largestbalance numeric, largestbalanceparty text)
 LANGUAGE sql
 STABLE
AS $function$
    WITH per AS (
        SELECT b.supplierid, b.suppliername, b.totalbalance, b.overdueamount
        FROM   spwatersupplierbalances(p_farmid) b
    )
    SELECT COALESCE(SUM(p.totalbalance), 0)::numeric(14,2),
           COUNT(*)::integer,
           COALESCE(SUM(p.overdueamount), 0)::numeric(14,2),
           COALESCE((SELECT SUM(sp.totalamount) FROM watersupplierpayments sp
                     WHERE sp.farmid = p_farmid
                       AND COALESCE(sp.status, 'Posted') = 'Posted'
                       AND NOT public.fnwatersupplier_iscreditkind(sp.sourcetype)   -- 426
                       AND sp.paymentdate::date = CURRENT_DATE), 0)::numeric(14,2),
           COALESCE(MAX(p.totalbalance), 0)::numeric(14,2),
           (SELECT p2.suppliername FROM per p2 ORDER BY p2.totalbalance DESC LIMIT 1)
    FROM   per p;
$function$;

CREATE OR REPLACE FUNCTION public.spwatersupplierpayment_history(p_farmid text, p_supplierid integer DEFAULT NULL::integer, p_documenttype text DEFAULT NULL::text, p_documentid integer DEFAULT NULL::integer, p_from date DEFAULT NULL::date, p_to date DEFAULT NULL::date)
 RETURNS TABLE(paymentid integer, supplierid integer, suppliername text, paymentdate timestamp without time zone, totalamount numeric, paymentmethod text, referenceno text, notes text, sourcetype text, status text, allocationcount integer, watercashaccountid integer, createdby text, reversedby text, reversedat timestamp without time zone, reversalreason text, createdat timestamp without time zone)
 LANGUAGE sql
 STABLE
AS $function$
    SELECT sp.watersupplierpaymentid,
           sp.supplierid,
           s.suppliername::text,
           sp.paymentdate,
           sp.totalamount,
           sp.paymentmethod::text,
           sp.referenceno::text,
           sp.notes::text,
           sp.sourcetype::text,
           COALESCE(sp.status, 'Posted')::text,
           (SELECT COUNT(*)::integer FROM supplierpaymentallocation sa
            WHERE sa.farmid = sp.farmid AND sa.module = 'water'
              AND sa.paymentid = sp.watersupplierpaymentid),
           sp.watercashaccountid,
           sp.createdby::text,
           sp.reversedby::text,
           sp.reversedat,
           sp.reversalreason::text
           , sp.createdat   -- 304: the entry time
    FROM   watersupplierpayments sp
    LEFT   JOIN watersuppliers s ON s.watersupplierid = sp.supplierid AND s.farmid = sp.farmid
    WHERE  sp.farmid = p_farmid
      -- 426: credit added by hand lives on Supplier Credits
      AND  NOT public.fnwatersupplier_iscreditkind(sp.sourcetype)
      AND  (p_supplierid IS NULL OR sp.supplierid = p_supplierid)
      AND  (p_from IS NULL OR sp.paymentdate::date >= p_from)
      AND  (p_to   IS NULL OR sp.paymentdate::date <= p_to)
      AND  (p_documentid IS NULL OR EXISTS (
              SELECT 1 FROM supplierpaymentallocation sa
              WHERE sa.paymentid = sp.watersupplierpaymentid
                AND sa.module = 'water'
                AND sa.documentid = p_documentid
                AND (p_documenttype IS NULL OR sa.documenttype = p_documenttype)))
    ORDER  BY sp.paymentdate DESC, sp.watersupplierpaymentid DESC;
$function$;

