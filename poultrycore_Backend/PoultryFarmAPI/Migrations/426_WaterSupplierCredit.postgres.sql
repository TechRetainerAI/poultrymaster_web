-- =============================================================================
-- 426_WaterSupplierCredit.postgres.sql   (Water credits programme W3; requires 423-425)
--
-- Purpose
-- -------
-- Poultry 370 for Water: supplier credit, advances, refunds and supplier debt.
-- Credit is DERIVED, never stored.
--
--  * SUPPLIER CREDIT is a watersupplierpayments row:
--      an ADVANCE        a real payment applied to nothing (cash out);
--      an OVERPAYMENT    a real payment applied to less than its amount;
--      a MANUAL credit   no cash: SupplierCreditNote / SupplierOpeningCredit /
--                        SupplierManualCredit, no account.
--    Credit = amount - posted allocations - posted refund lines.
--  * APPLYING credit is an allocation on the CREDIT's payment, fromcredit,
--    dated now. The document's amountpaid goes up as for a payment. No cash
--    and no extra expense row: water's P&L counts raw materials on their paid
--    amount (periodpnl), so the cost lands through amountpaid, as it would for
--    a payment.
--  * A REFUND is the supplier sending money back: money IN to the account
--    chosen ('WaterSupplierRefund'); reversible (kept as Reversed, money out).
--  * SUPPLIER DEBT (SD-00001): what is owed without a purchase here. A payable
--    -- fnwaterpayables 'SupplierDebt' -- so supplier balances, open items,
--    statements and payments see it. No purchase, stock, expense or cash.
--    Reversal is refused while anything is paid on it.
--  * CASH: the cash sync posts debts + the unapplied part as one CashOut keyed
--    to the payment (so the reversal gives it back); Cash Flow arm 3e shows it,
--    3g/3h the refunds; 3b/3c skip credit applied later; 3d gives back the
--    whole payment.
--  * A credit cannot be reversed while any of it is applied or refunded.
--
-- Deploy order: this migration, then the Farm API, then the web app.
-- =============================================================================
\set ON_ERROR_STOP on

BEGIN;

-- ============================================================ 1. tables =====
