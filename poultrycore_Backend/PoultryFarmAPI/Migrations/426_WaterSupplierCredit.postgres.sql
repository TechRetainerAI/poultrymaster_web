-- ================================================== 5. supplier debts ======
-- What the business already owes a supplier without a purchase here. A payable
-- (fnwaterpayables 'SupplierDebt'): no purchase, no stock, no expense, no cash.
CREATE OR REPLACE FUNCTION public.spwatersupplierdebt_create(p_farmid text, p_supplierid integer, p_amount numeric,
    p_debtdate date, p_entrytype text, p_description text, p_reference text DEFAULT NULL, p_notes text DEFAULT NULL,
    p_by text DEFAULT NULL)
RETURNS jsonb LANGUAGE plpgsql AS $f$
DECLARE v_id integer; v_no text; v_date date := COALESCE(p_debtdate, (now() AT TIME ZONE 'utc')::date);
BEGIN
    IF p_amount IS NULL OR p_amount <= 0 THEN RAISE EXCEPTION 'Enter an amount greater than 0.' USING ERRCODE = 'P0001'; END IF;
    IF p_description IS NULL OR length(btrim(p_description)) = 0 THEN
        RAISE EXCEPTION 'Describe what the debt is for.' USING ERRCODE = 'P0001';
    END IF;
    IF COALESCE(p_entrytype, '') NOT IN ('OpeningBalance', 'HistoricalDebt', 'Adjustment', 'Migration', 'ExternalTransaction', 'Other') THEN
        RAISE EXCEPTION 'Choose what kind of debt this is.' USING ERRCODE = 'P0001';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM watersuppliers s WHERE s.watersupplierid = p_supplierid AND s.farmid = p_farmid) THEN
        RAISE EXCEPTION 'Supplier does not belong to this company.' USING ERRCODE = 'P0001';
    END IF;
    IF v_date > (now() AT TIME ZONE 'utc')::date + 1 THEN
        RAISE EXCEPTION 'The debt date is in the future.' USING ERRCODE = 'P0001';
    END IF;
    PERFORM pg_advisory_xact_lock(hashtext('water-supplierdebtnumber:' || p_farmid));
    SELECT 'SD-' || lpad((COALESCE(MAX(NULLIF(regexp_replace(d.debtnumber, '\D', '', 'g'), '')::int), 0) + 1)::text, 5, '0')
    INTO   v_no FROM watersupplierdebts d WHERE d.farmid = p_farmid;
    INSERT INTO watersupplierdebts (farmid, debtnumber, supplierid, amount, debtdate, entrytype, description, reference, notes, createdby)
    VALUES (p_farmid, v_no, p_supplierid, round(p_amount, 2), v_date, p_entrytype, btrim(p_description),
            NULLIF(btrim(p_reference), ''), NULLIF(btrim(p_notes), ''), p_by)
    RETURNING debtid INTO v_id;
    RETURN jsonb_build_object('debtId', v_id, 'debtNumber', v_no);
END
$f$;

CREATE OR REPLACE FUNCTION public.spwatersupplierdebt_reverse(p_farmid text, p_debtid integer, p_reason text,
                                                              p_by text DEFAULT NULL)
RETURNS integer LANGUAGE plpgsql AS $f$
DECLARE v_d watersupplierdebts%ROWTYPE;
BEGIN
    IF p_reason IS NULL OR length(btrim(p_reason)) = 0 THEN
        RAISE EXCEPTION 'Give a reason for reversing the debt.' USING ERRCODE = 'P0001';
    END IF;
    SELECT * INTO v_d FROM watersupplierdebts d WHERE d.debtid = p_debtid AND d.farmid = p_farmid FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'Debt not found for this company.' USING ERRCODE = 'P0001'; END IF;
    IF v_d.status <> 'Posted' THEN RAISE EXCEPTION 'This debt has already been reversed.' USING ERRCODE = 'P0001'; END IF;
    IF v_d.amountpaid > 0 THEN
        RAISE EXCEPTION 'Payments have been applied to debt %. Reverse those payments first.', v_d.debtnumber USING ERRCODE = 'P0001';
    END IF;
    UPDATE watersupplierdebts SET status = 'Reversed', reversedby = p_by, reversedat = (now() AT TIME ZONE 'utc'),
           reversalreason = btrim(p_reason)
    WHERE  debtid = p_debtid;
    RETURN p_debtid;
END
$f$;

CREATE OR REPLACE FUNCTION public.spwatersupplierdebt_list(p_farmid text, p_supplierid integer DEFAULT NULL)
RETURNS TABLE(debtid integer, debtnumber text, supplierid integer, suppliername text, amount numeric, paid numeric,
