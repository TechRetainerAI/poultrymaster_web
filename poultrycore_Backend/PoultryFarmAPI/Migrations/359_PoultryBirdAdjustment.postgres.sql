-- =============================================================================
-- 359_PoultryBirdAdjustment.postgres.sql          (requires 325, 326, 338)
--
-- Purpose
-- -------
-- Adjust BIRDS for one flock, or for one batch's birds not yet placed in a
-- flock, from the Stock page.
--
-- WHY NOT A STOCK LEDGER ROW
-- --------------------------
-- Birds are the one poultry product whose count is NOT the stock ledger
-- (see 325): a flock's birds are its latest production record's
-- noofbirdsleft (else flock.quantity), and every bird reader -- Birds stock,
-- the flock list, the dashboard, birds-on-hand, closeout, feed / treatment
-- per-bird figures, platform billing -- reads that. A hand-posted 'Decrease'
-- on the Birds product moved none of them.
--
-- WHAT AN ADJUSTMENT DOES
-- -----------------------
--   Flock   The flock's LATEST production record opens with the corrected
--           count: noofbirds and noofbirdsleft both move by the adjustment,
--           so that day's "birds - mortality = left" still holds and the next
--           record (which starts from this one's birds left) carries it on.
--           Every reader above sees it at once. The record changed, the counts
--           before and after, who and why are kept on poultrybirdadjustments.
--           A flock with no production record yet is refused: its birds are
--           still its placed quantity, corrected on the Flocks page.
--   Batch   (no flock) Birds bought but not placed in any flock -- died in
--           transit, miscounted on delivery. spflock_getconsumedforbatch counts
--           them, so the batch has that many fewer (or more) birds to place.
--
-- Both post a 'Bird Adjustment' row to the bird ledger on the company's
-- business date, so the closing report's opening / closing birds move too.
-- Closed flocks are refused. Serialised with batch allocation (same advisory
-- lock key as BirdFlockService.AllocateBatchToFlocks).
--
-- The Stock page's manual movement now refuses the Birds product and points
-- here, so a bird row that changes nothing cannot be posted again.
-- =============================================================================

BEGIN;

CREATE TABLE IF NOT EXISTS public.poultrybirdadjustments (
    birdadjustmentid   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmid             varchar(450) NOT NULL,
    batchid            integer      NOT NULL,
    flockid            integer      NULL,          -- NULL = the batch's unplaced birds
    adjustmentdate     date         NOT NULL,      -- company business date
    movementtype       text         NOT NULL,
    quantity           integer      NOT NULL CHECK (quantity <> 0),   -- signed
    productionrecordid integer      NULL,          -- the record whose count moved
    birdsbefore        integer      NOT NULL,
    birdsafter         integer      NOT NULL,
    note               text         NULL,
    createdby          text         NULL,
    createdat          timestamp without time zone NOT NULL DEFAULT (now() AT TIME ZONE 'utc')
);
CREATE INDEX IF NOT EXISTS ix_poultrybirdadjustments_batch ON public.poultrybirdadjustments (farmid, batchid);
CREATE INDEX IF NOT EXISTS ix_poultrybirdadjustments_flock ON public.poultrybirdadjustments (farmid, flockid) WHERE flockid IS NOT NULL;

-- -----------------------------------------------------------------------------
-- Birds a batch has given out: placed basis (325) plus its unplaced-bird
-- adjustments. A batch-level decrease consumes birds; an increase frees them.
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.spflock_getconsumedforbatch(
    p_batchid          integer,
    p_farmid           text,
    p_flockidtoexclude integer DEFAULT NULL)
RETURNS integer
LANGUAGE plpgsql
AS $function$
DECLARE
    v_total integer;
BEGIN
    -- The opening reduction is joined per flock and excluded along with its
    -- flock, so "everything except this one" stays consistent across both terms.
    SELECT COALESCE(SUM(f.quantity), 0)
         + COALESCE(SUM(GREATEST(o.originallyplaced - o.openinglivebirds, 0)), 0)
    INTO   v_total
    FROM   flock f
    LEFT   JOIN public.poultryopeningflockposition o
           ON o.flockid = f.flockid AND o.farmid = f.farmid
    WHERE  f.batchid = p_batchid
      AND  f.farmid = p_farmid
      AND  (p_flockidtoexclude IS NULL OR f.flockid <> p_flockidtoexclude);

    -- 359: birds lost (or found) before being placed in any flock.
    v_total := COALESCE(v_total, 0) - COALESCE((
        SELECT SUM(a.quantity) FROM public.poultrybirdadjustments a
        WHERE  a.farmid = p_farmid AND a.batchid = p_batchid AND a.flockid IS NULL), 0);

    RETURN COALESCE(v_total, 0);
END
$function$;

-- -----------------------------------------------------------------------------
-- What the adjust form offers: every open batch, its unplaced birds, and each
-- of its flocks with the birds it holds now.
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.sppoultrybirdadjustment_options(p_farmid text)
RETURNS TABLE (batchid integer, batchcode text, batchname text, batchbirds integer, unplacedbirds integer,
               flockid integer, flockname text, livebirds integer, lastcountdate date,
               hasproductionrecord boolean, isclosed boolean)
LANGUAGE sql
STABLE
AS $function$
    SELECT b.batchid, b.batchcode::text, b.batchname::text, b.numberofbirds,
           GREATEST(b.numberofbirds - spflock_getconsumedforbatch(b.batchid, p_farmid, NULL), 0),
           f.flockid, f.name::text, bp.currentlivebirds, bp.lastcountdate,
           COALESCE(bp.productionrecordcount, 0) > 0,
           COALESCE(f.closeddate IS NOT NULL, FALSE)
    FROM   mainflockbatch b
    LEFT   JOIN flock f ON f.batchid = b.batchid AND f.farmid = p_farmid AND NOT f.isdeleted
    LEFT   JOIN LATERAL fnflock_birdposition(p_farmid, f.flockid) bp ON f.flockid IS NOT NULL
    WHERE  b.farmid = p_farmid
    ORDER  BY b.startdate DESC, b.batchid DESC, f.name;
$function$;

-- -----------------------------------------------------------------------------
-- Post one adjustment. p_quantity is SIGNED (the form's movement type sets it).
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.sppoultrybirdadjustment_post(
    p_farmid text, p_batchid integer, p_flockid integer, p_movementtype text,
    p_quantity integer, p_note text DEFAULT NULL, p_by text DEFAULT NULL)
RETURNS integer
LANGUAGE plpgsql
AS $function$
DECLARE
    v_today   date := fncompany_businessdate(p_farmid);
    v_flock   record;
    v_rec     record;
    v_live    integer;
    v_before  integer;
    v_after   integer;
    v_recid   integer;
    v_id      integer;
BEGIN
    IF COALESCE(p_quantity, 0) = 0 THEN
        RAISE EXCEPTION 'Enter how many birds to adjust.' USING ERRCODE = 'P0001';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM mainflockbatch b WHERE b.batchid = p_batchid AND b.farmid = p_farmid) THEN
        RAISE EXCEPTION 'That batch does not belong to this company.' USING ERRCODE = 'P0001';
    END IF;

    -- Same key as BirdFlockService.AllocateBatchToFlocks: an adjustment and an
    -- allocation of the same batch cannot both read the old figures.
    PERFORM pg_advisory_xact_lock(hashtext('flock-alloc:' || p_farmid || ':' || p_batchid));

    IF p_flockid IS NOT NULL THEN
        SELECT f.flockid, f.name, f.closeddate INTO v_flock
        FROM   flock f
        WHERE  f.flockid = p_flockid AND f.farmid = p_farmid AND f.batchid = p_batchid AND NOT f.isdeleted;
        IF NOT FOUND THEN
            RAISE EXCEPTION 'That flock is not part of the chosen batch.' USING ERRCODE = 'P0001';
        END IF;
        IF v_flock.closeddate IS NOT NULL THEN
            RAISE EXCEPTION 'Flock "%" is closed. Reopen it before adjusting its birds.', v_flock.name USING ERRCODE = 'P0001';
        END IF;

        SELECT r.id, r.noofbirds, r.noofbirdsleft INTO v_rec
        FROM   productionrecords r
        WHERE  r.farmid = p_farmid AND r.flockid = p_flockid
        ORDER  BY r.date DESC, r.id DESC
        LIMIT  1
        FOR UPDATE;
        IF NOT FOUND THEN
            RAISE EXCEPTION 'Flock "%" has no production record yet, so its birds are still the number placed. Correct the quantity on the Flocks page, or record its first day.', v_flock.name
                USING ERRCODE = 'P0001';
        END IF;

        SELECT bp.currentlivebirds INTO v_live FROM fnflock_birdposition(p_farmid, p_flockid) bp;
        v_before := COALESCE(v_live, 0);
        v_after  := v_before + p_quantity;
        IF v_after < 0 OR COALESCE(v_rec.noofbirdsleft, 0) + p_quantity < 0 THEN
            RAISE EXCEPTION 'Flock "%" has % birds, so it cannot lose %.', v_flock.name, v_before, -p_quantity
                USING ERRCODE = 'P0001';
        END IF;

        UPDATE productionrecords r
        SET    noofbirds     = GREATEST(COALESCE(r.noofbirds, 0) + p_quantity, 0),
               noofbirdsleft = COALESCE(r.noofbirdsleft, 0) + p_quantity,
               updatedat     = (now() AT TIME ZONE 'utc'),
               updatedby     = p_by
        WHERE  r.id = v_rec.id;
        v_recid := v_rec.id;
    ELSE
        SELECT GREATEST(b.numberofbirds - spflock_getconsumedforbatch(b.batchid, p_farmid, NULL), 0) INTO v_before
        FROM   mainflockbatch b WHERE b.batchid = p_batchid AND b.farmid = p_farmid;
        v_after := v_before + p_quantity;
        IF v_after < 0 THEN
            RAISE EXCEPTION 'This batch has % birds not placed in a flock, so it cannot lose %. To adjust birds already in a flock, choose the flock.', v_before, -p_quantity
                USING ERRCODE = 'P0001';
        END IF;
    END IF;

    INSERT INTO poultrybirdadjustments
        (farmid, batchid, flockid, adjustmentdate, movementtype, quantity, productionrecordid,
         birdsbefore, birdsafter, note, createdby)
    VALUES
        (p_farmid, p_batchid, p_flockid, v_today, COALESCE(NULLIF(btrim(p_movementtype), ''), 'Adjustment'),
         p_quantity, v_recid, v_before, v_after, NULLIF(btrim(COALESCE(p_note, '')), ''), p_by)
    RETURNING birdadjustmentid INTO v_id;

    -- The movements list shows this note: it always names what was adjusted.
    PERFORM sppoultrybirdstock_postdated(p_farmid, 'Bird Adjustment', p_quantity::numeric, v_id, v_today,
        (CASE WHEN p_flockid IS NULL
              THEN 'Batch ' || (SELECT b.batchcode FROM mainflockbatch b WHERE b.batchid = p_batchid) || ' (not placed)'
              ELSE 'Flock ' || v_flock.name END)
        || COALESCE(' - ' || NULLIF(btrim(COALESCE(p_note, '')), ''), ''),
        p_by);

    RETURN v_id;
END
$function$;

CREATE OR REPLACE FUNCTION public.sppoultrybirdadjustment_getall(p_farmid text)
RETURNS TABLE (birdadjustmentid integer, adjustmentdate date, batchid integer, batchcode text,
               flockid integer, flockname text, movementtype text, quantity integer,
               birdsbefore integer, birdsafter integer, productionrecordid integer,
               note text, createdby text, createdat timestamp without time zone)
LANGUAGE sql
STABLE
AS $function$
    SELECT a.birdadjustmentid, a.adjustmentdate, a.batchid, b.batchcode::text,
           a.flockid, f.name::text, a.movementtype, a.quantity,
           a.birdsbefore, a.birdsafter, a.productionrecordid,
           a.note, a.createdby, a.createdat
    FROM   poultrybirdadjustments a
    LEFT   JOIN mainflockbatch b ON b.batchid = a.batchid
    LEFT   JOIN flock f ON f.flockid = a.flockid
    WHERE  a.farmid = p_farmid
    ORDER  BY a.createdat DESC, a.birdadjustmentid DESC;
$function$;

-- -----------------------------------------------------------------------------
-- The manual stock movement no longer takes Birds: it moved nothing a bird
-- count reads. Inserted at the top of the live body (loud if it drifted).
-- -----------------------------------------------------------------------------
DO $patch$
DECLARE
    v_src text := replace(pg_get_functiondef('public.sppoultrystock_addtransaction'::regproc), E'\r', '');
    v_at  integer;
BEGIN
    IF position('359: birds are adjusted per flock' IN v_src) > 0 THEN
        RETURN;     -- already patched
    END IF;
    v_at := position(E'\nBEGIN\n' IN v_src);
    IF v_at = 0 THEN
        RAISE EXCEPTION '359: could not find BEGIN in sppoultrystock_addtransaction.';
    END IF;
    v_src := overlay(v_src PLACING E'\nBEGIN\n'
        || E'    -- 359: birds are adjusted per flock / batch (sppoultrybirdadjustment_post).\n'
        || E'    IF EXISTS (SELECT 1 FROM poultryproducts pp WHERE pp.poultryproductid = p_poultryproductid\n'
        || E'               AND (pp.isbirdproduct = TRUE OR pp.name = ''Birds'')) THEN\n'
        || E'        RAISE EXCEPTION ''Birds are adjusted per flock or batch: choose Birds on the Stock page and pick the flock.'' USING ERRCODE = ''P0001'';\n'
        || E'    END IF;\n'
        FROM v_at FOR length(E'\nBEGIN\n'));
    EXECUTE v_src;
END
$patch$;

COMMIT;
