        GRANT EXECUTE ON FUNCTION public.spwatersupplierpayment_history(text, integer, text, integer, date, date) TO poultryapp;
        GRANT EXECUTE ON FUNCTION public.spgenericcustomerpayment_history(text, integer, integer, date, date) TO poultryapp;
        GRANT EXECUTE ON FUNCTION public.spgenericsupplierpayment_history(text, integer, text, integer, date, date) TO poultryapp;
