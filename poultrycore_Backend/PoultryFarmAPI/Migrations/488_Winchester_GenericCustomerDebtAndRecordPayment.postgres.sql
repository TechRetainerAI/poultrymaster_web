-- =============================================================================
-- 488_Winchester_GenericCustomerDebtAndRecordPayment.postgres.sql
--
-- Two Poultry features copied to Generic, fitted to Generic's tables.
--
-- A. CUSTOMER DEBT (Poultry 369 / Water 425): what a customer owes WITHOUT a
--    sale -- owed from before the business used the system, a historical or
--    external transaction, a migration, an adjustment. The user records the
--    EVENT; what is still owed is derived:
--      genericcustomerdebts   one row per debt (CD-00001): customer, amount,
--                             date, entry type, description (required),
--                             reference, notes. Posted, or Reversed (kept, with
--                             who / when / why).
--      Owed on a debt       = amount - Posted allocations (module 'generic-debt',
--                             customerpaymentallocation.saleid holds the debt id).
--    A debt is NOT a sale: no revenue, no stock, no cash. It is owed: it shows
--    in Customer Balances (fngenericopeninvoices, so the balances list, summary,
--    open items, statement and dashboards all see it) and is paid like a sale.
--    Generic also keeps a running customer ledger (genericcustomers.
--    currentbalance, read by the Customers page and Daily Closing), so a debt
--    writes a 'DebtDebit' ledger line and its reversal a 'DebtReversal' line.
--    Reversing is refused while any payment is applied to it.
--
-- B. RECORD CUSTOMER PAYMENT (Poultry 367): a payment need not be applied in
--    full. spgenericcustomerpayment_record now accepts
--      allocations [{saleid, amount} | {debtid, amount}], possibly none;
--      allocated total <= the payment.
--    What is not applied is kept as the customer's credit: a row in
--    genericcustomercredits (CreditType 'Overpayment', or 'Advance' when nothing
--    was applied; ReferenceType 'CustomerPayment', ReferenceId = the payment),
--    which the Customer Credits panel already lists. One payment, one cash
--    movement, one 'PaymentCredit' ledger line, whatever the split (as before).
--    Reversing the payment reverses its debt allocations too and takes the
--    credit back -- refused if part of that credit has already been used.
--
-- Not copied: Poultry 382-384 (debt payments counted on Profit & Loss, the
-- "old debt" remainder with a sale type). Generic keeps 369's rule: a debt is
-- not revenue.
--
-- Can run twice. No BEGIN/COMMIT (RunMigration wraps the file).
-- Deploy order: this migration, then the Farm API, then the web app.
-- =============================================================================

-- ------------------------------------------------------------------ 1. table --
CREATE TABLE IF NOT EXISTS public.genericcustomerdebts (
    debtid             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmid             text          NOT NULL,
    debtnumber         text          NOT NULL,
    genericcustomerid  integer       NOT NULL,
    amount             numeric(14,2) NOT NULL CHECK (amount > 0),
    debtdate           date          NOT NULL,
    entrytype          text          NOT NULL CHECK (entrytype IN
                           ('OpeningBalance', 'HistoricalDebt', 'Adjustment', 'Migration', 'ExternalTransaction', 'Other')),
    description        text          NOT NULL,
    reference          text,
    notes              text,
    status             text          NOT NULL DEFAULT 'Posted' CHECK (status IN ('Posted', 'Reversed')),
    createdby          text,
    createdat          timestamp     NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    reversedby         text,
    reversedat         timestamp,
    reversalreason     text
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_genericcustomerdebts_number ON public.genericcustomerdebts (farmid, debtnumber);
CREATE INDEX IF NOT EXISTS ix_genericcustomerdebts_cust ON public.genericcustomerdebts (farmid, genericcustomerid) WHERE status = 'Posted';

-- --------------------------------------------------------- 2. derived money --
CREATE OR REPLACE FUNCTION public.fngenericcustomerdebt_paid(p_farmid text, p_debtid integer)
RETURNS numeric LANGUAGE sql STABLE AS $f$
    SELECT COALESCE(SUM(ca.amountapplied), 0)::numeric(14,2)
    FROM   customerpaymentallocation ca
    WHERE  ca.module = 'generic-debt' AND ca.saleid = p_debtid AND ca.farmid = p_farmid AND ca.status = 'Posted';
$f$;

CREATE OR REPLACE FUNCTION public.fngenericcustomerdebt_balance(p_farmid text, p_debtid integer)
RETURNS numeric LANGUAGE sql STABLE AS $f$
    SELECT CASE WHEN d.status = 'Posted'
                THEN GREATEST(d.amount - public.fngenericcustomerdebt_paid(p_farmid, d.debtid), 0)
                ELSE 0 END::numeric(14,2)
    FROM   genericcustomerdebts d
    WHERE  d.debtid = p_debtid AND d.farmid = p_farmid;
$f$;

-- --------------------------------------------------- 3. create / reverse / list --
CREATE OR REPLACE FUNCTION public.spgenericcustomerdebt_create(p_farmid text, p_customerid integer, p_amount numeric,
    p_debtdate date, p_entrytype text, p_description text, p_reference text DEFAULT NULL, p_notes text DEFAULT NULL,
    p_by text DEFAULT NULL)
RETURNS jsonb LANGUAGE plpgsql AS $f$
DECLARE
    v_id      integer;
    v_number  text;
    v_amount  numeric(14,2);
    v_custbal numeric(14,2);
BEGIN
    IF p_amount IS NULL OR round(p_amount, 2) <= 0 THEN
        RAISE EXCEPTION 'Enter the amount owed, greater than 0.' USING ERRCODE = 'P0001';
    END IF;
    IF p_entrytype IS NULL OR p_entrytype NOT IN ('OpeningBalance', 'HistoricalDebt', 'Adjustment', 'Migration', 'ExternalTransaction', 'Other') THEN
        RAISE EXCEPTION 'Choose why the customer owes this.' USING ERRCODE = 'P0001';
    END IF;
    IF NULLIF(btrim(COALESCE(p_description, '')), '') IS NULL THEN
        RAISE EXCEPTION 'Describe what the debt is for.' USING ERRCODE = 'P0001';
    END IF;
    IF p_debtdate IS NULL THEN
        RAISE EXCEPTION 'Give the date the debt is owed from.' USING ERRCODE = 'P0001';
    END IF;

    SELECT c.currentbalance INTO v_custbal
    FROM   genericcustomers c
    WHERE  c.genericcustomerid = p_customerid AND c.farmid = p_farmid
    FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Customer does not belong to this company.' USING ERRCODE = 'P0001';
    END IF;
    v_amount := round(p_amount, 2);

    PERFORM pg_advisory_xact_lock(hashtext('generic-customerdebt-no:' || p_farmid));
    SELECT 'CD-' || lpad((COALESCE(MAX(NULLIF(regexp_replace(d.debtnumber, '\D', '', 'g'), '')::int), 0) + 1)::text, 5, '0')
    INTO   v_number FROM genericcustomerdebts d WHERE d.farmid = p_farmid;

    INSERT INTO genericcustomerdebts
        (farmid, debtnumber, genericcustomerid, amount, debtdate, entrytype, description, reference, notes, createdby)
    VALUES
        (p_farmid, v_number, p_customerid, v_amount, p_debtdate, p_entrytype, left(btrim(p_description), 300),
         NULLIF(btrim(COALESCE(p_reference, '')), ''), NULLIF(btrim(COALESCE(p_notes, '')), ''), p_by)
    RETURNING debtid INTO v_id;

    -- Generic's running customer balance (Customers page, Daily Closing).
    INSERT INTO genericcustomerledger
        (farmid, genericcustomerid, transactiondate, transactiontype, paymentid,
         debitamount, creditamount, balanceaftertransaction, description, createdby)
    VALUES
        (p_farmid, p_customerid, p_debtdate::timestamp, 'DebtDebit', NULL,
         v_amount, 0, COALESCE(v_custbal, 0) + v_amount,
         'Customer debt ' || v_number || ': ' || left(btrim(p_description), 200), p_by);

    UPDATE genericcustomers
    SET    currentbalance = COALESCE(v_custbal, 0) + v_amount, updatedat = (now() AT TIME ZONE 'utc')
    WHERE  genericcustomerid = p_customerid AND farmid = p_farmid;

    RETURN jsonb_build_object('debtId', v_id, 'debtNumber', v_number);
END
$f$;

CREATE OR REPLACE FUNCTION public.spgenericcustomerdebt_reverse(p_farmid text, p_debtid integer, p_reason text, p_by text DEFAULT NULL)
RETURNS integer LANGUAGE plpgsql AS $f$
DECLARE
    v_d       record;
    v_paid    numeric(14,2);
    v_custbal numeric(14,2);
    v_now     timestamp := (now() AT TIME ZONE 'utc');
BEGIN
    IF NULLIF(btrim(COALESCE(p_reason, '')), '') IS NULL THEN
        RAISE EXCEPTION 'Give a reason for reversing the debt.' USING ERRCODE = 'P0001';
    END IF;
    SELECT d.* INTO v_d FROM genericcustomerdebts d WHERE d.debtid = p_debtid AND d.farmid = p_farmid FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Debt not found for this company.' USING ERRCODE = 'P0001';
    END IF;
    IF v_d.status <> 'Posted' THEN
        RAISE EXCEPTION 'Debt % has already been reversed.', v_d.debtnumber USING ERRCODE = 'P0001';
    END IF;
    v_paid := fngenericcustomerdebt_paid(p_farmid, p_debtid);
    IF v_paid > 0 THEN
        RAISE EXCEPTION '% has already been paid on debt %. Reverse those payments first (Customer Payments).', v_paid, v_d.debtnumber
            USING ERRCODE = 'P0001';
    END IF;

    UPDATE genericcustomerdebts d
    SET    status = 'Reversed', reversedby = p_by, reversedat = v_now, reversalreason = btrim(p_reason)
    WHERE  d.debtid = p_debtid;

    SELECT c.currentbalance INTO v_custbal
    FROM   genericcustomers c
    WHERE  c.genericcustomerid = v_d.genericcustomerid AND c.farmid = p_farmid
    FOR UPDATE;

    INSERT INTO genericcustomerledger
        (farmid, genericcustomerid, transactiondate, transactiontype, paymentid,
         debitamount, creditamount, balanceaftertransaction, description, createdby)
    VALUES
        (p_farmid, v_d.genericcustomerid, v_now, 'DebtReversal', NULL,
         0, v_d.amount, COALESCE(v_custbal, 0) - v_d.amount,
         'Reversal of customer debt ' || v_d.debtnumber || ': ' || btrim(p_reason), p_by);

    UPDATE genericcustomers
    SET    currentbalance = COALESCE(v_custbal, 0) - v_d.amount, updatedat = v_now
    WHERE  genericcustomerid = v_d.genericcustomerid AND farmid = p_farmid;

    RETURN p_debtid;
END
$f$;

CREATE OR REPLACE FUNCTION public.spgenericcustomerdebt_list(p_farmid text, p_customerid integer DEFAULT NULL)
RETURNS TABLE(debtid integer, debtnumber text, customerid integer, customername text, amount numeric, paid numeric,
              balance numeric, debtdate date, entrytype text, description text, reference text, notes text,
              status text, createdby text, createdat timestamp, reversedby text, reversedat timestamp, reversalreason text)
LANGUAGE sql STABLE AS $f$
    SELECT d.debtid, d.debtnumber, d.genericcustomerid, c.customername::text, d.amount,
           fngenericcustomerdebt_paid(p_farmid, d.debtid),
           fngenericcustomerdebt_balance(p_farmid, d.debtid),
           d.debtdate, d.entrytype, d.description, d.reference, d.notes, d.status,
           d.createdby, d.createdat, d.reversedby, d.reversedat, d.reversalreason
    FROM   genericcustomerdebts d
    LEFT   JOIN genericcustomers c ON c.genericcustomerid = d.genericcustomerid AND c.farmid = d.farmid
    WHERE  d.farmid = p_farmid AND (p_customerid IS NULL OR d.genericcustomerid = p_customerid)
    ORDER  BY d.debtdate DESC, d.debtid DESC;
$f$;

-- ------------------------------------- 4. debts are owed: open documents --
-- Same columns as before; a second arm for Posted debts. Every reader
-- (balances, summary, open items, statement, subscription dashboards) sees them.
CREATE OR REPLACE FUNCTION public.fngenericopeninvoices(p_farmid text)
 RETURNS TABLE(genericcustomerid integer, documenttype text, documentid integer, reference text, documentdate date, label text, totalamount numeric, amountpaid numeric, balance numeric, duedate date, cashaccountid integer)
 LANGUAGE sql
 STABLE
AS $function$
    SELECT g.genericcustomerid,
           CASE WHEN g.genericsubscriptionid IS NOT NULL THEN 'Invoice' ELSE 'Sale' END::text,
           g.genericsaleid,
           COALESCE(NULLIF(btrim(g.receiptnumber), ''), 'S' || g.genericsaleid::text)::text,
           g.saledate::date,
           COALESCE(NULLIF(btrim(g.notes), ''), g.salestype, 'Sale')::text,
           g.totalamount, g.amountpaid, GREATEST(g.balance, 0)::numeric(14,2),
           COALESCE(g.duedate, (g.saledate::date + COALESCE(c.paymenttermsdays, 0)))::date,
           g.genericcashaccountid
    FROM   genericsales g
    JOIN   genericcustomers c
           ON c.genericcustomerid = g.genericcustomerid AND c.farmid = g.farmid
    WHERE  g.farmid = p_farmid
      -- Draft invoices are not receivables: a generic sale reaches the customer
      -- ledger only when approved.
      AND  g.status = 'Approved'
      AND  COALESCE(g.isdeleted, FALSE) = FALSE
      AND  g.genericcustomerid IS NOT NULL

    UNION ALL

    -- 488: customer debts (owed without a sale).
    SELECT d.genericcustomerid,
           'CustomerDebt'::text,
           d.debtid,
           d.debtnumber,
           d.debtdate,
           d.description,
           d.amount,
           public.fngenericcustomerdebt_paid(p_farmid, d.debtid),
           public.fngenericcustomerdebt_balance(p_farmid, d.debtid),
           (d.debtdate + COALESCE(c.paymenttermsdays, 0))::date,
           NULL::integer
    FROM   genericcustomerdebts d
    JOIN   genericcustomers c
           ON c.genericcustomerid = d.genericcustomerid AND c.farmid = d.farmid
    WHERE  d.farmid = p_farmid
      AND  d.status = 'Posted';
$function$;

-- ------------------------------------------------- 5. record a payment --
CREATE OR REPLACE FUNCTION public.spgenericcustomerpayment_record(p_farmid text, p_customerid integer, p_amount numeric, p_allocations jsonb, p_paymentmethod text DEFAULT NULL::text, p_paymentdate timestamp without time zone DEFAULT NULL::timestamp without time zone, p_cashaccountid integer DEFAULT NULL::integer, p_reference text DEFAULT NULL::text, p_notes text DEFAULT NULL::text, p_sourcetype text DEFAULT 'CustomerBalances'::text, p_createdby text DEFAULT NULL::text)
 RETURNS integer
 LANGUAGE plpgsql
AS $function$
DECLARE
    v_paymentid  integer;
    v_date       timestamp := COALESCE(p_paymentdate, (now() at time zone 'utc'));
    v_amount     numeric(14,2) := round(p_amount, 2);
    v_allocated  numeric(14,2);
    v_salecount  integer;
    v_saledist   integer;
    v_debtcount  integer;
    v_debtdist   integer;
    v_minamount  numeric(14,2);
    v_missing    integer;
    v_row        record;
    v_before     numeric(14,2);
    v_custname   text;
    v_custbal    numeric(14,2);
    v_newbal     numeric(14,2);
    v_cashbal    numeric(14,2);
    v_left       numeric(14,2);
BEGIN
    IF p_amount IS NULL OR p_amount <= 0 THEN
        RAISE EXCEPTION 'Payment amount must be greater than 0.';
    END IF;

    SELECT c.customername, c.currentbalance INTO v_custname, v_custbal
    FROM   genericcustomers c
    WHERE  c.genericcustomerid = p_customerid AND c.farmid = p_farmid;
    IF v_custname IS NULL THEN
        RAISE EXCEPTION 'Customer does not belong to this company.';
    END IF;

    IF p_cashaccountid IS NOT NULL THEN
        SELECT a.currentbalance INTO v_cashbal
        FROM   genericcashaccounts a
        WHERE  a.genericcashaccountid = p_cashaccountid AND a.farmid = p_farmid;
        IF v_cashbal IS NULL THEN
            RAISE EXCEPTION 'Cash account does not belong to this company.';
        END IF;
    END IF;

    -- {saleid, amount} rows and (488) {debtid, amount} rows.
    SELECT COUNT(*) FILTER (WHERE a.saleid IS NOT NULL),
           COUNT(DISTINCT a.saleid),
           COUNT(*) FILTER (WHERE a.saleid IS NULL AND a.debtid IS NOT NULL),
           COUNT(DISTINCT a.debtid) FILTER (WHERE a.saleid IS NULL),
           COALESCE(SUM(a.amount), 0), COALESCE(MIN(a.amount), 0)
    INTO   v_salecount, v_saledist, v_debtcount, v_debtdist, v_allocated, v_minamount
    FROM   jsonb_to_recordset(COALESCE(p_allocations, '[]'::jsonb))
           AS a(saleid integer, debtid integer, amount numeric)
    WHERE  (a.saleid IS NOT NULL OR a.debtid IS NOT NULL) AND COALESCE(a.amount, 0) <> 0;

    IF v_saledist <> v_salecount THEN
        RAISE EXCEPTION 'The same invoice appears more than once in this payment.';
    END IF;
    IF v_debtdist <> v_debtcount THEN
        RAISE EXCEPTION 'The same debt appears more than once in this payment.';
    END IF;
    IF v_salecount + v_debtcount > 0 AND v_minamount <= 0 THEN
        RAISE EXCEPTION 'Each allocation must be greater than 0.';
    END IF;
    -- 488: a payment need not be applied in full (the rest is kept as credit),
    -- but it can never be applied beyond itself.
    IF v_allocated::numeric(14,2) > v_amount THEN
        RAISE EXCEPTION 'Allocated total (%) is more than the payment amount (%).',
              v_allocated::numeric(14,2), v_amount;
    END IF;

    INSERT INTO genericcustomerpayments
        (farmid, genericcustomerid, paymentdate, amount, paymentmethod,
         genericcashaccountid, referenceno, sourcetype, notes, status,
         createdby, approvedby, approvedat, createdat)
    VALUES
        (p_farmid, p_customerid, v_date, v_amount, p_paymentmethod,
         p_cashaccountid, p_reference, COALESCE(p_sourcetype, 'CustomerBalances'),
         p_notes, 'Approved', p_createdby, p_createdby,
         (now() at time zone 'utc'), (now() at time zone 'utc'))
    RETURNING genericcustomerpaymentid INTO v_paymentid;

    -- Oldest invoice first, so a part payment settles the debt that has been
    -- outstanding longest.
    FOR v_row IN
        SELECT a.saleid, a.amount::numeric(14,2) AS amount,
               g.balance, g.totalamount, g.amountpaid, g.saledate, g.receiptnumber
        FROM   jsonb_to_recordset(COALESCE(p_allocations, '[]'::jsonb))
               AS a(saleid integer, amount numeric)
        JOIN   genericsales g ON g.genericsaleid = a.saleid AND g.farmid = p_farmid
        WHERE  a.saleid IS NOT NULL AND COALESCE(a.amount, 0) <> 0
          AND  g.genericcustomerid = p_customerid
          AND  g.status = 'Approved'
          AND  COALESCE(g.isdeleted, FALSE) = FALSE
        ORDER  BY g.saledate, g.genericsaleid
    LOOP
        v_before := GREATEST(COALESCE(v_row.balance, 0), 0);

        IF v_before <= 0 THEN
            RAISE EXCEPTION 'Invoice % is already fully paid.',
                  COALESCE(v_row.receiptnumber, v_row.saleid::text);
        END IF;
        IF v_row.amount > v_before THEN
            RAISE EXCEPTION 'Cannot apply % to invoice % -- its balance is only %.',
                  v_row.amount, COALESCE(v_row.receiptnumber, v_row.saleid::text), v_before;
        END IF;

        UPDATE genericsales
        SET    amountpaid    = amountpaid + v_row.amount,
               balance       = GREATEST(balance - v_row.amount, 0),
               paymentstatus = CASE
                                   WHEN balance - v_row.amount <= 0 THEN 'Paid'
                                   ELSE 'PartiallyPaid' END,
               updatedat     = (now() at time zone 'utc')
        WHERE  genericsaleid = v_row.saleid AND farmid = p_farmid;

        INSERT INTO customerpaymentallocation
            (farmid, module, paymentid, saleid, amountapplied,
             salebalancebefore, salebalanceafter, status, createdby, createdat)
        VALUES
            (p_farmid, 'generic', v_paymentid, v_row.saleid, v_row.amount,
             v_before, v_before - v_row.amount, 'Posted', p_createdby, v_date);
    END LOOP;

    -- 488: customer debts, oldest first. The balance is derived from the
    -- allocations, so the allocation row is the whole posting.
    FOR v_row IN
        SELECT a.debtid, a.amount::numeric(14,2) AS amount, d.debtnumber
        FROM   jsonb_to_recordset(COALESCE(p_allocations, '[]'::jsonb))
               AS a(saleid integer, debtid integer, amount numeric)
        JOIN   genericcustomerdebts d ON d.debtid = a.debtid AND d.farmid = p_farmid
        WHERE  a.saleid IS NULL AND a.debtid IS NOT NULL AND COALESCE(a.amount, 0) <> 0
          AND  d.genericcustomerid = p_customerid
          AND  d.status = 'Posted'
        ORDER  BY d.debtdate, d.debtid
    LOOP
        PERFORM 1 FROM genericcustomerdebts d WHERE d.debtid = v_row.debtid FOR UPDATE;
        v_before := public.fngenericcustomerdebt_balance(p_farmid, v_row.debtid);
        IF v_before <= 0 THEN
            RAISE EXCEPTION 'Debt % is already fully paid.', v_row.debtnumber;
        END IF;
        IF v_row.amount > v_before THEN
            RAISE EXCEPTION 'Cannot apply % to debt % -- what is owed on it is only %.',
                  v_row.amount, v_row.debtnumber, v_before;
        END IF;

        INSERT INTO customerpaymentallocation
            (farmid, module, paymentid, saleid, amountapplied,
             salebalancebefore, salebalanceafter, status, createdby, createdat)
        VALUES
            (p_farmid, 'generic-debt', v_paymentid, v_row.debtid, v_row.amount,
             v_before, v_before - v_row.amount, 'Posted', p_createdby, v_date);
    END LOOP;

    -- Every id must have resolved to an APPROVED invoice / a Posted debt of this
    -- customer. Anything else and the caller is applying money to a document
    -- that cannot receive it.
    SELECT (v_salecount + v_debtcount) - COUNT(*) INTO v_missing
    FROM   customerpaymentallocation ca
    WHERE  ca.farmid = p_farmid AND ca.module IN ('generic', 'generic-debt') AND ca.paymentid = v_paymentid;
    IF v_missing <> 0 THEN
        RAISE EXCEPTION '% of the selected invoices or debts are not open for this customer.', v_missing;
    END IF;

    -- Customer ledger + running balance, matching what _Approve has always done.
    -- The whole payment: what is not applied leaves the customer in credit.
    v_newbal := v_custbal - v_amount;

    INSERT INTO genericcustomerledger
        (farmid, genericcustomerid, transactiondate, transactiontype, paymentid,
         debitamount, creditamount, balanceaftertransaction, description, createdby)
    VALUES
        (p_farmid, p_customerid, v_date, 'PaymentCredit', v_paymentid,
         0, v_amount, v_newbal, COALESCE(p_notes, 'Customer payment'), p_createdby);

    UPDATE genericcustomers
    SET    currentbalance = v_newbal, updatedat = (now() at time zone 'utc')
    WHERE  genericcustomerid = p_customerid AND farmid = p_farmid;

    -- 488: what is not applied is kept as the customer's credit.
    v_left := v_amount - v_allocated::numeric(14,2);
    IF v_left > 0 THEN
        INSERT INTO genericcustomercredits
            ("FarmId", "GenericCustomerId", "CustomerName", "CreditType", "Amount",
             "RemainingBalance", "CreditDate", "ReferenceType", "ReferenceId", "Notes",
             "Status", "CreatedBy", "CreatedAt")
        VALUES
            (p_farmid, p_customerid, v_custname,
             CASE WHEN v_allocated = 0 THEN 'Advance' ELSE 'Overpayment' END,
             v_left, v_left, v_date, 'CustomerPayment', v_paymentid,
             COALESCE(NULLIF(btrim(p_notes), ''),
                      CASE WHEN v_allocated = 0 THEN 'Advance payment' ELSE 'Kept from customer payment' END)
                 || ' (payment #' || v_paymentid::text || ')',
             'Active', p_createdby, (now() at time zone 'utc'));
    END IF;

    -- One CashIn for the whole payment, never one per allocation.
    IF p_cashaccountid IS NOT NULL THEN
        INSERT INTO genericcashtransactions
            (farmid, genericcashaccountid, transactiondate, transactiontype,
             sourcetype, sourceid, amount, balanceaftertransaction, description,
             createdby, approvedby, approvedat)
        VALUES
            (p_farmid, p_cashaccountid, v_date, 'CashIn', 'CustomerPayment', v_paymentid,
             v_amount, v_cashbal + v_amount, COALESCE(p_notes, 'Customer payment'),
             p_createdby, p_createdby, (now() at time zone 'utc'));

        UPDATE genericcashaccounts
        SET    currentbalance = v_cashbal + v_amount, updatedat = (now() at time zone 'utc')
        WHERE  genericcashaccountid = p_cashaccountid AND farmid = p_farmid;
    END IF;

    RETURN v_paymentid;
END;
$function$;

-- ------------------------------------- 6. reversing a payment (live patch) --
-- Adds, before the payment is marked Reversed: its debt allocations are
-- reversed too, and the credit it left is taken back (refused if used).
DO $patch$
DECLARE
    v_def text;
    v_old text;
    v_rep text;
BEGIN
    v_def := pg_get_functiondef('public.spgenericcustomerpayment_reverse(text,integer,text,text)'::regprocedure);
    IF position('generic-debt' IN v_def) = 0 THEN
        -- Anchored on the statement alone: 482 may have been saved with CRLF line ends.
        v_old := 'UPDATE genericcustomerpayments';
        IF (length(v_def) - length(replace(v_def, v_old, ''))) / length(v_old) <> 1 THEN
            RAISE EXCEPTION '488: spgenericcustomerpayment_reverse is not the expected shape (marker missing).';
        END IF;
        v_rep :=
'    -- 488: the credit this payment left is taken back; refused once used.
    IF EXISTS (SELECT 1 FROM genericcustomercredits cr
               WHERE cr."FarmId" = p_farmid AND cr."ReferenceType" = ''CustomerPayment''
                 AND cr."ReferenceId" = p_paymentid AND cr."Status" = ''Active''
                 AND cr."RemainingBalance" < cr."Amount") THEN
        RAISE EXCEPTION ''Part of the credit this payment left has already been used or refunded. Undo that first.'';
    END IF;
    UPDATE genericcustomercredits cr
    SET    "Status" = ''Reversed'', "RemainingBalance" = 0,
           "Notes" = left(COALESCE(cr."Notes", '''') || '' -- reversed with the payment: '' || p_reason, 1000)
    WHERE  cr."FarmId" = p_farmid AND cr."ReferenceType" = ''CustomerPayment''
      AND  cr."ReferenceId" = p_paymentid AND cr."Status" = ''Active'';

