-- ------------------------------------------- 7. payment details and history --
CREATE OR REPLACE FUNCTION public.spgenericcustomerpayment_allocations(p_farmid text, p_paymentid integer)
 RETURNS TABLE(allocationid integer, paymentid integer, documenttype text, documentid integer, reference text, documentdate date, label text, documenttotal numeric, amountapplied numeric, balancebefore numeric, balanceafter numeric, status text)
 LANGUAGE sql
 STABLE
AS $function$
    SELECT ca.allocationid, ca.paymentid,
           CASE WHEN ca.module = 'generic-debt' THEN 'CustomerDebt'
                WHEN g.genericsubscriptionid IS NOT NULL THEN 'Invoice' ELSE 'Sale' END::text,
           ca.saleid,
           CASE WHEN ca.module = 'generic-debt' THEN COALESCE(d.debtnumber, 'CD' || ca.saleid::text)
                ELSE COALESCE(NULLIF(btrim(g.receiptnumber), ''), 'S' || ca.saleid::text) END::text,
           CASE WHEN ca.module = 'generic-debt' THEN d.debtdate ELSE g.saledate::date END,
           CASE WHEN ca.module = 'generic-debt' THEN COALESCE(d.description, 'Customer debt')
                ELSE COALESCE(NULLIF(btrim(g.notes), ''), g.salestype, 'Sale') END::text,
           CASE WHEN ca.module = 'generic-debt' THEN d.amount ELSE g.totalamount END,
           ca.amountapplied, ca.salebalancebefore, ca.salebalanceafter,
           ca.status
    FROM   customerpaymentallocation ca
    LEFT   JOIN genericsales g ON ca.module = 'generic' AND g.genericsaleid = ca.saleid AND g.farmid = ca.farmid
    LEFT   JOIN genericcustomerdebts d ON ca.module = 'generic-debt' AND d.debtid = ca.saleid AND d.farmid = ca.farmid
    WHERE  ca.farmid = p_farmid AND ca.module IN ('generic', 'generic-debt') AND ca.paymentid = p_paymentid
    ORDER  BY ca.allocationid;
$function$;

CREATE OR REPLACE FUNCTION public.spgenericcustomerpayment_history(p_farmid text, p_customerid integer DEFAULT NULL::integer, p_saleid integer DEFAULT NULL::integer, p_from date DEFAULT NULL::date, p_to date DEFAULT NULL::date)
 RETURNS TABLE(paymentid integer, partyid integer, partyname text, paymentdate timestamp without time zone, totalamount numeric, paymentmethod text, reference text, notes text, sourcetype text, status text, allocationcount integer, cashaccountid integer, createdby text, reversedby text, reversedat timestamp without time zone, reversalreason text, createdat timestamp without time zone)
 LANGUAGE sql
 STABLE
AS $function$
    SELECT p.genericcustomerpaymentid, p.genericcustomerid, c.customername::text,
           p.paymentdate, p.amount, p.paymentmethod::text, p.referenceno,
           p.notes::text, p.sourcetype,
           -- The balances UI speaks Posted/Reversed; generic has always stored
           -- Draft/Approved/Cancelled. Translated here rather than leaving the
           -- frontend to guess.
           CASE p.status WHEN 'Approved' THEN 'Posted'
                         WHEN 'Reversed' THEN 'Reversed'
                         ELSE p.status END::text,
           -- 488: debts count as applied documents too.
           (SELECT COUNT(*)::integer FROM customerpaymentallocation ca
            WHERE ca.farmid = p_farmid AND ca.module IN ('generic', 'generic-debt')
              AND ca.paymentid = p.genericcustomerpaymentid),
           p.genericcashaccountid, p.createdby::text,
           p.reversedby, p.reversedat, p.reversalreason
           , p.createdat   -- 304: the entry time
    FROM   genericcustomerpayments p
    LEFT   JOIN genericcustomers c ON c.genericcustomerid = p.genericcustomerid
    WHERE  p.farmid = p_farmid
      AND  p.status IN ('Approved', 'Reversed')
      AND  (p_customerid IS NULL OR p.genericcustomerid = p_customerid)
      AND  (p_from IS NULL OR p.paymentdate::date >= p_from)
      AND  (p_to   IS NULL OR p.paymentdate::date <= p_to)
      AND  (p_saleid IS NULL OR EXISTS (
                SELECT 1 FROM customerpaymentallocation ca
                WHERE ca.farmid = p_farmid AND ca.module = 'generic'
                  AND ca.paymentid = p.genericcustomerpaymentid AND ca.saleid = p_saleid))
    ORDER  BY p.paymentdate DESC, p.genericcustomerpaymentid DESC;
$function$;
