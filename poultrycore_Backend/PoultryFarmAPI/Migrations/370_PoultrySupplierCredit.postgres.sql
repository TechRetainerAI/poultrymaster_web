-- ------------------------------------------------------- 2. credit, derived --
CREATE OR REPLACE FUNCTION public.fnpoultrysupplier_iscreditkind(p_sourcetype text)
RETURNS boolean LANGUAGE sql IMMUTABLE AS $f$
    SELECT COALESCE(p_sourcetype, '') IN ('SupplierCreditNote', 'SupplierOpeningCredit', 'SupplierManualCredit');
$f$;

CREATE OR REPLACE FUNCTION public.fnpoultrysupplierpayment_unapplied(p_farmid text, p_paymentid integer)
RETURNS numeric LANGUAGE sql STABLE AS $f$
    SELECT CASE WHEN sp.status <> 'Posted' THEN 0
                ELSE GREATEST(sp.totalamount
                     - COALESCE((SELECT SUM(sa.amountapplied) FROM supplierpaymentallocation sa
                                 WHERE sa.farmid = sp.farmid AND sa.module = 'poultry'
                                   AND sa.paymentid = sp.poultrysupplierpaymentid AND sa.status = 'Posted'), 0)
                     - COALESCE((SELECT SUM(rl.amount) FROM poultrysupplierrefundlines rl
                                 JOIN poultrysupplierrefunds r ON r.refundid = rl.refundid AND r.status = 'Posted'
                                 WHERE rl.farmid = sp.farmid AND rl.poultrysupplierpaymentid = sp.poultrysupplierpaymentid), 0), 0)
           END::numeric(14,2)
    FROM   poultrysupplierpayments sp
    WHERE  sp.poultrysupplierpaymentid = p_paymentid AND sp.farmid = p_farmid;
$f$;

CREATE OR REPLACE FUNCTION public.fnpoultrysupplier_credit(p_farmid text, p_supplierid integer)
RETURNS numeric LANGUAGE sql STABLE AS $f$
    SELECT COALESCE(SUM(public.fnpoultrysupplierpayment_unapplied(p_farmid, sp.poultrysupplierpaymentid)), 0)::numeric(14,2)
    FROM   poultrysupplierpayments sp
    WHERE  sp.farmid = p_farmid AND sp.supplierid = p_supplierid AND sp.status = 'Posted';
$f$;

-- Every credit event: a payment row that holds or held credit.
--   original = amount - what was applied when it was paid (not from credit)
--   applied  = applied later, from credit;  refunded = Posted refund lines
CREATE OR REPLACE FUNCTION public.sppoultrysuppliercredit_events(p_farmid text, p_supplierid integer DEFAULT NULL)
RETURNS TABLE(poultrysupplierpaymentid integer, creditnumber text, creditdate timestamp, supplierid integer,
              suppliername text, source text, sourcetype text, reference text, notes text, originalamount numeric,
              applied numeric, refunded numeric, available numeric, status text, ismanual boolean,
              poultrycashaccountid integer, accountname text)
LANGUAGE sql STABLE AS $f$
    WITH x AS (
        SELECT sp.*,
               COALESCE((SELECT SUM(sa.amountapplied) FROM supplierpaymentallocation sa
                         WHERE sa.farmid = sp.farmid AND sa.module = 'poultry' AND sa.paymentid = sp.poultrysupplierpaymentid
                           AND sa.status = 'Posted' AND NOT sa.fromcredit), 0) AS paidnow,
               COALESCE((SELECT SUM(sa.amountapplied) FROM supplierpaymentallocation sa
                         WHERE sa.farmid = sp.farmid AND sa.module = 'poultry' AND sa.paymentid = sp.poultrysupplierpaymentid
                           AND sa.status = 'Posted' AND sa.fromcredit), 0) AS appliedlater,
               COALESCE((SELECT SUM(rl.amount) FROM poultrysupplierrefundlines rl
                         JOIN poultrysupplierrefunds r ON r.refundid = rl.refundid AND r.status = 'Posted'
                         WHERE rl.farmid = sp.farmid AND rl.poultrysupplierpaymentid = sp.poultrysupplierpaymentid), 0) AS refundedamt,
               EXISTS (SELECT 1 FROM supplierpaymentallocation sa
                       WHERE sa.farmid = sp.farmid AND sa.module = 'poultry' AND sa.paymentid = sp.poultrysupplierpaymentid
                         AND NOT sa.fromcredit) AS hadallocations
        FROM   poultrysupplierpayments sp
        WHERE  sp.farmid = p_farmid AND sp.status = 'Posted' AND sp.supplierid IS NOT NULL
          AND  (p_supplierid IS NULL OR sp.supplierid = p_supplierid)
    )
    SELECT x.poultrysupplierpaymentid, ('SP-' || lpad(x.poultrysupplierpaymentid::text, 5, '0'))::text, x.paymentdate,
           x.supplierid, s.name::text,
           CASE x.sourcetype
                WHEN 'SupplierCreditNote'    THEN 'Credit note'
                WHEN 'SupplierOpeningCredit' THEN 'Opening credit'
                WHEN 'SupplierManualCredit'  THEN 'Manual credit'
                ELSE CASE WHEN x.hadallocations THEN 'Overpayment' ELSE 'Supplier advance' END
           END,
           x.sourcetype::text, x.referenceno::text, x.notes::text,
           (x.totalamount - x.paidnow)::numeric(14,2), x.appliedlater::numeric(14,2), x.refundedamt::numeric(14,2),
           fnpoultrysupplierpayment_unapplied(p_farmid, x.poultrysupplierpaymentid),
           CASE WHEN fnpoultrysupplierpayment_unapplied(p_farmid, x.poultrysupplierpaymentid) <= 0
                     AND x.refundedamt > 0 AND x.appliedlater = 0 THEN 'Refunded'
                WHEN fnpoultrysupplierpayment_unapplied(p_farmid, x.poultrysupplierpaymentid) <= 0 THEN 'Used'
                WHEN x.appliedlater > 0 OR x.refundedamt > 0 THEN 'Partly used'
                ELSE 'Available' END,
           (fnpoultrysupplier_iscreditkind(x.sourcetype) OR NOT x.hadallocations),
           x.poultrycashaccountid, a.accountname::text
    FROM   x
    LEFT   JOIN supplier s ON s.supplierid = x.supplierid AND s.farmid = x.farmid
    LEFT   JOIN poultrycashaccounts a ON a.poultrycashaccountid = x.poultrycashaccountid AND a.farmid = x.farmid
    WHERE  (x.totalamount - x.paidnow) > 0
    ORDER  BY x.paymentdate DESC, x.poultrysupplierpaymentid DESC;
$f$;

CREATE OR REPLACE FUNCTION public.sppoultrysuppliercredit_summary(p_farmid text)
RETURNS TABLE(supplierid integer, suppliername text, availablecredit numeric, creditcount integer, owed numeric)
LANGUAGE sql STABLE AS $f$
    SELECT s.supplierid, s.name::text, x.credit, x.n,
           COALESCE((SELECT SUM(d.balance) FROM fnpoultrypayables(p_farmid) d WHERE d.supplierid = s.supplierid), 0)::numeric(14,2)
    FROM (
        SELECT sp.supplierid,
               SUM(fnpoultrysupplierpayment_unapplied(p_farmid, sp.poultrysupplierpaymentid))::numeric(14,2) AS credit,
               COUNT(*) FILTER (WHERE fnpoultrysupplierpayment_unapplied(p_farmid, sp.poultrysupplierpaymentid) > 0)::integer AS n
        FROM   poultrysupplierpayments sp
        WHERE  sp.farmid = p_farmid AND sp.supplierid IS NOT NULL AND sp.status = 'Posted'
        GROUP  BY sp.supplierid
    ) x
    JOIN   supplier s ON s.supplierid = x.supplierid AND s.farmid = p_farmid
    WHERE  x.credit > 0
    ORDER  BY x.credit DESC;
$f$;

-- ------------------------------------------------ 3. manual credit (no cash) --
CREATE OR REPLACE FUNCTION public.sppoultrysuppliercredit_create(p_farmid text, p_supplierid integer, p_kind text,
    p_amount numeric, p_date timestamp DEFAULT NULL, p_reference text DEFAULT NULL, p_reason text DEFAULT NULL,
    p_by text DEFAULT NULL)
RETURNS integer LANGUAGE plpgsql AS $f$
DECLARE
    v_id integer;
BEGIN
    IF p_kind NOT IN ('SupplierCreditNote', 'SupplierOpeningCredit', 'SupplierManualCredit') THEN
        RAISE EXCEPTION 'Choose what the credit is: a credit note, an opening credit or a manual credit.' USING ERRCODE = 'P0001';
    END IF;
    IF p_amount IS NULL OR round(p_amount, 2) <= 0 THEN
        RAISE EXCEPTION 'Enter an amount greater than 0.' USING ERRCODE = 'P0001';
    END IF;
    IF NULLIF(btrim(COALESCE(p_reason, '')), '') IS NULL THEN
        RAISE EXCEPTION 'Give a reason for the credit.' USING ERRCODE = 'P0001';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM supplier s WHERE s.supplierid = p_supplierid AND s.farmid = p_farmid) THEN
        RAISE EXCEPTION 'Supplier does not belong to this company.' USING ERRCODE = 'P0001';
    END IF;
    -- No cash account: nothing moves through any account (the cash sync posts
    -- nothing without one).
    INSERT INTO poultrysupplierpayments
        (farmid, supplierid, paymentdate, totalamount, paymentmethod, poultrycashaccountid,
         referenceno, notes, sourcetype, status, createdby, createdat)
    VALUES
        (p_farmid, p_supplierid, COALESCE(p_date, (now() AT TIME ZONE 'utc')), round(p_amount, 2), NULL, NULL,
         NULLIF(btrim(COALESCE(p_reference, '')), ''), left(btrim(p_reason), 300), p_kind, 'Posted', p_by,
         (now() AT TIME ZONE 'utc'))
    RETURNING poultrysupplierpaymentid INTO v_id;
    RETURN v_id;
END
$f$;

-- ------------------------------------------------- 4. apply / unapply credit --
CREATE OR REPLACE FUNCTION public.sppoultrysuppliercredit_apply(p_farmid text, p_paymentid integer,
    p_documenttype text, p_documentid integer, p_amount numeric, p_by text DEFAULT NULL)
RETURNS integer LANGUAGE plpgsql AS $f$
DECLARE
    v_sp     record;
    v_doc    record;
    v_amt    numeric(14,2) := round(p_amount, 2);
    v_avail  numeric(14,2);
    v_before numeric(14,2);
    v_alloc  integer;
    v_gid    uuid;
    v_name   text;
    v_now    timestamp := (now() AT TIME ZONE 'utc');
BEGIN
    IF v_amt IS NULL OR v_amt <= 0 THEN
        RAISE EXCEPTION 'Enter an amount greater than 0.' USING ERRCODE = 'P0001';
    END IF;
    SELECT sp.* INTO v_sp FROM poultrysupplierpayments sp
    WHERE  sp.poultrysupplierpaymentid = p_paymentid AND sp.farmid = p_farmid;
    IF NOT FOUND OR v_sp.supplierid IS NULL THEN
        RAISE EXCEPTION 'That credit does not belong to this company.' USING ERRCODE = 'P0001';
    END IF;
    PERFORM pg_advisory_xact_lock(hashtext('poultry-suppliercredit:' || p_farmid || ':' || v_sp.supplierid::text));
    v_avail := fnpoultrysupplierpayment_unapplied(p_farmid, p_paymentid);
    IF v_amt > v_avail THEN
        RAISE EXCEPTION 'That credit only has % available.', v_avail USING ERRCODE = 'P0001';
    END IF;

    SELECT d.* INTO v_doc FROM fnpoultrypayables(p_farmid) d
    WHERE  d.documenttype = p_documenttype AND d.documentid = p_documentid;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'That item is not an open payable of this company.' USING ERRCODE = 'P0001';
    END IF;
    IF v_doc.supplierid IS DISTINCT FROM v_sp.supplierid THEN
        RAISE EXCEPTION 'That item is owed to a different supplier.' USING ERRCODE = 'P0001';
    END IF;
    v_before := GREATEST(COALESCE(v_doc.balance, 0), 0);
    IF v_before <= 0 THEN
        RAISE EXCEPTION '% is already fully paid.', v_doc.reference USING ERRCODE = 'P0001';
    END IF;
    IF v_amt > v_before THEN
        RAISE EXCEPTION 'Only % is owed on %.', v_before, v_doc.reference USING ERRCODE = 'P0001';
    END IF;
    IF EXISTS (SELECT 1 FROM supplierpaymentallocation sa
               WHERE sa.module = 'poultry' AND sa.paymentid = p_paymentid
                 AND sa.documenttype = p_documenttype AND sa.documentid = p_documentid) THEN
        RAISE EXCEPTION 'This credit has already been applied to % once. Use another credit, or pay it.', v_doc.reference
            USING ERRCODE = 'P0001';
    END IF;

    IF p_documenttype = 'RawMaterialPurchase' THEN
        UPDATE poultryrawmaterialpurchases pu
        SET    amountpaid = pu.amountpaid + v_amt, updatedat = v_now
        WHERE  pu.poultryrawmaterialpurchaseid = p_documentid AND pu.farmid = p_farmid;
    ELSIF p_documenttype = 'FlockBatch' THEN
        UPDATE mainflockbatch b SET amountpaid = b.amountpaid + v_amt
        WHERE  b.batchid = p_documentid AND b.farmid = p_farmid;
    ELSIF p_documenttype = 'SupplierDebt' THEN
        UPDATE poultrysupplierdebts d SET amountpaid = d.amountpaid + v_amt
        WHERE  d.debtid = p_documentid AND d.farmid = p_farmid;
    ELSIF p_documenttype = 'Expense' THEN
        UPDATE expense e
        SET    amountpaid = LEAST(COALESCE(e.amountpaid, e.amount) + v_amt, e.amount)
        WHERE  e.expenseid = p_documentid AND lower(e.farmid::text) = lower(p_farmid);
    ELSE
        RAISE EXCEPTION 'Credit cannot be applied to a %.', p_documenttype USING ERRCODE = 'P0001';
    END IF;

    INSERT INTO supplierpaymentallocation
        (farmid, module, paymentid, documenttype, documentid, amountapplied,
         documentbalancebefore, documentbalanceafter, status, createdby, createdat, fromcredit)
    VALUES
        (p_farmid, 'poultry', p_paymentid, p_documenttype, p_documentid, v_amt,
         v_before, v_before - v_amt, 'Posted', p_by, v_now, TRUE)
    RETURNING allocationid INTO v_alloc;

    -- The cost of a lot expensed at purchase, or of birds, lands now -- as a
    -- NonCash expense: the cash left with the credit's payment.
    BEGIN v_gid := p_farmid::uuid; EXCEPTION WHEN OTHERS THEN v_gid := NULL; END;
    SELECT s.name INTO v_name FROM supplier s WHERE s.supplierid = v_sp.supplierid AND s.farmid = p_farmid;
    IF v_gid IS NOT NULL
       AND (p_documenttype = 'FlockBatch'
            OR (p_documenttype = 'RawMaterialPurchase'
                AND fnpoultrycostrecognition_expenseatpurchase(
                        (SELECT pu.costrecognitionmethod FROM poultryrawmaterialpurchases pu
                         WHERE pu.poultryrawmaterialpurchaseid = p_documentid AND pu.farmid = p_farmid)))) THEN
        INSERT INTO expense (expensedate, category, description, amount, paymentmethod,
                             supplier, flockid, createddate, userid, farmid, sourcetype, sourceid)
        VALUES (v_now,
                CASE WHEN p_documenttype = 'FlockBatch' THEN 'Flock / Bird Purchase' ELSE 'Raw Materials / Inventory Purchase' END,
                'Supplier credit allocation #' || v_alloc::text || ' against ' || p_documenttype || ' #' || p_documentid::text
                    || ': ' || COALESCE(v_doc.label, ''),
                v_amt, 'NonCash', v_name, NULL, v_now, COALESCE(p_by, '0'), v_gid,
                CASE WHEN p_documenttype = 'FlockBatch' THEN 'MainFlockBatch' ELSE 'PoultryRawMaterialPurchase' END,
                p_documentid);
    END IF;

    -- The document's own "paid at entry" cash excludes allocations, so it is
    -- unchanged; re-sync anyway, as the payment path does.
    IF p_documenttype = 'RawMaterialPurchase' THEN
        PERFORM sppoultryrawmaterialpurchasecash_sync(p_farmid, p_documentid, v_doc.cashaccountid, FALSE, p_by);
    ELSIF p_documenttype = 'Expense' THEN
        PERFORM sppoultryexpensecash_resync(p_farmid, p_documentid, p_by);
    END IF;
    RETURN v_alloc;
END
$f$;

CREATE OR REPLACE FUNCTION public.sppoultrysuppliercredit_unapply(p_farmid text, p_allocationid integer,
    p_reason text, p_by text DEFAULT NULL)
RETURNS integer LANGUAGE plpgsql AS $f$
DECLARE
    v_a  record;
    v_sp record;
BEGIN
    IF NULLIF(btrim(COALESCE(p_reason, '')), '') IS NULL THEN
        RAISE EXCEPTION 'Give a reason.' USING ERRCODE = 'P0001';
    END IF;
    SELECT sa.* INTO v_a FROM supplierpaymentallocation sa
    WHERE  sa.allocationid = p_allocationid AND sa.farmid = p_farmid AND sa.module = 'poultry' FOR UPDATE;
    IF NOT FOUND OR NOT v_a.fromcredit THEN
        RAISE EXCEPTION 'That is not an application of supplier credit in this company.' USING ERRCODE = 'P0001';
    END IF;
    IF v_a.status <> 'Posted' THEN
        RAISE EXCEPTION 'That application has already been reversed.' USING ERRCODE = 'P0001';
    END IF;
    SELECT sp.* INTO v_sp FROM poultrysupplierpayments sp WHERE sp.poultrysupplierpaymentid = v_a.paymentid AND sp.farmid = p_farmid;
    PERFORM pg_advisory_xact_lock(hashtext('poultry-suppliercredit:' || p_farmid || ':' || v_sp.supplierid::text));

    IF v_a.documenttype = 'RawMaterialPurchase' THEN
        UPDATE poultryrawmaterialpurchases pu
        SET    amountpaid = GREATEST(pu.amountpaid - v_a.amountapplied, 0), updatedat = (now() AT TIME ZONE 'utc')
        WHERE  pu.poultryrawmaterialpurchaseid = v_a.documentid AND pu.farmid = p_farmid;
    ELSIF v_a.documenttype = 'FlockBatch' THEN
        UPDATE mainflockbatch b SET amountpaid = GREATEST(b.amountpaid - v_a.amountapplied, 0)
        WHERE  b.batchid = v_a.documentid AND b.farmid = p_farmid;
    ELSIF v_a.documenttype = 'SupplierDebt' THEN
        UPDATE poultrysupplierdebts d SET amountpaid = GREATEST(d.amountpaid - v_a.amountapplied, 0)
        WHERE  d.debtid = v_a.documentid AND d.farmid = p_farmid;
    ELSE
        UPDATE expense e
        SET    amountpaid = GREATEST(COALESCE(e.amountpaid, e.amount) - v_a.amountapplied, 0)
        WHERE  e.expenseid = v_a.documentid AND lower(e.farmid::text) = lower(p_farmid);
    END IF;

    -- Its NonCash cost comes off with it (expense has no status column; the
    -- trail is the allocation, kept as Reversed).
    DELETE FROM expense e
    WHERE  e.sourcetype IN ('PoultryRawMaterialPurchase', 'MainFlockBatch')
      AND  e.description LIKE 'Supplier credit allocation #' || p_allocationid::text || ' against %';

    UPDATE supplierpaymentallocation sa
    SET    status = 'Reversed', reversedby = p_by, reversedat = (now() AT TIME ZONE 'utc'), reversalreason = btrim(p_reason)
    WHERE  sa.allocationid = p_allocationid;

    IF v_a.documenttype = 'RawMaterialPurchase' THEN
        PERFORM sppoultryrawmaterialpurchasecash_sync(p_farmid, v_a.documentid, NULL, FALSE, p_by);
    ELSIF v_a.documenttype = 'Expense' THEN
        PERFORM sppoultryexpensecash_resync(p_farmid, v_a.documentid, p_by);
    END IF;
    RETURN p_allocationid;
END
$f$;

-- Applications of one supplier's credit (or all), newest first.
CREATE OR REPLACE FUNCTION public.sppoultrysuppliercredit_applications(p_farmid text, p_supplierid integer DEFAULT NULL)
RETURNS TABLE(allocationid integer, poultrysupplierpaymentid integer, creditnumber text, supplierid integer,
              suppliername text, documenttype text, documentid integer, reference text, label text, amount numeric,
              applieddate timestamp, status text, createdby text, reversedat timestamp, reversalreason text)
LANGUAGE sql STABLE AS $f$
    SELECT sa.allocationid, sa.paymentid, ('SP-' || lpad(sa.paymentid::text, 5, '0'))::text, sp.supplierid, s.name::text,
           sa.documenttype, sa.documentid,
           COALESCE(d.reference, sa.documenttype || ' #' || sa.documentid::text)::text, d.label::text,
           sa.amountapplied, sa.createdat, sa.status, sa.createdby, sa.reversedat, sa.reversalreason
    FROM   supplierpaymentallocation sa
    JOIN   poultrysupplierpayments sp ON sp.poultrysupplierpaymentid = sa.paymentid AND sp.farmid = sa.farmid
    LEFT   JOIN supplier s ON s.supplierid = sp.supplierid AND s.farmid = sp.farmid
    LEFT   JOIN fnpoultrypayables(p_farmid) d ON d.documenttype = sa.documenttype AND d.documentid = sa.documentid
    WHERE  sa.farmid = p_farmid AND sa.module = 'poultry' AND sa.fromcredit
      AND  (p_supplierid IS NULL OR sp.supplierid = p_supplierid)
    ORDER  BY sa.createdat DESC, sa.allocationid DESC;
$f$;

-- ------------------------------------------------------ 5. supplier refunds --
CREATE OR REPLACE FUNCTION public.sppoultrysupplierrefund_record(p_farmid text, p_paymentid integer, p_amount numeric,
    p_cashaccountid integer, p_paymentmethod text, p_refunddate date, p_reason text, p_by text DEFAULT NULL)
RETURNS integer LANGUAGE plpgsql AS $f$
DECLARE
    v_sp     record;
    v_amt    numeric(14,2) := round(p_amount, 2);
    v_avail  numeric(14,2);
    v_id     integer;
    v_number text;
    v_bal    numeric(14,2);
    v_txn    integer;
    v_name   text;
    v_date   date := COALESCE(p_refunddate, fncompany_businessdate(p_farmid));
BEGIN
    IF v_amt IS NULL OR v_amt <= 0 THEN
        RAISE EXCEPTION 'Enter an amount greater than 0.' USING ERRCODE = 'P0001';
    END IF;
    IF NULLIF(btrim(COALESCE(p_reason, '')), '') IS NULL THEN
        RAISE EXCEPTION 'Give a reason.' USING ERRCODE = 'P0001';
    END IF;
    SELECT sp.* INTO v_sp FROM poultrysupplierpayments sp
    WHERE  sp.poultrysupplierpaymentid = p_paymentid AND sp.farmid = p_farmid;
    IF NOT FOUND OR v_sp.supplierid IS NULL OR v_sp.status <> 'Posted' THEN
        RAISE EXCEPTION 'That credit does not belong to this company.' USING ERRCODE = 'P0001';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM poultrycashaccounts a WHERE a.poultrycashaccountid = p_cashaccountid AND a.farmid = p_farmid) THEN
