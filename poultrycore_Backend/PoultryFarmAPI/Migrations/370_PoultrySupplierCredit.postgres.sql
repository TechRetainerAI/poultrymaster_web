CREATE OR REPLACE FUNCTION public.sppoultrysupplierdebt_reverse(p_farmid text, p_debtid integer, p_reason text, p_by text DEFAULT NULL)
RETURNS integer LANGUAGE plpgsql AS $f$
DECLARE
    v_d record;
BEGIN
    IF NULLIF(btrim(COALESCE(p_reason, '')), '') IS NULL THEN
        RAISE EXCEPTION 'Give a reason for reversing the debt.' USING ERRCODE = 'P0001';
    END IF;
    SELECT d.* INTO v_d FROM poultrysupplierdebts d WHERE d.debtid = p_debtid AND d.farmid = p_farmid FOR UPDATE;
