CREATE OR REPLACE FUNCTION public.sppoultrysupplierrefund_reverse(p_farmid text, p_refundid integer, p_reason text, p_by text DEFAULT NULL)
RETURNS integer LANGUAGE plpgsql AS $f$
DECLARE
    v_r    record;
    v_bal  numeric(14,2);
    v_txn  integer;
    v_name text;
    v_date date := fncompany_businessdate(p_farmid);
BEGIN
    IF NULLIF(btrim(COALESCE(p_reason, '')), '') IS NULL THEN
        RAISE EXCEPTION 'Give a reason for reversing the refund.' USING ERRCODE = 'P0001';
    END IF;
    SELECT r.* INTO v_r FROM poultrysupplierrefunds r WHERE r.refundid = p_refundid AND r.farmid = p_farmid FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Refund not found for this company.' USING ERRCODE = 'P0001';
    END IF;
    PERFORM pg_advisory_xact_lock(hashtext('poultry-suppliercredit:' || p_farmid || ':' || v_r.supplierid::text));
    IF v_r.status <> 'Posted' THEN
        RAISE EXCEPTION 'Refund % has already been reversed.', v_r.refundnumber USING ERRCODE = 'P0001';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM poultrycashaccounts a WHERE a.poultrycashaccountid = v_r.poultrycashaccountid AND a.farmid = p_farmid) THEN
        RAISE EXCEPTION 'The account the refund came into no longer exists.' USING ERRCODE = 'P0001';
    END IF;
    SELECT s.name INTO v_name FROM supplier s WHERE s.supplierid = v_r.supplierid AND s.farmid = p_farmid;

    UPDATE poultrycashaccounts a
    SET    currentbalance = a.currentbalance - v_r.amount, updatedat = (now() AT TIME ZONE 'utc')
    WHERE  a.poultrycashaccountid = v_r.poultrycashaccountid AND a.farmid = p_farmid
    RETURNING a.currentbalance INTO v_bal;
    INSERT INTO poultrycashtransactions
        (farmid, poultrycashaccountid, transactiondate, transactiontype, sourcetype, sourceid,
         amount, balanceaftertransaction, description, createdby, approvedby, approvedat)
    VALUES
        (p_farmid, v_r.poultrycashaccountid, v_date::timestamp, 'CashOut', 'SupplierRefundReversal', v_r.refundid,
         -v_r.amount, v_bal, 'Supplier refund reversal ' || v_r.refundnumber || ' - ' || COALESCE(v_name, ''),
         p_by, p_by, (now() AT TIME ZONE 'utc'))
    RETURNING poultrycashtransactionid INTO v_txn;
    UPDATE poultrysupplierrefunds r
    SET    status = 'Reversed', reversedat = (now() AT TIME ZONE 'utc'), reversedby = p_by,
           reversalreason = btrim(p_reason), reversaldate = v_date, reversalcashtransactionid = v_txn
    WHERE  r.refundid = v_r.refundid;
    RETURN v_r.refundid;
END
$f$;

