-- =============================================================================
-- 370_PoultrySupplierCredit.postgres.sql
--
-- Purpose (Phase 4 of the manual-entry & credits programme)
-- -------
-- Supplier credit, advances, refunds and debt -- the supplier side of what
-- 351 / 363 / 367 / 369 built for customers. Credit is DERIVED, never stored.
--
-- SUPPLIER CREDIT
--   Every source of supplier credit is a row in poultrysupplierpayments:
--     an ADVANCE        a real payment applied to nothing (cash out);
--     an OVERPAYMENT    a real payment applied to less than its amount;
--     a MANUAL credit   no cash: sourcetype SupplierCreditNote /
--                       SupplierOpeningCredit / SupplierManualCredit, no account.
--   Credit on a payment = amount - Posted allocations - Posted refund lines
--   (fnpoultrysupplierpayment_unapplied).
--
--   APPLYING credit to a purchase / batch / bill / supplier debt is a new
--   allocation on the CREDIT'S payment, marked fromcredit, dated when applied.
--   The document's amountpaid goes up as for a payment. For a lot expensed at
--   purchase or a flock batch, the cost is booked as a NonCash expense on the
--   day it is applied (Profit & Loss yes, Cash Flow no -- the cash left with
--   the advance). Unapplying reverses exactly that.
--
--   A REFUND is the supplier sending money back out of credit: Money In to the
--   account chosen; reversible (Money Out, the refund kept as Reversed).
--
--   A credit source cannot be reversed while any of it is applied or refunded.
--
-- CASH FLOW
--   Supplier cash showed only through expense rows and allocations, so an
--   advance or an overpayment was invisible. New rows:
--     3e SupplierAdvance      the part of a payment not shown by any other row,
--                             on the payment's day (an advance stays an advance
--                             on that day, whatever it is applied to later);
--     3f SupplierDebtPayment  payments of supplier debts;
--     3g SupplierRefund / 3h SupplierRefundReversal.
--   A payment's Cash Flow therefore always totals its amount, on its own day.
--
-- SUPPLIER DEBT
--   poultrysupplierdebts (SD-00001): what the business already owes a
--   supplier without a purchase here. A payable: fnpoultrypayables gains a
--   'SupplierDebt' branch, so supplier balances, open items, statements and
--   payments see it. No purchase, no stock, no expense, no cash. Reversal is
--   refused while anything is paid on it.
--
-- Deploy order: this migration, then the API, then the web app.
-- =============================================================================
BEGIN;

