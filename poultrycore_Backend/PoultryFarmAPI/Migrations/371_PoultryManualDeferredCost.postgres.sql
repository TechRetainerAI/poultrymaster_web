-- =============================================================================
-- 371_PoultryManualDeferredCost.postgres.sql
--
-- Purpose (Phase 5 of the manual-entry & credits programme)
-- -------
-- Record cost for stock the farm already holds that NO purchase lot covers --
-- e.g. opening stock: B1 Feed 2,000 kg on hand with GHC 12,000 of historical
-- cost not yet in Profit & Loss. The cost is then recognised as the stock is
-- used, exactly like a purchase whose cost is expensed when consumed.
--
-- It is a LOT, like every purchase (the design of 264 / 288 keeps one cost
-- layer), marked lotsource = 'ManualDeferredCost':
--   quantity / remaining   the stock it covers, in the item's stock unit
--   deferred total / left  the amount; recognised by the existing draws
--   amountpaid = totalcost nothing is owed; no supplier, no account, no cash
-- A side record (poultrymanualdeferredcosts) holds the entry type, reason,
-- reference, who / when, and the reversal.
--
-- ONLY for uncovered stock: the quantity may not exceed the item's stock less
-- what its lots already hold (the stock usage would otherwise fail to draw:
-- "Not enough tracked batch stock"). Physical stock does not change.
--
-- REVERSAL takes back only what is not yet recognised: the deferred total is
-- cut to what has been recognised and nothing is left to recognise. The stock
-- (quantity) stays: it is real. Recognised history is never touched.
--
-- Readers that took every lot to be a purchase are patched (section 4):
-- physical stock, payables, cash, purchase lists and reports, purchase edit /
-- delete / pay-balance / upfront functions (which refuse the manual lot).
--
-- Deploy order: this migration, then the API, then the web app.
-- =============================================================================
BEGIN;

-- --------------------------------------------------------------- 1. tables --
ALTER TABLE public.poultryrawmaterialpurchases ADD COLUMN IF NOT EXISTS lotsource text;
CREATE INDEX IF NOT EXISTS ix_poultryrmpurchases_manualdeferred
    ON public.poultryrawmaterialpurchases (farmid, poultryrawmaterialitemid) WHERE lotsource = 'ManualDeferredCost';

CREATE TABLE IF NOT EXISTS public.poultrymanualdeferredcosts (
    entryid                       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmid                        text          NOT NULL,
    entrynumber                   text          NOT NULL,
    poultryrawmaterialpurchaseid  integer       NOT NULL REFERENCES public.poultryrawmaterialpurchases(poultryrawmaterialpurchaseid),
    poultryrawmaterialitemid      integer       NOT NULL,
    entrytype                     text          NOT NULL CHECK (entrytype IN
                                      ('OpeningDeferredCost', 'HistoricalDeferredCost', 'CostAdjustment', 'Migration', 'Other')),
    amount                        numeric(14,2) NOT NULL CHECK (amount > 0),
    quantity                      numeric(14,3) NOT NULL CHECK (quantity > 0),
    effectivedate                 date          NOT NULL,
    reason                        text          NOT NULL,
    reference                     text,
    notes                         text,
    status                        text          NOT NULL DEFAULT 'Posted' CHECK (status IN ('Posted', 'Reversed')),
    createdby                     text,
    createdat                     timestamp     NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    reversedby                    text,
    reversedat                    timestamp,
    reversalreason                text,
    reversedamount                numeric(14,2)
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_poultrymanualdeferredcosts_number ON public.poultrymanualdeferredcosts (farmid, entrynumber);
CREATE UNIQUE INDEX IF NOT EXISTS ux_poultrymanualdeferredcosts_lot ON public.poultrymanualdeferredcosts (poultryrawmaterialpurchaseid);

-- ---------------------------------------------------- 2. uncovered stock --
-- The item's stock less what its lots still hold (the lots usage draws from).
CREATE OR REPLACE FUNCTION public.fnpoultryrawmaterial_uncoveredstock(p_farmid text, p_itemid integer)
RETURNS numeric LANGUAGE sql STABLE AS $f$
    SELECT GREATEST(COALESCE(i.currentquantity, 0)
             - COALESCE((SELECT SUM(p.remainingquantity * COALESCE(NULLIF(p.productionunitsperpurchaseunit, 0), 1))
                         FROM   poultryrawmaterialpurchases p
                         WHERE  p.poultryrawmaterialitemid = i.poultryrawmaterialitemid AND p.farmid = i.farmid
                           AND  p.remainingquantity > 0), 0), 0)::numeric(14,3)
    FROM   poultryrawmaterialitems i
    WHERE  i.poultryrawmaterialitemid = p_itemid AND i.farmid = p_farmid;
$f$;

-- ------------------------------------------------------ 3. create / reverse --
CREATE OR REPLACE FUNCTION public.sppoultrymanualdeferredcost_create(p_farmid text, p_itemid integer, p_amount numeric,
    p_quantity numeric, p_effectivedate date, p_entrytype text, p_reason text, p_reference text DEFAULT NULL,
    p_notes text DEFAULT NULL, p_by text DEFAULT NULL)
RETURNS jsonb LANGUAGE plpgsql AS $f$
DECLARE
    v_item      record;
    v_amt       numeric(14,2) := round(p_amount, 2);
    v_qty       numeric(14,3) := round(p_quantity, 3);
    v_uncovered numeric(14,3);
    v_lot       integer;
    v_id        integer;
    v_number    text;
BEGIN
    IF v_amt IS NULL OR v_amt <= 0 THEN
        RAISE EXCEPTION 'Enter the cost, greater than 0.' USING ERRCODE = 'P0001';
    END IF;
    IF v_qty IS NULL OR v_qty <= 0 THEN
        RAISE EXCEPTION 'Enter the quantity of stock this cost is for, greater than 0.' USING ERRCODE = 'P0001';
    END IF;
    IF p_entrytype IS NULL OR p_entrytype NOT IN ('OpeningDeferredCost', 'HistoricalDeferredCost', 'CostAdjustment', 'Migration', 'Other') THEN
        RAISE EXCEPTION 'Choose what this cost is.' USING ERRCODE = 'P0001';
    END IF;
    IF NULLIF(btrim(COALESCE(p_reason, '')), '') IS NULL THEN
        RAISE EXCEPTION 'Give a reason.' USING ERRCODE = 'P0001';
    END IF;
    IF p_effectivedate IS NULL THEN
        RAISE EXCEPTION 'Give the date the cost applies from.' USING ERRCODE = 'P0001';
    END IF;
    SELECT i.* INTO v_item FROM poultryrawmaterialitems i
    WHERE  i.poultryrawmaterialitemid = p_itemid AND i.farmid = p_farmid FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'That item does not belong to this company.' USING ERRCODE = 'P0001';
    END IF;
    v_uncovered := fnpoultryrawmaterial_uncoveredstock(p_farmid, p_itemid);
    IF v_qty > v_uncovered THEN
        RAISE EXCEPTION 'Only % % of "%" is not already covered by a purchase. A manual cost can only cover stock no purchase covers.',
            v_uncovered, COALESCE(v_item.unitofmeasure, ''), v_item.itemname USING ERRCODE = 'P0001';
    END IF;

    INSERT INTO poultryrawmaterialpurchases
        (farmid, poultryrawmaterialitemid, suppliername, supplierid, purchasedate, quantity, unitcost, totalcost,
         productionunit, productionunitsperpurchaseunit, paymentmethod, amountpaid, notes, createdby, createdat,
         poultrycashaccountid, remainingquantity, costrecognitionmethod, deferredtotalcost, deferredremainingcost, lotsource)
    VALUES
        (p_farmid, p_itemid, NULL, NULL, p_effectivedate::timestamp, v_qty, round(v_amt / v_qty, 2), v_amt,
         v_item.unitofmeasure, 1, 'NonCash', v_amt, left('Manual deferred cost: ' || btrim(p_reason), 500),
         p_by, (now() AT TIME ZONE 'utc'),
         NULL, v_qty, 'EXPENSE_WHEN_CONSUMED', v_amt, v_amt, 'ManualDeferredCost')
    RETURNING poultryrawmaterialpurchaseid INTO v_lot;

    PERFORM pg_advisory_xact_lock(hashtext('poultry-manualdeferred-no:' || p_farmid));
    SELECT 'MDC-' || lpad((COALESCE(MAX(NULLIF(regexp_replace(m.entrynumber, '\D', '', 'g'), '')::int), 0) + 1)::text, 5, '0')
    INTO   v_number FROM poultrymanualdeferredcosts m WHERE m.farmid = p_farmid;

    INSERT INTO poultrymanualdeferredcosts
        (farmid, entrynumber, poultryrawmaterialpurchaseid, poultryrawmaterialitemid, entrytype, amount, quantity,
         effectivedate, reason, reference, notes, createdby)
    VALUES
        (p_farmid, v_number, v_lot, p_itemid, p_entrytype, v_amt, v_qty, p_effectivedate, btrim(p_reason),
         NULLIF(btrim(COALESCE(p_reference, '')), ''), NULLIF(btrim(COALESCE(p_notes, '')), ''), p_by)
    RETURNING entryid INTO v_id;

    RETURN jsonb_build_object('entryId', v_id, 'entryNumber', v_number, 'lotId', v_lot);
END
$f$;

CREATE OR REPLACE FUNCTION public.sppoultrymanualdeferredcost_reverse(p_farmid text, p_entryid integer, p_reason text, p_by text DEFAULT NULL)
RETURNS numeric LANGUAGE plpgsql AS $f$
DECLARE
    v_m   record;
    v_lot record;
    v_rev numeric(14,2);
BEGIN
    IF NULLIF(btrim(COALESCE(p_reason, '')), '') IS NULL THEN
        RAISE EXCEPTION 'Give a reason for reversing.' USING ERRCODE = 'P0001';
    END IF;
    SELECT m.* INTO v_m FROM poultrymanualdeferredcosts m WHERE m.entryid = p_entryid AND m.farmid = p_farmid FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Entry not found for this company.' USING ERRCODE = 'P0001';
    END IF;
    IF v_m.status <> 'Posted' THEN
        RAISE EXCEPTION '% has already been reversed.', v_m.entrynumber USING ERRCODE = 'P0001';
    END IF;
    SELECT p.* INTO v_lot FROM poultryrawmaterialpurchases p
    WHERE  p.poultryrawmaterialpurchaseid = v_m.poultryrawmaterialpurchaseid AND p.farmid = p_farmid FOR UPDATE;
    v_rev := v_lot.deferredremainingcost;

    -- Only what is not yet recognised comes off; what usage already put on
    -- Profit & Loss stays there. The stock is real, so its quantity stays.
    UPDATE poultryrawmaterialpurchases p
    SET    deferredtotalcost     = GREATEST(p.deferredtotalcost - p.deferredremainingcost, 0),
           deferredremainingcost = 0,
           updatedat             = (now() AT TIME ZONE 'utc')
    WHERE  p.poultryrawmaterialpurchaseid = v_lot.poultryrawmaterialpurchaseid;

    UPDATE poultrymanualdeferredcosts m
    SET    status = 'Reversed', reversedby = p_by, reversedat = (now() AT TIME ZONE 'utc'),
           reversalreason = btrim(p_reason), reversedamount = v_rev
    WHERE  m.entryid = p_entryid;
    RETURN v_rev;
END
$f$;

CREATE OR REPLACE FUNCTION public.sppoultrymanualdeferredcost_list(p_farmid text)
RETURNS TABLE(entryid integer, entrynumber text, poultryrawmaterialpurchaseid integer, poultryrawmaterialitemid integer,
              itemname text, unitofmeasure text, entrytype text, amount numeric, quantity numeric, effectivedate date,
              recognised numeric, remaining numeric, remainingquantity numeric, reason text, reference text, notes text,
              status text, createdby text, createdat timestamp, reversedby text, reversedat timestamp,
              reversalreason text, reversedamount numeric)
LANGUAGE sql STABLE AS $f$
    SELECT m.entryid, m.entrynumber, m.poultryrawmaterialpurchaseid, m.poultryrawmaterialitemid,
           i.itemname::text, i.unitofmeasure::text, m.entrytype, m.amount, m.quantity, m.effectivedate,
           GREATEST(p.deferredtotalcost - p.deferredremainingcost, 0)::numeric(14,2),
           p.deferredremainingcost, p.remainingquantity,
           m.reason, m.reference, m.notes, m.status, m.createdby, m.createdat,
           m.reversedby, m.reversedat, m.reversalreason, m.reversedamount
    FROM   poultrymanualdeferredcosts m
    JOIN   poultryrawmaterialpurchases p ON p.poultryrawmaterialpurchaseid = m.poultryrawmaterialpurchaseid
    LEFT   JOIN poultryrawmaterialitems i ON i.poultryrawmaterialitemid = m.poultryrawmaterialitemid
    WHERE  m.farmid = p_farmid
    ORDER  BY m.effectivedate DESC, m.entryid DESC;
$f$;

-- Items with stock no purchase covers (what a manual cost may be entered for).
CREATE OR REPLACE FUNCTION public.sppoultryrawmaterial_uncoveredstock(p_farmid text)
RETURNS TABLE(poultryrawmaterialitemid integer, itemname text, unitofmeasure text, currentquantity numeric, uncoveredquantity numeric)
LANGUAGE sql STABLE AS $f$
    SELECT i.poultryrawmaterialitemid, i.itemname::text, i.unitofmeasure::text, i.currentquantity,
           fnpoultryrawmaterial_uncoveredstock(p_farmid, i.poultryrawmaterialitemid)
    FROM   poultryrawmaterialitems i
    WHERE  i.farmid = p_farmid
      AND  fnpoultryrawmaterial_uncoveredstock(p_farmid, i.poultryrawmaterialitemid) > 0
    ORDER  BY i.itemname;
$f$;

-- ------------------------------------------------------- 4. live patches --
CREATE FUNCTION pg_temp.m371_patch(p_fn text, p_marker text, p_old text, p_new text)
RETURNS void LANGUAGE plpgsql AS $f$
DECLARE
    v_oid oid;
    v_n   integer;
    v_def text;
    v_old text := replace(p_old, chr(13), '');
    v_new text := replace(p_new, chr(13), '');
BEGIN
    SELECT count(*), min(p.oid) INTO v_n, v_oid
    FROM   pg_proc p WHERE p.proname = p_fn AND p.pronamespace = 'public'::regnamespace;
    IF v_n <> 1 THEN
        RAISE EXCEPTION '371: expected exactly one %, found %', p_fn, v_n;
    END IF;
    v_def := replace(pg_get_functiondef(v_oid), chr(13), '');
    IF position(replace(p_marker, chr(13), '') IN v_def) > 0 THEN
        RAISE NOTICE '371: % already patched (%), skipped', p_fn, p_marker;
        RETURN;
    END IF;
    v_n := (length(v_def) - length(replace(v_def, v_old, ''))) / greatest(length(v_old), 1);
    IF v_n <> 1 THEN
        RAISE EXCEPTION '371: anchor for % (%) found % times, expected 1', p_fn, p_marker, v_n;
    END IF;
    EXECUTE replace(v_def, v_old, v_new);
    RAISE NOTICE '371: patched % (%)', p_fn, p_marker;
END
$f$;

