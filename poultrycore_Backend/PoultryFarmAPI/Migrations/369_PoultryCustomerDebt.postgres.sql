-- =============================================================================
-- 369_PoultryCustomerDebt.postgres.sql
--
-- Purpose (Phase 3 of the manual-entry & credits programme)
-- -------
-- Record what a customer owes WITHOUT a sale: money owed from before the farm
-- used the system, a historical or external transaction, a migration, an
-- adjustment. The user records the EVENT; the balance is derived.
--
--   poultrycustomerdebts   one row per debt (CD-00001): customer, amount, date,
--                          entry type, description (required), reference, notes.
--                          Posted, or Reversed (kept, with who / when / why).
--   Owed on a debt       = amount - Posted allocations (module 'poultry-debt').
--
-- A debt is NOT a sale: no revenue, no stock, no cash, nothing on Daily Closing
-- or Profit & Loss. It is owed: Customer Balances, the statement, open items
-- in the payment dialog, credit 'still owes', Advanced Reports customer balance.
--
-- PAYING A DEBT is an ordinary customer payment. sppoultrycustomerpayment_record
-- accepts allocations {debtid, amount} beside {saleid, amount}: each becomes a
-- poultrypayments row with saleid NULL and the new debtid column, and an
-- allocation with module 'poultry-debt' (customerpaymentallocation.saleid holds
-- the debt id, namespaced by module). Cash comes in once for the whole payment.
-- Paying a debt needs the cash account (a debt has none of its own).
--
-- REVERSING a debt is refused while any payment is applied to it ("reverse
-- those payments first"); an unpaid debt is simply Reversed. No cash moves.
--
-- Readers of poultrypayments that took "saleid NULL" to mean credit are
-- patched to also look at debtid (see section 4).
--
-- Deploy order: this migration, then the API, then the web app.
-- =============================================================================
BEGIN;

-- --------------------------------------------------------------- 1. tables --
CREATE TABLE IF NOT EXISTS public.poultrycustomerdebts (
    debtid          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmid          text          NOT NULL,
    debtnumber      text          NOT NULL,
    customerid      integer       NOT NULL,
    amount          numeric(14,2) NOT NULL CHECK (amount > 0),
    debtdate        date          NOT NULL,
    entrytype       text          NOT NULL CHECK (entrytype IN
                        ('OpeningBalance', 'HistoricalDebt', 'Adjustment', 'Migration', 'ExternalTransaction', 'Other')),
    description     text          NOT NULL,
    reference       text,
    notes           text,
    status          text          NOT NULL DEFAULT 'Posted' CHECK (status IN ('Posted', 'Reversed')),
    createdby       text,
    createdat       timestamp     NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    reversedby      text,
    reversedat      timestamp,
    reversalreason  text
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_poultrycustomerdebts_number ON public.poultrycustomerdebts (farmid, debtnumber);
CREATE INDEX IF NOT EXISTS ix_poultrycustomerdebts_cust ON public.poultrycustomerdebts (farmid, customerid) WHERE status = 'Posted';

ALTER TABLE public.poultrypayments ADD COLUMN IF NOT EXISTS debtid integer;
CREATE INDEX IF NOT EXISTS ix_poultrypayments_debt ON public.poultrypayments (farmid, debtid) WHERE debtid IS NOT NULL;

-- A payment row is on a sale, on a debt, or is credit.
ALTER TABLE public.poultrypayments DROP CONSTRAINT IF EXISTS ck_poultrypayments_saleorcredit;
ALTER TABLE public.poultrypayments ADD CONSTRAINT ck_poultrypayments_saleorcredit
    CHECK (saleid IS NOT NULL
           OR (debtid IS NOT NULL AND customerid IS NOT NULL)
           OR (sourcetype IN ('OpeningCredit', 'Deposit', 'CreditNote') AND customerid IS NOT NULL));
ALTER TABLE public.poultrypayments DROP CONSTRAINT IF EXISTS ck_poultrypayments_saleordebt;
ALTER TABLE public.poultrypayments ADD CONSTRAINT ck_poultrypayments_saleordebt
    CHECK (saleid IS NULL OR debtid IS NULL);

-- ------------------------------------------------------------ 2. derived --
CREATE OR REPLACE FUNCTION public.fnpoultrycustomerdebt_paid(p_farmid text, p_debtid integer)
RETURNS numeric LANGUAGE sql STABLE AS $f$
    SELECT COALESCE(SUM(ca.amountapplied), 0)::numeric(14,2)
    FROM   customerpaymentallocation ca
    WHERE  ca.module = 'poultry-debt' AND ca.saleid = p_debtid AND ca.farmid = p_farmid AND ca.status = 'Posted';
$f$;

CREATE OR REPLACE FUNCTION public.fnpoultrycustomerdebt_balance(p_farmid text, p_debtid integer)
RETURNS numeric LANGUAGE sql STABLE AS $f$
    SELECT CASE WHEN d.status = 'Posted'
                THEN GREATEST(d.amount - public.fnpoultrycustomerdebt_paid(p_farmid, d.debtid), 0)
                ELSE 0 END::numeric(14,2)
    FROM   poultrycustomerdebts d
    WHERE  d.debtid = p_debtid AND d.farmid = p_farmid;
$f$;

-- What a customer owes on debts (optionally only those dated before a day).
CREATE OR REPLACE FUNCTION public.fnpoultrycustomer_debtowed(p_farmid text, p_customerid integer, p_before date DEFAULT NULL)
RETURNS numeric LANGUAGE sql STABLE AS $f$
    SELECT COALESCE(SUM(public.fnpoultrycustomerdebt_balance(p_farmid, d.debtid)), 0)::numeric(14,2)
    FROM   poultrycustomerdebts d
    WHERE  d.farmid = p_farmid AND d.customerid = p_customerid AND d.status = 'Posted'
      AND  (p_before IS NULL OR d.debtdate < p_before);
$f$;

-- ------------------------------------------------------ 3. create / reverse --
CREATE OR REPLACE FUNCTION public.sppoultrycustomerdebt_create(p_farmid text, p_customerid integer, p_amount numeric,
    p_debtdate date, p_entrytype text, p_description text, p_reference text DEFAULT NULL, p_notes text DEFAULT NULL,
    p_by text DEFAULT NULL)
RETURNS jsonb LANGUAGE plpgsql AS $f$
DECLARE
    v_id     integer;
    v_number text;
BEGIN
    IF p_amount IS NULL OR round(p_amount, 2) <= 0 THEN
        RAISE EXCEPTION 'Enter the amount owed, greater than 0.' USING ERRCODE = 'P0001';
    END IF;
    IF p_entrytype IS NULL OR p_entrytype NOT IN ('OpeningBalance', 'HistoricalDebt', 'Adjustment', 'Migration', 'ExternalTransaction', 'Other') THEN
        RAISE EXCEPTION 'Choose why the customer owes this.' USING ERRCODE = 'P0001';
    END IF;
    IF NULLIF(btrim(COALESCE(p_description, '')), '') IS NULL THEN
        RAISE EXCEPTION 'Describe what the debt is for.' USING ERRCODE = 'P0001';
    END IF;
    IF p_debtdate IS NULL THEN
        RAISE EXCEPTION 'Give the date the debt is owed from.' USING ERRCODE = 'P0001';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM customer c WHERE c.customerid = p_customerid AND c.farmid = p_farmid) THEN
        RAISE EXCEPTION 'Customer does not belong to this company.' USING ERRCODE = 'P0001';
    END IF;

    PERFORM pg_advisory_xact_lock(hashtext('poultry-customerdebt-no:' || p_farmid));
    SELECT 'CD-' || lpad((COALESCE(MAX(NULLIF(regexp_replace(d.debtnumber, '\D', '', 'g'), '')::int), 0) + 1)::text, 5, '0')
    INTO   v_number FROM poultrycustomerdebts d WHERE d.farmid = p_farmid;

    INSERT INTO poultrycustomerdebts
        (farmid, debtnumber, customerid, amount, debtdate, entrytype, description, reference, notes, createdby)
    VALUES
        (p_farmid, v_number, p_customerid, round(p_amount, 2), p_debtdate, p_entrytype, left(btrim(p_description), 300),
         NULLIF(btrim(COALESCE(p_reference, '')), ''), NULLIF(btrim(COALESCE(p_notes, '')), ''), p_by)
    RETURNING debtid INTO v_id;

    RETURN jsonb_build_object('debtId', v_id, 'debtNumber', v_number);
END
$f$;

CREATE OR REPLACE FUNCTION public.sppoultrycustomerdebt_reverse(p_farmid text, p_debtid integer, p_reason text, p_by text DEFAULT NULL)
RETURNS integer LANGUAGE plpgsql AS $f$
DECLARE
    v_d    record;
    v_paid numeric(14,2);
BEGIN
    IF NULLIF(btrim(COALESCE(p_reason, '')), '') IS NULL THEN
        RAISE EXCEPTION 'Give a reason for reversing the debt.' USING ERRCODE = 'P0001';
    END IF;
    SELECT d.* INTO v_d FROM poultrycustomerdebts d WHERE d.debtid = p_debtid AND d.farmid = p_farmid FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Debt not found for this company.' USING ERRCODE = 'P0001';
    END IF;
    IF v_d.status <> 'Posted' THEN
        RAISE EXCEPTION 'Debt % has already been reversed.', v_d.debtnumber USING ERRCODE = 'P0001';
    END IF;
    v_paid := fnpoultrycustomerdebt_paid(p_farmid, p_debtid);
    IF v_paid > 0 THEN
        RAISE EXCEPTION '% has already been paid on debt %. Reverse those payments first (Payments Received).', v_paid, v_d.debtnumber
            USING ERRCODE = 'P0001';
    END IF;
    UPDATE poultrycustomerdebts d
    SET    status = 'Reversed', reversedby = p_by, reversedat = (now() AT TIME ZONE 'utc'), reversalreason = btrim(p_reason)
    WHERE  d.debtid = p_debtid;
    RETURN p_debtid;
END
$f$;

CREATE OR REPLACE FUNCTION public.sppoultrycustomerdebt_list(p_farmid text, p_customerid integer DEFAULT NULL)
RETURNS TABLE(debtid integer, debtnumber text, customerid integer, customername text, amount numeric, paid numeric,
              balance numeric, debtdate date, entrytype text, description text, reference text, notes text,
              status text, createdby text, createdat timestamp, reversedby text, reversedat timestamp, reversalreason text)
LANGUAGE sql STABLE AS $f$
    SELECT d.debtid, d.debtnumber, d.customerid, c.name::text, d.amount,
           fnpoultrycustomerdebt_paid(p_farmid, d.debtid),
           fnpoultrycustomerdebt_balance(p_farmid, d.debtid),
           d.debtdate, d.entrytype, d.description, d.reference, d.notes, d.status,
           d.createdby, d.createdat, d.reversedby, d.reversedat, d.reversalreason
    FROM   poultrycustomerdebts d
    LEFT   JOIN customer c ON c.customerid = d.customerid AND c.farmid = d.farmid
    WHERE  d.farmid = p_farmid AND (p_customerid IS NULL OR d.customerid = p_customerid)
    ORDER  BY d.debtdate DESC, d.debtid DESC;
$f$;

-- Open debts of one customer, for the payment dialog (beside its open sales).
CREATE OR REPLACE FUNCTION public.sppoultrycustomeropendebts(p_farmid text, p_customerid integer)
RETURNS TABLE(debtid integer, debtnumber text, debtdate date, description text, entrytype text, amount numeric,
              paid numeric, balance numeric, duedate date, agedays integer, status text, isoverdue boolean)
LANGUAGE sql STABLE AS $f$
    SELECT d.debtid, d.debtnumber, d.debtdate, d.description, d.entrytype, d.amount,
           fnpoultrycustomerdebt_paid(p_farmid, d.debtid),
           fnpoultrycustomerdebt_balance(p_farmid, d.debtid),
           (d.debtdate + COALESCE(c.paymenttermsdays, 0))::date,
           GREATEST((CURRENT_DATE - d.debtdate), 0)::integer,
           CASE WHEN fnpoultrycustomerdebt_paid(p_farmid, d.debtid) > 0 THEN 'Partially Paid' ELSE 'Unpaid' END::text,
           ((d.debtdate + COALESCE(c.paymenttermsdays, 0)) < CURRENT_DATE)
    FROM   poultrycustomerdebts d
    JOIN   customer c ON c.customerid = d.customerid AND c.farmid = d.farmid
    WHERE  d.farmid = p_farmid AND d.customerid = p_customerid AND d.status = 'Posted'
      AND  fnpoultrycustomerdebt_balance(p_farmid, d.debtid) > 0
    ORDER  BY d.debtdate, d.debtid;
$f$;

