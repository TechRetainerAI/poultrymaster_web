-- 4g. Advanced Reports, Customer Balance: debts included (same columns).
CREATE OR REPLACE FUNCTION public.sppoultryreport_customerbalance(p_farmid text, p_enddate date, p_customername text DEFAULT NULL::text)
 RETURNS TABLE(customer text, customerid integer, contactphone text, totalsales numeric, totalpaid numeric, balance numeric, overdueamount numeric, opensalecount integer, lastsaledate date, lastpaymentdate timestamp without time zone)
 LANGUAGE sql
 STABLE
AS $function$
    -- 369: a customer debt is owed like a sale; it counts in Total (billed), Paid
    -- and Balance, but never in Last sale.
    WITH docs AS (
        SELECT COALESCE(c.name, s.customername)::text AS cname, c.customerid, c.contactphone::text AS phone,
               s.totalamount AS total,
               fnpoultrysalereceived(s.paid, s.totalamount, s.amountpaid) AS paid,
               fnpoultrysalebalance(s.paid, s.totalamount, s.amountpaid)  AS bal,
               s.saledate AS docdate, s.saledate AS saledate, COALESCE(c.paymenttermsdays, 0) AS terms,
               (SELECT MAX(pp.paymentdate) FROM poultrypayments pp
                WHERE pp.farmid = p_farmid AND pp.saleid = s.saleid
                  AND COALESCE(pp.status, 'Posted') = 'Posted') AS lastpay
        FROM   sale s
        LEFT   JOIN customer c ON c.customerid = s.customerid AND c.farmid = s.farmid
        WHERE  s.status = 'Posted' AND s.farmid = p_farmid
          AND  s.saledate < (p_enddate + 1)
          AND  s.customername IS NOT NULL AND btrim(s.customername) <> ''
          AND  (p_customername IS NULL OR s.customername = p_customername)
        UNION ALL
        SELECT c.name::text, c.customerid, c.contactphone::text,
               d.amount, d.amount - fnpoultrycustomerdebt_balance(p_farmid, d.debtid), fnpoultrycustomerdebt_balance(p_farmid, d.debtid),
               d.debtdate, NULL::date, COALESCE(c.paymenttermsdays, 0),
               (SELECT MAX(pp.paymentdate) FROM poultrypayments pp
                WHERE pp.farmid = p_farmid AND pp.debtid = d.debtid
                  AND COALESCE(pp.status, 'Posted') = 'Posted')
        FROM   poultrycustomerdebts d
        JOIN   customer c ON c.customerid = d.customerid AND c.farmid = d.farmid
        WHERE  d.status = 'Posted' AND d.farmid = p_farmid
          AND  d.debtdate < (p_enddate + 1)
          AND  (p_customername IS NULL OR c.name = p_customername)
    )
    SELECT x.cname, x.customerid, x.phone,
           SUM(x.total)::numeric(14,2), SUM(x.paid)::numeric(14,2), SUM(x.bal)::numeric(14,2),
           SUM(CASE WHEN (x.docdate + x.terms) < CURRENT_DATE THEN x.bal ELSE 0 END)::numeric(14,2),
           COUNT(*) FILTER (WHERE x.bal > 0)::integer,
           MAX(x.saledate), MAX(x.lastpay)
    FROM   docs x
    GROUP  BY x.cname, x.customerid, x.phone
    ORDER  BY SUM(x.bal) DESC;
$function$;

