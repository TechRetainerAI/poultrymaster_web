-- 4k. Payment drilldown shows what went to a debt (saleid is NULL for a debt
-- line, so the screen never links it as a sale). Same columns.
CREATE OR REPLACE FUNCTION public.sppoultrycustomerpayment_allocations(p_farmid text, p_paymentgroupid uuid)
 RETURNS TABLE(allocationid integer, paymentid integer, saleid integer, saledate date, product text, saletotal numeric, amountapplied numeric, salebalancebefore numeric, salebalanceafter numeric, status text)
 LANGUAGE sql
 STABLE
AS $function$
    SELECT ca.allocationid, ca.paymentid,
           CASE WHEN ca.module = 'poultry' THEN ca.saleid END,   -- 369: a debt id is not a sale id
           COALESCE(s.saledate, d.debtdate),
           CASE WHEN ca.module = 'poultry-debt' THEN 'Debt ' || COALESCE(d.debtnumber, '#' || ca.saleid::text)
                ELSE fnpoultrysale_productlabel(s.saleid) END,
           COALESCE(s.totalamount, d.amount), ca.amountapplied, ca.salebalancebefore, ca.salebalanceafter, ca.status
    FROM   customerpaymentallocation ca
    JOIN   poultrypayments pp ON pp.poultrypaymentid = ca.paymentid AND pp.farmid = ca.farmid
    LEFT   JOIN sale s ON ca.module = 'poultry' AND s.saleid = ca.saleid AND s.farmid = ca.farmid
    LEFT   JOIN poultrycustomerdebts d ON ca.module = 'poultry-debt' AND d.debtid = ca.saleid AND d.farmid = ca.farmid
    WHERE  ca.farmid = p_farmid AND ca.module IN ('poultry', 'poultry-debt')
      AND  pp.paymentgroupid = p_paymentgroupid
    ORDER  BY COALESCE(s.saledate, d.debtdate), ca.saleid;
$function$;

COMMIT;
