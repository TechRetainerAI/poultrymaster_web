-- =============================================================================
-- 478  Water: reverse an inventory (raw material) purchase -- the sale
--      reversal model, applied to purchases. Delete is retired.
-- =============================================================================
--
-- Copies 458 (water sale reversal):
--   * the purchase row is KEPT and stamped (purchasereversalid / reversedat /
--     reversedby / reversalreason) and a numbered reversal is written
--     (waterpurchasereversals, WPR-00001) with a snapshot of the preview;
--   * reason code from the list, "Other" needs a note (354);
--   * a server-side preview (spwaterpurchase_reversalpreview) with blockers,
--     money lines and a fingerprint; a stale preview is refused (HINT
--     'stale-preview'); an idempotency key makes a double click harmless;
--   * each money line is either KeepAsCredit or Refund (the sale's
--     ReversePayment), chosen per line.
--
-- What a reversal does:
--   1. supplier credit spent on the purchase goes back to the supplier
--      (spwatersuppliercredit_unapply), like a sale's applied customer credit;
--   2. stock: one 'PurchaseReversal' adjustment for the whole purchase, lot
--      emptied (remaining 0, deferred remaining 0) -- as 462's receipts;
--   3. money paid on the purchase, per line (paid at entry, each supplier
--      payment):
--        KeepAsCredit  a 'PurchaseReversalCredit' supplier-credit row, no cash
--                      (needs a supplier on the purchase);
--        Refund        a NEW CashIn today into the account the money left
--                      ('WaterPurchaseReversal'), and Cash Flow arm 3i.
--      The original payment, its expense and its CashOut stay: the money did
--      leave on that day. Append-only, like 458 kept its payments Posted.
--
-- Blocked while any of the lot has been used (user, 2026-11-23): the message
-- names the production records to reopen. Also blocked: receipt lots (reverse
-- the receipt), manual deferred costs, stock already short.
--
-- Readers: payables / purchase list / deferred rows / closing report already
-- skip reversed lots (462). P&L raw materials now skip them too, and count a
-- reversal credit when it is spent later (it is money, unlike a credit note --
-- fnwatersupplier_movednomoney). Supplier activity skips them. A payment a
-- reversal settled can no longer be reversed; a reversal credit can be
-- refunded or applied but not erased. spwaterrawmaterialpurchase_delete now
-- refuses.
--
-- Idempotent.
-- =============================================================================

BEGIN;

-- ---------------------------------------------------------------------------
-- 1. Tables and columns
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.waterpurchasereversals (
    purchasereversalid     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmid                 text        NOT NULL,
    reversalnumber         text        NOT NULL,
    waterrawmaterialpurchaseid integer NOT NULL,
    waterrawmaterialitemid integer,
    itemname               text,
    supplierid             integer,
    suppliername           text,
    purchasedate           timestamp,
    reasoncode             text,
    reason                 text        NOT NULL DEFAULT '',
    businessdate           date        NOT NULL,
    occurredat             timestamp   NOT NULL,
    reversedby             text,
    quantity               numeric(18,4),
    stockremoved           numeric(18,4),          -- production units taken back out
    totalcost              numeric(14,2) NOT NULL DEFAULT 0,
    paidamount             numeric(14,2) NOT NULL DEFAULT 0,
    outstandingamount      numeric(14,2) NOT NULL DEFAULT 0,
    creditreleased         numeric(14,2) NOT NULL DEFAULT 0,   -- supplier credit that had been applied, given back
    creditcreated          numeric(14,2) NOT NULL DEFAULT 0,   -- money kept as supplier credit
    refunded               numeric(14,2) NOT NULL DEFAULT 0,   -- money the supplier handed back
    paymenthandling        text        NOT NULL DEFAULT 'None',
    adjustmentid           integer,
    idempotencykey         text,
    snapshot               jsonb,
    createdat              timestamp   NOT NULL DEFAULT (now() AT TIME ZONE 'utc')
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_waterpurchasereversals_number ON public.waterpurchasereversals (farmid, reversalnumber);
CREATE UNIQUE INDEX IF NOT EXISTS ux_waterpurchasereversals_purchase ON public.waterpurchasereversals (farmid, waterrawmaterialpurchaseid);
CREATE UNIQUE INDEX IF NOT EXISTS ux_waterpurchasereversals_idem ON public.waterpurchasereversals (farmid, idempotencykey)
    WHERE idempotencykey IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.waterpurchasereversalpayments (
    purchasereversalpaymentid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchasereversalid     integer     NOT NULL REFERENCES public.waterpurchasereversals (purchasereversalid),
    farmid                 text        NOT NULL,
    linekey                text        NOT NULL,
    source                 text        NOT NULL,          -- 'PaidAtEntry' | 'SupplierPayment'
    watersupplierpaymentid integer,                       -- the payment, for SupplierPayment lines
    amount                 numeric(14,2) NOT NULL,
    action                 text        NOT NULL CHECK (action IN ('Refund', 'KeepAsCredit')),
    cashaccountid          integer,                       -- where a refund went back in
    cashtransactionid      integer,                       -- the refund's CashIn
    creditpaymentid        integer                        -- the PurchaseReversalCredit row
);
CREATE INDEX IF NOT EXISTS ix_waterpurchasereversalpayments_payment
    ON public.waterpurchasereversalpayments (farmid, watersupplierpaymentid);

ALTER TABLE public.waterrawmaterialpurchases ADD COLUMN IF NOT EXISTS purchasereversalid integer;
ALTER TABLE public.waterrawmaterialpurchases ADD COLUMN IF NOT EXISTS reversedby text;
ALTER TABLE public.waterrawmaterialpurchases ADD COLUMN IF NOT EXISTS reversalreason text;

-- ---------------------------------------------------------------------------
-- 2. A reversed purchase is history: nothing may change or delete it again,
--    except the reversal itself (GUC water.purchase_reversal).
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.trg_waterrmpurchase_reversedlock_fn()
RETURNS trigger LANGUAGE plpgsql AS $f$
DECLARE v_no text;
BEGIN
    IF OLD.purchasereversalid IS NULL OR current_setting('water.purchase_reversal', true) = 'on' THEN
        RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
    END IF;
    SELECT r.reversalnumber INTO v_no FROM public.waterpurchasereversals r
    WHERE  r.purchasereversalid = OLD.purchasereversalid;
    RAISE EXCEPTION 'Purchase #% was reversed (%). A reversed purchase can no longer be changed.',
          OLD.waterrawmaterialpurchaseid, COALESCE(v_no, 'reversal') USING ERRCODE = 'P0001';
END $f$;

DROP TRIGGER IF EXISTS trg_waterrmpurchase_reversedlock ON public.waterrawmaterialpurchases;
CREATE TRIGGER trg_waterrmpurchase_reversedlock
    BEFORE UPDATE OR DELETE ON public.waterrawmaterialpurchases
    FOR EACH ROW EXECUTE FUNCTION public.trg_waterrmpurchase_reversedlock_fn();

-- ---------------------------------------------------------------------------
-- 3. "Moved no money": the supplier-credit kinds that must never reach the
--    P&L. PurchaseReversalCredit is a credit kind (no cash when it is created,
--    lives on Supplier Credits) but it is money really paid earlier, so when it
--    is spent on a later purchase that purchase's cost IS on the P&L.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.fnwatersupplier_movednomoney(p_sourcetype text)
RETURNS boolean LANGUAGE sql IMMUTABLE AS $f$
    SELECT COALESCE(p_sourcetype, '') IN ('SupplierCreditNote', 'SupplierOpeningCredit', 'SupplierManualCredit');
$f$;

-- ---------------------------------------------------------------------------
-- 4. The reversal state: blockers, money lines, fingerprint
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.fnwaterpurchase_reversalstate(p_farmid text, p_purchaseid integer)
RETURNS jsonb LANGUAGE plpgsql STABLE AS $f$
DECLARE
    v_p        record;
    v_blockers jsonb := '[]'::jsonb;
    v_money    jsonb := '[]'::jsonb;
    v_mult     numeric;
    v_prodqty  numeric;
    v_receipt  text;
    v_used     text;
    v_credit   numeric(14,2);
    v_alloc    numeric(14,2);
    v_entry    numeric(14,2);
    v_entryacct integer;
    v_entryacctname text;
    v_hassupplier boolean;
    v_fp       text;
BEGIN
    SELECT p.*, i.itemname::text AS itemnm, i.unitofmeasure::text AS uom, i.currentquantity AS itemstock,
           COALESCE(NULLIF(btrim(s.suppliername), ''), NULLIF(btrim(p.suppliername), ''))::text AS suppnm
    INTO   v_p
    FROM   waterrawmaterialpurchases p
    LEFT   JOIN waterrawmaterialitems i ON i.waterrawmaterialitemid = p.waterrawmaterialitemid AND i.farmid = p.farmid
    LEFT   JOIN watersuppliers s ON s.watersupplierid = p.supplierid AND s.farmid = p.farmid
    WHERE  p.waterrawmaterialpurchaseid = p_purchaseid AND p.farmid = p_farmid;
    IF NOT FOUND THEN
        RETURN jsonb_build_object('found', false, 'payments', '[]'::jsonb,
               'blockers', jsonb_build_array(jsonb_build_object('code', 'NotFound',
                           'message', 'This purchase was not found for this company.')));
    END IF;

    v_mult    := COALESCE(NULLIF(v_p.productionunitsperpurchaseunit, 0), 1);
    v_prodqty := (v_p.quantity * v_mult)::numeric(18,4);
    v_hassupplier := v_p.supplierid IS NOT NULL;

    -- ---- blockers
    IF v_p.purchasereversalid IS NOT NULL OR v_p.reversedat IS NOT NULL THEN
        v_blockers := v_blockers || jsonb_build_object('code', 'AlreadyReversed',
                      'message', 'This purchase has already been reversed.');
    END IF;
    IF COALESCE(v_p.lotsource, '') = 'ManualDeferredCost' THEN
        v_blockers := v_blockers || jsonb_build_object('code', 'NotAPurchase',
                      'message', 'This is a manual deferred cost, not a purchase. Reverse it on Deferred costs.');
    END IF;
    SELECT r.receiptnumber INTO v_receipt
    FROM   waterpurchasereceiptlines rl
    JOIN   waterpurchasereceipts r ON r.waterpurchasereceiptid = rl.waterpurchasereceiptid
    WHERE  rl.waterrawmaterialpurchaseid = p_purchaseid AND r.farmid = p_farmid
    LIMIT  1;
    IF v_receipt IS NOT NULL THEN
        v_blockers := v_blockers || jsonb_build_object('code', 'ReceiptLot',
                      'message', 'This purchase was entered on purchase receipt ' || v_receipt
                                 || '. Reverse the receipt on Receive Purchase instead.');
    END IF;
    IF v_p.purchasereversalid IS NULL AND v_p.reversedat IS NULL AND (
           v_p.remainingquantity + 0.0005 < v_p.quantity
        OR COALESCE(v_p.deferredremainingcost, 0) + 0.005 < COALESCE(v_p.deferredtotalcost, 0)
        OR EXISTS (SELECT 1 FROM waterrawmaterialusagebatch ub WHERE ub.waterrawmaterialpurchaseid = p_purchaseid)) THEN
        SELECT string_agg(DISTINCT COALESCE(b.batchnumber, 'production record #' || u.waterproductionbatchid::text), ', ')
        INTO   v_used
        FROM   waterrawmaterialusagebatch ub
        JOIN   waterrawmaterialusage u ON u.waterrawmaterialusageid = ub.waterrawmaterialusageid
        LEFT   JOIN waterproductionbatches b ON b.waterproductionbatchid = u.waterproductionbatchid
        WHERE  ub.waterrawmaterialpurchaseid = p_purchaseid;
        v_blockers := v_blockers || jsonb_build_object('code', 'Consumed',
                      'message', COALESCE(v_p.itemnm, 'This item') || ': '
                                 || trim_scale(round(v_p.quantity - v_p.remainingquantity, 3))::text || ' of '
                                 || trim_scale(round(v_p.quantity, 3))::text || ' has already been used'
                                 || COALESCE(' by ' || v_used, '')
                                 || '. Reopen that production first, then reverse the purchase.');
    END IF;
    IF v_p.purchasereversalid IS NULL AND v_p.reversedat IS NULL
       AND COALESCE(v_p.itemstock, 0) + 0.0005 < v_prodqty THEN
        v_blockers := v_blockers || jsonb_build_object('code', 'StockShort',
                      'message', COALESCE(v_p.itemnm, 'This item') || ': only '
                                 || trim_scale(round(COALESCE(v_p.itemstock, 0), 3))::text || ' '
                                 || COALESCE(v_p.uom, '') || ' is in stock, but this purchase added '
                                 || trim_scale(round(v_prodqty, 3))::text
                                 || '. Stock was taken out by an adjustment, so reversing would leave it negative.');
    END IF;

    -- ---- applied supplier credit: always goes back to the supplier
    SELECT COALESCE(SUM(sa.amountapplied), 0) INTO v_credit
    FROM   supplierpaymentallocation sa
    WHERE  sa.farmid = p_farmid AND sa.module = 'water' AND sa.status = 'Posted'
      AND  sa.documenttype = 'RawMaterialPurchase' AND sa.documentid = p_purchaseid AND sa.fromcredit;

    SELECT COALESCE(SUM(sa.amountapplied), 0) INTO v_alloc
    FROM   supplierpaymentallocation sa
    WHERE  sa.farmid = p_farmid AND sa.module = 'water' AND sa.status = 'Posted'
      AND  sa.documenttype = 'RawMaterialPurchase' AND sa.documentid = p_purchaseid;

    -- ---- money paid when the purchase was entered (no supplier payment behind it)
    v_entry := GREATEST(COALESCE(v_p.amountpaid, 0) - v_alloc, 0);
    IF v_entry > 0.005 THEN
        -- It goes back to the account it left, if it left one: a deferred cash
        -- purchase never posted cash (275), and a refund must not invent some.
        SELECT ct.watercashaccountid, a.accountname::text INTO v_entryacct, v_entryacctname
        FROM   watercashtransactions ct
        LEFT   JOIN watercashaccounts a ON a.watercashaccountid = ct.watercashaccountid
        WHERE  ct.farmid = p_farmid AND ct.sourcetype = 'Expense' AND ct.amount < 0
          AND  ct.sourceid = v_p.linkedwaterexpenseid
          AND  EXISTS (SELECT 1 FROM waterexpenses e WHERE e.waterexpenseid = v_p.linkedwaterexpenseid
                       AND e.status = 'Approved' AND NOT COALESCE(e.isdeleted, false))
        ORDER  BY ct.watercashtransactionid
        LIMIT  1;
        v_money := v_money || jsonb_build_object(
            'key', 'entry', 'source', 'PaidAtEntry', 'paymentId', NULL,
            'paymentNumbers', 'Paid when the purchase was entered',
            'allocated', v_entry, 'paymentDate', v_p.purchasedate, 'paymentMethod', v_p.paymentmethod,
            'cashAccountId', v_entryacct, 'cashAccountName', v_entryacctname,
            'allowed', CASE WHEN v_hassupplier THEN '["KeepAsCredit","Refund"]'::jsonb ELSE '["Refund"]'::jsonb END,
            'default', CASE WHEN v_hassupplier THEN 'KeepAsCredit' ELSE 'Refund' END,
            'keepUnavailableReason', CASE WHEN NOT v_hassupplier THEN
                'This purchase has no supplier linked, so the money can only be recorded as refunded.' END,
            'noCashNote', CASE WHEN v_entryacct IS NULL THEN
                'This money was never recorded in a cash account, so a refund puts nothing back into one.' END);
    END IF;

    -- ---- supplier payments that paid this purchase (credit applications excluded)
    SELECT v_money || COALESCE(jsonb_agg(jsonb_build_object(
               'key', 'sp:' || x.paymentid, 'source', 'SupplierPayment', 'paymentId', x.paymentid,
               'paymentNumbers', 'Supplier payment SP-' || lpad(x.paymentid::text, 5, '0'),
               'allocated', x.amt, 'paymentDate', x.paymentdate, 'paymentMethod', x.paymentmethod,
               'cashAccountId', x.watercashaccountid, 'cashAccountName', x.accountname,
               'allowed', '["KeepAsCredit","Refund"]'::jsonb,
               'default', 'KeepAsCredit',
               'keepUnavailableReason', NULL,
               'noCashNote', CASE WHEN x.watercashaccountid IS NULL THEN
                   'This payment was not recorded in a cash account, so a refund puts nothing back into one.' END)
             ORDER BY x.paymentdate, x.paymentid), '[]'::jsonb)
    INTO   v_money
    FROM  (SELECT sp.watersupplierpaymentid AS paymentid, sp.paymentdate, sp.paymentmethod,
                  sp.watercashaccountid, a.accountname::text AS accountname,
                  SUM(sa.amountapplied)::numeric(14,2) AS amt
           FROM   supplierpaymentallocation sa
           JOIN   watersupplierpayments sp ON sp.watersupplierpaymentid = sa.paymentid AND sp.farmid = sa.farmid
           LEFT   JOIN watercashaccounts a ON a.watercashaccountid = sp.watercashaccountid
           WHERE  sa.farmid = p_farmid AND sa.module = 'water' AND sa.status = 'Posted'
             AND  sa.documenttype = 'RawMaterialPurchase' AND sa.documentid = p_purchaseid
             AND  NOT sa.fromcredit
           GROUP  BY sp.watersupplierpaymentid, sp.paymentdate, sp.paymentmethod, sp.watercashaccountid, a.accountname) x;

    -- ---- fingerprint: anything that would change what the reversal does
    SELECT md5(COALESCE(string_agg(t, '|' ORDER BY t), '')) INTO v_fp
    FROM (
        SELECT 'p' || p.waterrawmaterialpurchaseid || ':' || p.quantity || ':' || p.remainingquantity || ':'
               || p.totalcost || ':' || COALESCE(p.amountpaid, 0) || ':' || COALESCE(p.supplierid, 0) || ':'
               || COALESCE(p.purchasereversalid, 0) || ':' || COALESCE(p.deferredremainingcost, 0) AS t
        FROM   waterrawmaterialpurchases p WHERE p.farmid = p_farmid AND p.waterrawmaterialpurchaseid = p_purchaseid
        UNION ALL
        SELECT 'a' || sa.allocationid || ':' || sa.status || ':' || sa.amountapplied
        FROM   supplierpaymentallocation sa
        WHERE  sa.farmid = p_farmid AND sa.module = 'water'
          AND  sa.documenttype = 'RawMaterialPurchase' AND sa.documentid = p_purchaseid
        UNION ALL
        SELECT 'i' || i.waterrawmaterialitemid || ':' || i.currentquantity
        FROM   waterrawmaterialitems i WHERE i.waterrawmaterialitemid = v_p.waterrawmaterialitemid AND i.farmid = p_farmid
    ) z;

    RETURN jsonb_build_object(
        'found', true,
        'purchaseId', p_purchaseid,
        'purchaseDate', v_p.purchasedate,
        'itemId', v_p.waterrawmaterialitemid,
        'itemName', COALESCE(v_p.itemnm, 'Raw material'),
        'unit', v_p.uom,
        'quantity', v_p.quantity,
        'stockToRemove', v_prodqty,
        'supplierId', v_p.supplierid,
        'supplierName', COALESCE(v_p.suppnm, 'No supplier'),
        'total', v_p.totalcost,
        'paid', COALESCE(v_p.amountpaid, 0),
        'creditApplied', v_credit,
        'outstanding', GREATEST(v_p.totalcost - COALESCE(v_p.amountpaid, 0), 0),
        'deferred', COALESCE(v_p.deferredtotalcost, 0) > 0,
        'payments', v_money,
        'supplierCreditNow', CASE WHEN v_hassupplier THEN public.fnwatersupplier_credit(p_farmid, v_p.supplierid) ELSE 0 END,
        'blockers', v_blockers,
        'fingerprint', v_fp);
END $f$;

CREATE OR REPLACE FUNCTION public.spwaterpurchase_reversalpreview(p_farmid text, p_purchaseid integer)
RETURNS jsonb LANGUAGE sql STABLE AS $f$
    SELECT st || jsonb_build_object(
             'defaultCreditCreated', COALESCE((SELECT SUM((m->>'allocated')::numeric) FROM jsonb_array_elements(st->'payments') m
                                               WHERE m->>'default' = 'KeepAsCredit'), 0),
             'defaultRefunded',      COALESCE((SELECT SUM((m->>'allocated')::numeric) FROM jsonb_array_elements(st->'payments') m
                                               WHERE m->>'default' = 'Refund'), 0))
    FROM   (SELECT public.fnwaterpurchase_reversalstate(p_farmid, p_purchaseid) AS st) q;
$f$;

-- ---------------------------------------------------------------------------
-- 5. Reverse
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.spwaterpurchase_reverse(
    p_farmid text, p_purchaseid integer, p_reasoncode text, p_reason text,
    p_handling jsonb DEFAULT '{}'::jsonb, p_expectedfingerprint text DEFAULT NULL,
    p_idempotencykey text DEFAULT NULL, p_reversedby text DEFAULT NULL)
RETURNS integer LANGUAGE plpgsql AS $f$
DECLARE
    v_now      timestamp := (now() AT TIME ZONE 'utc');
    v_today    date      := fncompany_businessdate(p_farmid);
    v_state    jsonb;
    v_item     jsonb;
    v_action   text;
    v_reason   text;
    v_id       integer;
    v_existing integer;
    v_number   text;
    v_p        record;
    v_adjid    integer;
    v_amt      numeric(14,2);
    v_acct     integer;
    v_ctid     integer;
    v_cpid     integer;
    v_credit   numeric(14,2) := 0;
    v_refund   numeric(14,2) := 0;
    v_kinds    text[] := ARRAY[]::text[];
    a          record;
BEGIN
    IF NULLIF(btrim(COALESCE(p_reasoncode, '')), '') IS NULL AND NULLIF(btrim(COALESCE(p_reason, '')), '') IS NULL THEN
        RAISE EXCEPTION 'Give a reason for reversing this purchase.' USING ERRCODE = 'P0001';
    END IF;
    IF lower(btrim(COALESCE(p_reasoncode, ''))) = 'other' AND NULLIF(btrim(COALESCE(p_reason, '')), '') IS NULL THEN
        RAISE EXCEPTION 'Say in a few words what happened (the reason is "Other").' USING ERRCODE = 'P0001';
    END IF;
    v_reason := concat_ws(': ', NULLIF(btrim(COALESCE(p_reasoncode, '')), ''), NULLIF(btrim(COALESCE(p_reason, '')), ''));

    PERFORM pg_advisory_xact_lock(hashtext('water-purchasereversal:' || p_farmid || ':' || p_purchaseid::text));
    SELECT p.* INTO v_p FROM waterrawmaterialpurchases p
    WHERE  p.farmid = p_farmid AND p.waterrawmaterialpurchaseid = p_purchaseid FOR UPDATE;

    IF p_idempotencykey IS NOT NULL THEN
        SELECT r.purchasereversalid INTO v_existing FROM waterpurchasereversals r
        WHERE  r.farmid = p_farmid AND r.idempotencykey = p_idempotencykey;
        IF FOUND THEN RETURN v_existing; END IF;
    END IF;

    v_state := fnwaterpurchase_reversalstate(p_farmid, p_purchaseid);
    IF jsonb_array_length(v_state->'blockers') > 0 THEN
        RAISE EXCEPTION '%', v_state->'blockers'->0->>'message' USING ERRCODE = 'P0001';
    END IF;
    IF p_expectedfingerprint IS NOT NULL AND p_expectedfingerprint <> v_state->>'fingerprint' THEN
        RAISE EXCEPTION 'This purchase changed after the reversal preview was generated. Please review the updated impact before continuing.'
            USING ERRCODE = 'P0001', HINT = 'stale-preview';
    END IF;

    -- Validate every choice before changing anything.
    FOR v_item IN SELECT * FROM jsonb_array_elements(v_state->'payments') LOOP
        v_action := COALESCE(p_handling->>(v_item->>'key'), v_item->>'default');
        IF NOT (v_item->'allowed') ? v_action THEN
            RAISE EXCEPTION '%', COALESCE(v_item->>'keepUnavailableReason',
                  'Choose whether the supplier refunded ' || (v_item->>'paymentNumbers') || ' or it is kept as supplier credit.')
                  USING ERRCODE = 'P0001';
        END IF;
    END LOOP;

    PERFORM set_config('water.purchase_reversal', 'on', true);

    -- 1. Supplier credit spent on this purchase is the supplier's credit again.
    FOR a IN SELECT sa.allocationid FROM supplierpaymentallocation sa
             WHERE  sa.farmid = p_farmid AND sa.module = 'water' AND sa.status = 'Posted'
               AND  sa.documenttype = 'RawMaterialPurchase' AND sa.documentid = p_purchaseid AND sa.fromcredit LOOP
        PERFORM public.spwatersuppliercredit_unapply(p_farmid, a.allocationid, 'Purchase reversed: ' || v_reason, p_reversedby);
    END LOOP;

    -- 2. The reversal record (numbered first, so the stock note can name it).
    PERFORM pg_advisory_xact_lock(hashtext('water-purchasereversal-no:' || p_farmid));
    SELECT 'WPR-' || lpad((COALESCE(MAX(NULLIF(regexp_replace(r.reversalnumber, '\D', '', 'g'), '')::int), 0) + 1)::text, 5, '0')
    INTO   v_number
    FROM   waterpurchasereversals r WHERE r.farmid = p_farmid;

    -- 3. Stock: the opposite adjustment, then the lot emptied. The row is kept.
    SELECT x.waterrawmaterialadjustmentid INTO v_adjid
    FROM   public.spwaterrawmaterialitem_adjust(
               p_farmid, v_p.waterrawmaterialitemid, -((v_state->>'stockToRemove')::numeric),
               v_p.unitcost, 'PurchaseReversal',
               left('Purchase #' || p_purchaseid || ' reversed (' || v_number || '): ' || v_reason, 500),
               p_reversedby) x;

    INSERT INTO waterpurchasereversals
        (farmid, reversalnumber, waterrawmaterialpurchaseid, waterrawmaterialitemid, itemname, supplierid, suppliername,
         purchasedate, reasoncode, reason, businessdate, occurredat, reversedby, quantity, stockremoved,
         totalcost, paidamount, outstandingamount, creditreleased, adjustmentid, idempotencykey, snapshot)
    VALUES
        (p_farmid, v_number, p_purchaseid, v_p.waterrawmaterialitemid, v_state->>'itemName',
         v_p.supplierid, v_state->>'supplierName', v_p.purchasedate,
         NULLIF(btrim(p_reasoncode), ''), btrim(COALESCE(p_reason, '')), v_today, v_now, p_reversedby,
         v_p.quantity, (v_state->>'stockToRemove')::numeric,
         (v_state->>'total')::numeric, (v_state->>'paid')::numeric, (v_state->>'outstanding')::numeric,
         (v_state->>'creditApplied')::numeric, v_adjid, p_idempotencykey, v_state)
    RETURNING purchasereversalid INTO v_id;

    UPDATE waterrawmaterialpurchases p
    SET    remainingquantity = 0, deferredremainingcost = 0,
           reversedat = v_now, reversedby = p_reversedby, reversalreason = v_reason,
           purchasereversalid = v_id, updatedat = v_now
    WHERE  p.farmid = p_farmid AND p.waterrawmaterialpurchaseid = p_purchaseid;

    -- The purchase's automatic expense stays (Cash Flow shows the money that
    -- left on the purchase date); the P&L reads purchases, not this row
    -- (429), and skips reversed ones. Say so on the expense.
    UPDATE waterexpenses e
    SET    notes = left(COALESCE(e.notes, '') || chr(10) || 'Purchase reversed (' || v_number || ').', 1000),
           updatedat = v_now
    WHERE  e.waterexpenseid = v_p.linkedwaterexpenseid AND e.farmid = p_farmid;

    -- 4. The money, line by line.
    FOR v_item IN SELECT * FROM jsonb_array_elements(v_state->'payments') LOOP
        v_action := COALESCE(p_handling->>(v_item->>'key'), v_item->>'default');
        v_amt    := (v_item->>'allocated')::numeric;
        v_acct   := NULLIF(v_item->>'cashAccountId', '')::int;
        v_ctid   := NULL;
        v_cpid   := NULL;

        IF v_action = 'Refund' THEN
            -- The supplier handed the money back: a NEW CashIn today, into the
            -- account it left. The original payment and its cash stay as they were.
            IF v_acct IS NOT NULL THEN
                INSERT INTO watercashtransactions
                    (farmid, watercashaccountid, transactiondate, transactiontype, sourcetype, sourceid,
                     amount, description, createdby, approvedby, approvedat)
                VALUES
                    (p_farmid, v_acct, v_now, 'CashIn', 'WaterPurchaseReversal', v_id, v_amt,
                     left('Refund - purchase #' || p_purchaseid || ' reversed (' || v_number || ')', 500),
                     p_reversedby, p_reversedby, v_now)
                RETURNING watercashtransactionid INTO v_ctid;
                UPDATE watercashaccounts ca SET currentbalance = ca.currentbalance + v_amt, updatedat = v_now
                WHERE  ca.watercashaccountid = v_acct AND ca.farmid = p_farmid;
            END IF;
            v_refund := v_refund + v_amt;
        ELSE
            -- Kept: the supplier now owes us this money as credit. No cash moves.
            INSERT INTO watersupplierpayments
                (farmid, supplierid, paymentdate, totalamount, paymentmethod, watercashaccountid, referenceno, notes,
                 sourcetype, status, createdby, createdat)
            VALUES
                (p_farmid, v_p.supplierid, v_now, v_amt, 'NonCash', NULL, v_number,
                 left('Kept from reversed purchase #' || p_purchaseid || ' (' || (v_item->>'paymentNumbers') || ')', 1000),
                 'PurchaseReversalCredit', 'Posted', p_reversedby, v_now)
            RETURNING watersupplierpaymentid INTO v_cpid;
            v_credit := v_credit + v_amt;
        END IF;
        v_kinds := v_kinds || v_action;

        INSERT INTO waterpurchasereversalpayments
            (purchasereversalid, farmid, linekey, source, watersupplierpaymentid, amount, action,
             cashaccountid, cashtransactionid, creditpaymentid)
        VALUES
            (v_id, p_farmid, v_item->>'key', v_item->>'source', NULLIF(v_item->>'paymentId', '')::int, v_amt, v_action,
             CASE WHEN v_action = 'Refund' THEN v_acct END, v_ctid, v_cpid);
    END LOOP;

    UPDATE waterpurchasereversals r
    SET    creditcreated = v_credit, refunded = v_refund,
           paymenthandling = CASE
               WHEN array_length(v_kinds, 1) IS NULL THEN 'None'
               WHEN 'KeepAsCredit' = ALL (v_kinds) THEN 'KeepAsCredit'
               WHEN 'Refund' = ALL (v_kinds) THEN 'Refund'
               ELSE 'Mixed' END
    WHERE  r.purchasereversalid = v_id;

    PERFORM set_config('water.purchase_reversal', 'off', true);
    RETURN v_id;
END $f$;

