-- -----------------------------------------------------------------------------
-- 2. Line guards
-- -----------------------------------------------------------------------------
-- A one-line sale's line follows its header. Only fires for a sale that does
-- not own its lines; the header guard (351) has already decided whether the
-- header change itself is allowed.
CREATE OR REPLACE FUNCTION public.trg_sale_mirrorline_fn()
RETURNS trigger
LANGUAGE plpgsql
AS $function$
BEGIN
    PERFORM set_config('poultry.saleline_mirror', 'on', true);
    INSERT INTO saleline (saleid, farmid, lineno, product, poultryproductid, size, quantity, unitprice, totalamount)
    VALUES (NEW.saleid, NEW.farmid, 1, NEW.product, NEW.poultryproductid, NEW.size,
            NEW.quantity, NEW.unitprice, NEW.totalamount)
    ON CONFLICT (saleid, lineno) DO UPDATE
    SET    product = EXCLUDED.product, poultryproductid = EXCLUDED.poultryproductid, size = EXCLUDED.size,
           quantity = EXCLUDED.quantity, unitprice = EXCLUDED.unitprice, totalamount = EXCLUDED.totalamount
    WHERE  (saleline.product, saleline.poultryproductid, saleline.size, saleline.quantity, saleline.unitprice, saleline.totalamount)
           IS DISTINCT FROM
           (EXCLUDED.product, EXCLUDED.poultryproductid, EXCLUDED.size, EXCLUDED.quantity, EXCLUDED.unitprice, EXCLUDED.totalamount);
    PERFORM set_config('poultry.saleline_mirror', 'off', true);
    RETURN NULL;
END
$function$;

DROP TRIGGER IF EXISTS trg_sale_mirrorline ON public.sale;
CREATE TRIGGER trg_sale_mirrorline
    AFTER INSERT OR UPDATE OF product, quantity, unitprice, totalamount, poultryproductid, size, ismultiline
    ON public.sale FOR EACH ROW WHEN (NOT NEW.ismultiline)
    EXECUTE FUNCTION public.trg_sale_mirrorline_fn();

-- The lines of a posted sale are as fixed as the sale: written by the
-- transaction that posted it, the mirror, the system (reversal, migration),
-- flock closeout, or a delivery-generated sale -- the same exits as 351.
CREATE OR REPLACE FUNCTION public.trg_saleline_guard_fn()
RETURNS trigger
LANGUAGE plpgsql
AS $function$
DECLARE
    v_id   integer := COALESCE(NEW.saleid, OLD.saleid);
    v_desc text;
BEGIN
    IF current_setting('poultry.sale_system', true) = 'on'
       OR current_setting('poultry.saleline_mirror', true) = 'on'
       OR position(',' || v_id::text || ',' IN COALESCE(current_setting('poultry.sale_fresh', true), '')) > 0
       OR fnflock_closeoutinprogress() THEN
        RETURN COALESCE(NEW, OLD);
    END IF;

    SELECT s.saledescription INTO v_desc FROM sale s WHERE s.saleid = v_id;
    IF NOT FOUND THEN
        RETURN COALESCE(NEW, OLD);      -- the sale itself is being deleted (cascade)
    END IF;
    IF fnpoultrysale_isgenerated(v_desc) THEN
        RETURN COALESCE(NEW, OLD);
    END IF;
    RAISE EXCEPTION 'Sale #% is posted, so its lines can no longer be changed. Reverse the sale, or use Correct Sale.', v_id
        USING ERRCODE = 'P0001';
END
$function$;

DROP TRIGGER IF EXISTS trg_saleline_guard ON public.saleline;
CREATE TRIGGER trg_saleline_guard
    BEFORE INSERT OR UPDATE OR DELETE ON public.saleline
    FOR EACH ROW EXECUTE FUNCTION public.trg_saleline_guard_fn();

