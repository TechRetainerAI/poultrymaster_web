-- -----------------------------------------------------------------------------
-- 4. Merge SG groups.   5. ... and prove nothing but structure moved.
-- -----------------------------------------------------------------------------
CREATE TEMP TABLE m358_measure (phase text, farmid text, metric text, value numeric) ON COMMIT DROP;

CREATE FUNCTION pg_temp.m358_measure(p_phase text) RETURNS void LANGUAGE sql AS $f$
    INSERT INTO m358_measure
    SELECT p_phase, s.farmid, 'sales.' || s.status, SUM(s.totalamount) FROM sale s GROUP BY s.farmid, s.status
    UNION ALL
    SELECT p_phase, s.farmid, 'receivable', SUM(fnpoultrysalebalance(s.paid, s.totalamount, s.amountpaid))
    FROM sale s WHERE s.status = 'Posted' GROUP BY s.farmid
    UNION ALL
    SELECT p_phase, s.farmid, 'received', SUM(fnpoultrysalereceived(s.paid, s.totalamount, s.amountpaid))
    FROM sale s GROUP BY s.farmid
    UNION ALL
    SELECT p_phase, pp.farmid, 'payments.' || COALESCE(pp.status, 'Posted'), SUM(pp.amount)
    FROM poultrypayments pp GROUP BY pp.farmid, COALESCE(pp.status, 'Posted')
    UNION ALL
    SELECT p_phase, ca.farmid, 'allocations.' || ca.status, SUM(ca.amountapplied)
    FROM customerpaymentallocation ca WHERE ca.module = 'poultry' GROUP BY ca.farmid, ca.status
    UNION ALL
    SELECT p_phase, ct.farmid, 'cash', SUM(ct.amount) FROM poultrycashtransactions ct GROUP BY ct.farmid
    UNION ALL
    SELECT p_phase, a.farmid, 'cashbalance', SUM(a.currentbalance) FROM poultrycashaccounts a GROUP BY a.farmid
    UNION ALL
    SELECT p_phase, t.farmid, 'stock.' || t.poultryproductid, SUM(t.quantity)
    FROM poultrystocktransactions t GROUP BY t.farmid, t.poultryproductid
    UNION ALL
    SELECT p_phase, l.farmid, 'lines', SUM(l.totalamount) FROM saleline l GROUP BY l.farmid
    UNION ALL
    SELECT p_phase, c.farmid, 'credit.' || c.customerid, fnpoultrycustomer_credit(c.farmid, c.customerid)
    FROM customer c WHERE EXISTS (SELECT 1 FROM poultrypayments pp WHERE pp.customerid = c.customerid);
$f$;

SELECT pg_temp.m358_measure('before');

DO $merge$
DECLARE
    g       record;
    r       record;
    v_keep  integer;
    v_rest  integer[];
    v_pk    integer;
    v_amt   numeric(14,2);
    v_bb    numeric(14,2);
    v_ba    numeric(14,2);
    v_n     integer := 0;
BEGIN
    FOR g IN
        SELECT s.farmid::text AS farmid, s.salegroupno, array_agg(s.saleid ORDER BY s.saleid) AS ids
        FROM   sale s
        WHERE  NULLIF(btrim(COALESCE(s.salegroupno, '')), '') IS NOT NULL
        GROUP  BY s.farmid, s.salegroupno
        HAVING COUNT(*) > 1
        ORDER  BY s.farmid, s.salegroupno
    LOOP
        v_keep := g.ids[1];
        v_rest := g.ids[2:];

        -- The SG number is the evidence; the rows must also agree on who,
        -- when, what and in which state, or this is not one checkout.
        IF (SELECT COUNT(DISTINCT ROW(COALESCE(s.customerid, -1), lower(btrim(COALESCE(s.customername, ''))),
                                      s.saledate, s.status, COALESCE(s.salereversalid, -1),
                                      COALESCE(s.correctssaleid, -1), lower(btrim(s.product)),
                                      COALESCE(s.flockid, -1), COALESCE(s.poultrycashaccountid, -1)))
            FROM sale s WHERE s.saleid = ANY (g.ids)) > 1 THEN
            RAISE EXCEPTION '358: % % rows % disagree on customer/date/status/product/flock/account; not merging.',
                  g.farmid, g.salegroupno, g.ids;
        END IF;

        -- archive
        INSERT INTO saleline_migration355 (farmid, salegroupno, keptsaleid, kind, sourceid, data)
        SELECT g.farmid, g.salegroupno, v_keep, 'sale', s.saleid, to_jsonb(s) FROM sale s WHERE s.saleid = ANY (g.ids)
        UNION ALL
        SELECT g.farmid, g.salegroupno, v_keep, 'payment', pp.poultrypaymentid, to_jsonb(pp)
        FROM poultrypayments pp WHERE pp.farmid = g.farmid AND pp.saleid = ANY (g.ids)
        UNION ALL
        SELECT g.farmid, g.salegroupno, v_keep, 'allocation', ca.allocationid, to_jsonb(ca)
        FROM customerpaymentallocation ca WHERE ca.module = 'poultry' AND ca.farmid = g.farmid AND ca.saleid = ANY (g.ids)
        UNION ALL
        SELECT g.farmid, g.salegroupno, v_keep, 'stock', t.poultrystocktransactionid, to_jsonb(t)
        FROM poultrystocktransactions t WHERE t.farmid = g.farmid AND t.relatedid = ANY (g.ids)
          AND t.txntype IN ('Sale', 'Sale Reversal', 'Bird Sale')
        UNION ALL
        SELECT g.farmid, g.salegroupno, v_keep, 'cash', ct.poultrycashtransactionid, to_jsonb(ct)
        FROM poultrycashtransactions ct WHERE ct.farmid = g.farmid AND ct.sourcetype = 'Sale' AND ct.sourceid = ANY (g.ids)
        UNION ALL
        SELECT g.farmid, g.salegroupno, v_keep, 'reversal', r2.salereversalid, to_jsonb(r2)
        FROM poultrysalereversals r2 WHERE r2.farmid = g.farmid AND r2.saleids && g.ids;

        -- header first becomes multi-line, so the mirror leaves its lines alone
        UPDATE sale s SET ismultiline = TRUE WHERE s.saleid = v_keep;

        -- every row's line moves under the kept header, in entry order
        UPDATE saleline l
        SET    saleid = v_keep, lineno = x.rn
        FROM  (SELECT l2.salelineid, row_number() OVER (ORDER BY l2.saleid, l2.lineno) AS rn
               FROM saleline l2 WHERE l2.saleid = ANY (g.ids)) x
        WHERE  l.salelineid = x.salelineid;

        -- the header is the sum of its lines; received is kept as received
        UPDATE sale s
        SET    quantity         = a.qty,
               totalamount      = a.total,
               unitprice        = CASE WHEN a.qty > 0
                                       THEN round(a.total / CASE WHEN lower(s.product) LIKE '%egg%' THEN a.qty / 30.0 ELSE a.qty END, 2)
                                       ELSE 0 END,
               amountpaid       = a.received,
               paid             = a.allpaid,
               poultryproductid = NULL,
               size             = NULL,
               dateupdated      = (now() AT TIME ZONE 'utc')
        FROM  (SELECT SUM(x.quantity) AS qty, SUM(x.totalamount) AS total,
                      SUM(fnpoultrysalereceived(x.paid, x.totalamount, x.amountpaid)) AS received,
                      bool_and(COALESCE(x.paid, TRUE)) AS allpaid
               FROM sale x WHERE x.saleid = ANY (g.ids)) a
        WHERE  s.saleid = v_keep;

        -- stock: re-point, never re-post
        UPDATE poultrystocktransactions t SET relatedid = v_keep
        WHERE  t.farmid = g.farmid AND t.relatedid = ANY (v_rest)
          AND  t.txntype IN ('Sale', 'Sale Reversal', 'Bird Sale');

        -- cash received at the counter (walk-in): re-point, never re-post
        UPDATE poultrycashtransactions ct SET sourceid = v_keep
        WHERE  ct.farmid = g.farmid AND ct.sourcetype = 'Sale' AND ct.sourceid = ANY (v_rest);

        -- payments: one row per (payment, status) for this sale
        FOR r IN
            SELECT array_agg(pp.poultrypaymentid ORDER BY pp.poultrypaymentid) AS pids
            FROM   poultrypayments pp
            WHERE  pp.farmid = g.farmid AND pp.saleid = ANY (g.ids)
            GROUP  BY COALESCE(pp.paymentgroupid::text, 'row:' || pp.poultrypaymentid::text), COALESCE(pp.status, 'Posted')
        LOOP
            v_pk := r.pids[1];
            SELECT SUM(pp.amount) INTO v_amt FROM poultrypayments pp WHERE pp.poultrypaymentid = ANY (r.pids);
            UPDATE customerpaymentallocation ca SET paymentid = v_pk
            WHERE  ca.module = 'poultry' AND ca.farmid = g.farmid AND ca.paymentid = ANY (r.pids[2:]);
            UPDATE poultrycustomerrefundlines rl SET poultrypaymentid = v_pk
            WHERE  rl.farmid = g.farmid AND rl.poultrypaymentid = ANY (r.pids[2:]);
            UPDATE poultrycashtransactions ct SET sourceid = v_pk
            WHERE  ct.farmid = g.farmid AND ct.sourcetype IN ('CustomerPayment', 'CustomerPaymentReversal')
              AND  ct.sourceid = ANY (r.pids[2:]);
            DELETE FROM poultrypayments pp WHERE pp.poultrypaymentid = ANY (r.pids[2:]);
            UPDATE poultrypayments pp SET saleid = v_keep, amount = v_amt WHERE pp.poultrypaymentid = v_pk;
        END LOOP;

        -- allocations: one per (payment, status) for this sale
        FOR r IN
            SELECT array_agg(ca.allocationid ORDER BY ca.allocationid) AS aids
            FROM   customerpaymentallocation ca
            WHERE  ca.module = 'poultry' AND ca.farmid = g.farmid AND ca.saleid = ANY (g.ids)
            GROUP  BY ca.paymentid, ca.status
        LOOP
            SELECT SUM(ca.amountapplied), SUM(ca.salebalancebefore), SUM(ca.salebalanceafter)
            INTO   v_amt, v_bb, v_ba
            FROM   customerpaymentallocation ca WHERE ca.allocationid = ANY (r.aids);
            DELETE FROM customerpaymentallocation ca WHERE ca.allocationid = ANY (r.aids[2:]);
            UPDATE customerpaymentallocation ca
            SET    saleid = v_keep, amountapplied = v_amt, salebalancebefore = v_bb, salebalanceafter = v_ba
            WHERE  ca.allocationid = r.aids[1];
        END LOOP;

        -- reversal records and correction links name the kept sale
        UPDATE poultrysalereversals r2 SET saleids = ARRAY[v_keep]
        WHERE  r2.farmid = g.farmid AND r2.saleids && g.ids;
        UPDATE poultrysalereversals r2 SET correctionsaleid = v_keep
        WHERE  r2.farmid = g.farmid AND r2.correctionsaleid = ANY (v_rest);
        UPDATE sale s SET correctssaleid = v_keep
        WHERE  s.farmid = g.farmid AND s.correctssaleid = ANY (v_rest);

        IF EXISTS (SELECT 1 FROM flockcloseoutdispositions x WHERE x.saleid = ANY (v_rest))
           OR EXISTS (SELECT 1 FROM poultrydeliveries d WHERE d.linkedsaleid = ANY (v_rest))
           OR EXISTS (SELECT 1 FROM poultrydriverreturncustomersales d WHERE d.generatedsaleid = ANY (v_rest))
           OR EXISTS (SELECT 1 FROM poultryeggsalebackfill b WHERE b.saleid = ANY (v_rest)) THEN
            RAISE EXCEPTION '358: % % is referenced by a closeout/delivery/driver return/backfill; not merging.', g.farmid, g.salegroupno;
        END IF;

        DELETE FROM sale s WHERE s.saleid = ANY (v_rest);
        v_n := v_n + 1;
        RAISE NOTICE '358: % % -> sale #% with % lines', left(g.farmid, 8), g.salegroupno, v_keep, array_length(g.ids, 1);
    END LOOP;
    RAISE NOTICE '358: % grouped sales merged', v_n;
END
$merge$;

SELECT pg_temp.m358_measure('after');

DO $verify$
DECLARE
    v_bad text;
BEGIN
    SELECT string_agg(format('%s %s: %s -> %s', left(COALESCE(b.farmid, a.farmid), 8), COALESCE(b.metric, a.metric),
                             b.value, a.value), '; ')
    INTO   v_bad
    FROM  (SELECT * FROM m358_measure WHERE phase = 'before') b
    FULL   JOIN (SELECT * FROM m358_measure WHERE phase = 'after') a
           ON a.farmid = b.farmid AND a.metric = b.metric
    WHERE  COALESCE(a.value, 0) <> COALESCE(b.value, 0);
    IF v_bad IS NOT NULL THEN
        RAISE EXCEPTION '358: the merge moved money or stock: %', v_bad;
    END IF;

    SELECT string_agg('#' || s.saleid, ', ') INTO v_bad
    FROM   sale s
    WHERE  s.totalamount <> (SELECT COALESCE(SUM(l.totalamount), 0) FROM saleline l WHERE l.saleid = s.saleid);
    IF v_bad IS NOT NULL THEN
        RAISE EXCEPTION '358: header total differs from its lines: %', v_bad;
    END IF;

    IF EXISTS (SELECT 1 FROM sale s WHERE NOT EXISTS (SELECT 1 FROM saleline l WHERE l.saleid = s.saleid)) THEN
        RAISE EXCEPTION '358: a sale has no line.';
    END IF;
END
$verify$;

