-- RENUMBERED 2026-10-12 from 355 (teammates took 355-357). The dev database got
-- this file under its old number, which is why its audit table is still named
-- saleline_migration355 -- that name is live, so it is kept.
--
-- Purpose
-- -------
-- ONE customer sale = ONE `sale` row. What was sold inside it = `saleline`.
--
-- Until now a multi-size egg sale (343) was several `sale` rows sharing a
-- text label (salegroupno 'SG-00003'). Everything keyed on sale rows --
-- payments, allocations, Customer Balances, Payments Received, the Cash Flow
-- report -- therefore treated each egg size as its own customer sale:
-- "PAY-0015 applied to 2 sales", two Money In rows for one receipt, three
-- sales on a customer who had made two.
--
-- From here on:
--
--   sale       the header: customer, date, total, paid, status, SG number.
--              Every money reader keeps working on it, unchanged.
--   saleline   product, egg class, size, quantity, price, line total.
--              Every sale has >= 1 line. A one-line sale's line MIRRORS the
--              header (trigger), so the ten-odd code paths that write a
--              single sale need no change. A multi-line sale (ismultiline)
--              owns its lines and the header is their sum.
--   poultrystocktransactions.salelineid
--              which line a stock movement belongs to. Inventory stays per
--              line: JUMBO -757 and Large -548 remain two movements.
--
-- PHASE 1 LIMIT: every line of one sale is the same product (egg sizes may
-- differ). Readers that need the product of a sale (bird position, P&L by
-- product, flock closeout) still read the header product, which is exact for
-- such a sale. Mixed products in one sale need those readers on saleline
-- first (phase 2).
--
-- WHAT THIS MIGRATION DOES
-- ------------------------
--   1. saleline, sale.ismultiline, sale.requestkey, stock salelineid.
--   2. Guards: lines of a posted sale are as immutable as the sale (351).
--   3. Backfill: one line per existing sale; stock movements get their line.
--   4. Merge every existing SG group of several rows into ONE sale:
--        - the lowest saleid is kept as the header, every row becomes a line
--        - stock movements are RE-POINTED, never re-posted
--        - a payment's per-row rows become one row, allocations one per sale
--        - cash rows are re-pointed, never re-posted (the cash ledger already
--          held one CashIn per payment group -- 343 posted it that way)
--        - every touched row is archived to saleline_migration355 first
--      Grouping evidence is the explicit SG number only, never same customer
--      or time. Rows of one group that disagree on customer, date, status,
--      product or reversal ABORT the migration rather than merge.
--   5. Measures money, receivables, stock and cash per company before and
--      after the merge and RAISES if anything moved: only structure changes.
--   6. sppoultrysale_creategroup: ONE header, N lines, one stock sync, one
--      cash sync, one payment. Optional request key makes a double-submit
--      return the first sale instead of posting a second.
--   7. Readers: stock sync per line, reversal restores per line and previews
--      lines, sale reads return their lines, Cash Flow shows ONE row per
--      payment (not per sale it pays), egg sales report reads lines,
--      Customer Balances / Payments label "Fresh Eggs · 2 lines".
--   8. sppoultrysale_ensuregroup is retired: a posted sale cannot gain lines.
-- =============================================================================

