CREATE OR REPLACE FUNCTION public.spwatercustomerstatement(p_farmid text, p_customerid integer, p_from date DEFAULT NULL::date, p_to date DEFAULT NULL::date)
 RETURNS TABLE(entrydate date, entrytype text, reference text, description text, debit numeric, credit numeric, runningbalance numeric, saleid integer, sortkey integer, paymentgroupid uuid, allocationcount integer, sourcetype text)
 LANGUAGE sql
 STABLE
AS $function$
    WITH lines AS (
        -- Opening balance: what was owed before the window opened. p_from NULL
        -- means "the whole history", and a whole-history statement has nothing
        -- before it -- so the opening MUST be zero. The usual
        -- `p_from IS NULL OR ...` idiom here would instead match every sale ever
        -- and count the entire ledger twice.
        SELECT CASE WHEN p_from IS NULL THEN NULL::date ELSE p_from END AS entrydate,
               'OpeningBalance'::text  AS entrytype,
               NULL::text              AS reference,
               'Opening balance'::text AS description,
               CASE WHEN p_from IS NULL THEN 0::numeric(14,2) ELSE (COALESCE((
                   SELECT SUM(GREATEST(s.totalamount - s.amountpaid, 0))
                   FROM   watersales s
                   WHERE  s.farmid = p_farmid AND s.watercustomerid = p_customerid
                     AND  COALESCE(s.status, '') <> 'Cancelled'
                     AND  s.saledate::date < p_from), 0)
                 -- 423: debts dated before the window, as owed today
                 + COALESCE((SELECT SUM(public.fnwatercustomerdebt_balance(p_farmid, d.debtid))
                             FROM watercustomerdebts d
                             WHERE d.farmid = p_farmid AND d.watercustomerid = p_customerid
                               AND d.status = 'Posted' AND d.debtdate < p_from), 0))::numeric(14,2) END AS debit,
               0::numeric(14,2) AS credit,
               NULL::integer    AS saleid,
               0                AS sortkey,
               0                AS pin,
               NULL::uuid       AS paymentgroupid,
               NULL::integer    AS allocationcount,
               NULL::text       AS sourcetype

        UNION ALL

        SELECT s.saledate::date, 'Sale'::text,
               ('W' || s.watersaleid::text)::text,
               COALESCE(NULLIF(btrim(s.notes), ''), 'Water sale')::text,
               s.totalamount::numeric(14,2), 0::numeric(14,2),
               s.watersaleid, 1, 1,
               NULL::uuid, NULL::integer, 'Sale'::text
        FROM   watersales s
        WHERE  s.farmid = p_farmid AND s.watercustomerid = p_customerid
          AND  COALESCE(s.status, '') <> 'Cancelled'
          AND  (p_from IS NULL OR s.saledate::date >= p_from)
          AND  (p_to   IS NULL OR s.saledate::date <= p_to)

        UNION ALL

        -- Money the sale records as received with no payment row behind it --
        -- a sale entered as already paid. Without this the statement shows the
        -- debit and never the receipt, and its closing figure disagrees with
        -- the balances page. Only the POSITIVE remainder: a negative one means
        -- the payment rows exceed what the sale says it received, which is a
        -- data problem to surface, not to quietly subtract.
        SELECT s.saledate::date, 'Payment'::text,
               ('W' || s.watersaleid::text)::text,
               'Paid at point of sale'::text,
               0::numeric(14,2), v.residual,
               s.watersaleid, 2, 1,
               NULL::uuid, 1, 'Counter'::text
        FROM   watersales s
        CROSS  JOIN LATERAL (
            SELECT ROUND(GREATEST(COALESCE(s.amountpaid, 0), 0)
                       - COALESCE((SELECT SUM(p2.amount) FROM waterpayments p2
                                   WHERE p2.watersaleid = s.watersaleid
                                     AND p2.farmid = s.farmid
                                     AND COALESCE(p2.status, 'Posted') = 'Posted'), 0)
                       -- 422: applied credit has its own line below
                       - public.fnwatersale_creditapplied(p_farmid, s.watersaleid), 2) AS residual
        ) v
        WHERE  s.farmid = p_farmid AND s.watercustomerid = p_customerid
          AND  COALESCE(s.status, '') <> 'Cancelled'
          AND  v.residual > 0
          AND  (p_from IS NULL OR s.saledate::date >= p_from)
          AND  (p_to   IS NULL OR s.saledate::date <= p_to)

        UNION ALL

        -- ONE LINE PER PAYMENT EVENT.
        SELECT MIN(p.paymentdate)::date, 'Payment'::text,
               COALESCE(MIN(p.paymentnumber),
                        NULLIF(btrim(MIN(p.reference)), ''),
                        'PMT' || MIN(p.waterpaymentid)::text)::text,
               ('Payment'
                || COALESCE(' â€” ' || NULLIF(btrim(MIN(p.paymentmethod)), ''), '')
                || CASE WHEN COUNT(DISTINCT p.watersaleid) > 1
                        THEN ' across ' || COUNT(DISTINCT p.watersaleid)::text || ' sales'
                        ELSE COALESCE(' (sale W' || MIN(p.watersaleid)::text || ')', ' (customer debt)')
                   END)::text,
               0::numeric(14,2), SUM(p.amount)::numeric(14,2),
               CASE WHEN COUNT(DISTINCT p.watersaleid) = 1 THEN MIN(p.watersaleid) END,
               2, 1,
               p.paymentgroupid,
               COUNT(DISTINCT p.waterpaymentid)::integer,
               MIN(p.sourcetype)::text
        FROM   waterpayments p
        WHERE  p.farmid = p_farmid AND p.watercustomerid = p_customerid
          AND  COALESCE(p.status, 'Posted') = 'Posted'
          -- 422: only money paid onto sales; credit is on the Credits page and
          -- reaches the statement when it is applied (below)
          AND  (p.watersaleid IS NOT NULL OR p.waterdebtid IS NOT NULL)   -- 423: debt payments too
          -- A CANCELLED SALE'S PAYMENTS DO NOT CREDIT THE CUSTOMER. The debit
          -- leg above has always excluded cancelled sales; this leg did not, so
          -- their credits survived and drove the balance down -- one customer
          -- read as being OWED 13,414 because 17 payments against cancelled
          -- sales stayed on their statement. That is the whole of the drift
          -- between this statement and the balances page.
          --
          -- Written as NOT EXISTS-cancelled rather than EXISTS-not-cancelled on
          -- purpose: a payment whose sale row is missing entirely keeps showing,
          -- exactly as it does today. Only cancellation is being filtered.
          AND  NOT EXISTS (SELECT 1 FROM watersales s
                           WHERE s.watersaleid = p.watersaleid
                             AND s.farmid = p.farmid
                             AND COALESCE(s.status, '') = 'Cancelled')
          AND  (p_from IS NULL OR p.paymentdate::date >= p_from)
          AND  (p_to   IS NULL OR p.paymentdate::date <= p_to)
        GROUP  BY p.paymentgroupid
        UNION ALL
        -- 423: a debt recorded by hand
        SELECT d.debtdate, 'Debt'::text, d.debtnumber::text,
               (CASE WHEN d.saletype IS NOT NULL THEN 'Old debt: ' || d.saletype ELSE 'Customer debt' END
                || COALESCE(' - ' || NULLIF(btrim(d.description), ''), ''))::text,
               d.amount::numeric(14,2), 0::numeric(14,2),
               NULL::integer, 1, 1, NULL::uuid, NULL::integer, 'CustomerDebt'::text
        FROM   watercustomerdebts d
        WHERE  d.farmid = p_farmid AND d.watercustomerid = p_customerid AND d.status = 'Posted'
          AND  (p_from IS NULL OR d.debtdate >= p_from)
          AND  (p_to   IS NULL OR d.debtdate <= p_to)
        UNION ALL
        -- 422: credit applied to a sale
        SELECT ca.createdat::date, 'Payment'::text,
               COALESCE(cp.paymentnumber, 'CR' || cp.waterpaymentid::text)::text,
               ('Credit applied (sale W' || ca.saleid::text || ')')::text,
               0::numeric(14,2), ca.amountapplied::numeric(14,2),
               ca.saleid, 2, 1,
               cp.paymentgroupid, 1, 'CreditApplied'::text
        FROM   customerpaymentallocation ca
        JOIN   waterpayments cp ON cp.waterpaymentid = ca.paymentid AND cp.farmid = ca.farmid
        JOIN   watersales s ON s.watersaleid = ca.saleid AND s.farmid = ca.farmid
        WHERE  ca.farmid = p_farmid AND ca.module = 'water' AND ca.status = 'Posted'
          AND  cp.watersaleid IS NULL AND s.watercustomerid = p_customerid
          AND  COALESCE(s.status, '') <> 'Cancelled'
          AND  (p_from IS NULL OR ca.createdat::date >= p_from)
          AND  (p_to   IS NULL OR ca.createdat::date <= p_to)
    ),
    ordered AS (
        -- `reference` is the final tiebreaker now that two payments on one day
        -- can both have a null saleid.
        SELECT l.*,
               ROW_NUMBER() OVER (
                   ORDER BY l.pin, l.entrydate NULLS FIRST, l.sortkey,
                            l.saleid NULLS FIRST, l.reference) AS rn
        FROM   lines l
    )
    SELECT o.entrydate, o.entrytype, o.reference, o.description,
           o.debit, o.credit,
           SUM(o.debit - o.credit) OVER (ORDER BY o.rn
               ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW)::numeric(14,2),
           o.saleid, o.sortkey, o.paymentgroupid, o.allocationcount, o.sourcetype
    FROM   ordered o
    ORDER  BY o.rn;
$function$;

CREATE OR REPLACE FUNCTION public.spwatercashflow_rows(p_farmid text, p_fromdate timestamp without time zone DEFAULT NULL::timestamp without time zone, p_todate timestamp without time zone DEFAULT NULL::timestamp without time zone)
 RETURNS TABLE(rowsource text, offledger boolean, sourcerowid integer, cashaccountid integer, accountname text, transactiondate timestamp without time zone, transactiontype text, sourcetype text, sourceid integer, istransfer boolean, amount numeric, description text, flowgroup text, createdat timestamp without time zone)
 LANGUAGE plpgsql
 STABLE
AS $function$

DECLARE

    v_tbl  text;
    v_createdcol text;               -- 302: 'ca.createddate' or NULL

    v_from timestamp := COALESCE(p_fromdate, '-infinity'::timestamp);

    v_to   timestamp := COALESCE(p_todate,   'infinity'::timestamp);

BEGIN

    -- ---- 1. customer receipts, dated when the money arrived -----------------

    RETURN QUERY

    SELECT 'Receipt'::text,

           FALSE,

           p.waterpaymentid,

           NULL::integer,

           NULL::text,

           p.paymentdate,

           'CashIn'::text,

           'CustomerPayment'::text,

           p.watersaleid,

           FALSE,

           COALESCE(p.amount, 0)::numeric,

           COALESCE(NULLIF(btrim(p.note), ''),

                    NULLIF(btrim(p.reference), ''),

                    'Payment for sale #' || p.watersaleid::text,
                    CASE WHEN p.waterdebtid IS NOT NULL THEN 'Payment on a customer debt'   -- 423
                         ELSE 'Customer payment' END)::text,

           'OperatingIn'::text

           , p.createddate   -- 302: the entry time
    FROM   waterpayments p

    WHERE  lower(p.farmid::text) = lower(p_farmid)

      AND  COALESCE(p.amount, 0) <> 0

      -- A REVERSED payment is money that came back. 227 added this column and

      -- flips it on reversal rather than deleting the row, so without this filter

      -- the report counts a refunded receipt as income for ever.

      AND  COALESCE(p.status, 'Posted') = 'Posted'

      -- 422: opening credit and credit notes are credit, not money received.
      AND  NOT public.fnwater_isnocashcredit(p.sourcetype)

      AND  p.paymentdate >= v_from

      AND  p.paymentdate <= v_to;



    -- ---- 1b. 422: customer refunds -----------------------------------------
    -- Money out on the refund date, and it stays there when the refund is
    -- reversed (the money did leave); the reversal is money back in on its date.
    RETURN QUERY
    SELECT 'CustomerRefund'::text, FALSE, r.refundid, r.watercashaccountid, NULL::text,
           r.refunddate::timestamp, 'CashOut'::text, 'WaterCustomerRefund'::text, r.refundid, FALSE,
           -r.amount, ('Customer refund ' || r.refundnumber ||
                       COALESCE(' - ' || NULLIF(btrim(c.name), ''), ''))::text,
           'OperatingOut'::text, r.createdat
    FROM   watercustomerrefunds r
    LEFT   JOIN watercustomers c ON c.watercustomerid = r.watercustomerid AND c.farmid = r.farmid
    WHERE  r.farmid = p_farmid AND r.status IN ('Posted', 'Reversed')
      AND  r.refunddate::timestamp >= v_from AND r.refunddate::timestamp <= v_to;

    RETURN QUERY
    SELECT 'CustomerRefundReversal'::text, FALSE, r.refundid, r.watercashaccountid, NULL::text,
           r.reversedat, 'CashIn'::text, 'WaterCustomerRefund'::text, r.refundid, FALSE,
           r.amount, ('Reversal of customer refund ' || r.refundnumber)::text,
           'OperatingIn'::text, r.reversedat
    FROM   watercustomerrefunds r
    WHERE  r.farmid = p_farmid AND r.status = 'Reversed' AND r.reversedat IS NOT NULL
      AND  r.reversedat >= v_from AND r.reversedat <= v_to;

    -- ---- 2. the part paid at the point of sale -----------------------------

    -- Same reasoning as 235: a sale settled on the spot may never create a

    -- payment row, and the difference is what picks those up.

    RETURN QUERY

    SELECT 'SaleResidual'::text,

           FALSE,

           s.watersaleid,

           NULL::integer,

           NULL::text,

           s.saledate,

           'CashIn'::text,

           'Sale'::text,

           s.watersaleid,

           FALSE,

           v.residual,

           ('Sale #' || s.watersaleid::text)::text,

           'OperatingIn'::text

           , s.createddate   -- 302: the entry time
    FROM   watersales s

    CROSS  JOIN LATERAL (

        SELECT ROUND(

                   CASE WHEN COALESCE(s.status, '') = 'Paid'

                        THEN COALESCE(s.totalamount, 0)

                        ELSE LEAST(GREATEST(COALESCE(s.amountpaid, 0), 0),

                                   COALESCE(s.totalamount, 0))

                   END

                 - COALESCE((SELECT SUM(wp.amount)

                             FROM   waterpayments wp

                             WHERE  wp.watersaleid = s.watersaleid

                               AND  lower(wp.farmid::text) = lower(p_farmid)

                               -- Same reason: a reversed payment never covered

                               -- anything, so it must not reduce the residual.

                               AND  COALESCE(wp.status, 'Posted') = 'Posted'), 0)
                 -- 422: credit applied to the sale is not money taken at the till
                 - public.fnwatersale_creditapplied(p_farmid, s.watersaleid)

               , 2) AS residual

    ) v

    WHERE  lower(s.farmid::text) = lower(p_farmid)

      -- A cancelled sale is not income, whatever it once recorded as paid.

      AND  COALESCE(s.status, '') <> 'Cancelled'

      AND  v.residual > 0

      AND  s.saledate >= v_from

      AND  s.saledate <= v_to;



    -- ---- 3. money paid out when the bill was recorded -----------------------

    -- 236's gates are kept verbatim -- Approved, not deleted -- with two

    -- changes:

    --

    --   * the AMOUNT is what was actually paid at entry, not the whole bill:

    --     the resolved amountpaid, less anything a supplier payment has since

    --     covered (which the next arm reports on its own, later, date);

    --   * the `paymentmethod <> 'Credit'` filter is GONE, because the resolution

    --     subsumes it. A Credit bill resolves to 0 paid and drops out on

    --     `paidatentry > 0` instead -- same rows excluded, and a Credit bill

    --     that has since been part-paid is no longer wrongly invisible.

    RETURN QUERY

    SELECT 'Expense'::text,

           FALSE,

           e.waterexpenseid,

           e.watercashaccountid,

           NULL::text,

           e.expensedate,

           'CashOut'::text,

           'Expense'::text,

           e.waterexpenseid,

           FALSE,

           -v.paidatentry,

           COALESCE(NULLIF(btrim(e.description), ''),

                    NULLIF(btrim(e.paidto), ''),

                    'Expense #' || e.waterexpenseid::text)::text,

           'OperatingOut'::text

           , e.createdat   -- 302: the entry time
    FROM   waterexpenses e

    CROSS  JOIN LATERAL (

        SELECT GREATEST(

                   COALESCE(e.amountpaid,

                            CASE WHEN COALESCE(e.paymentmethod, '') = 'Credit'

                                 THEN 0 ELSE e.amount END)

                 - COALESCE((SELECT SUM(sa.amountapplied)

                             FROM   supplierpaymentallocation sa

                             WHERE  sa.farmid = p_farmid

                               AND  sa.module = 'water'

                               AND  sa.status = 'Posted'

                               AND  sa.documenttype = 'Expense'

                               AND  sa.documentid = e.waterexpenseid), 0)

               , 0)::numeric AS paidatentry

    ) v

    WHERE  lower(e.farmid::text) = lower(p_farmid)

      AND  COALESCE(e.isdeleted, false) = false

      AND  v.paidatentry > 0

      -- 047's rule: only an approved expense has been recognised at all.

      AND  COALESCE(e.status, '') = 'Approved'

      -- 259. 'NonCash' means "a cost recorded, but the money moved elsewhere".

      -- Loan interest and fees are written this way: the repayment's own arm

      -- below reports the FULL amount that left the account, so counting these

      -- rows here as well would take 12,500 out of the bank and 15,000 off the

      -- cash flow. Expense reports do not filter NonCash, so the cost still

      -- counts where it should.

      --

      -- No-op on today's data: there are zero water expenses with this marker.

      AND  COALESCE(e.paymentmethod, '') <> 'NonCash'

      -- 421: a supplier payment's own aggregated expense row is not read here.
      -- It holds only the part expensed at purchase and is Cancelled on
      -- reversal; the payment's cash is reported from the payment below (3c).
      AND  COALESCE(e.sourcetype, '') <> 'WaterSupplierPayment'

      AND  e.expensedate >= v_from

      AND  e.expensedate <= v_to;



    -- ---- 3b. money paid out later, against a bill already recorded ----------

    -- A supplier payment settling a bill. It belongs to the day the money moved,

    -- not the day the bill was entered.

    --

    -- Only documenttype='Expense'. A payment against a raw-material purchase

    -- books its own aggregated expense row dated the payment date (240) and is

    -- already counted by arm 3; adding it here would double it.

    RETURN QUERY

    SELECT 'ExpensePayment'::text,

           FALSE,

           sa.allocationid,

           sp.watercashaccountid,

           NULL::text,

           sp.paymentdate,

           'CashOut'::text,

           'ExpensePayment'::text,

           sa.documentid,

           FALSE,

           -sa.amountapplied::numeric,

           ('Payment for expense #' || sa.documentid::text ||

            COALESCE(' - ' || NULLIF(btrim(s.suppliername), ''), ''))::text,

           'OperatingOut'::text

           , sa.createdat   -- 302: the entry time
    FROM   supplierpaymentallocation sa

    JOIN   watersupplierpayments sp

           ON  sp.watersupplierpaymentid = sa.paymentid

           AND sp.farmid = sa.farmid

    LEFT   JOIN watersuppliers s

           ON  s.watersupplierid = sp.supplierid AND s.farmid = sp.farmid

    WHERE  sa.farmid = p_farmid

      AND  sa.module = 'water'

      -- 421: a reversed payment's money still LEFT on its date (376's rule);
      -- the reversal brings it back on its own date (3d). Allocations are only
      -- ever reversed together with their payment.
      AND  (sa.status = 'Posted' OR (sa.status = 'Reversed' AND sp.status = 'Reversed'))

      AND  sa.documenttype = 'Expense'

      AND  COALESCE(sp.status, 'Posted') IN ('Posted', 'Reversed')

      AND  sa.amountapplied <> 0

      AND  sp.paymentdate >= v_from

      AND  sp.paymentdate <= v_to;



    -- ---- 3c. 421: supplier payments for raw-material purchases ------------
    --
    -- The FULL purchase portion, on the payment date -- deferred lots included,
    -- because the supplier was paid for them whether or not their cost has
    -- reached the P&L (275). Reversed payments stay: the money did leave.
    RETURN QUERY
    SELECT 'SupplierPurchasePayment'::text,
           FALSE,
           sp.watersupplierpaymentid,
           sp.watercashaccountid,
           NULL::text,
           sp.paymentdate,
           'CashOut'::text,
           'WaterSupplierPayment'::text,
           sp.watersupplierpaymentid,
           FALSE,
           -x.amount,
           ('Supplier payment - raw material purchase' ||
            COALESCE(' - ' || NULLIF(btrim(s.suppliername), ''), ''))::text,
           'OperatingOut'::text,
           sp.createdat
    FROM   watersupplierpayments sp
    CROSS  JOIN LATERAL (
        SELECT COALESCE(SUM(sa.amountapplied), 0)::numeric AS amount
        FROM   supplierpaymentallocation sa
        WHERE  sa.farmid = sp.farmid AND sa.module = 'water'
          AND  sa.paymentid = sp.watersupplierpaymentid
          AND  sa.documenttype <> 'Expense'
          AND  (sa.status = 'Posted' OR (sa.status = 'Reversed' AND sp.status = 'Reversed'))
    ) x
    LEFT   JOIN watersuppliers s
           ON  s.watersupplierid = sp.supplierid AND s.farmid = sp.farmid
    WHERE  sp.farmid = p_farmid
      AND  COALESCE(sp.status, 'Posted') IN ('Posted', 'Reversed')
      AND  x.amount <> 0
      AND  sp.paymentdate >= v_from
      AND  sp.paymentdate <= v_to;

    -- ---- 3d. 421: a reversed supplier payment's money coming back ---------
    --
    -- Everything the payment paid out (purchases and bills), back in on the
    -- day it was reversed.
    RETURN QUERY
    SELECT 'SupplierPaymentReversal'::text,
           FALSE,
           sp.watersupplierpaymentid,
           sp.watercashaccountid,
           NULL::text,
           sp.reversedat,
           'CashIn'::text,
           'WaterSupplierPayment'::text,
           sp.watersupplierpaymentid,
           FALSE,
           x.amount,
           ('Reversal of supplier payment #' || sp.watersupplierpaymentid::text ||
            COALESCE(' - ' || NULLIF(btrim(s.suppliername), ''), ''))::text,
           'OperatingIn'::text,
           sp.reversedat
    FROM   watersupplierpayments sp
    CROSS  JOIN LATERAL (
        SELECT COALESCE(SUM(sa.amountapplied), 0)::numeric AS amount
        FROM   supplierpaymentallocation sa
        WHERE  sa.farmid = sp.farmid AND sa.module = 'water'
          AND  sa.paymentid = sp.watersupplierpaymentid
          AND  sa.status = 'Reversed'
    ) x
    LEFT   JOIN watersuppliers s
           ON  s.watersupplierid = sp.supplierid AND s.farmid = sp.farmid
    WHERE  sp.farmid = p_farmid
      AND  sp.status = 'Reversed'
      AND  sp.reversedat IS NOT NULL
      AND  x.amount <> 0
      AND  sp.reversedat >= v_from
      AND  sp.reversedat <= v_to;

    -- ---- 4. owner money (258) ----------------------------------------------

    -- Contributions and draws recorded through the Owner Money module.

    -- FINANCING, not operating: the owner funded the business or took funding

    -- back. Never revenue, never expense.

    --

    -- Reversed records are dropped entirely rather than netted to zero with a

    -- second row -- a contribution that was put in and taken back out is not

    -- funding, and showing both legs would put money the business never kept

    -- into Money In and Money Out.

    --

    -- Placed ABOVE the legacy capital arm on purpose: that arm RETURNs early

    -- when cashadjustment is absent, so anything below it is skipped on a

    -- company with no capital records.

    RETURN QUERY

    SELECT 'OwnerMoney'::text,

           FALSE,

           o.waterownermoneyid,

           o.watercashaccountid,

           a.accountname::text,

           o.transactiondate,

           CASE WHEN o.transactiontype = 'Contribution' THEN 'CashIn' ELSE 'CashOut' END::text,

           CASE WHEN o.transactiontype = 'Contribution' THEN 'OwnerContribution' ELSE 'OwnerDraw' END::text,

           o.waterownermoneyid,

           FALSE,

           -- Stored positive; the sign is applied here, once.

           (CASE WHEN o.transactiontype = 'Contribution' THEN o.amount ELSE -o.amount END)::numeric,

           COALESCE(NULLIF(btrim(o.notes), ''),

                    NULLIF(btrim(o.ownername), ''),

                    CASE WHEN o.transactiontype = 'Contribution'

                         THEN 'Owner contribution' ELSE 'Owner draw' END)::text,

           CASE WHEN o.transactiontype = 'Contribution' THEN 'FinancingIn' ELSE 'FinancingOut' END::text

           , o.createdat   -- 302: the entry time
    FROM   waterownermoney o

    LEFT   JOIN watercashaccounts a

           ON a.watercashaccountid = o.watercashaccountid

    WHERE  o.farmid = p_farmid

      AND  o.status = 'Posted'
      -- 297. A record backfilled from a Cash Flow adjustment has NO cash
      -- row of its own: the ADJUSTMENT is still the cash event, and the
      -- legacy adjustment arm below already reports it. Without this the
      -- same money is counted twice -- the trap 292 hit for loans.
      AND  o.sourceadjustmentid IS NULL

      AND  o.transactiondate >= v_from

      AND  o.transactiondate <= v_to;



    -- ---- 5. loans received (259) -------------------------------------------

    -- Borrowed money arriving. FINANCING: the business received it, it did not

    -- earn it, so it is money in and never revenue.

    --

    -- The AMOUNT RECEIVED, not the principal. A lender that withholds a fee

    -- pays out less than it lends, and only what arrived is cash in.

    --

    -- The timestamp carries 256's rule, baked in from the start rather than

    -- patched afterwards as it had to be on poultry: loandate is a DATE, so a

    -- plain cast gives midnight and a loan recorded this afternoon sorts below

    -- everything else recorded today. A loan dated TODAY reports the moment it

    -- was recorded; a BACK-DATED one keeps midnight, because using createdat

    -- unconditionally would drag last Tuesday's loan into today, above rows

    -- that really did happen after it.

    RETURN QUERY

    SELECT 'Loan'::text,

           FALSE,

           l.waterloanid,

           l.watercashaccountid,

           a.accountname::text,

           CASE WHEN l.loandate = l.createdat::date THEN l.createdat

                ELSE l.loandate::timestamp END,

           'CashIn'::text,

           'LoanReceived'::text,

           l.waterloanid,

           FALSE,

           l.amountreceived::numeric,

           ('Loan received from ' || l.lendername)::text,

           'FinancingIn'::text

           , l.createdat   -- 302: the entry time
    FROM   waterloans l

    LEFT   JOIN watercashaccounts a ON a.watercashaccountid = l.watercashaccountid

    WHERE  l.farmid = p_farmid

      AND  l.amountreceived > 0

      -- 293. A loan converted from a Cash Flow adjustment has NO cash row of

      -- its own: the ADJUSTMENT is the cash event, and the legacy adjustment arm

      -- already reports it. Without this the same borrowing is money-in twice --

      -- which is precisely what 292's stage check caught on the poultry side.

      AND  l.sourceadjustmentid IS NULL

      AND  l.status NOT IN ('Cancelled', 'Reversed', 'Draft')

      AND  (CASE WHEN l.loandate = l.createdat::date THEN l.createdat

                 ELSE l.loandate::timestamp END) >= v_from

      AND  (CASE WHEN l.loandate = l.createdat::date THEN l.createdat

                 ELSE l.loandate::timestamp END) <= v_to;



    -- ---- 6. loan repayments (259) ------------------------------------------

    -- The FULL payment leaves the account, so the full payment is money out --

    -- principal, interest and fees together.

    --

    -- This does NOT double count the interest and fee expenses those payments

    -- create: they are written paymentmethod = 'NonCash', and arm 3 above now

    -- skips NonCash. Expense reports read the expense table directly and still

    -- count them, which is the whole point -- cash out is 12,500, cost is 2,500.

    RETURN QUERY

    SELECT 'LoanPayment'::text,

           FALSE,

           p.waterloanpaymentid,

           p.watercashaccountid,

           a.accountname::text,

           p.paymentdate,

           'CashOut'::text,

           'LoanRepayment'::text,

           p.waterloanid,

           FALSE,

           -p.totalamount::numeric,

           ('Loan repayment to ' || l.lendername)::text,

           'FinancingOut'::text

           , p.createdat   -- 302: the entry time
    FROM   waterloanpayments p

    JOIN   waterloans l ON l.waterloanid = p.waterloanid

    LEFT   JOIN watercashaccounts a ON a.watercashaccountid = p.watercashaccountid

    WHERE  p.farmid = p_farmid

      AND  p.status = 'Posted'

      AND  p.paymentdate >= v_from

      AND  p.paymentdate <= v_to;



    -- ---- 7. capital in and out (legacy cash adjustments) --------------------

    -- Expected to return nothing on Water today -- see 236's header note.

    --

    -- MUST STAY LAST: it RETURNs early when the table is absent, and anything

    -- below it would be silently skipped.

    v_tbl := COALESCE(to_regclass('public.cashadjustment')::text,

                      to_regclass('public.cashadjustments')::text);



    -- 302: only reference the creation column if the resolved table has one.
    SELECT CASE WHEN EXISTS (
               SELECT 1 FROM information_schema.columns c
               WHERE  c.table_schema = 'public'
                 AND  c.table_name = replace(v_tbl, 'public.', '')
                 AND  c.column_name = 'createddate')
           THEN 'ca.createddate' ELSE 'NULL::timestamp' END
      INTO v_createdcol;

    IF v_tbl IS NULL THEN

        RETURN;

    END IF;



    RETURN QUERY EXECUTE format($sql$

        SELECT 'Adjustment'::text,

               FALSE,

               ca.adjustmentid,

               NULL::integer,

               NULL::text,

               ca.adjustmentdate,

               CASE WHEN ca.amount >= 0 THEN 'CashIn' ELSE 'CashOut' END::text,

               COALESCE(NULLIF(btrim(ca.adjustmenttype), ''), 'Adjustment')::text,

               ca.adjustmentid,

               FALSE,

               ca.amount::numeric,

               COALESCE(NULLIF(btrim(ca.description), ''), ca.adjustmenttype)::text,

               CASE WHEN ca.amount >= 0 THEN 'FinancingIn' ELSE 'FinancingOut' END::text,
               %s                       -- 302: the entry time

        FROM   %s ca

        WHERE  lower(ca.farmid::text) = lower($1)

          AND  ca.amount <> 0

          AND  ca.adjustmentdate >= $2

          AND  ca.adjustmentdate <= $3

    $sql$, v_createdcol, v_tbl)

    USING p_farmid, v_from, v_to;
    -- ---- 8. employee advances (313/315) ------------------------------------

    -- Disbursements out, manual repayments in, payroll deductions NOWHERE:

    -- a deduction moves no money, so it is not a cash event. The arms live in

    -- their own function, so this body is touched once and never again.

    RETURN QUERY

    SELECT * FROM public.spwateremployeeloan_cashflowrows(p_farmid, v_from, v_to);


END;

$function$;

CREATE OR REPLACE FUNCTION public.spwaterreport_periodpnl(p_farmid text, p_fromdate date, p_todate date)
 RETURNS TABLE(periodstart date, periodend date, totalincome numeric, totalexpenses numeric, rawmaterialcost numeric, productioncost numeric, totallosses numeric, netprofit numeric, profitmarginpct numeric, bagsproduced integer, bagssold integer, avgprofitperbag numeric)
 LANGUAGE plpgsql
AS $function$
DECLARE
    v_start             timestamp;
    v_end               timestamp;
    v_storefrontincome  numeric;
    v_driverincome      numeric;
    v_totalincome       numeric;
    v_rawmaterialcost   numeric;
    v_productioncost    numeric;
    v_generalexpenses   numeric;
    v_deliveryexpenses  numeric;
    v_operatingexpenses numeric;
    v_productionlosses  numeric;
    v_shortagelosses    numeric;
    v_totallosses       numeric;
    v_netprofit         numeric;
    v_bagsproduced      integer;
    v_storefrontbagssold numeric;
    v_driverbagssold    numeric;
    v_bagssold          integer;
    v_profitmargin      numeric;
    v_avgprofitperbag   numeric;
BEGIN
    v_start := p_fromdate::timestamp;
    v_end   := p_todate::timestamp + make_interval(days => 1);

    -- Storefront sales only (exclude DeliveryRun - that income is on the return).
    v_storefrontincome := COALESCE((
        SELECT SUM(s.totalamount) FROM watersales s
        WHERE s.farmid = p_farmid AND s.status NOT IN ('Cancelled')
          AND COALESCE(s.sourcetype, '') <> 'DeliveryRun'
          AND s.saledate >= v_start AND s.saledate < v_end), 0);

    -- Driver-return income for the day (cash + momo + bank + credit sold).
    v_driverincome := COALESCE((
        SELECT SUM(dr.cashcollected + dr.momocollected + dr.bankcollected + dr.creditsalesamount)
        FROM waterdriverreturns dr
        WHERE dr.farmid = p_farmid AND dr.status IN ('Draft','Approved')
          AND dr.returndate >= v_start AND dr.returndate < v_end), 0);

    -- 422: a credit note is an allowance given -- revenue the business gave up.
    v_totalincome := (v_storefrontincome + v_driverincome
                      - COALESCE((SELECT SUM(cn.amount) FROM waterpayments cn
                                  WHERE cn.farmid = p_farmid AND cn.sourcetype = 'CreditNote'
                                    AND COALESCE(cn.status, 'Posted') = 'Posted'
                                    AND cn.paymentdate >= v_start AND cn.paymentdate < v_end), 0)
                      -- 423 (382): money paid on debts recorded by hand is revenue
                      + (SELECT dc.total FROM public.fnwaterpl_debtcollections(p_farmid, v_start, v_end) dc))::numeric(14,2);

    -- Cash paid for raw materials (matches the closing's AmountPaid basis).
    v_rawmaterialcost := COALESCE((
        SELECT SUM(p.amountpaid) FROM waterrawmaterialpurchases p
        WHERE p.farmid = p_farmid AND p.purchasedate >= v_start AND p.purchasedate < v_end), 0);

    v_productioncost := COALESCE((
        SELECT SUM(b.totalproductioncost) FROM waterproductionbatches b
        WHERE b.farmid = p_farmid AND b.isdeleted = FALSE AND b.status = 'Approved'
          AND b.productiondate >= p_fromdate AND b.productiondate <= p_todate), 0);

    -- Operating expenses: general approved WaterExpenses (excl. the auto
    -- raw-material-purchase expense, already in RawMaterialCost) + delivery expenses.
    v_generalexpenses := COALESCE((
        SELECT SUM(e.amount) FROM waterexpenses e
        WHERE e.farmid = p_farmid AND e.isdeleted = FALSE AND e.status = 'Approved'
          AND COALESCE(e.sourcetype, '') <> 'RawMaterialPurchase'
          AND e.expensedate >= v_start AND e.expensedate < v_end), 0);

    v_deliveryexpenses := COALESCE((
        SELECT SUM(de.amount) FROM waterdeliveryexpenses de
        INNER JOIN waterdriverreturns dr ON dr.waterdriverreturnid = de.waterdriverreturnid
        WHERE dr.farmid = p_farmid AND dr.status IN ('Draft','Approved') AND de.isapproved = TRUE
          AND dr.returndate >= v_start AND dr.returndate < v_end), 0);

    v_operatingexpenses := (v_generalexpenses + v_deliveryexpenses)::numeric(14,2);

    -- Losses: production losses (damaged/rejected) + driver cash shortages.
    v_productionlosses := COALESCE((
        SELECT SUM(l.totalvalue) FROM waterproductionlosses l
        WHERE l.farmid = p_farmid AND l.lossdate >= v_start AND l.lossdate < v_end), 0);

    v_shortagelosses := COALESCE((
        SELECT SUM(dr.shortageamount) FROM waterdriverreturns dr
        WHERE dr.farmid = p_farmid AND dr.status IN ('Draft','Approved')
          AND dr.returndate >= v_start AND dr.returndate < v_end), 0);

    v_totallosses := (v_productionlosses + v_shortagelosses)::numeric(14,2);

    v_netprofit := (v_totalincome - v_rawmaterialcost - v_productioncost
                    - v_operatingexpenses - v_totallosses)::numeric(14,2);

    v_bagsproduced := COALESCE((
        SELECT SUM(b.bagsproduced - b.damagedbags)::int FROM waterproductionbatches b
        WHERE b.farmid = p_farmid AND b.isdeleted = FALSE AND b.status = 'Approved'
          AND b.productiondate >= p_fromdate AND b.productiondate <= p_todate), 0);

    -- Bags sold = storefront sale items (excl. DeliveryRun) + driver-return bags sold.
    v_storefrontbagssold := COALESCE((
        SELECT SUM(si.quantity) FROM watersales s
        INNER JOIN watersaleitems si ON si.watersaleid = s.watersaleid
        WHERE s.farmid = p_farmid AND s.status NOT IN ('Cancelled')
          AND COALESCE(s.sourcetype, '') <> 'DeliveryRun'
          AND s.saledate >= v_start AND s.saledate < v_end), 0);

    v_driverbagssold := COALESCE((
        SELECT SUM(dr.bagssold) FROM waterdriverreturns dr
        WHERE dr.farmid = p_farmid AND dr.status IN ('Draft','Approved')
          AND dr.returndate >= v_start AND dr.returndate < v_end), 0);

    -- T-SQL CAST(decimal AS INT) truncates toward zero; trunc() keeps that.
    v_bagssold := trunc(v_storefrontbagssold + v_driverbagssold)::int;

    v_profitmargin := (CASE WHEN v_totalincome > 0 THEN (v_netprofit / v_totalincome) * 100 ELSE 0 END)::numeric(8,2);
    v_avgprofitperbag := (CASE WHEN v_bagssold > 0 THEN v_netprofit / v_bagssold ELSE 0 END)::numeric(14,2);

    RETURN QUERY
    SELECT p_fromdate, p_todate,
           v_totalincome,
           v_operatingexpenses,   -- operating only
           v_rawmaterialcost,
           v_productioncost,
           v_totallosses,
           v_netprofit,
           v_profitmargin,
           v_bagsproduced,
           v_bagssold,
           v_avgprofitperbag;
END;
$function$;

CREATE OR REPLACE FUNCTION public.spwaterreport_pllines(p_farmid text, p_startdate date, p_enddate date)
 RETURNS TABLE(section text, linekey text, linelabel text, amount numeric, sortorder integer, isinformational boolean, entrycount integer)
 LANGUAGE sql
 STABLE
AS $function$
    -- periodpnl's own window, copied: half-open on the timestamp columns.
    WITH bounds AS (
        SELECT p_startdate::timestamp                              AS s,
               p_enddate::timestamp + make_interval(days => 1)     AS e
    ),
    -- ---- Revenue -----------------------------------------------------------
    rev AS (
        SELECT 'StorefrontSales'::text AS k, 'Storefront sales'::text AS lbl,
               COALESCE(SUM(s.totalamount), 0) AS amt, COUNT(*)::integer AS n, 1 AS ord
        FROM   watersales s, bounds b
        WHERE  s.farmid = p_farmid AND s.status NOT IN ('Cancelled')
          AND  COALESCE(s.sourcetype, '') <> 'DeliveryRun'
          AND  s.saledate >= b.s AND s.saledate < b.e
        UNION ALL
        -- Collections, not sales. periodpnl takes the driver's money rather than
        -- the DeliveryRun sale rows so the two cannot double-count, and the
        -- drilldown shows the returns for the same reason.
        SELECT 'DeliveryCollections', 'Delivery-run collections',
               COALESCE(SUM(dr.cashcollected + dr.momocollected
                          + dr.bankcollected + dr.creditsalesamount), 0),
               COUNT(*)::integer, 2
        FROM   waterdriverreturns dr, bounds b
        WHERE  dr.farmid = p_farmid AND dr.status IN ('Draft', 'Approved')
          AND  dr.returndate >= b.s AND dr.returndate < b.e
        UNION ALL
        -- 423 (382): money paid on customer debts recorded by hand
        SELECT 'DebtCollections', 'Customer debt collections', dc.total, dc.n, 4
        FROM   bounds b CROSS JOIN LATERAL public.fnwaterpl_debtcollections(p_farmid, b.s, b.e) dc
        UNION ALL
        -- 422: credit notes -- allowances given, negative revenue
        SELECT 'CreditNotes', 'Credit notes & allowances',
               -COALESCE(SUM(cn.amount), 0), COUNT(*)::integer, 3
        FROM   waterpayments cn, bounds b
        WHERE  cn.farmid = p_farmid AND cn.sourcetype = 'CreditNote'
          AND  COALESCE(cn.status, 'Posted') = 'Posted'
          AND  cn.paymentdate >= b.s AND cn.paymentdate < b.e
    ),
    -- ---- Direct cost -------------------------------------------------------
    direct AS (
        SELECT 'RawMaterials'::text AS k, 'Raw materials (paid)'::text AS lbl,
               COALESCE(SUM(p.amountpaid), 0) AS amt, COUNT(*)::integer AS n, 11 AS ord
        FROM   waterrawmaterialpurchases p, bounds b
        WHERE  p.farmid = p_farmid
          AND  p.purchasedate >= b.s AND p.purchasedate < b.e
        UNION ALL
        -- DATE comparison, inclusive both ends. periodpnl's own shape; see header.
        SELECT 'ProductionCost', 'Production cost',
               COALESCE(SUM(pb.totalproductioncost), 0), COUNT(*)::integer, 12
        FROM   waterproductionbatches pb
        WHERE  pb.farmid = p_farmid AND pb.isdeleted = FALSE AND pb.status = 'Approved'
          AND  pb.productiondate >= p_startdate AND pb.productiondate <= p_enddate
    ),
    -- ---- Operating / other cost -------------------------------------------
    -- The general expense pool periodpnl counts, itemised by 282's own P&L line
    -- so the P&L, the Expenses page and Financial Activity agree on the wording.
    exp AS (
        SELECT fnwaterexpense_plsection(l.line) AS sec,
               l.line                           AS k,
               fnwaterexpense_pllinelabel(l.line) AS lbl,
               COALESCE(SUM(e.amount), 0)       AS amt,
               COUNT(*)::integer                AS n
        FROM   waterexpenses e
        INNER  JOIN waterexpensecategories ec ON ec.waterexpensecategoryid = e.waterexpensecategoryid,
               bounds b
        -- Same four arguments fnwaterexpenserows passes, including the category
        -- NAME and the item category. Anything less and a legacy row lands on a
        -- different line here than it does on the Expenses page.
        CROSS  JOIN LATERAL (SELECT fnwaterexpense_costtype(
                                        e.financialcosttype::text, e.sourcetype::text,
                                        ec.name::text, e.paymentmethod::text) AS ct) c
        CROSS  JOIN LATERAL (SELECT fnwaterexpense_plline(
                                        c.ct, e.sourcetype::text, ec.name::text,
                                        fnwaterexpense_itemcategory(e.sourcetype::text, e.sourceid)) AS line) l
        WHERE  e.farmid = p_farmid
          AND  COALESCE(e.isdeleted, FALSE) = FALSE AND e.status = 'Approved'
          AND  COALESCE(e.sourcetype, '') <> 'RawMaterialPurchase'
          AND  e.expensedate >= b.s AND e.expensedate < b.e
        GROUP  BY 1, 2, 3
    ),
    deliv AS (
        SELECT 'DeliveryExpenses'::text AS k, 'Delivery expenses'::text AS lbl,
               COALESCE(SUM(de.amount), 0) AS amt, COUNT(*)::integer AS n
        FROM   waterdeliveryexpenses de
        JOIN   waterdriverreturns dr ON dr.waterdriverreturnid = de.waterdriverreturnid, bounds b
        WHERE  dr.farmid = p_farmid AND dr.status IN ('Draft', 'Approved')
          AND  de.isapproved = TRUE
          AND  dr.returndate >= b.s AND dr.returndate < b.e
    ),
    -- ---- Losses ------------------------------------------------------------
    loss AS (
        SELECT 'ProductionLosses'::text AS k, 'Production losses'::text AS lbl,
               COALESCE(SUM(pl.totalvalue), 0) AS amt, COUNT(*)::integer AS n, 61 AS ord
        FROM   waterproductionlosses pl, bounds b
        WHERE  pl.farmid = p_farmid
          AND  pl.lossdate >= b.s AND pl.lossdate < b.e
        UNION ALL
        SELECT 'DriverShortages', 'Driver cash shortages',
               COALESCE(SUM(dr.shortageamount), 0), COUNT(*) FILTER (WHERE dr.shortageamount <> 0)::integer, 62
        FROM   waterdriverreturns dr, bounds b
        WHERE  dr.farmid = p_farmid AND dr.status IN ('Draft', 'Approved')
          AND  dr.returndate >= b.s AND dr.returndate < b.e
    ),
    -- ---- Informational: cash moved, profit did not -------------------------
    fin AS (
        SELECT 'OwnerContributions'::text AS k, 'Owner Contributions'::text AS lbl,
               COALESCE(SUM(o.amount), 0) AS amt, COUNT(*)::integer AS n, 71 AS ord
        FROM   waterownermoney o, bounds b
        WHERE  o.farmid = p_farmid AND o.status = 'Posted'
          AND  o.transactiontype = 'Contribution'
          AND  o.transactiondate >= b.s AND o.transactiondate < b.e
        UNION ALL
        SELECT 'OwnerDraws', 'Owner Draws', COALESCE(SUM(o.amount), 0), COUNT(*)::integer, 72
        FROM   waterownermoney o, bounds b
        WHERE  o.farmid = p_farmid AND o.status = 'Posted'
          AND  o.transactiontype = 'Draw'
          AND  o.transactiondate >= b.s AND o.transactiondate < b.e
        UNION ALL
        SELECT 'LoansReceived', 'Loans Received', COALESCE(SUM(l.amountreceived), 0), COUNT(*)::integer, 73
        FROM   waterloans l, bounds b
        WHERE  l.farmid = p_farmid AND l.status NOT IN ('Reversed', 'Cancelled', 'Draft')
          AND  l.loandate >= b.s AND l.loandate < b.e
        UNION ALL
        SELECT 'LoanPrincipalRepaid', 'Loan Principal Repaid',
               COALESCE(SUM(pm.principalamount), 0), COUNT(*)::integer, 74
        FROM   waterloanpayments pm, bounds b
        WHERE  pm.farmid = p_farmid AND pm.status = 'Posted'
          AND  pm.paymentdate >= b.s AND pm.paymentdate < b.e
    ),
    cap AS (
        SELECT COALESCE(cat.categoryname, 'Other Assets')::text AS k,
               COALESCE(SUM(cc.amount), 0) AS amt, COUNT(*)::integer AS n
        FROM   watercapitalassetcosts cc
        JOIN   watercapitalassets a ON a.watercapitalassetid = cc.watercapitalassetid
        LEFT   JOIN waterassetcategories cat ON cat.waterassetcategoryid = a.waterassetcategoryid
        WHERE  cc.farmid = p_farmid AND cc.status = 'Posted'
          AND  cc.costdate >= p_startdate AND cc.costdate <= p_enddate
        GROUP  BY COALESCE(cat.categoryname, 'Other Assets')
    )
    SELECT 'Revenue', rev.k, rev.lbl, rev.amt::numeric(14,2), rev.ord, FALSE, rev.n
    FROM   rev WHERE rev.amt <> 0 OR rev.n > 0
    UNION ALL
    SELECT 'DirectCost', direct.k, direct.lbl, direct.amt::numeric(14,2), direct.ord, FALSE, direct.n
    FROM   direct WHERE direct.amt <> 0 OR direct.n > 0
    UNION ALL
    -- 282's own section decides which band an expense line sits in, so a
    -- depreciation or loan-interest row drops below Operating Profit rather
    -- than inflating it. Both bands together still equal periodpnl's
    -- totalexpenses, which is what keeps the statement reconciled.
    SELECT exp.sec, exp.k, exp.lbl, exp.amt::numeric(14,2),
           CASE exp.sec WHEN 'OperatingExpense' THEN 30 ELSE 50 END
             + CASE exp.k WHEN 'Payroll' THEN 1 WHEN 'Utilities' THEN 2
                          WHEN 'Transport' THEN 3 WHEN 'RepairsMaintenance' THEN 4
                          WHEN 'Depreciation' THEN 1 WHEN 'LoanInterest' THEN 2
                          WHEN 'LoanFees' THEN 3 ELSE 9 END,
           FALSE, exp.n
    FROM   exp WHERE exp.amt <> 0
    UNION ALL
    SELECT 'OperatingExpense', deliv.k, deliv.lbl, deliv.amt::numeric(14,2), 40, FALSE, deliv.n
    FROM   deliv WHERE deliv.amt <> 0 OR deliv.n > 0
    UNION ALL
    SELECT 'Loss', loss.k, loss.lbl, loss.amt::numeric(14,2), loss.ord, FALSE, loss.n
    FROM   loss WHERE loss.amt <> 0
    UNION ALL
    SELECT 'Financing', fin.k, fin.lbl, fin.amt::numeric(14,2), fin.ord, TRUE, fin.n
    FROM   fin WHERE fin.amt <> 0
    UNION ALL
    SELECT 'CapitalInvestment', cap.k, cap.k, cap.amt::numeric(14,2), 81, TRUE, cap.n
    FROM   cap WHERE cap.amt <> 0
    ORDER  BY 5, 2;
$function$;

CREATE OR REPLACE FUNCTION public.spwaterreport_plrevenuedetail(p_farmid text, p_startdate date, p_enddate date, p_linekey text DEFAULT NULL::text)
 RETURNS TABLE(entrydate timestamp without time zone, reference text, party text, detail text, amount numeric)
 LANGUAGE sql
 STABLE
AS $function$
    SELECT s.saledate, ('Sale #' || s.watersaleid)::text,
           COALESCE(c.name, 'Walk-in')::text,
           COALESCE(NULLIF(btrim(s.notes), ''), s.status)::text,
           s.totalamount::numeric(14,2)
    FROM   watersales s
    LEFT   JOIN watercustomers c ON c.watercustomerid = s.watercustomerid
    WHERE  s.farmid = p_farmid AND s.status NOT IN ('Cancelled')
      AND  COALESCE(s.sourcetype, '') <> 'DeliveryRun'
      AND  s.saledate >= p_startdate::timestamp
      AND  s.saledate <  p_enddate::timestamp + make_interval(days => 1)
      AND  (p_linekey IS NULL OR p_linekey = 'StorefrontSales')
    UNION ALL
    SELECT dr.returndate, ('Return #' || dr.waterdriverreturnid)::text,
           'Driver return'::text,
           (dr.bagssold::text || ' bag(s) sold')::text,
           (dr.cashcollected + dr.momocollected + dr.bankcollected + dr.creditsalesamount)::numeric(14,2)
    FROM   waterdriverreturns dr
    WHERE  dr.farmid = p_farmid AND dr.status IN ('Draft', 'Approved')
      AND  dr.returndate >= p_startdate::timestamp
      AND  dr.returndate <  p_enddate::timestamp + make_interval(days => 1)
      AND  (p_linekey IS NULL OR p_linekey = 'DeliveryCollections')
    UNION ALL
    -- 423 (382/384): debt payments; an old debt names what was sold
    SELECT p.paymentdate, COALESCE(p.paymentnumber, 'PAY' || p.waterpaymentid::text)::text,
           COALESCE(c.name, 'Customer')::text,
           (CASE WHEN d.saletype IS NOT NULL THEN 'Old debt collected: ' || d.saletype || ' - ' ELSE '' END
            || 'Debt ' || d.debtnumber)::text,
           p.amount::numeric(14,2)
    FROM   waterpayments p
    JOIN   watercustomerdebts d ON d.debtid = p.waterdebtid AND d.farmid = p.farmid
    LEFT   JOIN watercustomers c ON c.watercustomerid = p.watercustomerid AND c.farmid = p.farmid
    WHERE  p.farmid = p_farmid AND COALESCE(p.status, 'Posted') = 'Posted' AND NOT p.excludefrompl
      AND  p.paymentdate >= p_startdate::timestamp
      AND  p.paymentdate <  p_enddate::timestamp + make_interval(days => 1)
      AND  (p_linekey IS NULL OR p_linekey = 'DebtCollections')
    UNION ALL
    -- 422
    SELECT cn.paymentdate, COALESCE(cn.paymentnumber, 'CR' || cn.waterpaymentid::text)::text,
           COALESCE(c.name, 'Customer')::text,
           ('Credit note' || COALESCE(': ' || NULLIF(btrim(cn.note), ''), ''))::text,
           (-cn.amount)::numeric(14,2)
    FROM   waterpayments cn
    LEFT   JOIN watercustomers c ON c.watercustomerid = cn.watercustomerid AND c.farmid = cn.farmid
    WHERE  cn.farmid = p_farmid AND cn.sourcetype = 'CreditNote'
      AND  COALESCE(cn.status, 'Posted') = 'Posted'
      AND  cn.paymentdate >= p_startdate::timestamp
      AND  cn.paymentdate <  p_enddate::timestamp + make_interval(days => 1)
      AND  (p_linekey IS NULL OR p_linekey = 'CreditNotes')
    ORDER  BY 1 DESC, 2;
$function$;

