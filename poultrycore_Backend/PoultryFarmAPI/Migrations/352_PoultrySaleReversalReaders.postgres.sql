-- ---- fnflock_birdposition: birds sold from the flock
CREATE OR REPLACE FUNCTION public.fnflock_birdposition(p_farmid text, p_flockid integer)
 RETURNS TABLE(flockid integer, hasopeningposition boolean, historyknown boolean, originallyplaced integer, openingmortality integer, openingsold integer, openingculled integer, openingtransferred integer, openingother integer, openinglivebirds integer, recordedmortality integer, productionrecordcount integer, lastcountedbirds integer, lastcountdate date, correction integer, birdssold integer, birdsculled integer, birdstransferred integer, currentlivebirds integer)
 LANGUAGE plpgsql
 STABLE
AS $function$
BEGIN
    RETURN QUERY
    WITH f AS (
        SELECT fl.flockid AS c_flockid, COALESCE(fl.quantity, 0) AS c_quantity
        FROM   flock fl
        WHERE  fl.farmid = p_farmid AND fl.flockid = p_flockid
    ),
    o AS (
        -- One opening position per flock is what Initial Farm Setup writes;
        -- the latest wins if a second ever appears.
        SELECT op.*
        FROM   poultryopeningflockposition op
        WHERE  op.farmid = p_farmid AND op.flockid = p_flockid
        ORDER  BY op.openingpositionid DESC
        LIMIT  1
    ),
    pr AS (
        SELECT COALESCE(SUM(COALESCE(r.mortality, 0)), 0)::int AS c_mort,
               COUNT(*)::int                                    AS c_n
        FROM   productionrecords r
        WHERE  r.farmid = p_farmid AND r.flockid = p_flockid
    ),
    -- Latest count: newest date, then newest row -- the same tie-break the
    -- End of Flock report uses, so the two cannot pick different records.
    lr AS (
        SELECT r.noofbirdsleft AS c_left, r.date AS c_date
        FROM   productionrecords r
        WHERE  r.farmid = p_farmid AND r.flockid = p_flockid
        ORDER  BY r.date DESC, r.id DESC
        LIMIT  1
    ),
    s AS (
        SELECT COALESCE(ROUND(SUM(sa.quantity)), 0)::int AS c_sold
        FROM   sale sa
        WHERE  sa.status = 'Posted' AND sa.farmid = p_farmid AND sa.flockid = p_flockid
          AND  fnpoultrysale_isbirdsale(sa.product)
    ),
    d AS (
        -- Only the dispositions of the OPEN closeout. A reopened closeout's
        -- culls and transfers were reversed and no longer took any birds.
        SELECT COALESCE(SUM(x.quantity) FILTER (WHERE x.disposition = 'Cull'), 0)::int     AS c_culled,
               COALESCE(SUM(x.quantity) FILTER (WHERE x.disposition = 'Transfer'), 0)::int AS c_transferred
        FROM   flockcloseoutdispositions x
        JOIN   flockcloseouts c ON c.closeoutid = x.closeoutid
        WHERE  x.farmid = p_farmid AND x.flockid = p_flockid
          AND  x.reversedat IS NULL AND c.reopenedat IS NULL
    )
    SELECT
        f.c_flockid,
        (o.openingpositionid IS NOT NULL),
        -- No opening position means the app saw the flock from placement, so
        -- there is no unknown history.
        COALESCE(o.historyknown, TRUE),
        COALESCE(o.originallyplaced, f.c_quantity),
        COALESCE(o.historicalmortality, 0),
        COALESCE(o.historicalsold, 0),
        COALESCE(o.historicalculled, 0),
        COALESCE(o.historicaltransferred, 0),
        COALESCE(o.otheradjustment, 0),
        f.c_quantity,
        pr.c_mort,
        pr.c_n,
        GREATEST(COALESCE(lr.c_left, f.c_quantity), 0),
        lr.c_date,
        CASE WHEN lr.c_date IS NULL THEN 0
             ELSE GREATEST(COALESCE(lr.c_left, f.c_quantity), 0) - (f.c_quantity - pr.c_mort)
        END,
        s.c_sold,
        d.c_culled,
        d.c_transferred,
        GREATEST(COALESCE(lr.c_left, f.c_quantity), 0) - s.c_sold - d.c_culled - d.c_transferred
    FROM   f
    CROSS  JOIN pr
    CROSS  JOIN s
    CROSS  JOIN d
    LEFT   JOIN o  ON TRUE
    LEFT   JOIN lr ON TRUE;
END
$function$;

-- ---- fnflock_lifetimesummary: flock lifetime sales
CREATE OR REPLACE FUNCTION public.fnflock_lifetimesummary(p_farmid text, p_flockid integer DEFAULT NULL::integer, p_closedonly boolean DEFAULT false)
 RETURNS TABLE(flockid integer, flockname text, breed text, status text, batchid integer, batchcode text, batchname text, supplierid integer, suppliertype text, houseid integer, housename text, startdate date, closeddate date, daysinproduction integer, hasopeningposition boolean, historyknown boolean, originallyplaced integer, openinglivebirds integer, openingmortality integer, recordedmortality integer, birdssold integer, birdsculled integer, birdstransferred integer, finalbirds integer, trackedmortalityrate numeric, lifetimemortalityrate numeric, totaleggs bigint, productiondays integer, eggrevenue numeric, birdsalerevenue numeric, otherrevenue numeric, totalrevenue numeric, feedconsumedkg numeric, feedcost numeric, medicationcost numeric, birdcost numeric, birdcostrecorded boolean, laborcost numeric, otherdirectcost numeric, totalcost numeric, profit numeric, profitperoriginalbird numeric, revenueperoriginalbird numeric, feedkgperdozeneggs numeric)
 LANGUAGE plpgsql
 STABLE
AS $function$
DECLARE
    v_gid   uuid;
    v_today date;
BEGIN
    BEGIN
        v_gid := p_farmid::uuid;       -- expense.farmid is a uuid
    EXCEPTION WHEN OTHERS THEN
        v_gid := NULL;
    END;
    v_today := fncompany_businessdate(p_farmid);

    RETURN QUERY
    WITH fl AS (
        SELECT f.*
        FROM   flock f
        WHERE  f.farmid = p_farmid
          AND  COALESCE(f.isdeleted, FALSE) = FALSE
          AND  (p_flockid IS NULL OR f.flockid = p_flockid)
          AND  (NOT p_closedonly OR f.closeddate IS NOT NULL)
    ),
    pr AS (
        SELECT r.flockid AS c_flockid,
               SUM(COALESCE(r.totalproduction, 0))::bigint    AS c_eggs,
               COUNT(DISTINCT r.date)::int                    AS c_days,
               SUM(COALESCE(r.feedkg, 0))                     AS c_feedkg,
               SUM(COALESCE(r.totalfeedcost, 0))              AS c_feedcost,
               SUM(COALESCE(r.totalmedicationcost, 0))        AS c_medcost
        FROM   productionrecords r
        WHERE  r.farmid = p_farmid AND r.flockid IN (SELECT fl.flockid FROM fl)
        GROUP  BY r.flockid
    ),
    rev AS (
        SELECT s.flockid AS c_flockid,
               SUM(s.totalamount) FILTER (WHERE lower(COALESCE(s.product, '')) LIKE '%egg%') AS c_egg,
               SUM(s.totalamount) FILTER (WHERE fnpoultrysale_isbirdsale(s.product))         AS c_bird,
               SUM(s.totalamount)                                                            AS c_total
        FROM   sale s
        WHERE  s.status = 'Posted' AND s.farmid = p_farmid AND s.flockid IN (SELECT fl.flockid FROM fl)
        GROUP  BY s.flockid
    ),
    ex AS (
        SELECT e.flockid AS c_flockid,
               SUM(e.amount) FILTER (WHERE e.category ILIKE '%labo%' OR e.category ILIKE '%salary%'
                                        OR e.category ILIKE '%wage%' OR e.category ILIKE '%payroll%') AS c_labor,
               SUM(e.amount) FILTER (WHERE NOT (e.category ILIKE '%labo%' OR e.category ILIKE '%salary%'
                                        OR e.category ILIKE '%wage%' OR e.category ILIKE '%payroll%')) AS c_other
        FROM   expense e
        WHERE  e.farmid = v_gid
          AND  e.flockid IN (SELECT fl.flockid FROM fl)
          AND  e.poultrycapitalassetid IS NULL
          AND  COALESCE(e.financialcosttype, '') NOT IN ('CapitalAsset', 'NonCashExpense')
        GROUP  BY e.flockid
    ),
    base AS (
        SELECT fl.flockid                                         AS c_flockid,
               fl.name::text                                      AS c_name,
               fl.breed::text                                     AS c_breed,
               CASE WHEN fl.closeddate IS NOT NULL THEN 'Closed'
                    WHEN NOT COALESCE(fl.hasarrived, TRUE) THEN 'Pending'
                    WHEN COALESCE(fl.active, TRUE) THEN 'Active'
                    ELSE 'Inactive' END                           AS c_status,
               fl.batchid                                         AS c_batchid,
               b.batchcode::text                                  AS c_batchcode,
               b.batchname::text                                  AS c_batchname,
               b.supplierid                                       AS c_supplierid,
               b.suppliertype::text                               AS c_suppliertype,
               fl.houseid                                         AS c_houseid,
               h.housename::text                                  AS c_housename,
               fl.startdate                                       AS c_startdate,
               fl.closeddate                                      AS c_closeddate,
               GREATEST(COALESCE(fl.closeddate, v_today) - fl.startdate, 0)::int AS c_days,
               p.*,
               COALESCE(pr.c_eggs, 0)                             AS c_eggs,
               COALESCE(pr.c_days, 0)                             AS c_proddays,
               COALESCE(pr.c_feedkg, 0)                           AS c_feedkg,
               COALESCE(pr.c_feedcost, 0)                         AS c_feedcost,
               COALESCE(pr.c_medcost, 0)                          AS c_medcost,
               COALESCE(rev.c_egg, 0)                             AS c_eggrev,
               COALESCE(rev.c_bird, 0)                            AS c_birdrev,
               COALESCE(rev.c_total, 0)                           AS c_totalrev,
               COALESCE(ex.c_labor, 0)                            AS c_labor,
               COALESCE(ex.c_other, 0)                            AS c_other,
               CASE WHEN COALESCE(b.totalcost, 0) > 0 AND COALESCE(b.numberofbirds, 0) > 0
                    THEN ROUND(b.totalcost * p.originallyplaced / b.numberofbirds, 2)
                    ELSE 0 END                                    AS c_birdcost,
               (COALESCE(b.totalcost, 0) > 0 AND COALESCE(b.numberofbirds, 0) > 0) AS c_birdcostrecorded
        FROM   fl
        CROSS  JOIN LATERAL fnflock_birdposition(p_farmid, fl.flockid) p
        LEFT   JOIN mainflockbatch b ON b.batchid = fl.batchid AND b.farmid = fl.farmid
        LEFT   JOIN houses h         ON h.houseid = fl.houseid AND h.farmid = fl.farmid
        LEFT   JOIN pr  ON pr.c_flockid  = fl.flockid
        LEFT   JOIN rev ON rev.c_flockid = fl.flockid
        LEFT   JOIN ex  ON ex.c_flockid  = fl.flockid
    )
    SELECT
        c_flockid, c_name, c_breed, c_status,
        c_batchid, c_batchcode, c_batchname, c_supplierid, c_suppliertype,
        c_houseid, c_housename, c_startdate, c_closeddate, c_days,
        base.hasopeningposition, base.historyknown,
        base.originallyplaced, base.openinglivebirds, base.openingmortality, base.recordedmortality,
        base.birdssold, base.birdsculled, base.birdstransferred,
        base.currentlivebirds,
        CASE WHEN base.openinglivebirds > 0
             THEN ROUND(base.recordedmortality::numeric / base.openinglivebirds, 4) END,
        CASE WHEN base.historyknown AND base.originallyplaced > 0
             THEN ROUND((base.openingmortality + base.recordedmortality)::numeric / base.originallyplaced, 4) END,
        c_eggs, c_proddays,
        c_eggrev, c_birdrev, c_totalrev - c_eggrev - c_birdrev, c_totalrev,
        c_feedkg, c_feedcost, c_medcost, c_birdcost, c_birdcostrecorded, c_labor, c_other,
        c_feedcost + c_medcost + c_birdcost + c_labor + c_other,
        c_totalrev - (c_feedcost + c_medcost + c_birdcost + c_labor + c_other),
        CASE WHEN base.originallyplaced > 0
             THEN ROUND((c_totalrev - (c_feedcost + c_medcost + c_birdcost + c_labor + c_other))
                        / base.originallyplaced, 2) END,
        CASE WHEN base.originallyplaced > 0 THEN ROUND(c_totalrev / base.originallyplaced, 2) END,
        CASE WHEN c_eggs > 0 THEN ROUND(c_feedkg / (c_eggs / 12.0), 3) END
    FROM   base
    ORDER  BY c_startdate DESC, c_flockid DESC;
END
$function$;

-- ---- fnpoultrydailyclosing_livetotals: the day's sales and eggs sold to date
CREATE OR REPLACE FUNCTION public.fnpoultrydailyclosing_livetotals(p_farmid text, p_closingdate date)
 RETURNS TABLE(eggsproduced numeric, prodcost numeric, eggsdamaged numeric, closingstock numeric, feedusedqty numeric, medusedqty numeric, mortality numeric, eggssold numeric, eggsreturned numeric, totalincome numeric, creditsales numeric, cashcollected numeric, momocollected numeric, bankcollected numeric, customercollections numeric, totalexpenses numeric, cashbalance numeric, momobalance numeric, bankbalance numeric, cashathand numeric)
 LANGUAGE sql
AS $function$
    WITH
    pr AS (   -- production for the day (Production Log)
        SELECT COALESCE(SUM(COALESCE(p.totalproduction,0)),0)          AS eggsproduced,
               COALESCE(SUM(COALESCE(p.brokeneggs,0)),0)               AS eggsdamaged,
               COALESCE(SUM(COALESCE(p.totalcostofproduction,0)),0)    AS prodcost,
               COALESCE(SUM(COALESCE(p.mortality,0)),0)                AS mortalityqty,
               COALESCE(SUM(COALESCE(p.feedkg,0)),0)                   AS feedusedqty,
               COALESCE(SUM(COALESCE(p.totalmedicationconsumed,0)),0)  AS medusedqty
        FROM   productionrecords p
        WHERE  p.farmid = p_farmid AND p.date::date = p_closingdate
    ),
    sale AS (  -- sales for the day
        SELECT COALESCE(SUM(COALESCE(s.quantity,0)),0)                                          AS eggssold,
               COALESCE(SUM(COALESCE(s.totalamount,0)),0)                                       AS totalincome,
               COALESCE(SUM(CASE WHEN COALESCE(s.paid,FALSE) = FALSE THEN s.totalamount ELSE 0 END),0) AS creditsales,
               COALESCE(SUM(CASE WHEN s.paid = TRUE THEN s.totalamount ELSE 0 END),0)           AS cashcoll
        FROM   sale s
        WHERE  s.status = 'Posted' AND s.farmid = p_farmid AND s.saledate::date = p_closingdate
    ),
    egg AS (   -- cumulative egg stock as of the date
        SELECT COALESCE((SELECT SUM(COALESCE(p2.totalproduction,0) - COALESCE(p2.brokeneggs,0))
                         FROM public.productionrecords p2
                         WHERE p2.farmid = p_farmid AND p2.date::date <= p_closingdate),0) AS producedtodate,
               COALESCE((SELECT SUM(COALESCE(s2.quantity,0))
                         FROM public.sale s2
                         WHERE s2.status = 'Posted' AND s2.farmid = p_farmid AND s2.saledate::date <= p_closingdate),0) AS soldtodate
    ),
    pay AS (
        SELECT COALESCE(SUM(pp.amount::numeric(18,2)),0) AS customercollections
        FROM   poultrypayments pp
        WHERE  pp.farmid = p_farmid AND pp.paymentdate::date = p_closingdate
    ),
    exp AS (
        SELECT COALESCE(SUM(e.amount::numeric(18,2)),0) AS totalexpenses
        FROM   expense e
        WHERE  COALESCE(e.sourcetype, '') <> 'PoultryInternalUsage' AND e.farmid = (CASE WHEN p_farmid ~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
                                THEN p_farmid::uuid ELSE NULL END)
          AND  e.expensedate::date = p_closingdate
    ),
    bal AS (   -- flexible account-type matching (e.g. 'FarmCashBox' -> Cash)
        SELECT COALESCE(SUM(CASE WHEN a.accounttype ILIKE '%MoMo%' OR a.accounttype ILIKE '%Mobile%' THEN a.currentbalance ELSE 0 END),0) AS momobalance,
               COALESCE(SUM(CASE WHEN a.accounttype ILIKE '%Bank%' THEN a.currentbalance ELSE 0 END),0) AS bankbalance,
               COALESCE(SUM(CASE WHEN a.accounttype ILIKE '%MoMo%' OR a.accounttype ILIKE '%Mobile%' OR a.accounttype ILIKE '%Bank%' THEN 0 ELSE a.currentbalance END),0) AS cashbalance
        FROM   poultrycashaccounts a
        WHERE  a.farmid = p_farmid AND a.isactive = TRUE
    )
    SELECT
        pr.eggsproduced::numeric(18,3),
        pr.prodcost::numeric(18,2),
        pr.eggsdamaged::numeric(18,3),
        (egg.producedtodate - egg.soldtodate)::numeric(18,3)      AS closingstock,
        pr.feedusedqty::numeric(18,3),
        pr.medusedqty::numeric(18,3),
        pr.mortalityqty::numeric(18,3)                            AS mortality,
        sale.eggssold::numeric(18,3),
        0::numeric(18,3)                                          AS eggsreturned,
        sale.totalincome::numeric(18,2),
        sale.creditsales::numeric(18,2),
        sale.cashcoll::numeric(18,2)                              AS cashcollected,
        0::numeric(18,2)                                          AS momocollected,
        0::numeric(18,2)                                          AS bankcollected,
        pay.customercollections,
        exp.totalexpenses,
        bal.cashbalance::numeric(18,2),
        bal.momobalance::numeric(18,2),
        bal.bankbalance::numeric(18,2),
        ((sale.totalincome - sale.creditsales) + pay.customercollections - exp.totalexpenses)::numeric(18,2) AS cashathand
    FROM pr, sale, egg, pay, exp, bal
$function$;

-- ---- spbusinessoffice_companysnapshot: today's sales on the Business Office card
CREATE OR REPLACE FUNCTION public.spbusinessoffice_companysnapshot(p_farmid text, p_companytype text, p_today date DEFAULT NULL::date)
 RETURNS TABLE(metric1 numeric, metric2 numeric, metric3 numeric, metric4 numeric)
 LANGUAGE plpgsql
AS $function$
DECLARE
    v_today   date := p_today;
    v_feedin  numeric;
    v_feedout numeric;
    v_feedadj numeric;
BEGIN
    IF (v_today IS NULL) THEN v_today := (now() at time zone 'utc')::date; END IF;

    IF (p_companytype = 'Water') THEN
        RETURN QUERY
        SELECT
            COALESCE((
                SELECT SUM(b.bagsproduced) FROM waterproductionbatches b
                WHERE  b.farmid = p_farmid AND b.isdeleted = FALSE
                  AND  b.status <> 'Cancelled' AND b.productiondate = v_today), 0)::numeric(18,2),
            COALESCE((
                SELECT SUM(t.quantity) FROM waterstocktransactions t
                WHERE  t.farmid = p_farmid), 0)::numeric(18,2),
            ((SELECT COUNT(*) FROM waterdriverreturns r
              WHERE  r.farmid = p_farmid AND r.returndate::date = v_today))::numeric(18,2),
            COALESCE((
                SELECT SUM(s.totalamount) FROM watersales s
                WHERE  s.farmid = p_farmid AND s.status <> 'Cancelled'
                  AND  s.saledate::date = v_today), 0)::numeric(18,2);
        RETURN;
    END IF;

    IF (p_companytype = 'Poultry') THEN
        SELECT COALESCE(SUM(CASE
                    WHEN lower(btrim(COALESCE(i.unitofmeasure, ''))) LIKE '%ton%' THEN i.quantityinstock * 1000
                    WHEN lower(btrim(COALESCE(i.unitofmeasure, ''))) IN ('kg', 'kgs')
                      OR lower(btrim(COALESCE(i.unitofmeasure, ''))) LIKE '%kilogram%' THEN i.quantityinstock
                    WHEN lower(btrim(COALESCE(i.unitofmeasure, ''))) LIKE '%g%' THEN i.quantityinstock / 1000.0
                    ELSE i.quantityinstock
                   END), 0)
        INTO   v_feedin
        FROM   inventoryitem i
        WHERE  i.farmid = p_farmid
          AND  lower(btrim(COALESCE(i.category, ''))) LIKE '%feed%'
          AND  i.quantityinstock > 0;

        SELECT COALESCE(SUM(u.quantitykg), 0) INTO v_feedout
        FROM   feedusage u
        WHERE  u.farmid = p_farmid AND u.quantitykg > 0;

        SELECT COALESCE(SUM(a.feeddeltakg), 0) INTO v_feedadj
        FROM   feedinventoryadjustment a
        WHERE  a.farmid = p_farmid;

        RETURN QUERY
        SELECT
            COALESCE((
                SELECT SUM(p.totalproduction) FROM productionrecords p
                WHERE  p.farmid = p_farmid AND p.date = v_today), 0)::numeric(18,2),
            (v_feedin - v_feedout + v_feedadj)::numeric(18,2),
            COALESCE((
                SELECT SUM(p.mortality) FROM productionrecords p
                WHERE  p.farmid = p_farmid AND p.date = v_today), 0)::numeric(18,2),
            COALESCE((
                SELECT SUM(s.totalamount) FROM sale s
                WHERE  s.status = 'Posted' AND s.farmid = p_farmid AND s.saledate::date = v_today), 0)::numeric(18,2);
        RETURN;
    END IF;

    IF (p_companytype = 'Generic') THEN
        RETURN QUERY
        SELECT
            COALESCE((
                SELECT SUM(s.totalamount) FROM genericsales s
                WHERE  s.farmid = p_farmid AND s.isdeleted = FALSE AND s.status <> 'Cancelled'
                  AND  s.saledate::date = v_today), 0)::numeric(18,2),
            COALESCE((
                SELECT SUM(e.amount) FROM genericexpenses e
                WHERE  e.farmid = p_farmid AND e.isdeleted = FALSE AND e.status = 'Approved'
                  AND  e.expensedate::date = v_today), 0)::numeric(18,2),
            ((SELECT COUNT(*) FROM genericproducts p
              WHERE  p.farmid = p_farmid AND p.isdeleted = FALSE AND p.isactive = TRUE
                AND  p.trackinventory = TRUE AND p.currentstock <= p.minimumstockalert))::numeric(18,2),
            COALESCE((
                SELECT SUM(c.currentbalance) FROM genericcustomers c
                WHERE  c.farmid = p_farmid AND c.isdeleted = FALSE AND c.currentbalance > 0), 0)::numeric(18,2);
        RETURN;
    END IF;

    RETURN QUERY
    SELECT NULL::numeric(18,2), NULL::numeric(18,2), NULL::numeric(18,2), NULL::numeric(18,2);
END;
$function$;

-- ---- spdashboard_getsummary_rs1: dashboard sales today
CREATE OR REPLACE FUNCTION public.spdashboard_getsummary_rs1(p_farmid text)
 RETURNS TABLE(totaleggstoday integer, feedusedtodaykg numeric, salestoday numeric, expensestoday numeric, activeflocks integer)
 LANGUAGE plpgsql
AS $function$
BEGIN
    RETURN QUERY
    SELECT
        (SELECT COALESCE(SUM(ep.eggcount), 0)::integer
           FROM eggproduction ep
          WHERE ep.productiondate::date = CURRENT_DATE
            AND ep.farmid = p_farmid) AS totaleggstoday,
        (SELECT COALESCE(SUM(fu.quantitykg), 0)::numeric
           FROM feedusage fu
          WHERE fu.usagedate::date = CURRENT_DATE
            AND fu.farmid = p_farmid) AS feedusedtodaykg,
        (SELECT COALESCE(SUM(s.quantity * s.unitprice), 0)::numeric
           FROM sale s
          WHERE s.status = 'Posted' AND s.saledate::date = CURRENT_DATE
            AND s.farmid = p_farmid) AS salestoday,
        (SELECT COALESCE(SUM(e.amount), 0)::numeric
           FROM expense e
          WHERE e.expensedate::date = CURRENT_DATE
            AND e.farmid::text = p_farmid) AS expensestoday,
        (SELECT COUNT(*)::integer
           FROM flock f
          WHERE f.active = TRUE
            AND f.farmid = p_farmid) AS activeflocks;
END
$function$;

-- ---- spdashboard_getsummary_rs4: dashboard 30-day sales chart
CREATE OR REPLACE FUNCTION public.spdashboard_getsummary_rs4(p_farmid text)
 RETURNS TABLE(date text, totalsales numeric)
 LANGUAGE plpgsql
AS $function$
BEGIN
    RETURN QUERY
    SELECT
        to_char(s.saledate, 'MM-DD')::text,
        SUM(s.quantity * s.unitprice)::numeric
    FROM sale s
    WHERE s.status = 'Posted' AND s.saledate >= (CURRENT_DATE - 29)
      AND s.farmid = p_farmid
    GROUP BY to_char(s.saledate, 'MM-DD')
    ORDER BY 1;
END
$function$;

-- ---- spflock_closeout: a reversed sale cannot be a closeout disposition
CREATE OR REPLACE FUNCTION public.spflock_closeout(p_farmid text, p_flockid integer, p_closeddate date, p_reason text, p_notes text, p_closedby text, p_dispositions jsonb)
 RETURNS integer
 LANGUAGE plpgsql
AS $function$
DECLARE
    v_flock      flock%ROWTYPE;
    v_today      date;
    v_closeoutid integer;
    v_pos        record;
    v_row        record;
    v_dispid     integer;
    v_sale       record;
    v_sold       integer := 0;
    v_culled     integer := 0;
    v_transfer   integer := 0;
BEGIN
    IF p_reason IS NULL OR length(btrim(p_reason)) = 0 THEN
        RAISE EXCEPTION 'A reason is required to close a flock.' USING ERRCODE = 'P0001';
    END IF;
    IF p_closeddate IS NULL THEN
        RAISE EXCEPTION 'A closing date is required.' USING ERRCODE = 'P0001';
    END IF;

    SELECT * INTO v_flock FROM flock f
    WHERE  f.flockid = p_flockid AND f.farmid = p_farmid
    FOR UPDATE;

    IF NOT FOUND OR COALESCE(v_flock.isdeleted, FALSE) THEN
        RAISE EXCEPTION 'Flock not found on this farm.' USING ERRCODE = 'P0002';
    END IF;
    IF v_flock.closeddate IS NOT NULL THEN
        RAISE EXCEPTION 'Flock "%" is already closed.', v_flock.name USING ERRCODE = 'P0001';
    END IF;
    IF NOT COALESCE(v_flock.hasarrived, TRUE) THEN
        RAISE EXCEPTION 'Flock "%" has not arrived yet; there are no birds to close out.', v_flock.name
            USING ERRCODE = 'P0001';
    END IF;

    v_today := fncompany_businessdate(p_farmid);
    IF p_closeddate > v_today THEN
        RAISE EXCEPTION 'The closing date cannot be in the future.' USING ERRCODE = 'P0001';
    END IF;
    IF p_closeddate < v_flock.startdate THEN
        RAISE EXCEPTION 'The closing date cannot be before the flock started (%).',
            to_char(v_flock.startdate, 'DD Mon YYYY') USING ERRCODE = 'P0001';
    END IF;

    -- The position BEFORE this closeout's dispositions.
    SELECT * INTO v_pos FROM fnflock_birdposition(p_farmid, p_flockid);

    IF v_pos.lastcountdate IS NOT NULL AND p_closeddate < v_pos.lastcountdate THEN
        RAISE EXCEPTION 'The closing date cannot be before the last production record (%).',
            to_char(v_pos.lastcountdate, 'DD Mon YYYY') USING ERRCODE = 'P0001';
    END IF;

    INSERT INTO flockcloseouts (
        farmid, flockid, closeddate, reason, notes, closedby, wasactive, houseid,
        hasopeningposition, historyknown, originallyplaced,
        openingmortality, openingsold, openingculled, openingtransferred, openingother,
        openinglivebirds, recordedmortality, correction, lastcountedbirds, lastcountdate,
        soldbeforecloseout, livebirdsatcloseout, disposedsold, disposedculled, disposedtransferred)
    VALUES (
        p_farmid, p_flockid, p_closeddate, btrim(p_reason), NULLIF(btrim(COALESCE(p_notes, '')), ''),
        p_closedby, COALESCE(v_flock.active, TRUE), v_flock.houseid,
        v_pos.hasopeningposition, v_pos.historyknown, v_pos.originallyplaced,
        v_pos.openingmortality, v_pos.openingsold, v_pos.openingculled, v_pos.openingtransferred, v_pos.openingother,
        v_pos.openinglivebirds, v_pos.recordedmortality, v_pos.correction, v_pos.lastcountedbirds, v_pos.lastcountdate,
        -- Filled in below once the sales are linked.
        0, 0, 0, 0, 0)
    RETURNING closeoutid INTO v_closeoutid;

    FOR v_row IN
        SELECT j."disposition" AS disposition, j."quantity" AS quantity, j."saleId" AS saleid,
               NULLIF(btrim(COALESCE(j."destination", '')), '') AS destination,
               NULLIF(btrim(COALESCE(j."notes", '')), '') AS notes
        FROM   jsonb_to_recordset(COALESCE(p_dispositions, '[]'::jsonb))
               AS j("disposition" text, "quantity" integer, "saleId" integer, "destination" text, "notes" text)
    LOOP
        IF v_row.disposition NOT IN ('Sale', 'Cull', 'Transfer') THEN
            RAISE EXCEPTION 'Unknown disposition "%". Birds can be sold, culled or transferred.',
                COALESCE(v_row.disposition, '(blank)') USING ERRCODE = 'P0001';
        END IF;
        IF COALESCE(v_row.quantity, 0) <= 0 THEN
            RAISE EXCEPTION 'Every disposition needs a quantity above zero.' USING ERRCODE = 'P0001';
        END IF;

        IF v_row.disposition = 'Sale' THEN
            SELECT s.saleid, s.flockid, s.product, s.quantity INTO v_sale
            FROM   sale s WHERE s.status = 'Posted' AND s.saleid = v_row.saleid AND s.farmid = p_farmid;
            IF NOT FOUND THEN
                RAISE EXCEPTION 'Sale #% was not found on this farm.', v_row.saleid USING ERRCODE = 'P0001';
            END IF;
            IF v_sale.flockid IS DISTINCT FROM p_flockid OR NOT fnpoultrysale_isbirdsale(v_sale.product) THEN
                RAISE EXCEPTION 'Sale #% is not a bird sale of this flock.', v_row.saleid USING ERRCODE = 'P0001';
            END IF;
            IF v_sale.quantity <> v_row.quantity THEN
                RAISE EXCEPTION 'Sale #% sold % birds, not %.', v_row.saleid, v_sale.quantity, v_row.quantity
                    USING ERRCODE = 'P0001';
            END IF;
            v_sold := v_sold + v_row.quantity;
        ELSIF v_row.disposition = 'Transfer' THEN
            IF v_row.destination IS NULL THEN
                RAISE EXCEPTION 'Say where the transferred birds went.' USING ERRCODE = 'P0001';
            END IF;
            v_transfer := v_transfer + v_row.quantity;
        ELSE
            v_culled := v_culled + v_row.quantity;
        END IF;

        INSERT INTO flockcloseoutdispositions
            (closeoutid, farmid, flockid, disposition, quantity, saleid, destination, notes)
        VALUES
            (v_closeoutid, p_farmid, p_flockid, v_row.disposition, v_row.quantity,
             CASE WHEN v_row.disposition = 'Sale' THEN v_row.saleid END,
             CASE WHEN v_row.disposition = 'Transfer' THEN v_row.destination END,
             v_row.notes)
        RETURNING dispositionid INTO v_dispid;

        -- Birds leaving the company leave the bird ledger. Sales already posted
        -- their own 'Bird Sale' row when they were created. Dated to the
        -- closing date, so the closing report puts them on the right day.
        IF v_row.disposition = 'Cull' THEN
            PERFORM sppoultrybirdstock_postdated(p_farmid, 'Flock Cull', -v_row.quantity, v_dispid,
                                                 p_closeddate, 'Culled at flock closeout', p_closedby);
        ELSIF v_row.disposition = 'Transfer' THEN
            PERFORM sppoultrybirdstock_postdated(p_farmid, 'Flock Transfer Out', -v_row.quantity, v_dispid,
                                                 p_closeddate, 'Transferred out at flock closeout: ' || v_row.destination,
                                                 p_closedby);
        END IF;
    END LOOP;

    -- The position AFTER: the linked sales are already in birdssold, the culls
    -- and transfers in their own columns. Anything but zero is unreconciled.
    SELECT * INTO v_pos FROM fnflock_birdposition(p_farmid, p_flockid);

    IF v_pos.currentlivebirds > 0 THEN
        RAISE EXCEPTION 'Unresolved bird balance: % bird(s) are still unaccounted for. Sell, cull or transfer them, or record any unrecorded deaths as mortality on a production record, before closing.',
            v_pos.currentlivebirds USING ERRCODE = 'P0001';
    ELSIF v_pos.currentlivebirds < 0 THEN
        RAISE EXCEPTION 'Unresolved bird balance: the dispositions account for % more bird(s) than the flock has.',
            -v_pos.currentlivebirds USING ERRCODE = 'P0001';
    END IF;

    UPDATE flockcloseouts c
    SET    disposedsold        = v_sold,
           disposedculled      = v_culled,
           disposedtransferred = v_transfer,
           soldbeforecloseout  = v_pos.birdssold - v_sold,
           livebirdsatcloseout = v_sold + v_culled + v_transfer
    WHERE  c.closeoutid = v_closeoutid;

    PERFORM set_config('app.flock_closeout', 'on', true);

    -- active = false is what releases the house: occupancy counts active flocks
    -- only. houseid stays, so the flock-house history is not lost.
    UPDATE flock f
    SET    active             = FALSE,
           inactivationreason = 'closed',
           otherreason        = NULL,
           closeddate         = p_closeddate,
           closedat           = (now() AT TIME ZONE 'utc'),
           closedby           = p_closedby,
           closereason        = btrim(p_reason),
           closeoutid         = v_closeoutid,
           updatedat          = (now() AT TIME ZONE 'utc')
    WHERE  f.flockid = p_flockid AND f.farmid = p_farmid;

    PERFORM set_config('app.flock_closeout', 'off', true);

    RETURN v_closeoutid;
END
$function$;

-- ---- sppoultryclosingreport_get: closing report totals
CREATE OR REPLACE FUNCTION public.sppoultryclosingreport_get(p_farmid text, p_fromdate date, p_todate date)
 RETURNS TABLE(fromdate date, todate date, totalsales numeric, totalexpenses numeric, totalrawmaterialpurchases numeric, totalfeedcost numeric, totalmedicationcost numeric, totalcostofproduction numeric, netprofitloss numeric, totalowedbycustomers numeric, totaleggsproduced integer, totalgoodeggs integer, totalbrokeneggs integer, totalproductionrecords integer, avgeggsperday numeric, avgeggsperrecord numeric, totalfeedkg numeric, totalfeedconsumed numeric, totalmedicationconsumed numeric, avgproductioncostperegg numeric, openingeggstock numeric, closingeggstock numeric, eggssold numeric, rawmaterialspurchased numeric, rawmaterialsconsumed numeric, productionlossqty numeric, approvedlossvalue numeric, brokeneggstotal integer, cashsalescollected numeric, cashadjustmentsnet numeric, estimatedcashinflows numeric, placedbirds numeric, birdsleft numeric, birdslost numeric, openingbirds numeric, birdspurchased numeric, birdssold numeric, mortalitycount integer, closingbirds numeric, mortalityratepct numeric, eggsloadedfordelivery numeric, eggsreturned numeric, drivercollections numeric, deliveryexpenses numeric)
 LANGUAGE plpgsql
AS $function$
DECLARE
    v_gid uuid;
    v_egg integer;
    v_bird integer;
    v_totalsales      numeric(18,2);
    v_eggssold        numeric(18,3);
    v_cashsales       numeric(18,2);
    v_creditsales     numeric(18,2);
    v_totalexpenses   numeric(18,2) := 0;
    v_rawmatexpense   numeric(18,2) := 0;
    v_rawpurchases    numeric(18,2);
    v_rawconsumed     numeric(18,3);
    v_eggsproduced    integer       := 0;
    v_brokeneggs      integer       := 0;
    v_prodrecords     integer       := 0;
    v_feedcost        numeric(18,2) := 0;
    v_medcost         numeric(18,2) := 0;
    v_prodcost        numeric(18,2) := 0;
    v_feedconsumed    numeric(18,3) := 0;
    v_medconsumed     numeric(18,3) := 0;
    v_proddays        integer       := 0;
    v_feedkg          numeric(18,3) := 0;
    v_mortalityprod   numeric(18,3) := 0;
    v_prodlossqty     numeric(18,3);
    v_lossrecordval   numeric(18,2);
    v_closingeggstock numeric(18,3) := 0;
    v_openingeggstock numeric(18,3) := 0;
    v_placedbirds     numeric(18,3);
    v_birdsleft       numeric(18,3);
    v_birdslost       numeric(18,3);
    v_openingbirds    numeric(18,3) := 0;
    v_closingbirds    numeric(18,3) := 0;
    v_birdspurchased  numeric(18,3) := 0;
    v_birdssold       numeric(18,3) := 0;
    v_cashadjnet      numeric(18,2);
BEGIN
    BEGIN
        v_gid := p_farmid::uuid;
    EXCEPTION WHEN OTHERS THEN
        v_gid := NULL;
    END;

    SELECT pp.poultryproductid INTO v_egg
    FROM   poultryproducts pp
    WHERE  pp.farmid = p_farmid AND (pp.israweggproduct = TRUE OR pp.name IN ('Eggs', 'Chicken Eggs'))
    ORDER  BY pp.israweggproduct DESC, pp.poultryproductid
    LIMIT 1;

    SELECT pp.poultryproductid INTO v_bird
    FROM   poultryproducts pp
    WHERE  pp.farmid = p_farmid AND (pp.isbirdproduct = TRUE OR pp.name = 'Birds')
    ORDER  BY pp.isbirdproduct DESC, pp.poultryproductid
    LIMIT 1;

    -- ---- Money ---------------------------------------------------------------
    v_totalsales  := COALESCE((SELECT SUM(s.totalamount) FROM sale s WHERE s.status = 'Posted' AND s.farmid = p_farmid AND s.saledate BETWEEN p_fromdate AND p_todate), 0);
    v_eggssold    := COALESCE((SELECT SUM(s.quantity)    FROM sale s WHERE s.status = 'Posted' AND s.farmid = p_farmid AND s.saledate BETWEEN p_fromdate AND p_todate), 0);
    v_cashsales   := COALESCE((SELECT SUM(s.totalamount) FROM sale s WHERE s.status = 'Posted' AND s.farmid = p_farmid AND s.saledate BETWEEN p_fromdate AND p_todate AND s.paid = TRUE), 0);
    v_creditsales := COALESCE((SELECT SUM(s.totalamount) FROM sale s WHERE s.status = 'Posted' AND s.farmid = p_farmid AND s.saledate BETWEEN p_fromdate AND p_todate AND COALESCE(s.paid, FALSE) = FALSE), 0);

    IF v_gid IS NOT NULL THEN
        v_totalexpenses := COALESCE((SELECT SUM(e.amount) FROM expense e
                                     WHERE e.farmid = v_gid AND e.expensedate::date BETWEEN p_fromdate AND p_todate), 0);
        v_rawmatexpense := COALESCE((SELECT SUM(e.amount) FROM expense e
                                     WHERE e.farmid = v_gid AND e.expensedate::date BETWEEN p_fromdate AND p_todate
                                       AND e.category = 'Raw Materials / Inventory Purchase'), 0);
    END IF;

    v_rawpurchases := COALESCE((SELECT SUM(pu.totalcost) FROM poultryrawmaterialpurchases pu
                                WHERE pu.farmid = p_farmid AND pu.purchasedate::date BETWEEN p_fromdate AND p_todate AND pu.reversedat IS NULL), 0);
    v_rawconsumed  := COALESCE((SELECT SUM(us.quantityused) FROM poultryrawmaterialusage us
                                WHERE us.farmid = p_farmid AND us.useddate::date BETWEEN p_fromdate AND p_todate), 0);

    -- ---- Production (from ProductionRecords - same as the Production Log) -----
    SELECT COALESCE(SUM(r.totalproduction), 0), COALESCE(SUM(r.brokeneggs), 0), COUNT(*)::int,
           COALESCE(SUM(r.totalfeedcost), 0), COALESCE(SUM(r.totalmedicationcost), 0), COALESCE(SUM(r.totalcostofproduction), 0),
           COALESCE(SUM(r.totalfeedconsumed), 0), COALESCE(SUM(r.totalmedicationconsumed), 0), COUNT(DISTINCT r.date)::int,
           COALESCE(SUM(r.feedkg), 0), COALESCE(SUM(r.mortality), 0)
    INTO   v_eggsproduced, v_brokeneggs, v_prodrecords,
           v_feedcost, v_medcost, v_prodcost,
           v_feedconsumed, v_medconsumed, v_proddays,
           v_feedkg, v_mortalityprod
    FROM   productionrecords r
    WHERE  r.farmid = p_farmid AND r.date BETWEEN p_fromdate AND p_todate;

    v_prodlossqty   := COALESCE((SELECT SUM(pl.quantitylost) FROM poultryproductionloss pl
                                 WHERE pl.farmid = p_farmid AND pl.lossdate::date BETWEEN p_fromdate AND p_todate), 0);
    v_lossrecordval := COALESCE((SELECT SUM(lr.estimatedvalue) FROM poultrylossrecords lr
                                 WHERE lr.farmid = p_farmid AND lr.lossdate::date BETWEEN p_fromdate AND p_todate
                                   AND lr.status = 'Approved'), 0);

    -- ---- Egg stock (inventory module; 0 when not configured) ------------------
    IF v_egg IS NOT NULL THEN
        v_closingeggstock := COALESCE((SELECT SUM(st.quantity) FROM poultrystocktransactions st
                                       WHERE st.farmid = p_farmid AND st.poultryproductid = v_egg
                                         AND st.createddate::date <= p_todate), 0);
        v_openingeggstock := COALESCE((SELECT SUM(st.quantity) FROM poultrystocktransactions st
                                       WHERE st.farmid = p_farmid AND st.poultryproductid = v_egg
                                         AND st.createddate::date < p_fromdate), 0);
    END IF;

    -- ---- Birds (from Flock + ProductionRecords - same as the Production Log) --
    v_placedbirds := COALESCE((
        SELECT SUM(f.quantity) FROM flock f
        WHERE f.farmid = p_farmid AND f.active = TRUE AND f.hasarrived = TRUE AND COALESCE(f.isdeleted, FALSE) = FALSE), 0);

    v_birdsleft := COALESCE((
        SELECT SUM(
            CASE
                WHEN lr.noofbirdsleft IS NULL           THEN f.quantity
                WHEN lr.noofbirdsleft < 0               THEN 0
                WHEN lr.noofbirdsleft > f.quantity      THEN f.quantity
                ELSE lr.noofbirdsleft
            END)
        FROM flock f
        LEFT JOIN LATERAL (
            SELECT pr.noofbirdsleft
            FROM   productionrecords pr
            WHERE  pr.farmid = p_farmid AND pr.flockid = f.flockid AND pr.date <= p_todate
            ORDER  BY pr.date DESC
            LIMIT 1
        ) lr ON TRUE
        WHERE f.farmid = p_farmid AND f.active = TRUE AND f.hasarrived = TRUE AND COALESCE(f.isdeleted, FALSE) = FALSE), 0);

    v_birdslost := CASE WHEN v_placedbirds - v_birdsleft > 0 THEN v_placedbirds - v_birdsleft ELSE 0 END;

    -- Inventory-based bird movements (0 when the module is not configured).
    IF v_bird IS NOT NULL THEN
        v_openingbirds := COALESCE((SELECT SUM(st.quantity) FROM poultrystocktransactions st
                                    WHERE st.farmid = p_farmid AND st.poultryproductid = v_bird
                                      AND st.createddate::date < p_fromdate), 0);
        v_closingbirds := COALESCE((SELECT SUM(st.quantity) FROM poultrystocktransactions st
                                    WHERE st.farmid = p_farmid AND st.poultryproductid = v_bird
                                      AND st.createddate::date <= p_todate), 0);
        v_birdspurchased := COALESCE((SELECT SUM(st.quantity) FROM poultrystocktransactions st
                                      WHERE st.farmid = p_farmid AND st.poultryproductid = v_bird
                                        AND st.txntype = 'Bird Batch Purchase'
                                        AND st.createddate::date BETWEEN p_fromdate AND p_todate), 0);
        v_birdssold := -COALESCE((SELECT SUM(st.quantity) FROM poultrystocktransactions st
                                  WHERE st.farmid = p_farmid AND st.poultryproductid = v_bird
                                    AND st.txntype = 'Bird Sale'
                                    AND st.createddate::date BETWEEN p_fromdate AND p_todate), 0);
    END IF;

    v_cashadjnet := COALESCE((SELECT SUM(CASE WHEN ca.adjustmenttype IN ('In','Deposit','Add','Increase','Credit')  THEN ca.amount
                                              WHEN ca.adjustmenttype IN ('Out','Withdraw','Deduct','Decrease','Debit') THEN -ca.amount
                                              ELSE ca.amount END)
                              FROM cashadjustment ca
                              WHERE ca.farmid = p_farmid AND ca.adjustmentdate::date BETWEEN p_fromdate AND p_todate), 0);

    RETURN QUERY SELECT
        p_fromdate, p_todate,
        v_totalsales, v_totalexpenses, v_rawpurchases,
        v_feedcost, v_medcost, v_prodcost,
        (v_totalsales - v_totalexpenses)::numeric(18,2), v_creditsales,
        v_eggsproduced, (v_eggsproduced - v_brokeneggs)::int, v_brokeneggs,
        v_prodrecords,
        (CASE WHEN v_proddays    > 0 THEN v_eggsproduced * 1.0 / v_proddays    ELSE 0 END)::numeric(18,2),
        (CASE WHEN v_prodrecords > 0 THEN v_eggsproduced * 1.0 / v_prodrecords ELSE 0 END)::numeric(18,2),
        v_feedkg,
        v_feedconsumed, v_medconsumed,
        (CASE WHEN v_eggsproduced > 0 THEN v_prodcost / v_eggsproduced ELSE 0 END)::numeric(18,4),
        v_openingeggstock, v_closingeggstock, v_eggssold,
        v_rawpurchases, v_rawconsumed,
        v_prodlossqty, v_lossrecordval, v_brokeneggs,
        v_cashsales, v_cashadjnet, (v_cashsales + v_cashadjnet)::numeric(18,2),
        -- Birds (Production-Log reconciled)
        v_placedbirds, v_birdsleft, v_birdslost,
        v_openingbirds, v_birdspurchased, v_birdssold,
        v_mortalityprod::int, v_closingbirds,
        (CASE WHEN v_placedbirds > 0 THEN v_mortalityprod / v_placedbirds * 100 ELSE 0 END)::numeric(9,2),
        -- Delivery (populated by delivery module reconciliation)
        0::numeric(18,3), 0::numeric(18,3),
        0::numeric(18,2), 0::numeric(18,2);
END;
$function$;

-- ---- sppoultrycustomerbalances: receivables
CREATE OR REPLACE FUNCTION public.sppoultrycustomerbalances(p_farmid text, p_from date DEFAULT NULL::date, p_to date DEFAULT NULL::date, p_customerid integer DEFAULT NULL::integer, p_status text DEFAULT 'All'::text, p_minbalance numeric DEFAULT NULL::numeric, p_search text DEFAULT NULL::text)
 RETURNS TABLE(customerid integer, customername text, contactphone text, contactemail text, paymenttermsdays integer, totalbalance numeric, opensalecount integer, oldestsaledate date, latestsaledate date, lastpaymentdate timestamp without time zone, overdueamount numeric, totalsales numeric, totalpaid numeric)
 LANGUAGE sql
 STABLE
AS $function$
    WITH opensales AS (
        SELECT s.customerid, s.saleid, s.saledate, s.totalamount,
               fnpoultrysalebalance(s.paid, s.totalamount, s.amountpaid)  AS balance,
               fnpoultrysalereceived(s.paid, s.totalamount, s.amountpaid) AS received,
               COALESCE(c.paymenttermsdays, 0)                            AS terms
        FROM   sale s
        JOIN   customer c ON c.customerid = s.customerid AND c.farmid = s.farmid
        WHERE  s.status = 'Posted' AND s.farmid = p_farmid
          AND  s.customerid IS NOT NULL
          AND  (p_customerid IS NULL OR s.customerid = p_customerid)
          AND  (p_from IS NULL OR s.saledate >= p_from)
          AND  (p_to   IS NULL OR s.saledate <= p_to)
          AND  fnpoultrysalebalance(s.paid, s.totalamount, s.amountpaid) > 0
    ),
    filtered AS (
        SELECT o.*,
               (o.saledate + o.terms)                          AS duedate,
               ((o.saledate + o.terms) < CURRENT_DATE)         AS isoverdue
        FROM   opensales o
        WHERE  CASE COALESCE(p_status, 'All')
                    WHEN 'Partial' THEN o.received > 0
                    WHEN 'Unpaid'  THEN o.received = 0
                    WHEN 'Overdue' THEN (o.saledate + o.terms) < CURRENT_DATE
                    ELSE TRUE
               END
    )
    SELECT c.customerid,
           c.name::text,
           c.contactphone::text,
           c.contactemail::text,
           COALESCE(c.paymenttermsdays, 0),
           SUM(f.balance)::numeric(14,2),
           COUNT(*)::integer,
           MIN(f.saledate),
           MAX(f.saledate),
           (SELECT MAX(pp.paymentdate) FROM poultrypayments pp
            WHERE pp.farmid = p_farmid AND pp.customerid = c.customerid
              AND COALESCE(pp.status, 'Posted') = 'Posted'),
           SUM(CASE WHEN f.isoverdue THEN f.balance ELSE 0 END)::numeric(14,2),
           SUM(f.totalamount)::numeric(14,2),
           SUM(f.received)::numeric(14,2)
    FROM   filtered f
    JOIN   customer c ON c.customerid = f.customerid AND c.farmid = p_farmid
    WHERE  (p_search IS NULL OR btrim(p_search) = ''
            OR c.name ILIKE '%' || btrim(p_search) || '%'
            OR COALESCE(c.contactphone, '') ILIKE '%' || btrim(p_search) || '%')
    GROUP  BY c.customerid, c.name, c.contactphone, c.contactemail, c.paymenttermsdays
    HAVING (p_minbalance IS NULL OR SUM(f.balance) >= p_minbalance)
    ORDER  BY SUM(f.balance) DESC;
$function$;

-- ---- sppoultrycustomeropensales: open sales a payment can be applied to
CREATE OR REPLACE FUNCTION public.sppoultrycustomeropensales(p_farmid text, p_customerid integer, p_from date DEFAULT NULL::date, p_to date DEFAULT NULL::date, p_status text DEFAULT 'All'::text)
 RETURNS TABLE(saleid integer, saledate date, product text, saledescription text, totalamount numeric, amountpaid numeric, balance numeric, duedate date, agedays integer, status text, isoverdue boolean, poultrycashaccountid integer)
 LANGUAGE sql
 STABLE
AS $function$
    SELECT s.saleid, s.saledate, s.product::text, s.saledescription::text,
           s.totalamount,
           fnpoultrysalereceived(s.paid, s.totalamount, s.amountpaid),
           fnpoultrysalebalance(s.paid, s.totalamount, s.amountpaid),
           (s.saledate + COALESCE(c.paymenttermsdays, 0))::date,
           GREATEST((CURRENT_DATE - s.saledate), 0)::integer,
           CASE WHEN fnpoultrysalereceived(s.paid, s.totalamount, s.amountpaid) > 0
                THEN 'Partially Paid' ELSE 'Unpaid' END::text,
           ((s.saledate + COALESCE(c.paymenttermsdays, 0)) < CURRENT_DATE),
           s.poultrycashaccountid
    FROM   sale s
    JOIN   customer c ON c.customerid = s.customerid AND c.farmid = s.farmid
    WHERE  s.status = 'Posted' AND s.farmid = p_farmid
      AND  s.customerid = p_customerid
      AND  (p_from IS NULL OR s.saledate >= p_from)
      AND  (p_to   IS NULL OR s.saledate <= p_to)
      AND  fnpoultrysalebalance(s.paid, s.totalamount, s.amountpaid) > 0
      AND  CASE COALESCE(p_status, 'All')
                WHEN 'Partial' THEN fnpoultrysalereceived(s.paid, s.totalamount, s.amountpaid) > 0
                WHEN 'Unpaid'  THEN fnpoultrysalereceived(s.paid, s.totalamount, s.amountpaid) = 0
                WHEN 'Overdue' THEN (s.saledate + COALESCE(c.paymenttermsdays, 0)) < CURRENT_DATE
                ELSE TRUE
           END
    ORDER  BY s.saledate, s.saleid;
$function$;

-- ---- sppoultrydailyclosing_workspace_core: daily closing workspace sales
CREATE OR REPLACE FUNCTION public.sppoultrydailyclosing_workspace_core(p_farmid text, p_businessdate date DEFAULT NULL::date, p_asof timestamp with time zone DEFAULT now())
 RETURNS jsonb
 LANGUAGE plpgsql
 STABLE
AS $function$
#variable_conflict use_column
DECLARE
    v_tz        text      := public.fncompany_timezone(p_farmid);
    v_local     timestamp := p_asof AT TIME ZONE public.fncompany_timezone(p_farmid);
    v_today     date;
    v_date      date;
    v_farmuuid  uuid;
    v_sym       text;
    pol         record;
    comp        record;
    pr          record;
    sl          record;
    pay         record;
    cf          record;
    rec         record;
    ex          record;
    v_unposted       jsonb;
    v_impossible     jsonb;
    v_mortality      jsonb;
    v_negative       jsonb;
    v_lowstock       jsonb;
    v_lowfeed        jsonb;
    v_driverreturns  integer;
    v_openloadings   integer;
    v_prevclosed     boolean;
    v_usesclosing    boolean;
    v_checks         jsonb := '[]'::jsonb;
    v_item           jsonb;
    v_level          text;
BEGIN
    IF p_farmid IS NULL OR btrim(p_farmid) = '' THEN
        RAISE EXCEPTION 'Company ID is required.';
    END IF;

    v_today := v_local::date;
    v_date  := COALESCE(p_businessdate, v_today);
    IF v_date > v_today THEN
        RAISE EXCEPTION 'Business date % is in the future for this company (today is %).', v_date, v_today;
    END IF;

    -- expense.farmid is uuid; everything else is text. Same guard the closing
    -- live totals use, so a non-uuid id simply matches no expense.
    v_farmuuid := CASE WHEN p_farmid ~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
                       THEN p_farmid::uuid END;
    SELECT NULLIF(btrim(f.currencysymbol), '') INTO v_sym
    FROM farms f WHERE lower(f.farmid::text) = lower(p_farmid) OR f.id = p_farmid LIMIT 1;

    SELECT * INTO pol FROM public.sppoultrydailyclosingpolicy_get(p_farmid);

    -- ---- Production -------------------------------------------------------
    SELECT * INTO comp FROM public.sppoultryactivity_productioncompletenesssummary(p_farmid, v_date, p_asof);

    SELECT count(*)::int                                                         AS records,
           COALESCE(sum(p.totalproduction), 0)                                   AS eggs,
           COALESCE(sum(COALESCE(p.brokeneggs,0) + COALESCE(p.meatyeggs,0)
                      + COALESCE(p.softeggs,0) + COALESCE(p.losteggs,0)), 0)     AS damaged,
           COALESCE(sum(p.mortality), 0)                                         AS mortality,
           COALESCE(sum(p.feedkg), 0)                                            AS feedkg,
           COALESCE(sum(p.totalmedicationconsumed), 0)                           AS medication,
           COALESCE(sum(p.totalcostofproduction), 0)                             AS cost
    INTO pr
    FROM productionrecords p
    WHERE p.farmid = p_farmid AND p.date = v_date;

    SELECT COALESCE(jsonb_agg(jsonb_build_object('id', r.id, 'status', r.status,
                                                 'name', COALESCE(NULLIF(btrim(r.batchname), ''), r.batchselectiontype))
                              ORDER BY r.id), '[]'::jsonb)
    INTO v_unposted
    FROM productionbatchrecords r
    WHERE r.farmid = p_farmid AND r.productiondate = v_date
      AND r.status IN ('Draft', 'PendingAllocation', 'Allocated');

    -- Only what cannot happen: negative counts, or more deaths than birds when
    -- the bird count was entered (noofbirds = 0 is used for "not entered").
    SELECT COALESCE(jsonb_agg(jsonb_build_object('recordId', p.id, 'flockId', p.flockid, 'flock', f.name,
                                                 'birds', p.noofbirds, 'mortality', p.mortality,
                                                 'birdsLeft', p.noofbirdsleft) ORDER BY p.id), '[]'::jsonb)
    INTO v_impossible
    FROM productionrecords p
    LEFT JOIN flock f ON f.flockid = p.flockid
    WHERE p.farmid = p_farmid AND p.date = v_date
      AND (p.noofbirdsleft < 0 OR p.mortality < 0 OR p.noofbirds < 0
           OR (p.noofbirds > 0 AND p.mortality > p.noofbirds));

    SELECT COALESCE(jsonb_agg(jsonb_build_object('flockId', m.flockid, 'flock', m.name,
                                                 'mortality', m.mort, 'birds', m.birds,
                                                 'pct', round(100.0 * m.mort / m.birds, 2))
                              ORDER BY 100.0 * m.mort / m.birds DESC), '[]'::jsonb)
    INTO v_mortality
    FROM (SELECT p.flockid, f.name, sum(p.mortality) AS mort, max(p.noofbirds) AS birds
          FROM productionrecords p LEFT JOIN flock f ON f.flockid = p.flockid
          WHERE p.farmid = p_farmid AND p.date = v_date AND p.noofbirds > 0
          GROUP BY p.flockid, f.name) m
    WHERE m.mort > 0 AND 100.0 * m.mort / m.birds > pol.unusualmortalitypct;

    -- ---- Sales ------------------------------------------------------------
    SELECT count(*)::int                                                            AS n,
           COALESCE(sum(s.totalamount), 0)                                          AS total,
           COALESCE(sum(s.totalamount) FILTER (WHERE COALESCE(s.paid, TRUE)), 0)    AS cash,
           COALESCE(sum(s.totalamount) FILTER (WHERE NOT COALESCE(s.paid, TRUE)), 0) AS credit
    INTO sl
    FROM sale s
    WHERE s.status = 'Posted' AND s.farmid = p_farmid AND s.saledate = v_date;

    SELECT count(DISTINCT COALESCE(pp.paymentgroupid::text, 'row:' || pp.poultrypaymentid))::int AS n,
           COALESCE(sum(pp.amount), 0) AS total
    INTO pay
    FROM poultrypayments pp
    WHERE pp.farmid = p_farmid AND COALESCE(pp.status, 'Posted') = 'Posted'
      AND pp.paymentdate::date = v_date;

    -- ---- Cash (the Cash Flow report's own function, one inclusive day) ----
    SELECT * INTO cf FROM public.sppoultrycashflow_summary(
        p_farmid, v_date::timestamp, (v_date + 1)::timestamp - interval '1 microsecond');

    SELECT count(*)::int                           AS n,
           COALESCE(sum(c.systembalance), 0)       AS expected,
           COALESCE(sum(c.actualbalance), 0)       AS actual,
           COALESCE(sum(c.difference), 0)          AS difference
    INTO rec
    FROM poultrycashreconciliations c
    WHERE c.farmid = p_farmid AND c.status = 'Posted' AND c.reconciliationdate::date = v_date;

    -- ---- Expenses ---------------------------------------------------------
    SELECT count(*)::int AS n,
           COALESCE(sum(e.amount), 0) AS total,
           COALESCE(sum(LEAST(COALESCE(e.amountpaid, e.amount), e.amount))
                    FILTER (WHERE e.paymentmethod IS DISTINCT FROM 'NonCash'), 0) AS cash,
           COALESCE(sum(GREATEST(e.amount - COALESCE(e.amountpaid, e.amount), 0))
                    FILTER (WHERE e.paymentmethod IS DISTINCT FROM 'NonCash'), 0) AS credit,
           COALESCE(sum(e.amount) FILTER (WHERE e.paymentmethod = 'NonCash'), 0)  AS noncash
    INTO ex
    FROM expense e
    WHERE e.farmid = v_farmuuid AND e.expensedate::date = v_date;

    -- ---- Inventory exceptions (current stock) -----------------------------
    SELECT COALESCE(jsonb_agg(jsonb_build_object('itemId', i.poultryrawmaterialitemid, 'item', i.itemname,
                                                 'quantity', i.currentquantity, 'unit', i.unitofmeasure)
                              ORDER BY i.itemname), '[]'::jsonb)
    INTO v_negative
    FROM poultryrawmaterialitems i
    WHERE i.farmid = p_farmid AND COALESCE(i.isactive, TRUE) AND i.currentquantity < 0;

    SELECT COALESCE(jsonb_agg(jsonb_build_object('itemId', x.poultryrawmaterialitemid, 'item', x.itemname,
                                                 'quantity', x.currentquantity, 'unit', x.unitofmeasure,
                                                 'dailyUse', round(x.daily, 3),
                                                 'daysRemaining', round(x.currentquantity / x.daily, 1))
                              ORDER BY x.currentquantity / x.daily), '[]'::jsonb)
    INTO v_lowfeed
    FROM (SELECT i.poultryrawmaterialitemid, i.itemname, i.currentquantity, i.unitofmeasure,
                 sum(f.quantityconsumed) / 7.0 AS daily
          FROM poultryrawmaterialitems i
          JOIN productionrecordfeeds f ON f.poultryrawmaterialitemid = i.poultryrawmaterialitemid
          JOIN productionrecords p     ON p.id = f.productionrecordid AND p.farmid = p_farmid
          WHERE i.farmid = p_farmid AND COALESCE(i.isactive, TRUE)
            AND p.date BETWEEN v_date - 6 AND v_date
          GROUP BY i.poultryrawmaterialitemid, i.itemname, i.currentquantity, i.unitofmeasure) x
    WHERE x.daily > 0 AND x.currentquantity >= 0 AND x.currentquantity / x.daily < pol.lowfeeddays;

    -- Reorder-level breaches not already reported as low feed or negative.
    SELECT COALESCE(jsonb_agg(jsonb_build_object('itemId', i.poultryrawmaterialitemid, 'item', i.itemname,
                                                 'quantity', i.currentquantity, 'minimum', i.minimumstockalert,
                                                 'unit', i.unitofmeasure) ORDER BY i.itemname), '[]'::jsonb)
    INTO v_lowstock
    FROM poultryrawmaterialitems i
    WHERE i.farmid = p_farmid AND COALESCE(i.isactive, TRUE)
      AND COALESCE(i.minimumstockalert, 0) > 0 AND i.currentquantity >= 0
      AND i.currentquantity <= i.minimumstockalert
      AND NOT EXISTS (SELECT 1 FROM jsonb_array_elements(v_lowfeed) lf
                      WHERE (lf->>'itemId')::int = i.poultryrawmaterialitemid);

    -- ---- Outstanding ------------------------------------------------------
    SELECT count(*)::int INTO v_driverreturns
    FROM poultrydriverreturns d
    WHERE d.farmid = p_farmid AND d.status = 'Draft' AND d.returndate::date = v_date;

    SELECT count(*)::int INTO v_openloadings
    FROM poultryvehicleloadings l
    WHERE l.farmid = p_farmid AND l.status = 'Loaded' AND NOT COALESCE(l.isdeleted, FALSE)
      AND l.loaddate::date = v_date
      AND NOT EXISTS (SELECT 1 FROM poultrydriverreturns d
                      WHERE d.poultryvehicleloadingid = l.poultryvehicleloadingid AND d.status = 'Approved');

    v_prevclosed := EXISTS (SELECT 1 FROM poultrydailyclosings c
                            WHERE c.farmid = p_farmid AND c.closingdate = v_date - 1 AND c.status = 'Approved');
    v_usesclosing := EXISTS (SELECT 1 FROM poultrydailyclosings c
                             WHERE c.farmid = p_farmid AND c.closingdate < v_date);

    -- ---- Checklist --------------------------------------------------------
    -- Each item: key, section, status (Complete | Warning | Blocking), title,
    -- description, action (a key the UI maps to a page -- never a URL here).

    IF comp.expectedcount = 0 THEN
        v_item := jsonb_build_object('key', 'production.recorded', 'section', 'production', 'status', 'Complete',
            'title', 'No flocks are expected to report production', 'description', NULL, 'action', NULL);
    ELSIF comp.missingcount = 0 THEN
        v_item := jsonb_build_object('key', 'production.recorded', 'section', 'production', 'status', 'Complete',
            'title', 'All flock production entered',
            'description', format('%s of %s flocks reported.', comp.completedcount, comp.expectedcount), 'action', NULL);
    ELSE
        v_item := jsonb_build_object('key', 'production.recorded', 'section', 'production', 'status', pol.missingproduction,
            'title', format('Production missing for %s of %s flocks', comp.missingcount, comp.expectedcount),
            'description', CASE WHEN comp.awaitingpostingcount > 0
                                THEN format('%s of them are in a batch entry that has not been posted.', comp.awaitingpostingcount) END,
            'action', 'missing-production');
    END IF;
    v_checks := v_checks || v_item;

    v_checks := v_checks || CASE WHEN jsonb_array_length(v_unposted) = 0
        THEN jsonb_build_object('key', 'production.unposted', 'section', 'production', 'status', 'Complete',
                 'title', 'No unposted batch production', 'description', NULL, 'action', NULL)
        ELSE jsonb_build_object('key', 'production.unposted', 'section', 'production', 'status', pol.unpostedproduction,
                 'title', format('%s batch production %s not posted', jsonb_array_length(v_unposted),
                                 CASE WHEN jsonb_array_length(v_unposted) = 1 THEN 'entry' ELSE 'entries' END),
                 'description', 'Production is only recorded once a batch is allocated and posted.',
                 'action', 'unposted-batches') END;

    v_checks := v_checks || CASE WHEN jsonb_array_length(v_impossible) = 0
        THEN jsonb_build_object('key', 'production.birdcounts', 'section', 'production', 'status', 'Complete',
                 'title', 'Bird counts are consistent', 'description', NULL, 'action', NULL)
        ELSE jsonb_build_object('key', 'production.birdcounts', 'section', 'production', 'status', pol.impossiblebirdcounts,
                 'title', format('Impossible bird counts on %s production %s', jsonb_array_length(v_impossible),
                                 CASE WHEN jsonb_array_length(v_impossible) = 1 THEN 'record' ELSE 'records' END),
                 'description', 'Negative birds or mortality, or more deaths than birds recorded.',
                 'action', 'production-records') END;

    v_checks := v_checks || CASE WHEN jsonb_array_length(v_mortality) = 0
        THEN jsonb_build_object('key', 'production.mortality', 'section', 'production', 'status', 'Complete',
                 'title', format('Mortality within %s%%', pol.unusualmortalitypct::float8), 'description', NULL, 'action', NULL)
        ELSE jsonb_build_object('key', 'production.mortality', 'section', 'production', 'status', 'Warning',
                 'title', format('Unusual mortality in %s %s', jsonb_array_length(v_mortality),
                                 CASE WHEN jsonb_array_length(v_mortality) = 1 THEN 'flock' ELSE 'flocks' END),
                 'description', (SELECT string_agg(format('%s %s%%', m->>'flock', m->>'pct'), ', ')
                                 FROM jsonb_array_elements(v_mortality) m),
                 'action', 'production-records') END;

    IF comp.duplicateflockcount > 0 THEN
        v_checks := v_checks || jsonb_build_object('key', 'production.duplicates', 'section', 'production',
            'status', 'Warning',
            'title', format('%s %s more than one production record', comp.duplicateflockcount,
                            CASE WHEN comp.duplicateflockcount = 1 THEN 'flock has' ELSE 'flocks have' END),
            'description', 'Totals include every record; check whether one is a duplicate.', 'action', 'production-records');
    END IF;

    IF rec.n > 0 THEN
        v_checks := v_checks || CASE WHEN abs(rec.difference) <= pol.cashdifferencetolerance
            THEN jsonb_build_object('key', 'cash.difference', 'section', 'cash', 'status', 'Complete',
                     'title', 'Cash count matches the books',
                     'description', format('%s account %s counted.', rec.n, CASE WHEN rec.n = 1 THEN 'was' ELSE 'were' END),
                     'action', NULL)
            ELSE jsonb_build_object('key', 'cash.difference', 'section', 'cash', 'status', pol.cashdifference,
                     'title', format('Cash difference %s', public.fnpoultryclosing_money(v_sym, rec.difference)),
                     'description', format('Counted %s against %s expected.',
                                           public.fnpoultryclosing_money(v_sym, rec.actual),
                                           public.fnpoultryclosing_money(v_sym, rec.expected)),
                     'action', 'cash-count') END;
    ELSIF pol.requirecashcount THEN
        v_checks := v_checks || jsonb_build_object('key', 'cash.difference', 'section', 'cash', 'status', 'Warning',
            'title', 'No cash count posted for this day', 'description', NULL, 'action', 'cash-count');
    END IF;

    IF jsonb_array_length(v_lowfeed) = 0 THEN
        v_checks := v_checks || jsonb_build_object('key', 'inventory.lowfeed', 'section', 'inventory', 'status', 'Complete',
            'title', format('Feed stock above %s days', pol.lowfeeddays::float8), 'description', NULL, 'action', NULL);
    ELSE
        FOR v_item IN SELECT value FROM jsonb_array_elements(v_lowfeed) LOOP
            v_checks := v_checks || jsonb_build_object(
                'key', 'inventory.lowfeed.' || (v_item->>'itemId'), 'section', 'inventory', 'status', 'Warning',
                'title', format('%s estimated %s days remaining', v_item->>'item', v_item->>'daysRemaining'),
                'description', format('%s %s in stock, using about %s a day.',
                                      v_item->>'quantity', COALESCE(v_item->>'unit', ''), v_item->>'dailyUse'),
                'action', 'inventory');
        END LOOP;
    END IF;

    IF jsonb_array_length(v_lowstock) > 0 THEN
        v_checks := v_checks || jsonb_build_object('key', 'inventory.lowstock', 'section', 'inventory', 'status', 'Warning',
            'title', format('%s %s at or below reorder level', jsonb_array_length(v_lowstock),
                            CASE WHEN jsonb_array_length(v_lowstock) = 1 THEN 'item' ELSE 'items' END),
            'description', (SELECT string_agg(x->>'item', ', ') FROM jsonb_array_elements(v_lowstock) x),
            'action', 'inventory');
    END IF;

    IF jsonb_array_length(v_negative) > 0 THEN
        v_checks := v_checks || jsonb_build_object('key', 'inventory.negative', 'section', 'inventory',
            'status', pol.negativestock,
            'title', format('%s %s negative stock', jsonb_array_length(v_negative),
                            CASE WHEN jsonb_array_length(v_negative) = 1 THEN 'item has' ELSE 'items have' END),
            'description', (SELECT string_agg(x->>'item', ', ') FROM jsonb_array_elements(v_negative) x),
            'action', 'inventory');
    END IF;

    IF sl.credit > 0 THEN
        v_checks := v_checks || jsonb_build_object('key', 'sales.credit', 'section', 'sales', 'status', 'Warning',
            'title', format('%s sold on credit', public.fnpoultryclosing_money(v_sym, sl.credit)),
            'description', 'Outstanding until the customer pays.', 'action', 'customer-balances');
    END IF;

    v_checks := v_checks || CASE WHEN v_driverreturns + v_openloadings = 0
        THEN jsonb_build_object('key', 'outstanding.driverreturns', 'section', 'outstanding', 'status', 'Complete',
                 'title', 'No pending driver returns', 'description', NULL, 'action', NULL)
        ELSE jsonb_build_object('key', 'outstanding.driverreturns', 'section', 'outstanding', 'status', pol.pendingdriverreturns,
                 'title', format('%s driver %s not reconciled', v_driverreturns + v_openloadings,
                                 CASE WHEN v_driverreturns + v_openloadings = 1 THEN 'trip' ELSE 'trips' END),
                 'description', format('%s draft return(s), %s loading(s) with no approved return.', v_driverreturns, v_openloadings),
                 'action', 'driver-returns') END;

    IF v_date = v_today THEN
        v_checks := v_checks || jsonb_build_object('key', 'day.notover', 'section', 'alerts', 'status', 'Warning',
            'title', format('The business day is not over yet (%s local time)', to_char(v_local, 'HH24:MI')),
            'description', 'Anything recorded later today will show as a change after closing.', 'action', NULL);
    END IF;

    IF v_usesclosing AND NOT v_prevclosed THEN
        v_checks := v_checks || jsonb_build_object('key', 'closing.previousday', 'section', 'alerts', 'status', 'Warning',
            'title', format('%s is not closed', to_char(v_date - 1, 'FMMon FMDD')),
            'description', NULL, 'action', 'previous-day');
    END IF;

    -- Blocking first, then warnings, then complete; stable within a level.
    SELECT COALESCE(jsonb_agg(c.value ORDER BY
               CASE c.value->>'status' WHEN 'Blocking' THEN 0 WHEN 'Warning' THEN 1 ELSE 2 END, c.ordinality), '[]'::jsonb)
    INTO v_checks
    FROM jsonb_array_elements(v_checks) WITH ORDINALITY c;

    RETURN jsonb_build_object(
        'farmId',        p_farmid,
        'businessDate',  v_date,
        'companyToday',  v_today,
        'companyLocalTime', v_local,
        'timeZoneId',    v_tz,
        'currencySymbol', v_sym,
        'generatedAtUtc', p_asof,
        'production', jsonb_build_object(
            'expectedFlocks',  comp.expectedcount,
            'reportedFlocks',  comp.completedcount,
            'missingFlocks',   comp.missingcount,
            'awaitingPosting', comp.awaitingpostingcount,
            'duplicateFlocks', comp.duplicateflockcount,
            'records',         pr.records,
            'eggsProduced',    pr.eggs,
            'eggsDamaged',     pr.damaged,
            'goodEggs',        pr.eggs - pr.damaged,
            'mortality',       pr.mortality,
            'feedKg',          pr.feedkg,
            'medicationUsed',  pr.medication,
            'productionCost',  pr.cost,
            'unpostedBatches', v_unposted,
            'impossibleBirdCounts', v_impossible,
            'unusualMortality', v_mortality),
        'sales', jsonb_build_object(
            'count',            sl.n,
            'revenue',          sl.total,
            'cashSales',        sl.cash,
            'creditSales',      sl.credit,
            'paymentsReceived', pay.total,
            'paymentsCount',    pay.n,
            -- Receivables grow by what was sold on credit and shrink by what
            -- customers paid. Payments are cash received, never revenue.
            'receivablesChange', sl.credit - pay.total),
        'cash', jsonb_build_object(
            'moneyIn',        cf.moneyin,
            'moneyOut',       cf.moneyout,
            'netCashFlow',    cf.netcashflow,
            'openingCash',    cf.openingbalance,
            'closingCash',    cf.cashathand,
            'reconciliations', rec.n,
            'expectedCash',   CASE WHEN rec.n > 0 THEN rec.expected END,
            'actualCash',     CASE WHEN rec.n > 0 THEN rec.actual END,
            'difference',     CASE WHEN rec.n > 0 THEN rec.difference END),
        'expenses', jsonb_build_object(
            'count',    ex.n,
            'total',    ex.total,
            'cash',     ex.cash,
            'credit',   ex.credit,
            'nonCash',  ex.noncash),
        'inventory', jsonb_build_object(
            'lowFeed',       v_lowfeed,
            'lowStock',      v_lowstock,
            'negativeStock', v_negative),
        'outstanding', jsonb_build_object(
            'unpostedBatches',       jsonb_array_length(v_unposted),
            'draftDriverReturns',    v_driverreturns,
            'loadingsWithoutReturn', v_openloadings,
            'previousDayClosed',     v_prevclosed),
        'policy', jsonb_build_object(
            'missingProduction',       pol.missingproduction,
            'unpostedProduction',      pol.unpostedproduction,
            'impossibleBirdCounts',    pol.impossiblebirdcounts,
            'pendingDriverReturns',    pol.pendingdriverreturns,
            'negativeStock',           pol.negativestock,
            'cashDifference',          pol.cashdifference,
            'cashDifferenceTolerance', pol.cashdifferencetolerance,
            'requireCashCount',        pol.requirecashcount,
            'lowFeedDays',             pol.lowfeeddays,
            'unusualMortalityPct',     pol.unusualmortalitypct,
            'isCustomised',            pol.iscustomised),
        'checklist', v_checks,
        'counts', jsonb_build_object(
            'blocking', (SELECT count(*) FROM jsonb_array_elements(v_checks) c WHERE c->>'status' = 'Blocking'),
            'warning',  (SELECT count(*) FROM jsonb_array_elements(v_checks) c WHERE c->>'status' = 'Warning'),
            'complete', (SELECT count(*) FROM jsonb_array_elements(v_checks) c WHERE c->>'status' = 'Complete'))
    );
END;
$function$;

-- ---- sppoultryreport_costperegg: report
CREATE OR REPLACE FUNCTION public.sppoultryreport_costperegg(p_farmid text, p_startdate date, p_enddate date, p_flockid integer DEFAULT NULL::integer, p_includeclosedflocks boolean DEFAULT false)
 RETURNS TABLE(flockid integer, flockname text, eggsproduced bigint, feedcost numeric, medicinevaccinecost numeric, laborcost numeric, totalallocatedcost numeric, sellingpriceperunit numeric)
 LANGUAGE plpgsql
AS $function$
DECLARE
    v_gid uuid;
BEGIN
    BEGIN
        v_gid := p_farmid::uuid;               -- TRY_CONVERT(UNIQUEIDENTIFIER, @FarmId)
    EXCEPTION WHEN OTHERS THEN
        v_gid := NULL;
    END;

    RETURN QUERY
    WITH eggs AS (
        SELECT r.flockid AS c_flockid, SUM(r.totalproduction::bigint) AS c_eggs
        FROM   productionrecords r
        WHERE  r.farmid = p_farmid AND r.date >= p_startdate AND r.date <= p_enddate
        GROUP  BY r.flockid
    ),
    cost AS (
        SELECT e.flockid AS c_flockid,
            SUM(CASE WHEN e.category ILIKE '%feed%' THEN e.amount ELSE 0 END)                       AS c_feedcost,
            SUM(CASE WHEN e.category ILIKE '%medic%' OR e.category ILIKE '%vaccin%'
                       OR e.category ILIKE '%drug%'  OR e.category ILIKE '%health%'
                     THEN e.amount ELSE 0 END)                                                      AS c_medcost,
            SUM(CASE WHEN e.category ILIKE '%labo%'   OR e.category ILIKE '%salary%'
                       OR e.category ILIKE '%wage%'   OR e.category ILIKE '%payroll%'
                     THEN e.amount ELSE 0 END)                                                      AS c_laborcost,
            SUM(e.amount)                                                                           AS c_totalcost
        FROM   expense e
        WHERE  e.farmid = v_gid
          AND  e.expensedate >= p_startdate AND e.expensedate < (p_enddate + 1)
        GROUP  BY e.flockid
    ),
    avgprice AS (
        SELECT s.flockid AS c_flockid,
               CASE WHEN SUM(s.quantity) = 0 THEN NULL
                    ELSE SUM(s.totalamount) / NULLIF(SUM(s.quantity), 0) END                        AS c_avgunitprice
        FROM   sale s
        WHERE  s.status = 'Posted' AND s.farmid = p_farmid
          AND  s.saledate >= p_startdate AND s.saledate < (p_enddate + 1)
        GROUP  BY s.flockid
    )
    SELECT
        f.flockid,
        f.name::text                          AS flockname,
        COALESCE(eggs.c_eggs, 0)::bigint      AS eggsproduced,
        COALESCE(cost.c_feedcost, 0)          AS feedcost,
        COALESCE(cost.c_medcost, 0)           AS medicinevaccinecost,
        COALESCE(cost.c_laborcost, 0)         AS laborcost,
        COALESCE(cost.c_totalcost, 0)         AS totalallocatedcost,
        avgprice.c_avgunitprice               AS sellingpriceperunit
    FROM   flock f
    LEFT JOIN eggs     ON eggs.c_flockid     = f.flockid
    LEFT JOIN cost     ON cost.c_flockid     = f.flockid
    LEFT JOIN avgprice ON avgprice.c_flockid = f.flockid
    WHERE  f.farmid = p_farmid
      AND  (p_flockid IS NULL OR f.flockid = p_flockid)
      AND  (p_includeclosedflocks OR COALESCE(f.active, TRUE))
    ORDER  BY f.name;
END
$function$;

