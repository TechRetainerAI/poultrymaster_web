-- =============================================================================
-- 352  Readers learn about Reversed sales                    (requires 351)
-- =============================================================================
--
-- A reversed sale stays in `sale` (351) but is no longer a sale: no revenue,
-- no receivable, no eggs or birds sold, nothing on a dashboard. Before 351 the
-- same sale would have been DELETED, so every reader below is given the
-- one-line filter that makes a reversal read exactly as that delete used to --
-- `<alias>.status = 'Posted'` -- and nothing else changes in it.
--
-- Deliberately NOT filtered (they show history, or read money, not sales):
--   spsale_getall / getbyid        list reversed sales (351), the page filters
--   sppoultrypayment_getall        a payment on a reversed sale is still a payment
--   sppoultrycustomerpayment_allocations     allocation history (Reversed rows included)
--   spflock_closeouthistory        the history of a closeout
--   fnpoultrypaymentgroupaccount   which account a payment went to
--   fnpoultryfa_events             reads revenue through fnpoultrypl_revenuelines
--
-- Every body below is the LIVE definition (pg_get_functiondef, 2026-10-09)
-- with only the marked change -- several of them exist nowhere else in the
-- repo. Generated by scratchpad/gen352.py; each edit asserted its match count.
--
-- Cash Flow (sppoultrycashflow_rows) gains two legs and one rule:
--   ReceiptReversal  a reversed payment, Money Out on the day it was reversed
--                    (contra-sales: OperatingIn, negative). The receipt itself
--                    stays on its own date, so both are visible and net zero.
--                    This also applies to payments reversed BEFORE 351, which
--                    used to vanish from the report instead.
--   CustomerRefund   money handed back out of customer credit.
--   residual         active sales only; "already covered" is what is applied
--                    to the sale (fnpoultrysale_allocated), so credit applied
--                    from another payment is not counted as new cash.
--
-- Idempotent (CREATE OR REPLACE, same signatures). PostgreSQL.
-- =============================================================================

