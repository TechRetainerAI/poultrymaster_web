        COALESCE(f.active, TRUE)                                                                    AS active
    FROM   flock f
    LEFT JOIN rev  ON rev.c_flockid  = f.flockid
    LEFT JOIN eggs ON eggs.c_flockid = f.flockid
    LEFT JOIN cost ON cost.c_flockid = f.flockid
