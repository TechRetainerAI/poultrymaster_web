    RETURN QUERY
    WITH pr AS (
        SELECT r.flockid AS c_flockid,
               SUM(r.totalproduction::bigint)                                                                                     AS c_eggs,
               SUM((COALESCE(r.brokeneggs,0)+COALESCE(r.meatyeggs,0)+COALESCE(r.softeggs,0)+COALESCE(r.losteggs,0))::bigint)      AS c_broken,
