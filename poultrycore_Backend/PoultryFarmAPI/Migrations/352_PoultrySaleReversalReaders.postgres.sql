                THEN s.totalamount ELSE 0 END)                                                      AS c_birdrevenue,
            SUM(s.totalamount)                                                                      AS c_revenue
        FROM   sale s
        WHERE  s.status = 'Posted' AND s.farmid = p_farmid
          AND  s.saledate >= p_startdate AND s.saledate < (p_enddate + 1)
        GROUP  BY s.flockid
    ),
