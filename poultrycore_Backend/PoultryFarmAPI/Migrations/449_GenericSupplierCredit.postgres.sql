-- =============================================================================
-- 449_GenericSupplierCredit.postgres.sql   (Report 40, Part 2; requires 248, 448)
--
-- Poultry 370 / Water 426 for Generic: supplier credit, advances, refunds and
-- supplier debt, so Generic's Supplier Payments, Supplier Balances and Supplier
-- Credits & Advances work like Poultry's. Credit is DERIVED, never stored.
--
--  * A posted Generic supplier payment is status 'Approved' with a sourcetype
--    (spgenericsupplierpayment_record or a manual credit). The old Draft/Approve
--    payment documents (no sourcetype) are never credit.
--  * SUPPLIER CREDIT is a genericsupplierpayments row:
--      an ADVANCE        a real payment applied to nothing (cash out);
--      an OVERPAYMENT    a real payment applied to less than its amount;
--      a MANUAL credit   no cash: SupplierCreditNote / SupplierOpeningCredit /
--                        SupplierManualCredit, no account.
--    Credit = amount - posted allocations - posted refund lines.
--  * APPLYING credit is an allocation on the CREDIT's payment (fromcredit),
--    dated now: the bill's amount paid goes up, no cash moves, and the
--    supplier's ledger balance comes down (CreditApplied).
--  * A REFUND is the supplier sending money back: money IN to the account
--    chosen; reversible.
--  * SUPPLIER DEBT (SD-00001): owed without a purchase here. A payable
--    (fngenericpayables 'SupplierDebt') on the supplier's ledger; reversal is
--    refused while anything is paid on it.
--  * spgenericsupplierpayment_record now takes a payment applied to less than
--    its amount (the rest is credit) or to nothing (an advance). The supplier
--    ledger moves by what was APPLIED only; the cash by the whole payment.
--    spgenericsupplierpayment_reverse is refused while the payment's credit is
--    applied or refunded.
--  * The one row of the old genericsuppliercredits list becomes a manual
--    credit; spgenericsuppliercredit_create (old POST route) writes the new way.
--  * Cash Flow: + the unapplied part of a payment (cash out), + refunds (cash
--    in); an expense paid from credit is counted only for the rest (its cash
--    left with the advance).
--  * Statement: manual credits and refunds appear; payment history and
--    "payments today" leave manual credits out (no money moved).
--
-- Deploy order: this migration, then the Farm API, then the web app.
-- Idempotent.
-- =============================================================================

-- ============================================================ 1. tables =====
