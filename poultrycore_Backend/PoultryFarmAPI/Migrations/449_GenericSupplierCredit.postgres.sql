    VALUES (v_id, p_farmid, p_paymentid, v_amt);
    PERFORM public.fngenericcash_move(p_farmid, p_cashaccountid, v_amt, v_date::timestamp, 'GenericSupplierRefund', v_id,
        'Supplier refund ' || v_no, p_by);
