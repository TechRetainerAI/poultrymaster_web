-- ===================================================== 2. credit, derived ===
CREATE OR REPLACE FUNCTION public.fngenericsupplier_iscreditkind(p_sourcetype text)
RETURNS boolean LANGUAGE sql IMMUTABLE AS $f$
    SELECT COALESCE(p_sourcetype, '') IN ('SupplierCreditNote', 'SupplierOpeningCredit', 'SupplierManualCredit');
$f$;

-- Posted the new way (record / manual credit), not an old Draft/Approve document.
CREATE OR REPLACE FUNCTION public.fngenericsupplierpayment_isposted(p_status text, p_sourcetype text)
RETURNS boolean LANGUAGE sql IMMUTABLE AS $f$
    SELECT COALESCE(p_status, '') = 'Approved' AND p_sourcetype IS NOT NULL;
$f$;

CREATE OR REPLACE FUNCTION public.fngenericsupplierpayment_unapplied(p_farmid text, p_paymentid integer)
RETURNS numeric LANGUAGE sql STABLE AS $f$
    SELECT CASE WHEN NOT public.fngenericsupplierpayment_isposted(sp.status, sp.sourcetype) THEN 0
                ELSE GREATEST(sp.amount
                     - COALESCE((SELECT SUM(sa.amountapplied) FROM supplierpaymentallocation sa
                                 WHERE sa.farmid = sp.farmid AND sa.module = 'generic'
                                   AND sa.paymentid = sp.genericsupplierpaymentid AND sa.status = 'Posted'), 0)
                     - COALESCE((SELECT SUM(rl.amount) FROM genericsupplierrefundlines rl
                                 JOIN genericsupplierrefunds r ON r.refundid = rl.refundid AND r.status = 'Posted'
                                 WHERE rl.farmid = sp.farmid AND rl.genericsupplierpaymentid = sp.genericsupplierpaymentid), 0), 0)
           END::numeric(14,2)
    FROM   genericsupplierpayments sp
    WHERE  sp.genericsupplierpaymentid = p_paymentid AND sp.farmid = p_farmid;
$f$;

CREATE OR REPLACE FUNCTION public.spgenericsuppliercredit_events(p_farmid text, p_supplierid integer DEFAULT NULL)
RETURNS TABLE(genericsupplierpaymentid integer, creditnumber text, creditdate timestamp, supplierid integer,
              suppliername text, source text, sourcetype text, reference text, notes text, originalamount numeric,
              applied numeric, refunded numeric, available numeric, status text, ismanual boolean,
              genericcashaccountid integer, accountname text)
LANGUAGE sql STABLE AS $f$
    WITH x AS (
        SELECT sp.*,
               COALESCE((SELECT SUM(sa.amountapplied) FROM supplierpaymentallocation sa
                         WHERE sa.farmid = sp.farmid AND sa.module = 'generic' AND sa.paymentid = sp.genericsupplierpaymentid
                           AND sa.status = 'Posted' AND NOT sa.fromcredit), 0) AS paidnow,
               COALESCE((SELECT SUM(sa.amountapplied) FROM supplierpaymentallocation sa
                         WHERE sa.farmid = sp.farmid AND sa.module = 'generic' AND sa.paymentid = sp.genericsupplierpaymentid
                           AND sa.status = 'Posted' AND sa.fromcredit), 0) AS appliedlater,
               COALESCE((SELECT SUM(rl.amount) FROM genericsupplierrefundlines rl
                         JOIN genericsupplierrefunds r ON r.refundid = rl.refundid AND r.status = 'Posted'
                         WHERE rl.farmid = sp.farmid AND rl.genericsupplierpaymentid = sp.genericsupplierpaymentid), 0) AS refundedamt,
               EXISTS (SELECT 1 FROM supplierpaymentallocation sa
                       WHERE sa.farmid = sp.farmid AND sa.module = 'generic' AND sa.paymentid = sp.genericsupplierpaymentid
                         AND NOT sa.fromcredit) AS hadallocations
        FROM   genericsupplierpayments sp
        WHERE  sp.farmid = p_farmid AND public.fngenericsupplierpayment_isposted(sp.status, sp.sourcetype)
          AND  sp.genericsupplierid IS NOT NULL
          AND  (p_supplierid IS NULL OR sp.genericsupplierid = p_supplierid)
    )
    SELECT x.genericsupplierpaymentid, ('SP-' || lpad(x.genericsupplierpaymentid::text, 5, '0'))::text, x.paymentdate,
           x.genericsupplierid, s.suppliername::text,
           CASE x.sourcetype
                WHEN 'SupplierCreditNote'    THEN 'Credit note'
                WHEN 'SupplierOpeningCredit' THEN 'Opening credit'
                WHEN 'SupplierManualCredit'  THEN 'Manual credit'
                ELSE CASE WHEN x.hadallocations THEN 'Overpayment' ELSE 'Supplier advance' END
           END::text,
           x.sourcetype::text, x.referenceno::text, x.notes::text,
           (x.amount - x.paidnow)::numeric(14,2), x.appliedlater::numeric(14,2), x.refundedamt::numeric(14,2),
           public.fngenericsupplierpayment_unapplied(p_farmid, x.genericsupplierpaymentid),
           CASE WHEN public.fngenericsupplierpayment_unapplied(p_farmid, x.genericsupplierpaymentid) <= 0
                     AND x.refundedamt > 0 AND x.appliedlater = 0 THEN 'Refunded'
                WHEN public.fngenericsupplierpayment_unapplied(p_farmid, x.genericsupplierpaymentid) <= 0 THEN 'Used'
                WHEN x.appliedlater > 0 OR x.refundedamt > 0 THEN 'Partly used'
                ELSE 'Available' END::text,
           (public.fngenericsupplier_iscreditkind(x.sourcetype) OR NOT x.hadallocations),
           x.genericcashaccountid, a.accountname::text
    FROM   x
    LEFT   JOIN genericsuppliers s ON s.genericsupplierid = x.genericsupplierid AND s.farmid = x.farmid
    LEFT   JOIN genericcashaccounts a ON a.genericcashaccountid = x.genericcashaccountid AND a.farmid = x.farmid
    WHERE  (x.amount - x.paidnow) > 0
    ORDER  BY x.paymentdate DESC, x.genericsupplierpaymentid DESC;
$f$;

-- ================================================== 5. supplier debts (payable first) ===
-- fngenericpayables gains the SupplierDebt arm (the rest is 448's body).
CREATE OR REPLACE FUNCTION public.fngenericpayables(p_farmid text)
 RETURNS TABLE(documenttype text, documentid integer, supplierid integer, docdate date, label text, reference text, totalcost numeric, amountpaid numeric, balance numeric, cashaccountid integer, duedate date)
 LANGUAGE sql
 STABLE
AS $function$
    SELECT 'Purchase'::text, p.genericpurchaseid, p.genericsupplierid,
           p.purchasedate::date,
           COALESCE(NULLIF(btrim(p.notes), ''), 'Purchase')::text,
           ('P' || p.genericpurchaseid::text)::text,
           COALESCE(p.totalamount, 0)::numeric(14,2),
           COALESCE(p.amountpaid, 0)::numeric(14,2),
           GREATEST(COALESCE(p.totalamount, 0) - COALESCE(p.amountpaid, 0), 0)::numeric(14,2),
           p.genericcashaccountid,
           NULL::date
    FROM   genericpurchases p
    WHERE  p.farmid = p_farmid
      AND  COALESCE(p.isdeleted, FALSE) = FALSE
      AND  p.genericsupplierid IS NOT NULL
      AND  COALESCE(p.status, '') <> 'Cancelled'

    UNION ALL

    SELECT 'Expense'::text, e.genericexpenseid, e.genericsupplierid,
           e.expensedate::date,
           COALESCE(NULLIF(btrim(e.description), ''), 'Expense')::text,
           ('E' || e.genericexpenseid::text)::text,
           COALESCE(e.amount, 0)::numeric(14,2),
           COALESCE(e.amountpaid, e.amount)::numeric(14,2),
           GREATEST(COALESCE(e.amount, 0) - COALESCE(e.amountpaid, e.amount), 0)::numeric(14,2),
           e.genericcashaccountid,
           e.duedate
    FROM   genericexpenses e
    WHERE  e.farmid = p_farmid
      AND  COALESCE(e.isdeleted, FALSE) = FALSE
      AND  e.genericsupplierid IS NOT NULL
      AND  e.sourcetype IS NULL
      AND  COALESCE(e.paymentmethod, '') <> 'NonCash'
      AND  e.status = 'Approved'

    UNION ALL

    -- 449: debts recorded by hand (owed without a purchase here).
    SELECT 'SupplierDebt'::text, d.debtid, d.supplierid, d.debtdate,
           d.description::text, d.debtnumber::text,
           d.amount, d.amountpaid, GREATEST(d.amount - d.amountpaid, 0)::numeric(14,2),
           NULL::integer, NULL::date
    FROM   genericsupplierdebts d
    WHERE  d.farmid = p_farmid AND d.status = 'Posted';
$function$;

CREATE OR REPLACE FUNCTION public.spgenericsuppliercredit_summary(p_farmid text)
RETURNS TABLE(supplierid integer, suppliername text, availablecredit numeric, creditcount integer, owed numeric)
LANGUAGE sql STABLE AS $f$
    SELECT e.supplierid, MIN(e.suppliername)::text, SUM(e.available)::numeric(14,2),
           COUNT(*) FILTER (WHERE e.available > 0)::integer,
           COALESCE((SELECT SUM(d.balance) FROM fngenericpayables(p_farmid) d WHERE d.supplierid = e.supplierid), 0)::numeric(14,2)
    FROM   public.spgenericsuppliercredit_events(p_farmid, NULL) e
    GROUP  BY e.supplierid
    HAVING SUM(e.available) > 0
    ORDER  BY SUM(e.available) DESC;
$f$;

CREATE OR REPLACE FUNCTION public.spgenericsuppliercredit_applications(p_farmid text, p_supplierid integer DEFAULT NULL)
RETURNS TABLE(allocationid integer, genericsupplierpaymentid integer, creditnumber text, supplierid integer,
              suppliername text, documenttype text, documentid integer, reference text, label text, amount numeric,
              applieddate timestamp, status text, createdby text, reversedat timestamp, reversalreason text)
LANGUAGE sql STABLE AS $f$
    SELECT sa.allocationid, sp.genericsupplierpaymentid, ('SP-' || lpad(sp.genericsupplierpaymentid::text, 5, '0'))::text,
           sp.genericsupplierid, s.suppliername::text, sa.documenttype, sa.documentid,
           COALESCE(d.reference, LEFT(sa.documenttype, 1) || sa.documentid::text), d.label,
           sa.amountapplied, sa.createdat, sa.status, sa.createdby, sa.reversedat, sa.reversalreason
    FROM   supplierpaymentallocation sa
    JOIN   genericsupplierpayments sp ON sp.genericsupplierpaymentid = sa.paymentid AND sp.farmid = sa.farmid
    LEFT   JOIN genericsuppliers s ON s.genericsupplierid = sp.genericsupplierid AND s.farmid = sp.farmid
    LEFT   JOIN fngenericpayables(p_farmid) d ON d.documenttype = sa.documenttype AND d.documentid = sa.documentid
    WHERE  sa.farmid = p_farmid AND sa.module = 'generic' AND sa.fromcredit
      AND  (p_supplierid IS NULL OR sp.genericsupplierid = p_supplierid)
    ORDER  BY sa.createdat DESC, sa.allocationid DESC;
$f$;

-- Supplier ledger: one row, and the balance it leaves. p_owed > 0 owes more.
CREATE OR REPLACE FUNCTION public.fngenericsupplier_ledgermove(p_farmid text, p_supplierid integer, p_owed numeric,
    p_type text, p_description text, p_by text, p_paymentid integer DEFAULT NULL)
RETURNS void LANGUAGE plpgsql AS $f$
DECLARE v_bal numeric(14,2);
BEGIN
    IF COALESCE(p_owed, 0) = 0 THEN RETURN; END IF;
    SELECT COALESCE(s.currentbalance, 0) INTO v_bal FROM genericsuppliers s
    WHERE  s.genericsupplierid = p_supplierid AND s.farmid = p_farmid FOR UPDATE;
    INSERT INTO genericsupplierledger
        (farmid, genericsupplierid, transactiondate, transactiontype, paymentid,
         debitamount, creditamount, balanceaftertransaction, description, createdby)
    VALUES (p_farmid, p_supplierid, (now() AT TIME ZONE 'utc'), p_type, p_paymentid,
            GREATEST(-p_owed, 0), GREATEST(p_owed, 0), GREATEST(v_bal + p_owed, 0), p_description, p_by);
    UPDATE genericsuppliers SET currentbalance = GREATEST(v_bal + p_owed, 0), updatedat = (now() AT TIME ZONE 'utc')
    WHERE  genericsupplierid = p_supplierid AND farmid = p_farmid;
END
$f$;

-- Cash account: one movement, and the balance it leaves. p_amount > 0 is money in.
CREATE OR REPLACE FUNCTION public.fngenericcash_move(p_farmid text, p_accountid integer, p_amount numeric,
    p_date timestamp, p_sourcetype text, p_sourceid integer, p_description text, p_by text, p_checknegative boolean DEFAULT FALSE)
RETURNS void LANGUAGE plpgsql AS $f$
DECLARE v_bal numeric(14,2); v_neg boolean;
BEGIN
    SELECT a.currentbalance, a.allownegativebalance INTO v_bal, v_neg FROM genericcashaccounts a
    WHERE  a.genericcashaccountid = p_accountid AND a.farmid = p_farmid FOR UPDATE;
    IF v_bal IS NULL THEN RAISE EXCEPTION 'Cash account does not belong to this company.' USING ERRCODE = 'P0001'; END IF;
    IF p_checknegative AND v_bal + p_amount < 0 AND v_neg = FALSE THEN
        RAISE EXCEPTION 'Not enough money in the cash account: it has %.', v_bal USING ERRCODE = 'P0001';
    END IF;
    INSERT INTO genericcashtransactions
        (farmid, genericcashaccountid, transactiondate, transactiontype, sourcetype, sourceid,
         amount, balanceaftertransaction, description, createdby, approvedby, approvedat)
    VALUES (p_farmid, p_accountid, p_date, CASE WHEN p_amount >= 0 THEN 'CashIn' ELSE 'CashOut' END,
            p_sourcetype, p_sourceid, p_amount, v_bal + p_amount, p_description, p_by, p_by, (now() AT TIME ZONE 'utc'));
    UPDATE genericcashaccounts SET currentbalance = v_bal + p_amount, updatedat = (now() AT TIME ZONE 'utc')
    WHERE  genericcashaccountid = p_accountid AND farmid = p_farmid;
END
$f$;

-- ================================================= 3. writers: credit ======
CREATE OR REPLACE FUNCTION public.spgenericsuppliercredit_createmanual(p_farmid text, p_supplierid integer, p_kind text,
    p_amount numeric, p_date timestamp DEFAULT NULL, p_reference text DEFAULT NULL, p_reason text DEFAULT NULL,
    p_by text DEFAULT NULL)
RETURNS integer LANGUAGE plpgsql AS $f$
DECLARE v_id integer; v_date timestamp := COALESCE(p_date, (now() AT TIME ZONE 'utc'));
BEGIN
    IF p_kind NOT IN ('SupplierCreditNote', 'SupplierOpeningCredit', 'SupplierManualCredit') THEN
        RAISE EXCEPTION 'Choose what the credit is: a credit note, an opening credit or a manual credit.' USING ERRCODE = 'P0001';
    END IF;
    IF p_amount IS NULL OR round(p_amount, 2) <= 0 THEN
        RAISE EXCEPTION 'Enter an amount greater than 0.' USING ERRCODE = 'P0001';
    END IF;
    IF NULLIF(btrim(COALESCE(p_reason, '')), '') IS NULL THEN
        RAISE EXCEPTION 'Give a reason for the credit.' USING ERRCODE = 'P0001';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM genericsuppliers s WHERE s.genericsupplierid = p_supplierid AND s.farmid = p_farmid) THEN
        RAISE EXCEPTION 'Supplier does not belong to this company.' USING ERRCODE = 'P0001';
    END IF;
    IF v_date > (now() AT TIME ZONE 'utc') + interval '1 day' THEN
        RAISE EXCEPTION 'The credit date is in the future.' USING ERRCODE = 'P0001';
    END IF;
    INSERT INTO genericsupplierpayments
        (farmid, genericsupplierid, paymentdate, amount, paymentmethod, genericcashaccountid, referenceno, notes,
         sourcetype, status, createdby, approvedby, approvedat, createdat)
    VALUES (p_farmid, p_supplierid, v_date, round(p_amount, 2), 'NonCash', NULL, NULLIF(btrim(p_reference), ''),
            btrim(p_reason), p_kind, 'Approved', p_by, p_by, (now() AT TIME ZONE 'utc'), (now() AT TIME ZONE 'utc'))
    RETURNING genericsupplierpaymentid INTO v_id;
    RETURN v_id;
END
$f$;

-- The old POST supplier-credits route writes the new way too.
CREATE OR REPLACE FUNCTION public.spgenericsuppliercredit_create(p_farmid text, p_supplierid integer, p_credittype character varying,
    p_amount numeric, p_creditdate timestamp without time zone, p_notes text, p_createdby text)
RETURNS integer LANGUAGE plpgsql AS $f$
BEGIN
    RETURN public.spgenericsuppliercredit_createmanual(p_farmid, p_supplierid,
        CASE p_credittype WHEN 'CreditNote' THEN 'SupplierCreditNote' ELSE 'SupplierManualCredit' END,
        p_amount, p_creditdate, NULL, COALESCE(NULLIF(btrim(p_notes), ''), p_credittype::text), p_createdby);
END
$f$;

-- Bump / drop what a payable document shows as paid.
CREATE OR REPLACE FUNCTION public.fngenericpayable_addpaid(p_farmid text, p_documenttype text, p_documentid integer, p_delta numeric)
RETURNS void LANGUAGE plpgsql AS $f$
BEGIN
    IF p_documenttype = 'Expense' THEN
        UPDATE genericexpenses
        SET    amountpaid = LEAST(GREATEST(COALESCE(amountpaid, amount) + p_delta, 0), amount),
               updatedat  = (now() AT TIME ZONE 'utc')
        WHERE  genericexpenseid = p_documentid AND farmid = p_farmid;
    ELSIF p_documenttype = 'SupplierDebt' THEN
        UPDATE genericsupplierdebts SET amountpaid = LEAST(GREATEST(amountpaid + p_delta, 0), amount)
        WHERE  debtid = p_documentid AND farmid = p_farmid;
    ELSIF p_documenttype = 'Purchase' THEN
        UPDATE genericpurchases
        SET    amountpaid    = LEAST(GREATEST(COALESCE(amountpaid, 0) + p_delta, 0), totalamount),
               balance       = GREATEST(totalamount - LEAST(GREATEST(COALESCE(amountpaid, 0) + p_delta, 0), totalamount), 0),
               paymentstatus = CASE WHEN COALESCE(amountpaid, 0) + p_delta >= totalamount THEN 'Paid'
                                    WHEN COALESCE(amountpaid, 0) + p_delta <= 0 THEN 'Unpaid'
                                    ELSE 'PartiallyPaid' END,
               updatedat     = (now() AT TIME ZONE 'utc')
        WHERE  genericpurchaseid = p_documentid AND farmid = p_farmid;
    ELSE
        RAISE EXCEPTION 'Unknown payable type "%".', p_documenttype USING ERRCODE = 'P0001';
    END IF;
END
$f$;

CREATE OR REPLACE FUNCTION public.spgenericsuppliercredit_reverse(p_farmid text, p_paymentid integer, p_reason text,
                                                                  p_by text DEFAULT NULL)
RETURNS integer LANGUAGE plpgsql AS $f$
DECLARE v_sp genericsupplierpayments%ROWTYPE;
BEGIN
    IF NULLIF(btrim(COALESCE(p_reason, '')), '') IS NULL THEN
        RAISE EXCEPTION 'Give a reason for reversing the credit.' USING ERRCODE = 'P0001';
    END IF;
    SELECT * INTO v_sp FROM genericsupplierpayments sp
    WHERE  sp.genericsupplierpaymentid = p_paymentid AND sp.farmid = p_farmid FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'That credit does not belong to this company.' USING ERRCODE = 'P0001'; END IF;
    IF NOT public.fngenericsupplierpayment_isposted(v_sp.status, v_sp.sourcetype) THEN
        RAISE EXCEPTION 'This credit has already been reversed.' USING ERRCODE = 'P0001';
    END IF;
    IF EXISTS (SELECT 1 FROM supplierpaymentallocation sa WHERE sa.farmid = p_farmid AND sa.module = 'generic'
               AND sa.paymentid = p_paymentid AND sa.status = 'Posted' AND sa.fromcredit) THEN
        RAISE EXCEPTION 'Part of this credit has been applied. Undo those applications first.' USING ERRCODE = 'P0001';
    END IF;
    IF EXISTS (SELECT 1 FROM genericsupplierrefundlines rl JOIN genericsupplierrefunds r ON r.refundid = rl.refundid
               WHERE rl.farmid = p_farmid AND rl.genericsupplierpaymentid = p_paymentid AND r.status = 'Posted') THEN
        RAISE EXCEPTION 'Part of this credit has been refunded. Reverse the refund first.' USING ERRCODE = 'P0001';
    END IF;
    IF NOT public.fngenericsupplier_iscreditkind(v_sp.sourcetype) THEN
        RETURN public.spgenericsupplierpayment_reverse(p_farmid, p_paymentid, btrim(p_reason), p_by);
    END IF;
    UPDATE genericsupplierpayments SET status = 'Reversed', reversedby = p_by, reversedat = (now() AT TIME ZONE 'utc'),
           reversalreason = btrim(p_reason), updatedat = (now() AT TIME ZONE 'utc')
    WHERE  genericsupplierpaymentid = p_paymentid AND farmid = p_farmid;
    RETURN 1;
END
$f$;

CREATE OR REPLACE FUNCTION public.spgenericsuppliercredit_apply(p_farmid text, p_paymentid integer,
    p_documenttype text, p_documentid integer, p_amount numeric, p_by text DEFAULT NULL)
RETURNS integer LANGUAGE plpgsql AS $f$
DECLARE
    v_sp     genericsupplierpayments%ROWTYPE;
    v_doc    record;
    v_amt    numeric(14,2) := round(p_amount, 2);
    v_avail  numeric(14,2);
    v_before numeric(14,2);
    v_id     integer;
BEGIN
    IF v_amt IS NULL OR v_amt <= 0 THEN
        RAISE EXCEPTION 'Enter an amount greater than 0.' USING ERRCODE = 'P0001';
    END IF;
    SELECT * INTO v_sp FROM genericsupplierpayments sp
    WHERE  sp.genericsupplierpaymentid = p_paymentid AND sp.farmid = p_farmid FOR UPDATE;
    IF NOT FOUND OR v_sp.genericsupplierid IS NULL THEN
        RAISE EXCEPTION 'That credit does not belong to this company.' USING ERRCODE = 'P0001';
    END IF;
    v_avail := public.fngenericsupplierpayment_unapplied(p_farmid, p_paymentid);
    IF v_amt > v_avail THEN
        RAISE EXCEPTION 'That credit only has % available.', v_avail USING ERRCODE = 'P0001';
    END IF;
    SELECT * INTO v_doc FROM fngenericpayables(p_farmid) d
    WHERE  d.documenttype = COALESCE(p_documenttype, 'Purchase') AND d.documentid = p_documentid;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'That item is not an open payable of this company.' USING ERRCODE = 'P0001';
    END IF;
    IF v_doc.supplierid IS DISTINCT FROM v_sp.genericsupplierid THEN
        RAISE EXCEPTION 'That item is owed to a different supplier.' USING ERRCODE = 'P0001';
    END IF;
    v_before := v_doc.balance;
    IF v_before <= 0 THEN RAISE EXCEPTION '% is already fully paid.', v_doc.reference USING ERRCODE = 'P0001'; END IF;
    IF v_amt > v_before THEN RAISE EXCEPTION 'Only % is owed on %.', v_before, v_doc.reference USING ERRCODE = 'P0001'; END IF;
    IF EXISTS (SELECT 1 FROM supplierpaymentallocation sa
               WHERE sa.farmid = p_farmid AND sa.module = 'generic' AND sa.paymentid = p_paymentid
                 AND sa.documenttype = v_doc.documenttype AND sa.documentid = p_documentid AND sa.status = 'Posted') THEN
        RAISE EXCEPTION 'This credit has already been applied to % once. Use another credit, or pay it.', v_doc.reference
            USING ERRCODE = 'P0001';
    END IF;
    PERFORM public.fngenericpayable_addpaid(p_farmid, v_doc.documenttype, p_documentid, v_amt);
    INSERT INTO supplierpaymentallocation
        (farmid, module, paymentid, documenttype, documentid, amountapplied,
         documentbalancebefore, documentbalanceafter, status, createdby, createdat, fromcredit)
    VALUES (p_farmid, 'generic', p_paymentid, v_doc.documenttype, p_documentid, v_amt,
            v_before, v_before - v_amt, 'Posted', p_by, (now() AT TIME ZONE 'utc'), TRUE)
    RETURNING allocationid INTO v_id;
    PERFORM public.fngenericsupplier_ledgermove(p_farmid, v_sp.genericsupplierid, -v_amt, 'CreditApplied',
        'Credit SP-' || lpad(p_paymentid::text, 5, '0') || ' applied to ' || v_doc.reference, p_by, p_paymentid);
    RETURN v_id;
END
$f$;

CREATE OR REPLACE FUNCTION public.spgenericsuppliercredit_unapply(p_farmid text, p_allocationid integer,
    p_reason text, p_by text DEFAULT NULL)
RETURNS integer LANGUAGE plpgsql AS $f$
DECLARE v_a supplierpaymentallocation%ROWTYPE; v_sup integer;
BEGIN
    IF NULLIF(btrim(COALESCE(p_reason, '')), '') IS NULL THEN
        RAISE EXCEPTION 'Give a reason.' USING ERRCODE = 'P0001';
    END IF;
    SELECT * INTO v_a FROM supplierpaymentallocation sa
    WHERE  sa.allocationid = p_allocationid AND sa.farmid = p_farmid AND sa.module = 'generic' FOR UPDATE;
    IF NOT FOUND OR NOT v_a.fromcredit THEN
        RAISE EXCEPTION 'That is not an application of supplier credit in this company.' USING ERRCODE = 'P0001';
    END IF;
    IF v_a.status <> 'Posted' THEN
        RAISE EXCEPTION 'That application has already been reversed.' USING ERRCODE = 'P0001';
    END IF;
    PERFORM public.fngenericpayable_addpaid(p_farmid, v_a.documenttype, v_a.documentid, -v_a.amountapplied);
    UPDATE supplierpaymentallocation
    SET    status = 'Reversed', reversedby = p_by, reversedat = (now() AT TIME ZONE 'utc'), reversalreason = btrim(p_reason)
    WHERE  allocationid = p_allocationid;
    SELECT sp.genericsupplierid INTO v_sup FROM genericsupplierpayments sp
    WHERE  sp.genericsupplierpaymentid = v_a.paymentid AND sp.farmid = p_farmid;
    PERFORM public.fngenericsupplier_ledgermove(p_farmid, v_sup, v_a.amountapplied, 'CreditUnapplied',
        'Credit application undone: ' || btrim(p_reason), p_by, v_a.paymentid);
    RETURN p_allocationid;
END
