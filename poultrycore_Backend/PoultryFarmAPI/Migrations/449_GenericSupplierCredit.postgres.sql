-- spgenericsupplierpayment_record (248): a payment may now be applied to less
-- than its amount, or to nothing; supplier debts are payable; the ledger moves
-- by what was applied.
CREATE OR REPLACE FUNCTION public.spgenericsupplierpayment_record(p_farmid text, p_supplierid integer, p_amount numeric,
    p_allocations jsonb, p_paymentmethod text DEFAULT NULL::text, p_paymentdate timestamp without time zone DEFAULT NULL::timestamp without time zone,
    p_cashaccountid integer DEFAULT NULL::integer, p_reference text DEFAULT NULL::text, p_notes text DEFAULT NULL::text,
    p_sourcetype text DEFAULT 'SupplierBalances'::text, p_createdby text DEFAULT NULL::text)
RETURNS integer
LANGUAGE plpgsql
AS $f$
DECLARE
    v_paymentid integer;
    v_date      timestamp := COALESCE(p_paymentdate, (now() at time zone 'utc'));
    v_allocated numeric(14,2);
    v_count     integer;
    v_distinct  integer;
    v_minamount numeric(14,2);
    v_matched   integer := 0;
    v_row       record;
BEGIN
    IF COALESCE(p_amount, 0) <= 0 THEN
        RAISE EXCEPTION 'Payment amount must be greater than 0.';
    END IF;
    IF p_supplierid IS NULL THEN
        RAISE EXCEPTION 'A supplier is required to make a payment.';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM genericsuppliers s
                   WHERE s.genericsupplierid = p_supplierid AND s.farmid = p_farmid) THEN
        RAISE EXCEPTION 'Supplier does not belong to this company.';
    END IF;
    SELECT COALESCE(SUM(a.amount), 0), COUNT(*), COUNT(DISTINCT (a.documenttype, a.documentid)), MIN(a.amount)
      INTO v_allocated, v_count, v_distinct, v_minamount
    FROM   jsonb_to_recordset(COALESCE(p_allocations, '[]'::jsonb))
           AS a(documenttype text, documentid integer, amount numeric);
    IF v_distinct <> v_count THEN
        RAISE EXCEPTION 'The same bill appears more than once in this payment.';
    END IF;
    IF v_count > 0 AND COALESCE(v_minamount, 0) <= 0 THEN
        RAISE EXCEPTION 'Every allocation must be greater than 0.';
    END IF;
    -- 449: what is not applied is kept as the supplier's credit.
    IF ROUND(v_allocated, 2) > ROUND(p_amount, 2) THEN
        RAISE EXCEPTION 'Applied total (%) is more than the payment amount (%).',
              ROUND(v_allocated, 2), ROUND(p_amount, 2);
    END IF;
    IF p_cashaccountid IS NOT NULL
       AND NOT EXISTS (SELECT 1 FROM genericcashaccounts a
                       WHERE a.genericcashaccountid = p_cashaccountid AND a.farmid = p_farmid) THEN
        RAISE EXCEPTION 'Cash account does not belong to this company.';
    END IF;

    INSERT INTO genericsupplierpayments
        (farmid, genericsupplierid, paymentdate, amount, paymentmethod,
         genericcashaccountid, status, notes, referenceno, sourcetype,
         createdby, approvedby, approvedat, createdat)
    VALUES
        (p_farmid, p_supplierid, v_date, p_amount, COALESCE(p_paymentmethod, 'Cash'),
         p_cashaccountid, 'Approved', p_notes, p_reference, COALESCE(p_sourcetype, 'SupplierBalances'),
         p_createdby, p_createdby, (now() at time zone 'utc'), (now() at time zone 'utc'))
    RETURNING genericsupplierpaymentid INTO v_paymentid;

    FOR v_row IN
        SELECT a.documenttype, a.documentid, a.amount, d.balance AS docbalance, d.label
        FROM   jsonb_to_recordset(COALESCE(p_allocations, '[]'::jsonb))
               AS a(documenttype text, documentid integer, amount numeric)
        JOIN   fngenericpayables(p_farmid) d
               ON d.documenttype = a.documenttype AND d.documentid = a.documentid
        WHERE  d.supplierid = p_supplierid
        ORDER  BY d.docdate, a.documentid
    LOOP
        IF v_row.amount > v_row.docbalance + 0.005 THEN
            RAISE EXCEPTION 'Cannot apply % to % -- its balance is only %.',
                  ROUND(v_row.amount, 2), v_row.label, ROUND(v_row.docbalance, 2);
        END IF;
        PERFORM public.fngenericpayable_addpaid(p_farmid, v_row.documenttype, v_row.documentid, v_row.amount);
        INSERT INTO supplierpaymentallocation
            (farmid, module, paymentid, documenttype, documentid, amountapplied,
             documentbalancebefore, documentbalanceafter, status, createdby, createdat)
        VALUES
            (p_farmid, 'generic', v_paymentid, v_row.documenttype, v_row.documentid,
             v_row.amount, v_row.docbalance, v_row.docbalance - v_row.amount, 'Posted', p_createdby, v_date);
        v_matched := v_matched + 1;
    END LOOP;
    IF v_matched <> v_count THEN
        RAISE EXCEPTION '% of the selected bills do not belong to this supplier or company.', v_count - v_matched;
    END IF;

    -- The supplier owes less by what was applied; the rest is their credit.
    PERFORM public.fngenericsupplier_ledgermove(p_farmid, p_supplierid, -v_allocated, 'PaymentDebit',
        COALESCE(p_notes, 'Supplier payment'), p_createdby, v_paymentid);

    IF p_cashaccountid IS NOT NULL THEN
        PERFORM public.fngenericcash_move(p_farmid, p_cashaccountid, -p_amount, v_date, 'SupplierPayment', v_paymentid,
            COALESCE(p_notes, 'Supplier payment'), p_createdby);
    END IF;
    RETURN v_paymentid;
END;
$f$;

-- spgenericsupplierpayment_reverse (248): refused while its credit is applied
-- or refunded; gives back what IT applied, on the documents and the ledger.
CREATE OR REPLACE FUNCTION public.spgenericsupplierpayment_reverse(p_farmid text, p_paymentid integer,
    p_reason text DEFAULT NULL::text, p_reversedby text DEFAULT NULL::text)
RETURNS integer
LANGUAGE plpgsql
AS $f$
DECLARE
    v_now      timestamp := (now() at time zone 'utc');
    v_sp       genericsupplierpayments%ROWTYPE;
    v_own      numeric(14,2) := 0;
    v_count    integer := 0;
    v_row      record;
BEGIN
    SELECT * INTO v_sp FROM genericsupplierpayments sp
    WHERE  sp.genericsupplierpaymentid = p_paymentid AND sp.farmid = p_farmid FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Payment not found for this company.';
    END IF;
    IF COALESCE(v_sp.status, '') = 'Reversed' THEN
        RAISE EXCEPTION 'Only a posted payment can be reversed (this one is Reversed).';
    END IF;
    IF COALESCE(btrim(p_reason), '') = '' THEN
        RAISE EXCEPTION 'A reason is required to reverse a payment.';
    END IF;
    IF public.fngenericsupplier_iscreditkind(v_sp.sourcetype) THEN
        RETURN public.spgenericsuppliercredit_reverse(p_farmid, p_paymentid, p_reason, p_reversedby);
    END IF;
    IF EXISTS (SELECT 1 FROM supplierpaymentallocation sa WHERE sa.farmid = p_farmid AND sa.module = 'generic'
               AND sa.paymentid = p_paymentid AND sa.status = 'Posted' AND sa.fromcredit) THEN
        RAISE EXCEPTION 'Part of this payment''s credit has been applied. Undo those applications on Supplier Credits first.';
    END IF;
    IF EXISTS (SELECT 1 FROM genericsupplierrefundlines rl JOIN genericsupplierrefunds r ON r.refundid = rl.refundid
               WHERE rl.farmid = p_farmid AND rl.genericsupplierpaymentid = p_paymentid AND r.status = 'Posted') THEN
        RAISE EXCEPTION 'Part of this payment''s credit has been refunded. Reverse the refund on Supplier Credits first.';
    END IF;
    FOR v_row IN
        SELECT sa.allocationid, sa.documenttype, sa.documentid, sa.amountapplied
        FROM   supplierpaymentallocation sa
        WHERE  sa.farmid = p_farmid AND sa.module = 'generic'
          AND  sa.paymentid = p_paymentid AND sa.status = 'Posted' AND NOT sa.fromcredit
    LOOP
        PERFORM public.fngenericpayable_addpaid(p_farmid, v_row.documenttype, v_row.documentid, -v_row.amountapplied);
        UPDATE supplierpaymentallocation SET status = 'Reversed', reversedby = p_reversedby, reversedat = v_now,
               reversalreason = p_reason
        WHERE  allocationid = v_row.allocationid;
        v_own := v_own + v_row.amountapplied;
        v_count := v_count + 1;
    END LOOP;
    -- An old Draft/Approve payment (no sourcetype) took its whole amount off the ledger.
    IF v_sp.sourcetype IS NULL THEN v_own := v_sp.amount; END IF;
    PERFORM public.fngenericsupplier_ledgermove(p_farmid, v_sp.genericsupplierid, v_own, 'PaymentReversal',
        'Reversal of payment #' || p_paymentid::text || ': ' || p_reason, p_reversedby, p_paymentid);
    IF v_sp.genericcashaccountid IS NOT NULL THEN
        PERFORM public.fngenericcash_move(p_farmid, v_sp.genericcashaccountid, v_sp.amount, v_now, 'SupplierPayment',
            p_paymentid, 'Reversal of payment #' || p_paymentid::text, p_reversedby);
    END IF;
    UPDATE genericsupplierpayments
    SET    status = 'Reversed', reversedby = p_reversedby, reversedat = v_now,
           reversalreason = p_reason, updatedat = v_now
    WHERE  genericsupplierpaymentid = p_paymentid AND farmid = p_farmid;
    RETURN v_count;
END;
$f$;

-- ------------------------------------------- the old credits list, moved -----
DO $mv$
DECLARE c record; v_id integer;
BEGIN
    FOR c IN SELECT * FROM genericsuppliercredits
             WHERE COALESCE("Status", '') <> 'Migrated' AND COALESCE("RemainingBalance", 0) > 0
               AND "GenericSupplierId" IS NOT NULL
    LOOP
        INSERT INTO genericsupplierpayments
            (farmid, genericsupplierid, paymentdate, amount, paymentmethod, genericcashaccountid, notes,
             sourcetype, status, createdby, approvedby, approvedat, createdat)
        VALUES (c."FarmId", c."GenericSupplierId", COALESCE(c."CreditDate", now() AT TIME ZONE 'utc'),
                round(c."RemainingBalance", 2), 'NonCash', NULL,
                COALESCE(NULLIF(btrim(c."Notes"), ''), c."CreditType"::text) || ' (moved from the old credits list)',
                CASE c."CreditType" WHEN 'CreditNote' THEN 'SupplierCreditNote' ELSE 'SupplierManualCredit' END,
                'Approved', c."CreatedBy", c."CreatedBy", now() AT TIME ZONE 'utc', now() AT TIME ZONE 'utc')
        RETURNING genericsupplierpaymentid INTO v_id;
        UPDATE genericsuppliercredits SET "Status" = 'Migrated', "ReferenceType" = 'GenericSupplierPayment', "ReferenceId" = v_id
        WHERE  "GenericSupplierCreditId" = c."GenericSupplierCreditId";
    END LOOP;
END
$mv$;

-- ---- Cash Flow (448 body + 449 arms)
CREATE OR REPLACE FUNCTION public.spgenericcashflow_rows(p_farmid text, p_fromdate timestamp without time zone DEFAULT NULL::timestamp without time zone, p_todate timestamp without time zone DEFAULT NULL::timestamp without time zone)
 RETURNS TABLE(rowsource text, offledger boolean, sourcerowid integer, cashaccountid integer, accountname text, transactiondate timestamp without time zone, transactiontype text, sourcetype text, sourceid integer, istransfer boolean, amount numeric, description text, flowgroup text, createdat timestamp without time zone)
 LANGUAGE plpgsql
 STABLE
AS $function$
DECLARE
    v_from timestamp := COALESCE(p_fromdate, '-infinity'::timestamp);
    v_to   timestamp := COALESCE(p_todate,   'infinity'::timestamp);
BEGIN
    -- ---- 1. customer receipts ---------------------------------------------------
    -- Money received from customers against sales/invoices.
    RETURN QUERY
    SELECT 'Receipt'::text,
           FALSE,
           p.genericcustomerpaymentid,
           p.genericcashaccountid,
           NULL::text,
           p.paymentdate::timestamp,
           'CashIn'::text,
           'CustomerPayment'::text,
           p.genericcustomerpaymentid,
           FALSE,
           COALESCE(p.amount, 0)::numeric,
           COALESCE(
               NULLIF(btrim(p.notes), ''),
               NULLIF(btrim(p.referenceno), ''),
               'Customer payment #' || p.genericcustomerpaymentid::text
           )::text,
           'OperatingIn'::text,
           p.createdat::timestamp
    FROM   genericcustomerpayments p
    WHERE  lower(p.farmid::text) = lower(p_farmid)
      AND  COALESCE(p.amount, 0) > 0
      AND  COALESCE(p.status, 'Posted') <> 'Reversed'
      AND  p.paymentdate::timestamp >= v_from
      AND  p.paymentdate::timestamp <= v_to;

    -- ---- 2. sale residuals (part paid at counter) -------------------------------
    -- A sale entered as already paid or partially paid. The residual is the
    -- amount paid that did NOT create a genericcustomerpayments row.
    RETURN QUERY
    SELECT 'SaleResidual'::text,
           FALSE,
           s.genericsaleid,
           s.genericcashaccountid,
           NULL::text,
           s.saledate::timestamp,
           'CashIn'::text,
           'Sale'::text,
           s.genericsaleid,
           FALSE,
           v.residual,
           ('Sale #' || s.genericsaleid::text ||
            COALESCE(' - ' || NULLIF(btrim(c.customername), ''), ''))::text,
           'OperatingIn'::text,
           s.createdat::timestamp
    FROM   genericsales s
    LEFT   JOIN genericcustomers c ON c.genericcustomerid = s.genericcustomerid
    CROSS  JOIN LATERAL (
        SELECT ROUND(
                   CASE WHEN COALESCE(s.paymentstatus, '') = 'Paid'
                        THEN COALESCE(s.totalamount, 0)
                        ELSE LEAST(GREATEST(COALESCE(s.amountpaid, 0), 0),
                                   COALESCE(s.totalamount, 0))
                   END
                 - COALESCE((SELECT SUM(pp.amount)
                             FROM   genericcustomerpayments pp
                             WHERE  pp.linkedsaleid = s.genericsaleid
                               AND  lower(pp.farmid::text) = lower(p_farmid)
                               AND  COALESCE(pp.status, 'Posted') <> 'Reversed'), 0)
               , 2) AS residual
    ) v
    WHERE  lower(s.farmid::text) = lower(p_farmid)
      AND  COALESCE(s.isdeleted, FALSE) = FALSE
      AND  v.residual > 0
      AND  s.saledate::timestamp >= v_from
      AND  s.saledate::timestamp <= v_to;

    -- ---- 3. expenses (all operational spending) ---------------------------------
    -- Every kind of spending: supplier payments, staff payments, recurring,
    -- purchases, etc. all INSERT INTO genericexpenses. NonCash (internal use)
    -- is excluded — that records stock leaving without money moving.
    RETURN QUERY
    SELECT 'Expense'::text,
           FALSE,
           e.genericexpenseid,
           e.genericcashaccountid,
           NULL::text,
           e.expensedate::timestamp,
           'CashOut'::text,
           'Expense'::text,
           e.genericexpenseid,
           FALSE,
           -- 449: the part paid from supplier credit left with the advance
           -(COALESCE(e.amount, 0)
             - COALESCE((SELECT SUM(sa.amountapplied) FROM supplierpaymentallocation sa
                         WHERE sa.module = 'generic' AND sa.documenttype = 'Expense'
                           AND sa.documentid = e.genericexpenseid AND sa.status = 'Posted'
                           AND sa.fromcredit), 0))::numeric,
           COALESCE(NULLIF(btrim(e.description), ''), 'Expense')::text,
           'OperatingOut'::text,
           e.createdat::timestamp
    FROM   genericexpenses e
    WHERE  lower(e.farmid::text) = lower(p_farmid)
      AND  COALESCE(e.amount, 0) > 0
      AND  COALESCE(e.isdeleted, FALSE) = FALSE
      AND  COALESCE(e.paymentmethod, '') <> 'NonCash'
      AND  COALESCE(e.status, 'Approved') = 'Approved'   -- 448
      AND  e.expensedate::timestamp >= v_from
      AND  e.expensedate::timestamp <= v_to;

    -- ---- 4. payroll (only paid runs WITHOUT a linked expense) --------------------
    -- If payroll creates a linked expense, the expense leg already counts it.
    -- Only add standalone paid payroll runs that have no genericexpenseid.
    IF to_regclass('public.genericpayrollruns') IS NOT NULL THEN
        RETURN QUERY EXECUTE format($sql$
            SELECT 'Payroll'::text,
                   FALSE,
                   pr.genericpayrollrunid,
                   pr.genericcashaccountid,
                   NULL::text,
                   COALESCE(pr.paidat, pr.createdat)::timestamp,
                   'CashOut'::text,
                   'Payroll'::text,
                   pr.genericpayrollrunid,
                   FALSE,
                   -COALESCE(pr.totalnetpay, 0)::numeric,
                   COALESCE(
                       NULLIF(btrim(pr.notes), ''),
                       'Payroll ' || to_char(pr.periodstart, 'DD Mon') || ' - ' || to_char(pr.periodend, 'DD Mon YYYY')
                   )::text,
                   'OperatingOut'::text,
                   pr.createdat::timestamp
            FROM   genericpayrollruns pr
            WHERE  lower(pr.farmid::text) = lower($1)
              AND  pr.status = 'Paid'
              AND  COALESCE(pr.totalnetpay, 0) > 0
              AND  COALESCE(pr.isdeleted, FALSE) = FALSE
              AND  NOT EXISTS (
                       SELECT 1 FROM genericexpenses e
                       WHERE  e.sourcetype = 'Payroll'
                         AND  e.sourceid = pr.genericpayrollrunid
                         AND  lower(e.farmid::text) = lower($1)
                         AND  COALESCE(e.isdeleted, FALSE) = FALSE
                   )
              AND  COALESCE(pr.paidat, pr.createdat)::timestamp >= $2
              AND  COALESCE(pr.paidat, pr.createdat)::timestamp <= $3
        $sql$)
        USING p_farmid, v_from, v_to;
    END IF;

    -- ---- 5. owner contributions (financing in) ----------------------------------
    RETURN QUERY
    SELECT 'OwnerContribution'::text,
           FALSE,
           oc.genericownerentryid,
           oc.genericcashaccountid,
           NULL::text,
           oc.entrydate::timestamp,
           'CashIn'::text,
           'OwnerInjection'::text,
           oc.genericownerentryid,
           FALSE,
           COALESCE(oc.amount, 0)::numeric,
           COALESCE(
               NULLIF(btrim(oc.notes), ''),
               'Owner contribution' || COALESCE(' - ' || NULLIF(btrim(oc.ownername), ''), '')
           )::text,
           'FinancingIn'::text,
           oc.createdat::timestamp
    FROM   genericownercontributiondraws oc
    WHERE  lower(oc.farmid::text) = lower(p_farmid)
      AND  oc.entrytype = 'Contribution'
      AND  oc.status = 'Posted'
      AND  COALESCE(oc.amount, 0) > 0
      AND  oc.entrydate::timestamp >= v_from
      AND  oc.entrydate::timestamp <= v_to;

    -- ---- 6. owner draws (financing out) -----------------------------------------
    RETURN QUERY
    SELECT 'OwnerDraw'::text,
           FALSE,
           oc.genericownerentryid,
           oc.genericcashaccountid,
           NULL::text,
           oc.entrydate::timestamp,
           'CashOut'::text,
           'Withdrawal'::text,
           oc.genericownerentryid,
           FALSE,
           -COALESCE(oc.amount, 0)::numeric,
           COALESCE(
               NULLIF(btrim(oc.notes), ''),
               'Owner draw' || COALESCE(' - ' || NULLIF(btrim(oc.ownername), ''), '')
           )::text,
           'FinancingOut'::text,
           oc.createdat::timestamp
    FROM   genericownercontributiondraws oc
    WHERE  lower(oc.farmid::text) = lower(p_farmid)
      AND  oc.entrytype = 'Draw'
      AND  oc.status = 'Posted'
      AND  COALESCE(oc.amount, 0) > 0
      AND  oc.entrydate::timestamp >= v_from
      AND  oc.entrydate::timestamp <= v_to;

    -- ---- 7. loans received (financing in) ---------------------------------------
    IF to_regclass('public."GenericLoans"') IS NOT NULL THEN
        RETURN QUERY
        SELECT 'LoanReceived'::text,
               FALSE,
               l."GenericLoanId",
               l."GenericCashAccountId",
               NULL::text,
               COALESCE(l."LoanDate", l."CreatedAt")::timestamp,
               'CashIn'::text,
               'LoanReceived'::text,
               l."GenericLoanId",
               FALSE,
               COALESCE(l."AmountReceived", 0)::numeric,
               COALESCE(
                   NULLIF(btrim(l."Notes"), ''),
                   'Loan from ' || COALESCE(NULLIF(btrim(l."LenderName"), ''), 'unknown lender')
               )::text,
               'FinancingIn'::text,
               l."CreatedAt"::timestamp
        FROM   "GenericLoans" l
        WHERE  l."FarmId" = p_farmid
          AND  l."Status" IN ('Active', 'Paid')
          AND  COALESCE(l."AmountReceived", 0) > 0
          AND  COALESCE(l."LoanDate", l."CreatedAt")::timestamp >= v_from
          AND  COALESCE(l."LoanDate", l."CreatedAt")::timestamp <= v_to;
    END IF;

    -- ---- 8. loan repayments (financing out) -------------------------------------
    IF to_regclass('public."GenericLoanPayments"') IS NOT NULL THEN
        RETURN QUERY
        SELECT 'LoanRepayment'::text,
               FALSE,
               lp."GenericLoanPaymentId",
               lp."GenericCashAccountId",
               NULL::text,
               lp."PaymentDate"::timestamp,
               'CashOut'::text,
               'LoanRepayment'::text,
               lp."GenericLoanPaymentId",
               FALSE,
               -COALESCE(lp."TotalPayment", 0)::numeric,
               COALESCE(
                   NULLIF(btrim(lp."Notes"), ''),
                   'Loan repayment #' || lp."GenericLoanPaymentId"::text
               )::text,
               'FinancingOut'::text,
               lp."CreatedAt"::timestamp
        FROM   "GenericLoanPayments" lp
        WHERE  lp."FarmId" = p_farmid
          AND  COALESCE(lp."IsReversed", FALSE) = FALSE
          AND  COALESCE(lp."TotalPayment", 0) > 0
          AND  lp."PaymentDate"::timestamp >= v_from
          AND  lp."PaymentDate"::timestamp <= v_to;
    END IF;

    -- ---- 449a. supplier advances (the part of a payment not applied) -----------
    RETURN QUERY
    SELECT 'SupplierAdvance'::text,
           FALSE,
           sp.genericsupplierpaymentid,
           sp.genericcashaccountid,
           NULL::text,
           sp.paymentdate::timestamp,
           'CashOut'::text,
           'SupplierPayment'::text,
           sp.genericsupplierpaymentid,
           FALSE,
           -(sp.amount - COALESCE((SELECT SUM(sa.amountapplied) FROM supplierpaymentallocation sa
                                   WHERE sa.farmid = sp.farmid AND sa.module = 'generic'
                                     AND sa.paymentid = sp.genericsupplierpaymentid
                                     AND sa.status = 'Posted' AND NOT sa.fromcredit), 0))::numeric,
           ('Supplier advance SP-' || lpad(sp.genericsupplierpaymentid::text, 5, '0'))::text,
           'OperatingOut'::text,
           sp.createdat::timestamp
    FROM   genericsupplierpayments sp
    WHERE  lower(sp.farmid::text) = lower(p_farmid)
      AND  public.fngenericsupplierpayment_isposted(sp.status, sp.sourcetype)
      AND  NOT public.fngenericsupplier_iscreditkind(sp.sourcetype)
      AND  sp.genericcashaccountid IS NOT NULL
      AND  sp.paymentdate::timestamp >= v_from
      AND  sp.paymentdate::timestamp <= v_to
      AND  sp.amount - COALESCE((SELECT SUM(sa.amountapplied) FROM supplierpaymentallocation sa
                                 WHERE sa.farmid = sp.farmid AND sa.module = 'generic'
                                   AND sa.paymentid = sp.genericsupplierpaymentid
                                   AND sa.status = 'Posted' AND NOT sa.fromcredit), 0) > 0;

    -- ---- 449b. supplier refunds (money back from a supplier) -------------------
    RETURN QUERY
    SELECT 'SupplierRefund'::text,
           FALSE,
           r.refundid,
           r.genericcashaccountid,
           NULL::text,
           r.refunddate::timestamp,
           'CashIn'::text,
           'GenericSupplierRefund'::text,
           r.refundid,
           FALSE,
           r.amount::numeric,
           ('Supplier refund ' || r.refundnumber)::text,
           'OperatingIn'::text,
           r.createdat::timestamp
    FROM   genericsupplierrefunds r
    WHERE  lower(r.farmid::text) = lower(p_farmid)
      AND  r.status = 'Posted'
      AND  r.refunddate::timestamp >= v_from
      AND  r.refunddate::timestamp <= v_to;

    -- ---- 9. legacy cash adjustments (shared table) ------------------------------
    -- The cashadjustment table is used by all rails for capital events before
    -- dedicated owner-money and loan tables existed. Include any that belong
    -- to this farm.
    IF to_regclass('public.cashadjustment') IS NOT NULL OR
       to_regclass('public.cashadjustments') IS NOT NULL THEN

        RETURN QUERY EXECUTE format($sql$
            SELECT 'Adjustment'::text,
                   FALSE,
                   ca.adjustmentid,
                   NULL::integer,
                   NULL::text,
                   ca.adjustmentdate,
                   CASE WHEN ca.amount >= 0 THEN 'CashIn' ELSE 'CashOut' END::text,
                   COALESCE(NULLIF(btrim(ca.adjustmenttype), ''), 'Adjustment')::text,
                   ca.adjustmentid,
                   FALSE,
                   ca.amount::numeric,
                   COALESCE(NULLIF(btrim(ca.description), ''), ca.adjustmenttype)::text,
                   CASE WHEN ca.amount >= 0 THEN 'FinancingIn' ELSE 'FinancingOut' END::text,
                   NULL::timestamp
            FROM   %s ca
            WHERE  lower(ca.farmid::text) = lower($1)
              AND  ca.amount <> 0
              AND  ca.adjustmentdate >= $2
              AND  ca.adjustmentdate <= $3
        $sql$, COALESCE(to_regclass('public.cashadjustment')::text,
                        to_regclass('public.cashadjustments')::text))
        USING p_farmid, v_from, v_to;
    END IF;
END;
$function$;

CREATE OR REPLACE FUNCTION public.spgenericsupplierpayment_history(p_farmid text, p_supplierid integer DEFAULT NULL::integer, p_documenttype text DEFAULT NULL::text, p_documentid integer DEFAULT NULL::integer, p_from date DEFAULT NULL::date, p_to date DEFAULT NULL::date)
 RETURNS TABLE(paymentid integer, partyid integer, partyname text, paymentdate timestamp without time zone, totalamount numeric, paymentmethod text, reference text, notes text, sourcetype text, status text, allocationcount integer, cashaccountid integer, createdby text, reversedby text, reversedat timestamp without time zone, reversalreason text, createdat timestamp without time zone)
 LANGUAGE sql
 STABLE
AS $function$
    SELECT sp.genericsupplierpaymentid, sp.genericsupplierid, s.suppliername::text,
           sp.paymentdate, sp.amount, sp.paymentmethod::text, sp.referenceno,
           sp.notes::text, sp.sourcetype,
           (CASE WHEN COALESCE(sp.status, '') = 'Reversed' THEN 'Reversed' ELSE 'Posted' END)::text,
           (SELECT COUNT(*)::integer FROM supplierpaymentallocation sa
             WHERE sa.farmid = sp.farmid AND sa.module = 'generic'
               AND sa.paymentid = sp.genericsupplierpaymentid),
           sp.genericcashaccountid, sp.createdby, sp.reversedby, sp.reversedat, sp.reversalreason
           , sp.createdat   -- 304: the entry time
    FROM   genericsupplierpayments sp
    LEFT   JOIN genericsuppliers s ON s.genericsupplierid = sp.genericsupplierid
                                  AND s.farmid = sp.farmid
    WHERE  sp.farmid = p_farmid
      AND  NOT public.fngenericsupplier_iscreditkind(sp.sourcetype)   -- 449
      AND  (p_supplierid IS NULL OR sp.genericsupplierid = p_supplierid)
      AND  (p_from IS NULL OR sp.paymentdate::date >= p_from)
      AND  (p_to   IS NULL OR sp.paymentdate::date <= p_to)
      AND  (p_documentid IS NULL OR EXISTS (
               SELECT 1 FROM supplierpaymentallocation sa
               WHERE sa.farmid = sp.farmid AND sa.module = 'generic'
                 AND sa.paymentid = sp.genericsupplierpaymentid
                 AND sa.documentid = p_documentid
                 AND (p_documenttype IS NULL OR sa.documenttype = p_documenttype)))
    ORDER  BY sp.paymentdate DESC, sp.genericsupplierpaymentid DESC;
$function$;

CREATE OR REPLACE FUNCTION public.spgenericsupplierbalancesummary(p_farmid text)
 RETURNS TABLE(totalbalance numeric, partycount integer, overduebalance numeric, paymentstoday numeric, largestbalance numeric, largestbalanceparty text)
 LANGUAGE sql
 STABLE
AS $function$
    WITH b AS (SELECT * FROM spgenericsupplierbalances(p_farmid))
    SELECT ROUND(COALESCE(SUM(b.totalbalance), 0), 2),
           COUNT(*)::integer,
           ROUND(COALESCE(SUM(b.overdueamount), 0), 2),
           ROUND(COALESCE((SELECT SUM(sp.amount) FROM genericsupplierpayments sp
                            WHERE sp.farmid = p_farmid
                              AND sp.paymentdate::date = CURRENT_DATE
                              AND COALESCE(sp.status, '') <> 'Reversed'
                              AND NOT public.fngenericsupplier_iscreditkind(sp.sourcetype)), 0), 2),
           ROUND(COALESCE(MAX(b.totalbalance), 0), 2),
           (SELECT b2.partyname FROM b b2 ORDER BY b2.totalbalance DESC LIMIT 1)
    FROM   b;
$function$;

CREATE OR REPLACE FUNCTION public.spgenericsupplierstatement(p_farmid text, p_supplierid integer, p_from date DEFAULT NULL::date, p_to date DEFAULT NULL::date)
 RETURNS TABLE(entrydate date, entrytype text, reference text, description text, debit numeric, credit numeric, runningbalance numeric, documenttype text, documentid integer, sortkey integer)
 LANGUAGE sql
 STABLE
AS $function$
    -- The supplier statement is the mirror of the customer one: a bill CREDITS
    -- the supplier (increases what is owed) and a payment DEBITS them. The
    -- running balance is what we still owe.
    WITH ev AS (
        SELECT d.docdate AS entrydate, d.documenttype AS entrytype, d.reference,
               d.label AS description, 0::numeric AS debit, d.totalcost AS credit,
               d.documenttype, d.documentid, 1 AS sortkey
        FROM   fngenericpayables(p_farmid) d
        WHERE  d.supplierid = p_supplierid

        UNION ALL

        SELECT sp.paymentdate::date, 'Payment'::text,
               COALESCE(sp.referenceno, 'PAY-' || sp.genericsupplierpaymentid::text),
               COALESCE(sp.notes, 'Supplier payment')::text,
               sp.amount, 0::numeric,
               'Payment'::text, sp.genericsupplierpaymentid, 2
        FROM   genericsupplierpayments sp
        WHERE  sp.farmid = p_farmid AND sp.genericsupplierid = p_supplierid
          AND  COALESCE(sp.status, '') <> 'Reversed'
          AND  NOT public.fngenericsupplier_iscreditkind(sp.sourcetype)

        UNION ALL

        -- 449: a credit added by hand lowers what is owed, like a payment.
        SELECT sp.paymentdate::date, 'Credit'::text,
               COALESCE(sp.referenceno, 'SP-' || lpad(sp.genericsupplierpaymentid::text, 5, '0')),
               COALESCE(sp.notes, 'Supplier credit')::text,
               sp.amount, 0::numeric,
               'Credit'::text, sp.genericsupplierpaymentid, 3
        FROM   genericsupplierpayments sp
        WHERE  sp.farmid = p_farmid AND sp.genericsupplierid = p_supplierid
          AND  sp.status = 'Approved' AND public.fngenericsupplier_iscreditkind(sp.sourcetype)

        UNION ALL

        -- 449: money the supplier sent back out of credit.
        SELECT r.refunddate, 'Refund'::text, r.refundnumber, r.reason, 0::numeric, r.amount,
               'Refund'::text, r.refundid, 4
        FROM   genericsupplierrefunds r
        WHERE  r.farmid = p_farmid AND r.supplierid = p_supplierid AND r.status = 'Posted'
    )
    SELECT ev.entrydate, ev.entrytype, ev.reference, ev.description,
           ROUND(ev.debit, 2), ROUND(ev.credit, 2),
           ROUND(SUM(ev.credit - ev.debit) OVER (
                 ORDER BY ev.entrydate, ev.sortkey, ev.documentid
                 ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW), 2),
           ev.documenttype, ev.documentid, ev.sortkey
    FROM   ev
    WHERE  (p_from IS NULL OR ev.entrydate >= p_from)
      AND  (p_to   IS NULL OR ev.entrydate <= p_to)
    ORDER  BY ev.entrydate, ev.sortkey, ev.documentid;
$function$;
