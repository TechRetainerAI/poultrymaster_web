        EXECUTE 'GRANT EXECUTE ON FUNCTION public.sppoultryfinance_seeddefaults(text) TO "Techretainer"';
        EXECUTE 'GRANT EXECUTE ON FUNCTION public.sppoultrycompany_getprofile(text) TO "Techretainer"';
        EXECUTE 'GRANT EXECUTE ON FUNCTION public.sppoultrycompany_setup(text, text, text, text, text, text, text, integer, integer, text, text, text, text, text) TO "Techretainer"';
        EXECUTE 'GRANT EXECUTE ON FUNCTION public.sppoultrycompany_updateprofile(text, text, text, text, text, text, text, integer, integer, text, text, text, text, text) TO "Techretainer"';
        RAISE NOTICE '212: granted table + sppoultrycompany_* to Techretainer.';
    END IF;
END
$grant$;

