-- =============================================================================
-- 422_WaterCustomerCredit.postgres.sql   (Water credits programme W1; requires 421)
--
-- Purpose
-- -------
-- Water had no customer credit at all: a payment had to equal the sales it
-- paid, there was no customer advance, no opening credit, no credit note and no
-- refund.  This brings poultry's 351/363/367 to Water, reshaped for how Water
-- counts money.
--
-- The model
-- ---------
--  * A CREDIT is a waterpayments row with NO sale (watersaleid NULL), kind in
--    sourcetype:
--      Deposit        customer advance -- money in NOW, to a chosen account
--                     (CashIn 'WaterCustomerAdvance'); user decision 2026-11-12
--      Overpayment    what a customer payment left after its sales -- same
--                     money as the payment, so collected the same way (closing)
--      OpeningCredit  credit held before the system -- no money
--      CreditNote     an allowance -- no money; NEGATIVE revenue on the P&L
--  * APPLYING credit to a sale is an allocation only (customerpaymentallocation
--    from the credit row to the sale) -- no payment row on the sale, so Daily
--    Closing and Cash Flow can never read applied credit as cash.  A sale's
--    amountpaid = posted payments on it + credit applied to it.
--  * A REFUND (watercustomerrefunds + lines naming the credit it drew from) is
--    real money out of an account (CashOut 'WaterCustomerRefund'); reversing it
--    keeps the refund (Reversed) and puts the money back (CashIn).
--  * Available credit = credit rows - applications - posted refunds.
--
-- Readers patched (live bodies, 2026-11-12, after 421)
-- ----------------------------------------------------
--   spwatersale_recompute, fnwatersale_owedasof, spwaterpayment_record
--   spwatercustomerpayment_record  (remainder -> Overpayment credit)
--   spwatercustomerpayment_reverse (hand-made credit refused; refunded refused;
--                                   sales its credit paid are owed again)
--   spwatersale_delete / _cancel, spwaterdriverreturn_reverse (release credit)
--   fnwaterdailyclosing_livetotals (collections skip advances / no-cash credit)
--   spwatercashflow_rows / _detail (no-cash credit is not a receipt; applied
--                                   credit is not till money; refund arms)
--   spwatercustomerstatement       (applied credit has its own line)
--   spwatercustomerbalancesummary, spwatercustomerpayment_history
--   spwaterreport_periodpnl, _pllines, _plrevenuedetail (credit notes)
--
-- Not changed on purpose: spwaterreport_plsummary keeps its columns (its
-- totalrevenue comes from periodpnl, so it already nets credit notes).
--
-- Deploy order: this migration, then the Farm API, then the web app.
-- =============================================================================
\set ON_ERROR_STOP on

BEGIN;

-- ============================================================ 1. schema =====
-- A credit is a waterpayments row with NO sale.  Four kinds:
--   Deposit        customer advance: real money, posted to a cash account now
--   Overpayment    what a customer payment left over after its sales: same
--                  money as the payment it came with (collected at closing)
--   OpeningCredit  credit the customer already held before the system: no money
--   CreditNote     an allowance given: no money; negative revenue on the P&L
ALTER TABLE public.waterpayments ALTER COLUMN watersaleid DROP NOT NULL;
ALTER TABLE public.waterpayments DROP CONSTRAINT IF EXISTS ck_waterpayments_saleorcredit;
ALTER TABLE public.waterpayments ADD CONSTRAINT ck_waterpayments_saleorcredit CHECK (
       watersaleid IS NOT NULL
    OR (sourcetype IN ('Deposit', 'Overpayment', 'OpeningCredit', 'CreditNote') AND watercustomerid IS NOT NULL));

CREATE TABLE IF NOT EXISTS public.watercustomerrefunds (
    refundid            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmid              text          NOT NULL,
    refundnumber        text          NOT NULL,
    watercustomerid     integer       NOT NULL,
    amount              numeric(14,2) NOT NULL CHECK (amount > 0),
    refunddate          date          NOT NULL,
    watercashaccountid  integer       NOT NULL,
    paymentmethod       text,
    reason              text          NOT NULL,
    status              text          NOT NULL DEFAULT 'Posted' CHECK (status IN ('Posted', 'Reversed')),
    createdby           text,
    createdat           timestamp     NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    reversedby          text,
    reversedat          timestamp,
    reversalreason      text,
    reversaldate        date
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_watercustomerrefunds_number ON public.watercustomerrefunds (farmid, refundnumber);
CREATE INDEX IF NOT EXISTS ix_watercustomerrefunds_customer ON public.watercustomerrefunds (farmid, watercustomerid);

-- Which credit each refund drew from (one refund can take from several).
CREATE TABLE IF NOT EXISTS public.watercustomerrefundlines (
    refundlineid    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    refundid        integer       NOT NULL REFERENCES public.watercustomerrefunds (refundid),
    farmid          text          NOT NULL,
    waterpaymentid  integer       NOT NULL,
    amount          numeric(14,2) NOT NULL CHECK (amount > 0)
);
CREATE INDEX IF NOT EXISTS ix_watercustomerrefundlines_payment ON public.watercustomerrefundlines (farmid, waterpaymentid);

-- ======================================================= 2. credit basics ====
CREATE OR REPLACE FUNCTION public.fnwater_iscreditkind(p_kind text)
RETURNS boolean LANGUAGE sql IMMUTABLE AS $f$
    SELECT COALESCE(p_kind, '') IN ('Deposit', 'Overpayment', 'OpeningCredit', 'CreditNote');
$f$;

-- Credit that is not money the business received.
CREATE OR REPLACE FUNCTION public.fnwater_isnocashcredit(p_kind text)
RETURNS boolean LANGUAGE sql IMMUTABLE AS $f$
    SELECT COALESCE(p_kind, '') IN ('OpeningCredit', 'CreditNote');
$f$;

-- Credit added by hand on the Customer Credits page (reversed there, not as a payment).
CREATE OR REPLACE FUNCTION public.fnwater_ismanualcredit(p_kind text)
RETURNS boolean LANGUAGE sql IMMUTABLE AS $f$
    SELECT COALESCE(p_kind, '') IN ('Deposit', 'OpeningCredit', 'CreditNote');
$f$;

-- What is left of one credit row: its amount less what was applied to sales
-- and what was refunded.  0 for anything that is not a posted credit row.
CREATE OR REPLACE FUNCTION public.fnwaterpayment_unapplied(p_farmid text, p_waterpaymentid integer)
RETURNS numeric LANGUAGE sql STABLE AS $f$
    SELECT COALESCE((
        SELECT GREATEST(p.amount
               - COALESCE((SELECT SUM(ca.amountapplied) FROM customerpaymentallocation ca
                           WHERE ca.farmid = p.farmid AND ca.module = 'water'
                             AND ca.paymentid = p.waterpaymentid AND ca.status = 'Posted'), 0)
               - COALESCE((SELECT SUM(rl.amount) FROM watercustomerrefundlines rl
                           JOIN watercustomerrefunds r ON r.refundid = rl.refundid
                           WHERE rl.farmid = p.farmid AND rl.waterpaymentid = p.waterpaymentid
                             AND r.status = 'Posted'), 0), 0)
        FROM   waterpayments p
        WHERE  p.farmid = p_farmid AND p.waterpaymentid = p_waterpaymentid
          AND  p.watersaleid IS NULL AND COALESCE(p.status, 'Posted') = 'Posted'), 0)::numeric(14,2);
$f$;

CREATE OR REPLACE FUNCTION public.fnwatercustomer_credit(p_farmid text, p_customerid integer)
RETURNS numeric LANGUAGE sql STABLE AS $f$
    SELECT COALESCE(SUM(public.fnwaterpayment_unapplied(p_farmid, p.waterpaymentid)), 0)::numeric(14,2)
    FROM   waterpayments p
    WHERE  p.farmid = p_farmid AND p.watercustomerid = p_customerid
      AND  p.watersaleid IS NULL AND COALESCE(p.status, 'Posted') = 'Posted';
$f$;

-- Credit applied to a sale: posted allocations whose payment row has no sale.
CREATE OR REPLACE FUNCTION public.fnwatersale_creditapplied(p_farmid text, p_watersaleid integer)
RETURNS numeric LANGUAGE sql STABLE AS $f$
    SELECT COALESCE(SUM(ca.amountapplied), 0)::numeric(14,2)
    FROM   customerpaymentallocation ca
    JOIN   waterpayments p ON p.waterpaymentid = ca.paymentid AND p.farmid = ca.farmid
    WHERE  ca.farmid = p_farmid AND ca.module = 'water' AND ca.saleid = p_watersaleid
      AND  ca.status = 'Posted' AND p.watersaleid IS NULL;
$f$;

-- Hand back the credit applied to a sale that is going away (deleted, cancelled,
-- or its driver return reversed).  The credit becomes available again.
CREATE OR REPLACE FUNCTION public.fnwatersale_releasecredit(p_farmid text, p_watersaleid integer, p_by text, p_reason text)
RETURNS integer LANGUAGE plpgsql AS $f$
DECLARE v_n integer;
BEGIN
    UPDATE customerpaymentallocation ca
    SET    status = 'Reversed', reversedby = p_by, reversedat = (now() AT TIME ZONE 'utc'),
           reversalreason = p_reason
    FROM   waterpayments p
    WHERE  p.waterpaymentid = ca.paymentid AND p.farmid = ca.farmid
      AND  ca.farmid = p_farmid AND ca.module = 'water' AND ca.saleid = p_watersaleid
      AND  ca.status = 'Posted' AND p.watersaleid IS NULL;
    GET DIAGNOSTICS v_n = ROW_COUNT;
    RETURN v_n;
END
$f$;

-- ============================================================ 3. readers ====
CREATE OR REPLACE FUNCTION public.spwatercustomercredit_list(p_farmid text, p_customerid integer)
RETURNS TABLE(waterpaymentid integer, paymentgroupid uuid, paymentnumber text, paymentdate timestamp,
              amount numeric, unapplied numeric, sourcetype text, saleid integer, salestatus text,
              watercashaccountid integer)
LANGUAGE sql STABLE AS $f$
    SELECT p.waterpaymentid, p.paymentgroupid, p.paymentnumber::text, p.paymentdate,
           p.amount::numeric(14,2), public.fnwaterpayment_unapplied(p_farmid, p.waterpaymentid),
           p.sourcetype::text, NULL::integer, NULL::text, p.watercashaccountid
    FROM   waterpayments p
    WHERE  p.farmid = p_farmid AND p.watercustomerid = p_customerid
      AND  p.watersaleid IS NULL AND COALESCE(p.status, 'Posted') = 'Posted'
      AND  public.fnwaterpayment_unapplied(p_farmid, p.waterpaymentid) > 0
    ORDER  BY p.paymentdate, p.waterpaymentid;
$f$;

CREATE OR REPLACE FUNCTION public.spwatercustomercredit_summary(p_farmid text)
RETURNS TABLE(customerid integer, customername text, availablecredit numeric, paymentcount integer, outstanding numeric)
LANGUAGE sql STABLE AS $f$
    SELECT c.watercustomerid, c.name::text, x.credit, x.n,
           COALESCE((SELECT SUM(GREATEST(s.totalamount - s.amountpaid, 0)) FROM watersales s
                     WHERE s.farmid = p_farmid AND s.watercustomerid = c.watercustomerid
                       AND COALESCE(s.status, '') <> 'Cancelled'), 0)::numeric(14,2)
    FROM (
        SELECT p.watercustomerid,
               SUM(public.fnwaterpayment_unapplied(p_farmid, p.waterpaymentid))::numeric(14,2) AS credit,
               COUNT(*) FILTER (WHERE public.fnwaterpayment_unapplied(p_farmid, p.waterpaymentid) > 0)::integer AS n
        FROM   waterpayments p
        WHERE  p.farmid = p_farmid AND p.watersaleid IS NULL
          AND  COALESCE(p.status, 'Posted') = 'Posted'
        GROUP  BY p.watercustomerid
    ) x
    JOIN   watercustomers c ON c.watercustomerid = x.watercustomerid AND c.farmid = p_farmid
    WHERE  x.credit > 0
    ORDER  BY x.credit DESC;
$f$;

-- Every credit (live or reversed) with Original / Applied / Refunded / Available.
CREATE OR REPLACE FUNCTION public.spwatercustomercredit_events(p_farmid text, p_customerid integer DEFAULT NULL)
RETURNS TABLE(waterpaymentid integer, paymentgroupid uuid, paymentnumber text, creditdate timestamp,
              customerid integer, customername text, source text, sourcetype text, saleid integer,
              salegroupno text, reference text, originalamount numeric, applied numeric, refunded numeric,
              available numeric, status text, ismanual boolean, watercashaccountid integer)
LANGUAGE sql STABLE AS $f$
    SELECT p.waterpaymentid, p.paymentgroupid, p.paymentnumber::text, p.paymentdate,
           p.watercustomerid, c.name::text,
           CASE p.sourcetype WHEN 'Deposit' THEN 'Customer advance'
                             WHEN 'Overpayment' THEN 'Payment left over'
                             WHEN 'OpeningCredit' THEN 'Opening credit'
                             WHEN 'CreditNote' THEN 'Credit note'
                             ELSE COALESCE(p.sourcetype, 'Credit') END::text,
           p.sourcetype::text, NULL::integer, NULL::text,
           COALESCE(NULLIF(btrim(p.reference), ''), NULL)::text,
           p.amount::numeric(14,2), a.applied, r.refunded,
           CASE WHEN COALESCE(p.status, 'Posted') = 'Posted'
                THEN GREATEST(p.amount - a.applied - r.refunded, 0) ELSE 0 END::numeric(14,2),
           COALESCE(p.status, 'Posted')::text,
           public.fnwater_ismanualcredit(p.sourcetype),
           p.watercashaccountid
    FROM   waterpayments p
    LEFT   JOIN watercustomers c ON c.watercustomerid = p.watercustomerid AND c.farmid = p.farmid
    CROSS  JOIN LATERAL (SELECT COALESCE(SUM(ca.amountapplied), 0)::numeric(14,2) AS applied
                         FROM customerpaymentallocation ca
                         WHERE ca.farmid = p.farmid AND ca.module = 'water'
                           AND ca.paymentid = p.waterpaymentid AND ca.status = 'Posted') a
    CROSS  JOIN LATERAL (SELECT COALESCE(SUM(rl.amount), 0)::numeric(14,2) AS refunded
                         FROM watercustomerrefundlines rl JOIN watercustomerrefunds rf ON rf.refundid = rl.refundid
                         WHERE rl.farmid = p.farmid AND rl.waterpaymentid = p.waterpaymentid
                           AND rf.status = 'Posted') r
    WHERE  p.farmid = p_farmid AND p.watersaleid IS NULL
      AND  (p_customerid IS NULL OR p.watercustomerid = p_customerid)
    ORDER  BY p.paymentdate DESC, p.waterpaymentid DESC;
$f$;

CREATE OR REPLACE FUNCTION public.spwatercustomercredit_manuallist(p_farmid text)
RETURNS TABLE(paymentgroupid uuid, waterpaymentid integer, paymentnumber text, kind text,
              creditdate timestamp, customerid integer, customername text, amount numeric,
              used numeric, refunded numeric, remaining numeric, status text,
              watercashaccountid integer, cashaccountname text, paymentmethod text,
              reference text, reason text, createdby text, createdat timestamp,
              reversedat timestamp, reversalreason text)
LANGUAGE sql STABLE AS $f$
    SELECT p.paymentgroupid, p.waterpaymentid, p.paymentnumber::text, p.sourcetype::text,
           p.paymentdate, p.watercustomerid, c.name::text, p.amount::numeric(14,2),
           e.applied, e.refunded, e.available, COALESCE(p.status, 'Posted')::text,
           p.watercashaccountid, a.accountname::text, p.paymentmethod::text,
           p.reference::text, p.note::text, p.createdby::text, p.createddate,
           p.reversedat, p.reversalreason
    FROM   waterpayments p
    JOIN   public.spwatercustomercredit_events(p_farmid, NULL) e ON e.waterpaymentid = p.waterpaymentid
    LEFT   JOIN watercustomers c ON c.watercustomerid = p.watercustomerid AND c.farmid = p.farmid
    LEFT   JOIN watercashaccounts a ON a.watercashaccountid = p.watercashaccountid AND a.farmid = p.farmid
    WHERE  p.farmid = p_farmid AND p.watersaleid IS NULL
      AND  public.fnwater_ismanualcredit(p.sourcetype)
    ORDER  BY p.paymentdate DESC, p.waterpaymentid DESC;
$f$;

-- ============================================================ 4. writers ====
-- Credit added by hand.  Kinds: Deposit (customer advance -- money in now, to a
-- cash account), OpeningCredit, CreditNote (no money).
CREATE OR REPLACE FUNCTION public.spwatercustomercredit_create(
    p_farmid text, p_customerid integer, p_kind text, p_amount numeric,
    p_date timestamp DEFAULT NULL, p_cashaccountid integer DEFAULT NULL, p_paymentmethod text DEFAULT NULL,
    p_reference text DEFAULT NULL, p_reason text DEFAULT NULL, p_by text DEFAULT NULL)
RETURNS jsonb LANGUAGE plpgsql AS $f$
DECLARE
    v_kind  text := btrim(COALESCE(p_kind, ''));
    v_date  timestamp := COALESCE(p_date, (now() AT TIME ZONE 'utc'));
    v_amt   numeric(14,2) := round(p_amount, 2);
    v_id    integer;
    v_group uuid := gen_random_uuid();
    v_no    text;
BEGIN
    IF NOT public.fnwater_ismanualcredit(v_kind) THEN
        RAISE EXCEPTION 'Choose what kind of credit this is.' USING ERRCODE = 'P0001';
    END IF;
    IF v_amt IS NULL OR v_amt <= 0 THEN
        RAISE EXCEPTION 'Enter an amount greater than 0.' USING ERRCODE = 'P0001';
    END IF;
    IF p_reason IS NULL OR length(btrim(p_reason)) = 0 THEN
        RAISE EXCEPTION 'Give a reason for the credit.' USING ERRCODE = 'P0001';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM watercustomers c WHERE c.watercustomerid = p_customerid AND c.farmid = p_farmid) THEN
        RAISE EXCEPTION 'Customer does not belong to this company.' USING ERRCODE = 'P0001';
    END IF;
    IF v_date > (now() AT TIME ZONE 'utc') + interval '1 day' THEN
        RAISE EXCEPTION 'The credit date is in the future.' USING ERRCODE = 'P0001';
    END IF;
    IF v_kind = 'Deposit' THEN
        IF p_cashaccountid IS NULL THEN
            RAISE EXCEPTION 'Choose the account the customer''s money went into.' USING ERRCODE = 'P0001';
        END IF;
        IF NOT EXISTS (SELECT 1 FROM watercashaccounts a WHERE a.watercashaccountid = p_cashaccountid
                       AND a.farmid = p_farmid AND a.isactive) THEN
            RAISE EXCEPTION 'Cash account does not belong to this company.' USING ERRCODE = 'P0001';
        END IF;
    END IF;

    INSERT INTO waterpayments
        (farmid, watersaleid, amount, paymentmethod, paymentdate, reference, note, createdby, createddate,
         status, sourcetype, watercustomerid, watercashaccountid, paymentgroupid)
    VALUES
        (p_farmid, NULL, v_amt,
         CASE WHEN v_kind = 'Deposit' THEN COALESCE(NULLIF(btrim(p_paymentmethod), ''), 'Cash') ELSE 'NonCash' END,
         v_date, NULLIF(btrim(p_reference), ''), btrim(p_reason), p_by, (now() AT TIME ZONE 'utc'),
         'Posted', v_kind, p_customerid,
         CASE WHEN v_kind = 'Deposit' THEN p_cashaccountid END, v_group)
    RETURNING waterpaymentid, paymentnumber INTO v_id, v_no;

    -- A customer advance is real money: it goes into the account now (user
    -- decision 2026-11-12), and the daily closing does not count it again.
    IF v_kind = 'Deposit' THEN
        INSERT INTO watercashtransactions
            (farmid, watercashaccountid, transactiondate, transactiontype, sourcetype, sourceid,
             amount, description, createdby, approvedby, approvedat)
        VALUES
            (p_farmid, p_cashaccountid, v_date, 'CashIn', 'WaterCustomerAdvance', v_id, v_amt,
             'Customer advance ' || COALESCE(v_no, '#' || v_id::text), p_by, p_by, (now() AT TIME ZONE 'utc'));
        UPDATE watercashaccounts SET currentbalance = currentbalance + v_amt, updatedat = (now() AT TIME ZONE 'utc')
        WHERE  watercashaccountid = p_cashaccountid AND farmid = p_farmid;
    END IF;

    RETURN jsonb_build_object('paymentGroupId', v_group, 'waterPaymentId', v_id, 'paymentNumber', v_no);
END
$f$;

-- Reverse a credit added by hand.  Credit already used on sales is released
-- (those sales are owed again); credit already refunded blocks it.  A customer
-- advance's money goes back out of its account.
CREATE OR REPLACE FUNCTION public.spwatercustomercredit_reverse(
    p_farmid text, p_paymentgroupid uuid, p_reason text, p_by text DEFAULT NULL)
RETURNS integer LANGUAGE plpgsql AS $f$
DECLARE
    v_p    waterpayments%ROWTYPE;
    v_sale integer;
    v_now  timestamp := (now() AT TIME ZONE 'utc');
BEGIN
    IF p_reason IS NULL OR length(btrim(p_reason)) = 0 THEN
        RAISE EXCEPTION 'Give a reason for reversing the credit.' USING ERRCODE = 'P0001';
    END IF;
    SELECT * INTO v_p FROM waterpayments p
    WHERE  p.farmid = p_farmid AND p.paymentgroupid = p_paymentgroupid AND p.watersaleid IS NULL
    FOR UPDATE;
    IF NOT FOUND OR NOT public.fnwater_ismanualcredit(v_p.sourcetype) THEN
        RAISE EXCEPTION 'That credit was not found for this company.' USING ERRCODE = 'P0001';
    END IF;
    IF EXISTS (SELECT 1 FROM waterpayments p WHERE p.farmid = p_farmid AND p.paymentgroupid = p_paymentgroupid
               AND p.watersaleid IS NOT NULL) THEN
        RAISE EXCEPTION 'This credit came with a payment -- reverse the payment instead.' USING ERRCODE = 'P0001';
    END IF;
    IF COALESCE(v_p.status, 'Posted') <> 'Posted' THEN
        RAISE EXCEPTION 'This credit has already been reversed.' USING ERRCODE = 'P0001';
    END IF;
    IF EXISTS (SELECT 1 FROM watercustomerrefundlines rl JOIN watercustomerrefunds r ON r.refundid = rl.refundid
               WHERE rl.farmid = p_farmid AND rl.waterpaymentid = v_p.waterpaymentid AND r.status = 'Posted') THEN
        RAISE EXCEPTION 'Part of this credit has been refunded. Reverse the refund first.' USING ERRCODE = 'P0001';
    END IF;

    FOR v_sale IN
        UPDATE customerpaymentallocation ca
        SET    status = 'Reversed', reversedby = p_by, reversedat = v_now, reversalreason = p_reason
        WHERE  ca.farmid = p_farmid AND ca.module = 'water' AND ca.paymentid = v_p.waterpaymentid
          AND  ca.status = 'Posted'
        RETURNING ca.saleid
    LOOP
        PERFORM public.spwatersale_recompute(p_farmid, v_sale);
    END LOOP;

    UPDATE waterpayments SET status = 'Reversed', reversedby = p_by, reversedat = v_now, reversalreason = p_reason
    WHERE  waterpaymentid = v_p.waterpaymentid AND farmid = p_farmid;

    IF v_p.sourcetype = 'Deposit' AND v_p.watercashaccountid IS NOT NULL THEN
        INSERT INTO watercashtransactions
            (farmid, watercashaccountid, transactiondate, transactiontype, sourcetype, sourceid,
             amount, description, createdby, approvedby, approvedat)
        VALUES
            (p_farmid, v_p.watercashaccountid, v_now, 'CashOut', 'WaterCustomerAdvance', v_p.waterpaymentid,
             -v_p.amount, 'Reversal of customer advance ' || COALESCE(v_p.paymentnumber, '#' || v_p.waterpaymentid::text),
             p_by, p_by, v_now);
        UPDATE watercashaccounts SET currentbalance = currentbalance - v_p.amount, updatedat = v_now
        WHERE  watercashaccountid = v_p.watercashaccountid AND farmid = p_farmid;
    END IF;
    RETURN 1;
END
$f$;

-- Apply a customer's credit to one of their sales.  An allocation only: no
-- payment row on the sale, no money in, no cash movement.
CREATE OR REPLACE FUNCTION public.spwatercustomercredit_apply(p_farmid text, p_customerid integer, p_saleid integer,
                                                              p_amount numeric, p_by text DEFAULT NULL)
RETURNS numeric LANGUAGE plpgsql AS $f$
DECLARE
    v_s    watersales%ROWTYPE;
    v_bal  numeric(14,2);
    v_left numeric(14,2) := round(p_amount, 2);
    v_take numeric(14,2);
    v_src  record;
    v_now  timestamp := (now() AT TIME ZONE 'utc');
BEGIN
    IF p_amount IS NULL OR p_amount <= 0 THEN
        RAISE EXCEPTION 'Enter an amount greater than 0.' USING ERRCODE = 'P0001';
    END IF;
    PERFORM pg_advisory_xact_lock(hashtext('water-customercredit:' || p_farmid || ':' || p_customerid::text));
    SELECT * INTO v_s FROM watersales s WHERE s.watersaleid = p_saleid AND s.farmid = p_farmid FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Sale #% was not found for this company.', p_saleid USING ERRCODE = 'P0001';
    END IF;
    IF COALESCE(v_s.status, '') = 'Cancelled' THEN
        RAISE EXCEPTION 'Sale #% is cancelled.', p_saleid USING ERRCODE = 'P0001';
    END IF;
    IF v_s.watercustomerid IS DISTINCT FROM p_customerid THEN
        RAISE EXCEPTION 'Sale #% does not belong to this customer.', p_saleid USING ERRCODE = 'P0001';
    END IF;
    v_bal := GREATEST(v_s.totalamount - v_s.amountpaid, 0);
    IF v_bal <= 0 THEN
        RAISE EXCEPTION 'Sale #% is already fully paid.', p_saleid USING ERRCODE = 'P0001';
    END IF;
    IF v_left > v_bal THEN
        RAISE EXCEPTION 'Sale #% only has % outstanding.', p_saleid, v_bal USING ERRCODE = 'P0001';
    END IF;
    IF v_left > public.fnwatercustomer_credit(p_farmid, p_customerid) THEN
        RAISE EXCEPTION 'The customer only has % of credit available.', public.fnwatercustomer_credit(p_farmid, p_customerid)
            USING ERRCODE = 'P0001';
    END IF;
    FOR v_src IN SELECT * FROM public.spwatercustomercredit_list(p_farmid, p_customerid) LOOP
        EXIT WHEN v_left <= 0;
        -- one allocation row per (credit, sale) pair, ever
        CONTINUE WHEN EXISTS (SELECT 1 FROM customerpaymentallocation ca
                              WHERE ca.module = 'water' AND ca.paymentid = v_src.waterpaymentid AND ca.saleid = p_saleid);
        v_take := LEAST(v_left, v_src.unapplied);
        INSERT INTO customerpaymentallocation
            (farmid, module, paymentid, saleid, amountapplied, salebalancebefore, salebalanceafter,
             status, createdby, createdat)
        VALUES (p_farmid, 'water', v_src.waterpaymentid, p_saleid, v_take, v_bal, v_bal - v_take, 'Posted', p_by, v_now);
        v_bal  := v_bal - v_take;
        v_left := v_left - v_take;
    END LOOP;
    IF v_left > 0 THEN
        RAISE EXCEPTION 'Only % of the credit could be applied to sale #% (the rest came from a credit already applied to it once).',
              round(p_amount, 2) - v_left, p_saleid USING ERRCODE = 'P0001';
    END IF;
    PERFORM public.spwatersale_recompute(p_farmid, p_saleid);
    RETURN round(p_amount, 2);
END
$f$;

-- Give credit back to the customer: real money out of the chosen account.
-- p_paymentid = refund that one credit; NULL = oldest credit first.
CREATE OR REPLACE FUNCTION public.spwatercustomerrefund_record(p_farmid text, p_customerid integer, p_amount numeric,
    p_cashaccountid integer, p_paymentmethod text, p_refunddate date, p_reason text, p_by text DEFAULT NULL,
    p_paymentid integer DEFAULT NULL)
RETURNS integer LANGUAGE plpgsql AS $f$
DECLARE
    v_left  numeric(14,2) := round(p_amount, 2);
    v_take  numeric(14,2);
    v_src   record;
    v_id    integer;
    v_no    text;
    v_date  date := COALESCE(p_refunddate, (now() AT TIME ZONE 'utc')::date);
    v_acct  watercashaccounts%ROWTYPE;
BEGIN
    IF p_amount IS NULL OR p_amount <= 0 THEN
        RAISE EXCEPTION 'Enter a refund amount greater than 0.' USING ERRCODE = 'P0001';
    END IF;
    IF p_reason IS NULL OR length(btrim(p_reason)) = 0 THEN
        RAISE EXCEPTION 'Give a reason for the refund.' USING ERRCODE = 'P0001';
    END IF;
    SELECT * INTO v_acct FROM watercashaccounts a WHERE a.watercashaccountid = p_cashaccountid AND a.farmid = p_farmid;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Choose the account the refund is paid from.' USING ERRCODE = 'P0001';
    END IF;
    IF NOT COALESCE(v_acct.allownegativebalance, FALSE) AND v_acct.currentbalance < v_left THEN
        RAISE EXCEPTION '% only has % -- the refund would take it below zero.', v_acct.accountname, v_acct.currentbalance
            USING ERRCODE = 'P0001';
    END IF;
    PERFORM pg_advisory_xact_lock(hashtext('water-customercredit:' || p_farmid || ':' || p_customerid::text));
    IF p_paymentid IS NOT NULL THEN
        IF NOT EXISTS (SELECT 1 FROM waterpayments p WHERE p.waterpaymentid = p_paymentid AND p.farmid = p_farmid
                       AND p.watercustomerid = p_customerid AND p.watersaleid IS NULL) THEN
            RAISE EXCEPTION 'That credit does not belong to this customer.' USING ERRCODE = 'P0001';
        END IF;
        IF public.fnwaterpayment_unapplied(p_farmid, p_paymentid) < v_left THEN
            RAISE EXCEPTION 'That credit only has % available.', public.fnwaterpayment_unapplied(p_farmid, p_paymentid)
                USING ERRCODE = 'P0001';
        END IF;
    ELSIF public.fnwatercustomer_credit(p_farmid, p_customerid) < v_left THEN
        RAISE EXCEPTION 'The customer only has % of credit available.', public.fnwatercustomer_credit(p_farmid, p_customerid)
            USING ERRCODE = 'P0001';
    END IF;

    PERFORM pg_advisory_xact_lock(hashtext('water-refundnumber:' || p_farmid));
    SELECT 'RF-' || lpad((COALESCE(MAX(NULLIF(regexp_replace(r.refundnumber, '\D', '', 'g'), '')::int), 0) + 1)::text, 4, '0')
    INTO   v_no FROM watercustomerrefunds r WHERE r.farmid = p_farmid;

    INSERT INTO watercustomerrefunds
        (farmid, refundnumber, watercustomerid, amount, refunddate, watercashaccountid, paymentmethod, reason, createdby)
    VALUES (p_farmid, v_no, p_customerid, v_left, v_date, p_cashaccountid,
            COALESCE(NULLIF(btrim(p_paymentmethod), ''), 'Cash'), btrim(p_reason), p_by)
    RETURNING refundid INTO v_id;

    FOR v_src IN SELECT * FROM public.spwatercustomercredit_list(p_farmid, p_customerid) c
                 WHERE p_paymentid IS NULL OR c.waterpaymentid = p_paymentid LOOP
        EXIT WHEN v_left <= 0;
        v_take := LEAST(v_left, v_src.unapplied);
        INSERT INTO watercustomerrefundlines (refundid, farmid, waterpaymentid, amount)
        VALUES (v_id, p_farmid, v_src.waterpaymentid, v_take);
        v_left := v_left - v_take;
    END LOOP;
    IF v_left > 0 THEN
        RAISE EXCEPTION 'The credit could not cover the refund.' USING ERRCODE = 'P0001';
    END IF;

    INSERT INTO watercashtransactions
        (farmid, watercashaccountid, transactiondate, transactiontype, sourcetype, sourceid,
         amount, description, createdby, approvedby, approvedat)
    VALUES (p_farmid, p_cashaccountid, v_date::timestamp, 'CashOut', 'WaterCustomerRefund', v_id,
            -round(p_amount, 2), 'Customer refund ' || v_no, p_by, p_by, (now() AT TIME ZONE 'utc'));
    UPDATE watercashaccounts SET currentbalance = currentbalance - round(p_amount, 2), updatedat = (now() AT TIME ZONE 'utc')
    WHERE  watercashaccountid = p_cashaccountid AND farmid = p_farmid;
    RETURN v_id;
END
$f$;

-- The refund stays (Reversed); the money goes back into the account it left
-- from and the credit becomes available again.
CREATE OR REPLACE FUNCTION public.spwatercustomerrefund_reverse(p_farmid text, p_refundid integer, p_reason text,
                                                                p_by text DEFAULT NULL)
RETURNS integer LANGUAGE plpgsql AS $f$
DECLARE
    v_r   watercustomerrefunds%ROWTYPE;
    v_now timestamp := (now() AT TIME ZONE 'utc');
BEGIN
    IF p_reason IS NULL OR length(btrim(p_reason)) = 0 THEN
        RAISE EXCEPTION 'Give a reason for reversing the refund.' USING ERRCODE = 'P0001';
    END IF;
    SELECT * INTO v_r FROM watercustomerrefunds r WHERE r.refundid = p_refundid AND r.farmid = p_farmid FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Refund not found for this company.' USING ERRCODE = 'P0001';
    END IF;
    IF v_r.status <> 'Posted' THEN
        RAISE EXCEPTION 'This refund has already been reversed.' USING ERRCODE = 'P0001';
    END IF;
    UPDATE watercustomerrefunds
    SET    status = 'Reversed', reversedby = p_by, reversedat = v_now, reversalreason = btrim(p_reason),
           reversaldate = v_now::date
    WHERE  refundid = p_refundid;
    INSERT INTO watercashtransactions
        (farmid, watercashaccountid, transactiondate, transactiontype, sourcetype, sourceid,
         amount, description, createdby, approvedby, approvedat)
    VALUES (p_farmid, v_r.watercashaccountid, v_now, 'CashIn', 'WaterCustomerRefund', p_refundid,
            v_r.amount, 'Reversal of customer refund ' || v_r.refundnumber, p_by, p_by, v_now);
    UPDATE watercashaccounts SET currentbalance = currentbalance + v_r.amount, updatedat = v_now
    WHERE  watercashaccountid = v_r.watercashaccountid AND farmid = p_farmid;
    RETURN p_refundid;
END
$f$;

CREATE OR REPLACE FUNCTION public.spwatercustomerrefund_list(p_farmid text, p_customerid integer DEFAULT NULL)
RETURNS TABLE(refundid integer, refundnumber text, customerid integer, customername text, amount numeric,
              refunddate date, watercashaccountid integer, accountname text, paymentmethod text, reason text,
              status text, createdby text, createdat timestamp, paymentnumbers text,
              reversedat timestamp, reversedby text, reversalreason text, reversaldate date)
LANGUAGE sql STABLE AS $f$
    SELECT r.refundid, r.refundnumber, r.watercustomerid, c.name::text, r.amount, r.refunddate,
           r.watercashaccountid, a.accountname::text, r.paymentmethod, r.reason, r.status, r.createdby, r.createdat,
           (SELECT string_agg(COALESCE(p.paymentnumber, '#' || p.waterpaymentid::text), ', ' ORDER BY p.waterpaymentid)
            FROM watercustomerrefundlines rl JOIN waterpayments p ON p.waterpaymentid = rl.waterpaymentid
            WHERE rl.refundid = r.refundid)::text,
           r.reversedat, r.reversedby, r.reversalreason, r.reversaldate
    FROM   watercustomerrefunds r
    LEFT   JOIN watercustomers c ON c.watercustomerid = r.watercustomerid AND c.farmid = r.farmid
    LEFT   JOIN watercashaccounts a ON a.watercashaccountid = r.watercashaccountid AND a.farmid = r.farmid
    WHERE  r.farmid = p_farmid AND (p_customerid IS NULL OR r.watercustomerid = p_customerid)
    ORDER  BY r.refunddate DESC, r.refundid DESC;
$f$;

