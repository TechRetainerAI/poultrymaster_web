CREATE OR REPLACE FUNCTION public.spwatercustomerstatement(p_farmid text, p_customerid integer, p_from date DEFAULT NULL::date, p_to date DEFAULT NULL::date)
 RETURNS TABLE(entrydate date, entrytype text, reference text, description text, debit numeric, credit numeric, runningbalance numeric, saleid integer, sortkey integer, paymentgroupid uuid, allocationcount integer, sourcetype text)
 LANGUAGE sql
 STABLE
AS $function$
    WITH lines AS (
        -- Opening balance: what was owed before the window opened. p_from NULL
        -- means "the whole history", and a whole-history statement has nothing
        -- before it -- so the opening MUST be zero. The usual
        -- `p_from IS NULL OR ...` idiom here would instead match every sale ever
        -- and count the entire ledger twice.
        SELECT CASE WHEN p_from IS NULL THEN NULL::date ELSE p_from END AS entrydate,
               'OpeningBalance'::text  AS entrytype,
               NULL::text              AS reference,
               'Opening balance'::text AS description,
               CASE WHEN p_from IS NULL THEN 0::numeric(14,2) ELSE COALESCE((
                   SELECT SUM(GREATEST(s.totalamount - s.amountpaid, 0))
                   FROM   watersales s
                   WHERE  s.farmid = p_farmid AND s.watercustomerid = p_customerid
                     AND  COALESCE(s.status, '') <> 'Cancelled'
                     AND  s.saledate::date < p_from), 0)::numeric(14,2) END AS debit,
               0::numeric(14,2) AS credit,
               NULL::integer    AS saleid,
               0                AS sortkey,
               0                AS pin,
               NULL::uuid       AS paymentgroupid,
               NULL::integer    AS allocationcount,
               NULL::text       AS sourcetype

        UNION ALL

        SELECT s.saledate::date, 'Sale'::text,
               ('W' || s.watersaleid::text)::text,
               COALESCE(NULLIF(btrim(s.notes), ''), 'Water sale')::text,
               s.totalamount::numeric(14,2), 0::numeric(14,2),
               s.watersaleid, 1, 1,
               NULL::uuid, NULL::integer, 'Sale'::text
        FROM   watersales s
        WHERE  s.farmid = p_farmid AND s.watercustomerid = p_customerid
          AND  COALESCE(s.status, '') <> 'Cancelled'
          AND  (p_from IS NULL OR s.saledate::date >= p_from)
          AND  (p_to   IS NULL OR s.saledate::date <= p_to)

        UNION ALL

        -- Money the sale records as received with no payment row behind it --
        -- a sale entered as already paid. Without this the statement shows the
        -- debit and never the receipt, and its closing figure disagrees with
        -- the balances page. Only the POSITIVE remainder: a negative one means
        -- the payment rows exceed what the sale says it received, which is a
        -- data problem to surface, not to quietly subtract.
        SELECT s.saledate::date, 'Payment'::text,
               ('W' || s.watersaleid::text)::text,
               'Paid at point of sale'::text,
               0::numeric(14,2), v.residual,
               s.watersaleid, 2, 1,
               NULL::uuid, 1, 'Counter'::text
        FROM   watersales s
        CROSS  JOIN LATERAL (
            SELECT ROUND(GREATEST(COALESCE(s.amountpaid, 0), 0)
                       - COALESCE((SELECT SUM(p2.amount) FROM waterpayments p2
                                   WHERE p2.watersaleid = s.watersaleid
                                     AND p2.farmid = s.farmid
                                     AND COALESCE(p2.status, 'Posted') = 'Posted'), 0)
                       -- 422: applied credit has its own line below
                       - public.fnwatersale_creditapplied(p_farmid, s.watersaleid), 2) AS residual
        ) v
        WHERE  s.farmid = p_farmid AND s.watercustomerid = p_customerid
          AND  COALESCE(s.status, '') <> 'Cancelled'
          AND  v.residual > 0
          AND  (p_from IS NULL OR s.saledate::date >= p_from)
          AND  (p_to   IS NULL OR s.saledate::date <= p_to)

        UNION ALL

        -- ONE LINE PER PAYMENT EVENT.
        SELECT MIN(p.paymentdate)::date, 'Payment'::text,
               COALESCE(MIN(p.paymentnumber),
                        NULLIF(btrim(MIN(p.reference)), ''),
                        'PMT' || MIN(p.waterpaymentid)::text)::text,
               ('Payment'
                || COALESCE(' â€” ' || NULLIF(btrim(MIN(p.paymentmethod)), ''), '')
                || CASE WHEN COUNT(DISTINCT p.watersaleid) > 1
                        THEN ' across ' || COUNT(DISTINCT p.watersaleid)::text || ' sales'
                        ELSE ' (sale W' || MIN(p.watersaleid)::text || ')'
                   END)::text,
               0::numeric(14,2), SUM(p.amount)::numeric(14,2),
               CASE WHEN COUNT(DISTINCT p.watersaleid) = 1 THEN MIN(p.watersaleid) END,
               2, 1,
               p.paymentgroupid,
               COUNT(DISTINCT p.waterpaymentid)::integer,
               MIN(p.sourcetype)::text
        FROM   waterpayments p
        WHERE  p.farmid = p_farmid AND p.watercustomerid = p_customerid
          AND  COALESCE(p.status, 'Posted') = 'Posted'
          -- 422: only money paid onto sales; credit is on the Credits page and
          -- reaches the statement when it is applied (below)
          AND  p.watersaleid IS NOT NULL
          -- A CANCELLED SALE'S PAYMENTS DO NOT CREDIT THE CUSTOMER. The debit
          -- leg above has always excluded cancelled sales; this leg did not, so
          -- their credits survived and drove the balance down -- one customer
          -- read as being OWED 13,414 because 17 payments against cancelled
          -- sales stayed on their statement. That is the whole of the drift
          -- between this statement and the balances page.
          --
          -- Written as NOT EXISTS-cancelled rather than EXISTS-not-cancelled on
          -- purpose: a payment whose sale row is missing entirely keeps showing,
          -- exactly as it does today. Only cancellation is being filtered.
          AND  NOT EXISTS (SELECT 1 FROM watersales s
                           WHERE s.watersaleid = p.watersaleid
                             AND s.farmid = p.farmid
                             AND COALESCE(s.status, '') = 'Cancelled')
          AND  (p_from IS NULL OR p.paymentdate::date >= p_from)
          AND  (p_to   IS NULL OR p.paymentdate::date <= p_to)
        GROUP  BY p.paymentgroupid
        UNION ALL
        -- 422: credit applied to a sale
        SELECT ca.createdat::date, 'Payment'::text,
               COALESCE(cp.paymentnumber, 'CR' || cp.waterpaymentid::text)::text,
               ('Credit applied (sale W' || ca.saleid::text || ')')::text,
               0::numeric(14,2), ca.amountapplied::numeric(14,2),
               ca.saleid, 2, 1,
               cp.paymentgroupid, 1, 'CreditApplied'::text
        FROM   customerpaymentallocation ca
        JOIN   waterpayments cp ON cp.waterpaymentid = ca.paymentid AND cp.farmid = ca.farmid
        JOIN   watersales s ON s.watersaleid = ca.saleid AND s.farmid = ca.farmid
        WHERE  ca.farmid = p_farmid AND ca.module = 'water' AND ca.status = 'Posted'
          AND  cp.watersaleid IS NULL AND s.watercustomerid = p_customerid
          AND  COALESCE(s.status, '') <> 'Cancelled'
          AND  (p_from IS NULL OR ca.createdat::date >= p_from)
          AND  (p_to   IS NULL OR ca.createdat::date <= p_to)
    ),
    ordered AS (
        -- `reference` is the final tiebreaker now that two payments on one day
        -- can both have a null saleid.
        SELECT l.*,
               ROW_NUMBER() OVER (
                   ORDER BY l.pin, l.entrydate NULLS FIRST, l.sortkey,
                            l.saleid NULLS FIRST, l.reference) AS rn
        FROM   lines l
    )
    SELECT o.entrydate, o.entrytype, o.reference, o.description,
           o.debit, o.credit,
           SUM(o.debit - o.credit) OVER (ORDER BY o.rn
               ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW)::numeric(14,2),
           o.saleid, o.sortkey, o.paymentgroupid, o.allocationcount, o.sourcetype
    FROM   ordered o
    ORDER  BY o.rn;
$function$;

CREATE OR REPLACE FUNCTION public.spwatercustomerbalancesummary(p_farmid text)
 RETURNS TABLE(totalbalance numeric, partycount integer, overduebalance numeric, paymentstoday numeric, largestbalance numeric, largestbalanceparty text)
 LANGUAGE sql
 STABLE
AS $function$
    WITH per AS (
        SELECT b.customerid, b.customername, b.totalbalance, b.overdueamount
        FROM   spwatercustomerbalances(p_farmid) b
    )
    SELECT COALESCE(SUM(p.totalbalance), 0)::numeric(14,2),
           COUNT(*)::integer,
           COALESCE(SUM(p.overdueamount), 0)::numeric(14,2),
           COALESCE((SELECT SUM(w.amount) FROM waterpayments w
                     WHERE w.farmid = p_farmid
                       AND COALESCE(w.status, 'Posted') = 'Posted'
                       AND NOT public.fnwater_isnocashcredit(w.sourcetype)   -- 422
                       AND w.paymentdate::date = CURRENT_DATE), 0)::numeric(14,2),
           COALESCE(MAX(p.totalbalance), 0)::numeric(14,2),
           (SELECT p2.customername FROM per p2 ORDER BY p2.totalbalance DESC LIMIT 1)
    FROM   per p;
$function$;

CREATE OR REPLACE FUNCTION public.spwatercustomerpayment_history(p_farmid text, p_customerid integer DEFAULT NULL::integer, p_saleid integer DEFAULT NULL::integer, p_from date DEFAULT NULL::date, p_to date DEFAULT NULL::date)
 RETURNS TABLE(paymentgroupid uuid, paymentnumber text, customerid integer, customername text, paymentdate timestamp without time zone, totalamount numeric, paymentmethod text, reference text, note text, sourcetype text, status text, allocationcount integer, watercashaccountid integer, createdby text, reversedby text, reversedat timestamp without time zone, reversalreason text, saleid integer, saletotal numeric, balancebefore numeric, amountapplied numeric, balanceafter numeric, createdat timestamp without time zone)
 LANGUAGE sql
 STABLE
AS $function$
    SELECT p.paymentgroupid,
           MIN(p.paymentnumber)::text,
           MIN(p.watercustomerid),
           MIN(c.name)::text,
           MIN(p.paymentdate),
           SUM(p.amount)::numeric(14,2),
           MIN(p.paymentmethod)::text,
           MIN(p.reference)::text,
           MIN(p.note)::text,
           MIN(p.sourcetype)::text,
           MIN(COALESCE(p.status, 'Posted'))::text,
           -- DISTINCT on the payment row, not COUNT(*): the joins below are 1:1
           -- today, and this stays right if one of them ever is not.
           COUNT(DISTINCT p.waterpaymentid)::integer,
           MIN(p.watercashaccountid),
           MIN(p.createdby)::text,
           MIN(p.reversedby)::text,
           MIN(p.reversedat),
           MIN(p.reversalreason)::text,
           CASE WHEN COUNT(DISTINCT p.waterpaymentid) = 1 THEN MIN(p.watersaleid) END,
           CASE WHEN COUNT(DISTINCT p.waterpaymentid) = 1 THEN MIN(s.totalamount)::numeric(14,2) END,
           CASE WHEN COUNT(DISTINCT p.waterpaymentid) = 1 THEN MIN(ca.salebalancebefore)::numeric(14,2) END,
           CASE WHEN COUNT(DISTINCT p.waterpaymentid) = 1 THEN MIN(ca.amountapplied)::numeric(14,2) END,
           CASE WHEN COUNT(DISTINCT p.waterpaymentid) = 1 THEN MIN(ca.salebalanceafter)::numeric(14,2) END
           , MIN(p.createddate)   -- 304: the entry time
    FROM   waterpayments p
    LEFT   JOIN watercustomers c ON c.watercustomerid = p.watercustomerid AND c.farmid = p.farmid
    LEFT   JOIN watersales s     ON s.watersaleid = p.watersaleid AND s.farmid = p.farmid
    -- Payments taken before 227 have no allocation row; those columns come back
    -- NULL and the page falls back to what it can show.
    LEFT   JOIN customerpaymentallocation ca
           ON  ca.module = 'water'
           AND ca.paymentid = p.waterpaymentid
           AND ca.farmid = p.farmid
           -- 422: the payment's own sale only; a credit row's applications to
           -- other sales would multiply the payment's amount
           AND ca.saleid = p.watersaleid
    WHERE  p.farmid = p_farmid
      AND  (p_customerid IS NULL OR p.watercustomerid = p_customerid)
      AND  (p_from IS NULL OR p.paymentdate::date >= p_from)
      AND  (p_to   IS NULL OR p.paymentdate::date <= p_to)
      AND  (p_saleid IS NULL OR EXISTS (
              SELECT 1 FROM waterpayments p2
              WHERE p2.paymentgroupid = p.paymentgroupid AND p2.watersaleid = p_saleid))
    GROUP  BY p.paymentgroupid
    -- 422: credit added by hand lives on the Customer Credits page
    HAVING bool_or(NOT public.fnwater_ismanualcredit(p.sourcetype))
    ORDER  BY MIN(p.paymentdate) DESC;
$function$;

CREATE OR REPLACE FUNCTION public.spwaterreport_periodpnl(p_farmid text, p_fromdate date, p_todate date)
 RETURNS TABLE(periodstart date, periodend date, totalincome numeric, totalexpenses numeric, rawmaterialcost numeric, productioncost numeric, totallosses numeric, netprofit numeric, profitmarginpct numeric, bagsproduced integer, bagssold integer, avgprofitperbag numeric)
 LANGUAGE plpgsql
AS $function$
DECLARE
    v_start             timestamp;
    v_end               timestamp;
    v_storefrontincome  numeric;
    v_driverincome      numeric;
    v_totalincome       numeric;
    v_rawmaterialcost   numeric;
    v_productioncost    numeric;
    v_generalexpenses   numeric;
    v_deliveryexpenses  numeric;
    v_operatingexpenses numeric;
    v_productionlosses  numeric;
    v_shortagelosses    numeric;
    v_totallosses       numeric;
    v_netprofit         numeric;
    v_bagsproduced      integer;
    v_storefrontbagssold numeric;
    v_driverbagssold    numeric;
    v_bagssold          integer;
    v_profitmargin      numeric;
    v_avgprofitperbag   numeric;
BEGIN
    v_start := p_fromdate::timestamp;
    v_end   := p_todate::timestamp + make_interval(days => 1);

    -- Storefront sales only (exclude DeliveryRun - that income is on the return).
    v_storefrontincome := COALESCE((
        SELECT SUM(s.totalamount) FROM watersales s
        WHERE s.farmid = p_farmid AND s.status NOT IN ('Cancelled')
          AND COALESCE(s.sourcetype, '') <> 'DeliveryRun'
          AND s.saledate >= v_start AND s.saledate < v_end), 0);

    -- Driver-return income for the day (cash + momo + bank + credit sold).
    v_driverincome := COALESCE((
        SELECT SUM(dr.cashcollected + dr.momocollected + dr.bankcollected + dr.creditsalesamount)
        FROM waterdriverreturns dr
        WHERE dr.farmid = p_farmid AND dr.status IN ('Draft','Approved')
          AND dr.returndate >= v_start AND dr.returndate < v_end), 0);

    -- 422: a credit note is an allowance given -- revenue the business gave up.
    v_totalincome := (v_storefrontincome + v_driverincome
                      - COALESCE((SELECT SUM(cn.amount) FROM waterpayments cn
                                  WHERE cn.farmid = p_farmid AND cn.sourcetype = 'CreditNote'
                                    AND COALESCE(cn.status, 'Posted') = 'Posted'
                                    AND cn.paymentdate >= v_start AND cn.paymentdate < v_end), 0))::numeric(14,2);

    -- Cash paid for raw materials (matches the closing's AmountPaid basis).
    v_rawmaterialcost := COALESCE((
        SELECT SUM(p.amountpaid) FROM waterrawmaterialpurchases p
        WHERE p.farmid = p_farmid AND p.purchasedate >= v_start AND p.purchasedate < v_end), 0);

    v_productioncost := COALESCE((
        SELECT SUM(b.totalproductioncost) FROM waterproductionbatches b
        WHERE b.farmid = p_farmid AND b.isdeleted = FALSE AND b.status = 'Approved'
          AND b.productiondate >= p_fromdate AND b.productiondate <= p_todate), 0);

    -- Operating expenses: general approved WaterExpenses (excl. the auto
    -- raw-material-purchase expense, already in RawMaterialCost) + delivery expenses.
    v_generalexpenses := COALESCE((
        SELECT SUM(e.amount) FROM waterexpenses e
        WHERE e.farmid = p_farmid AND e.isdeleted = FALSE AND e.status = 'Approved'
          AND COALESCE(e.sourcetype, '') <> 'RawMaterialPurchase'
          AND e.expensedate >= v_start AND e.expensedate < v_end), 0);

    v_deliveryexpenses := COALESCE((
        SELECT SUM(de.amount) FROM waterdeliveryexpenses de
        INNER JOIN waterdriverreturns dr ON dr.waterdriverreturnid = de.waterdriverreturnid
        WHERE dr.farmid = p_farmid AND dr.status IN ('Draft','Approved') AND de.isapproved = TRUE
          AND dr.returndate >= v_start AND dr.returndate < v_end), 0);

    v_operatingexpenses := (v_generalexpenses + v_deliveryexpenses)::numeric(14,2);

    -- Losses: production losses (damaged/rejected) + driver cash shortages.
    v_productionlosses := COALESCE((
        SELECT SUM(l.totalvalue) FROM waterproductionlosses l
        WHERE l.farmid = p_farmid AND l.lossdate >= v_start AND l.lossdate < v_end), 0);

    v_shortagelosses := COALESCE((
        SELECT SUM(dr.shortageamount) FROM waterdriverreturns dr
        WHERE dr.farmid = p_farmid AND dr.status IN ('Draft','Approved')
          AND dr.returndate >= v_start AND dr.returndate < v_end), 0);

    v_totallosses := (v_productionlosses + v_shortagelosses)::numeric(14,2);

    v_netprofit := (v_totalincome - v_rawmaterialcost - v_productioncost
                    - v_operatingexpenses - v_totallosses)::numeric(14,2);

    v_bagsproduced := COALESCE((
        SELECT SUM(b.bagsproduced - b.damagedbags)::int FROM waterproductionbatches b
        WHERE b.farmid = p_farmid AND b.isdeleted = FALSE AND b.status = 'Approved'
          AND b.productiondate >= p_fromdate AND b.productiondate <= p_todate), 0);

    -- Bags sold = storefront sale items (excl. DeliveryRun) + driver-return bags sold.
    v_storefrontbagssold := COALESCE((
        SELECT SUM(si.quantity) FROM watersales s
        INNER JOIN watersaleitems si ON si.watersaleid = s.watersaleid
        WHERE s.farmid = p_farmid AND s.status NOT IN ('Cancelled')
          AND COALESCE(s.sourcetype, '') <> 'DeliveryRun'
          AND s.saledate >= v_start AND s.saledate < v_end), 0);

    v_driverbagssold := COALESCE((
        SELECT SUM(dr.bagssold) FROM waterdriverreturns dr
        WHERE dr.farmid = p_farmid AND dr.status IN ('Draft','Approved')
          AND dr.returndate >= v_start AND dr.returndate < v_end), 0);

    -- T-SQL CAST(decimal AS INT) truncates toward zero; trunc() keeps that.
    v_bagssold := trunc(v_storefrontbagssold + v_driverbagssold)::int;

    v_profitmargin := (CASE WHEN v_totalincome > 0 THEN (v_netprofit / v_totalincome) * 100 ELSE 0 END)::numeric(8,2);
    v_avgprofitperbag := (CASE WHEN v_bagssold > 0 THEN v_netprofit / v_bagssold ELSE 0 END)::numeric(14,2);

    RETURN QUERY
    SELECT p_fromdate, p_todate,
           v_totalincome,
           v_operatingexpenses,   -- operating only
           v_rawmaterialcost,
           v_productioncost,
           v_totallosses,
           v_netprofit,
           v_profitmargin,
           v_bagsproduced,
           v_bagssold,
           v_avgprofitperbag;
END;
$function$;

CREATE OR REPLACE FUNCTION public.spwaterreport_pllines(p_farmid text, p_startdate date, p_enddate date)
 RETURNS TABLE(section text, linekey text, linelabel text, amount numeric, sortorder integer, isinformational boolean, entrycount integer)
 LANGUAGE sql
 STABLE
AS $function$
    -- periodpnl's own window, copied: half-open on the timestamp columns.
    WITH bounds AS (
        SELECT p_startdate::timestamp                              AS s,
               p_enddate::timestamp + make_interval(days => 1)     AS e
    ),
    -- ---- Revenue -----------------------------------------------------------
    rev AS (
        SELECT 'StorefrontSales'::text AS k, 'Storefront sales'::text AS lbl,
               COALESCE(SUM(s.totalamount), 0) AS amt, COUNT(*)::integer AS n, 1 AS ord
        FROM   watersales s, bounds b
        WHERE  s.farmid = p_farmid AND s.status NOT IN ('Cancelled')
          AND  COALESCE(s.sourcetype, '') <> 'DeliveryRun'
          AND  s.saledate >= b.s AND s.saledate < b.e
        UNION ALL
        -- Collections, not sales. periodpnl takes the driver's money rather than
        -- the DeliveryRun sale rows so the two cannot double-count, and the
        -- drilldown shows the returns for the same reason.
        SELECT 'DeliveryCollections', 'Delivery-run collections',
               COALESCE(SUM(dr.cashcollected + dr.momocollected
                          + dr.bankcollected + dr.creditsalesamount), 0),
               COUNT(*)::integer, 2
        FROM   waterdriverreturns dr, bounds b
        WHERE  dr.farmid = p_farmid AND dr.status IN ('Draft', 'Approved')
          AND  dr.returndate >= b.s AND dr.returndate < b.e
        UNION ALL
        -- 422: credit notes -- allowances given, negative revenue
        SELECT 'CreditNotes', 'Credit notes & allowances',
               -COALESCE(SUM(cn.amount), 0), COUNT(*)::integer, 3
        FROM   waterpayments cn, bounds b
        WHERE  cn.farmid = p_farmid AND cn.sourcetype = 'CreditNote'
          AND  COALESCE(cn.status, 'Posted') = 'Posted'
          AND  cn.paymentdate >= b.s AND cn.paymentdate < b.e
    ),
    -- ---- Direct cost -------------------------------------------------------
    direct AS (
        SELECT 'RawMaterials'::text AS k, 'Raw materials (paid)'::text AS lbl,
               COALESCE(SUM(p.amountpaid), 0) AS amt, COUNT(*)::integer AS n, 11 AS ord
        FROM   waterrawmaterialpurchases p, bounds b
        WHERE  p.farmid = p_farmid
          AND  p.purchasedate >= b.s AND p.purchasedate < b.e
        UNION ALL
        -- DATE comparison, inclusive both ends. periodpnl's own shape; see header.
        SELECT 'ProductionCost', 'Production cost',
               COALESCE(SUM(pb.totalproductioncost), 0), COUNT(*)::integer, 12
        FROM   waterproductionbatches pb
        WHERE  pb.farmid = p_farmid AND pb.isdeleted = FALSE AND pb.status = 'Approved'
          AND  pb.productiondate >= p_startdate AND pb.productiondate <= p_enddate
    ),
    -- ---- Operating / other cost -------------------------------------------
    -- The general expense pool periodpnl counts, itemised by 282's own P&L line
    -- so the P&L, the Expenses page and Financial Activity agree on the wording.
    exp AS (
        SELECT fnwaterexpense_plsection(l.line) AS sec,
               l.line                           AS k,
               fnwaterexpense_pllinelabel(l.line) AS lbl,
               COALESCE(SUM(e.amount), 0)       AS amt,
               COUNT(*)::integer                AS n
        FROM   waterexpenses e
        INNER  JOIN waterexpensecategories ec ON ec.waterexpensecategoryid = e.waterexpensecategoryid,
               bounds b
        -- Same four arguments fnwaterexpenserows passes, including the category
        -- NAME and the item category. Anything less and a legacy row lands on a
        -- different line here than it does on the Expenses page.
        CROSS  JOIN LATERAL (SELECT fnwaterexpense_costtype(
                                        e.financialcosttype::text, e.sourcetype::text,
                                        ec.name::text, e.paymentmethod::text) AS ct) c
        CROSS  JOIN LATERAL (SELECT fnwaterexpense_plline(
                                        c.ct, e.sourcetype::text, ec.name::text,
                                        fnwaterexpense_itemcategory(e.sourcetype::text, e.sourceid)) AS line) l
        WHERE  e.farmid = p_farmid
          AND  COALESCE(e.isdeleted, FALSE) = FALSE AND e.status = 'Approved'
          AND  COALESCE(e.sourcetype, '') <> 'RawMaterialPurchase'
          AND  e.expensedate >= b.s AND e.expensedate < b.e
        GROUP  BY 1, 2, 3
    ),
    deliv AS (
        SELECT 'DeliveryExpenses'::text AS k, 'Delivery expenses'::text AS lbl,
               COALESCE(SUM(de.amount), 0) AS amt, COUNT(*)::integer AS n
        FROM   waterdeliveryexpenses de
        JOIN   waterdriverreturns dr ON dr.waterdriverreturnid = de.waterdriverreturnid, bounds b
        WHERE  dr.farmid = p_farmid AND dr.status IN ('Draft', 'Approved')
          AND  de.isapproved = TRUE
          AND  dr.returndate >= b.s AND dr.returndate < b.e
    ),
    -- ---- Losses ------------------------------------------------------------
    loss AS (
        SELECT 'ProductionLosses'::text AS k, 'Production losses'::text AS lbl,
               COALESCE(SUM(pl.totalvalue), 0) AS amt, COUNT(*)::integer AS n, 61 AS ord
        FROM   waterproductionlosses pl, bounds b
        WHERE  pl.farmid = p_farmid
          AND  pl.lossdate >= b.s AND pl.lossdate < b.e
        UNION ALL
        SELECT 'DriverShortages', 'Driver cash shortages',
               COALESCE(SUM(dr.shortageamount), 0), COUNT(*) FILTER (WHERE dr.shortageamount <> 0)::integer, 62
        FROM   waterdriverreturns dr, bounds b
        WHERE  dr.farmid = p_farmid AND dr.status IN ('Draft', 'Approved')
          AND  dr.returndate >= b.s AND dr.returndate < b.e
    ),
    -- ---- Informational: cash moved, profit did not -------------------------
    fin AS (
        SELECT 'OwnerContributions'::text AS k, 'Owner Contributions'::text AS lbl,
               COALESCE(SUM(o.amount), 0) AS amt, COUNT(*)::integer AS n, 71 AS ord
        FROM   waterownermoney o, bounds b
        WHERE  o.farmid = p_farmid AND o.status = 'Posted'
          AND  o.transactiontype = 'Contribution'
          AND  o.transactiondate >= b.s AND o.transactiondate < b.e
        UNION ALL
        SELECT 'OwnerDraws', 'Owner Draws', COALESCE(SUM(o.amount), 0), COUNT(*)::integer, 72
        FROM   waterownermoney o, bounds b
        WHERE  o.farmid = p_farmid AND o.status = 'Posted'
          AND  o.transactiontype = 'Draw'
          AND  o.transactiondate >= b.s AND o.transactiondate < b.e
        UNION ALL
        SELECT 'LoansReceived', 'Loans Received', COALESCE(SUM(l.amountreceived), 0), COUNT(*)::integer, 73
        FROM   waterloans l, bounds b
        WHERE  l.farmid = p_farmid AND l.status NOT IN ('Reversed', 'Cancelled', 'Draft')
          AND  l.loandate >= b.s AND l.loandate < b.e
        UNION ALL
        SELECT 'LoanPrincipalRepaid', 'Loan Principal Repaid',
               COALESCE(SUM(pm.principalamount), 0), COUNT(*)::integer, 74
        FROM   waterloanpayments pm, bounds b
        WHERE  pm.farmid = p_farmid AND pm.status = 'Posted'
          AND  pm.paymentdate >= b.s AND pm.paymentdate < b.e
    ),
    cap AS (
        SELECT COALESCE(cat.categoryname, 'Other Assets')::text AS k,
               COALESCE(SUM(cc.amount), 0) AS amt, COUNT(*)::integer AS n
        FROM   watercapitalassetcosts cc
        JOIN   watercapitalassets a ON a.watercapitalassetid = cc.watercapitalassetid
        LEFT   JOIN waterassetcategories cat ON cat.waterassetcategoryid = a.waterassetcategoryid
        WHERE  cc.farmid = p_farmid AND cc.status = 'Posted'
          AND  cc.costdate >= p_startdate AND cc.costdate <= p_enddate
        GROUP  BY COALESCE(cat.categoryname, 'Other Assets')
    )
    SELECT 'Revenue', rev.k, rev.lbl, rev.amt::numeric(14,2), rev.ord, FALSE, rev.n
    FROM   rev WHERE rev.amt <> 0 OR rev.n > 0
    UNION ALL
    SELECT 'DirectCost', direct.k, direct.lbl, direct.amt::numeric(14,2), direct.ord, FALSE, direct.n
    FROM   direct WHERE direct.amt <> 0 OR direct.n > 0
    UNION ALL
    -- 282's own section decides which band an expense line sits in, so a
    -- depreciation or loan-interest row drops below Operating Profit rather
    -- than inflating it. Both bands together still equal periodpnl's
    -- totalexpenses, which is what keeps the statement reconciled.
    SELECT exp.sec, exp.k, exp.lbl, exp.amt::numeric(14,2),
           CASE exp.sec WHEN 'OperatingExpense' THEN 30 ELSE 50 END
             + CASE exp.k WHEN 'Payroll' THEN 1 WHEN 'Utilities' THEN 2
                          WHEN 'Transport' THEN 3 WHEN 'RepairsMaintenance' THEN 4
                          WHEN 'Depreciation' THEN 1 WHEN 'LoanInterest' THEN 2
                          WHEN 'LoanFees' THEN 3 ELSE 9 END,
           FALSE, exp.n
    FROM   exp WHERE exp.amt <> 0
    UNION ALL
    SELECT 'OperatingExpense', deliv.k, deliv.lbl, deliv.amt::numeric(14,2), 40, FALSE, deliv.n
    FROM   deliv WHERE deliv.amt <> 0 OR deliv.n > 0
    UNION ALL
    SELECT 'Loss', loss.k, loss.lbl, loss.amt::numeric(14,2), loss.ord, FALSE, loss.n
    FROM   loss WHERE loss.amt <> 0
    UNION ALL
    SELECT 'Financing', fin.k, fin.lbl, fin.amt::numeric(14,2), fin.ord, TRUE, fin.n
    FROM   fin WHERE fin.amt <> 0
    UNION ALL
    SELECT 'CapitalInvestment', cap.k, cap.k, cap.amt::numeric(14,2), 81, TRUE, cap.n
    FROM   cap WHERE cap.amt <> 0
    ORDER  BY 5, 2;
$function$;

CREATE OR REPLACE FUNCTION public.spwaterreport_plrevenuedetail(p_farmid text, p_startdate date, p_enddate date, p_linekey text DEFAULT NULL::text)
 RETURNS TABLE(entrydate timestamp without time zone, reference text, party text, detail text, amount numeric)
 LANGUAGE sql
 STABLE
AS $function$
    SELECT s.saledate, ('Sale #' || s.watersaleid)::text,
           COALESCE(c.name, 'Walk-in')::text,
           COALESCE(NULLIF(btrim(s.notes), ''), s.status)::text,
           s.totalamount::numeric(14,2)
    FROM   watersales s
    LEFT   JOIN watercustomers c ON c.watercustomerid = s.watercustomerid
    WHERE  s.farmid = p_farmid AND s.status NOT IN ('Cancelled')
      AND  COALESCE(s.sourcetype, '') <> 'DeliveryRun'
      AND  s.saledate >= p_startdate::timestamp
      AND  s.saledate <  p_enddate::timestamp + make_interval(days => 1)
      AND  (p_linekey IS NULL OR p_linekey = 'StorefrontSales')
    UNION ALL
    SELECT dr.returndate, ('Return #' || dr.waterdriverreturnid)::text,
           'Driver return'::text,
           (dr.bagssold::text || ' bag(s) sold')::text,
           (dr.cashcollected + dr.momocollected + dr.bankcollected + dr.creditsalesamount)::numeric(14,2)
    FROM   waterdriverreturns dr
    WHERE  dr.farmid = p_farmid AND dr.status IN ('Draft', 'Approved')
      AND  dr.returndate >= p_startdate::timestamp
      AND  dr.returndate <  p_enddate::timestamp + make_interval(days => 1)
      AND  (p_linekey IS NULL OR p_linekey = 'DeliveryCollections')
    UNION ALL
    -- 422
    SELECT cn.paymentdate, COALESCE(cn.paymentnumber, 'CR' || cn.waterpaymentid::text)::text,
           COALESCE(c.name, 'Customer')::text,
           ('Credit note' || COALESCE(': ' || NULLIF(btrim(cn.note), ''), ''))::text,
           (-cn.amount)::numeric(14,2)
    FROM   waterpayments cn
    LEFT   JOIN watercustomers c ON c.watercustomerid = cn.watercustomerid AND c.farmid = cn.farmid
    WHERE  cn.farmid = p_farmid AND cn.sourcetype = 'CreditNote'
      AND  COALESCE(cn.status, 'Posted') = 'Posted'
      AND  cn.paymentdate >= p_startdate::timestamp
      AND  cn.paymentdate <  p_enddate::timestamp + make_interval(days => 1)
      AND  (p_linekey IS NULL OR p_linekey = 'CreditNotes')
    ORDER  BY 1 DESC, 2;
$function$;

