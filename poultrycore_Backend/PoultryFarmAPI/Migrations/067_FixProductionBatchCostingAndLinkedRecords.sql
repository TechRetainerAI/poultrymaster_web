        SachetsPerBag            INT           NOT NULL CONSTRAINT DF_WaterProductionLosses_SPB DEFAULT (30),
        CostPerBag               DECIMAL(14,4) NOT NULL CONSTRAINT DF_WaterProductionLosses_CPB DEFAULT (0),
        BagsLossValue            DECIMAL(14,2) NOT NULL CONSTRAINT DF_WaterProductionLosses_BagsVal DEFAULT (0),
        SachetsLossValue         DECIMAL(14,2) NOT NULL CONSTRAINT DF_WaterProductionLosses_SacVal DEFAULT (0),
        TotalValue               AS (BagsLossValue + SachetsLossValue) PERSISTED,
        Reason                   NVARCHAR(500) NULL,
        Status                   NVARCHAR(20)  NOT NULL CONSTRAINT DF_WaterProductionLosses_Status DEFAULT ('Approved'),
        Notes                    NVARCHAR(1000) NULL,
        CreatedBy                NVARCHAR(450) NULL,
        CreatedAt                DATETIME2     NOT NULL CONSTRAINT DF_WaterProductionLosses_CreatedAt DEFAULT (SYSUTCDATETIME()),
        IsDeleted                BIT           NOT NULL CONSTRAINT DF_WaterProductionLosses_IsDeleted DEFAULT (0),
        CONSTRAINT FK_WaterProductionLosses_Product FOREIGN KEY (WaterProductId)
            REFERENCES dbo.WaterProducts (WaterProductId)
    );

    CREATE INDEX IX_WaterProductionLosses_FarmId    ON dbo.WaterProductionLosses (FarmId);
    CREATE INDEX IX_WaterProductionLosses_Date      ON dbo.WaterProductionLosses (LossDate);
    CREATE INDEX IX_WaterProductionLosses_Source    ON dbo.WaterProductionLosses (SourceType, SourceId);
    CREATE INDEX IX_WaterProductionLosses_Product   ON dbo.WaterProductionLosses (WaterProductId);
END
GO

-- =============================================================================
-- 3. Helper: spWaterExpenseCategory_EnsureProductionDefaults
-- =============================================================================
-- Inserts (idempotently) the four production-related categories used by the
-- Approve SP. Safe to call repeatedly — uses NOT EXISTS guards.
CREATE OR ALTER PROCEDURE dbo.spWaterExpenseCategory_EnsureProductionDefaults
    @FarmId NVARCHAR(450)
AS
BEGIN
    SET NOCOUNT ON;

    IF NOT EXISTS (SELECT 1 FROM dbo.WaterExpenseCategories
                   WHERE FarmId = @FarmId AND Name = N'Electricity / Utilities')
        INSERT INTO dbo.WaterExpenseCategories (FarmId, Name, Description, IsActive)
        VALUES (@FarmId, N'Electricity / Utilities',
                N'Auto-created for production-linked electricity expenses.', 1);

    IF NOT EXISTS (SELECT 1 FROM dbo.WaterExpenseCategories
                   WHERE FarmId = @FarmId AND Name = N'Fuel')
        INSERT INTO dbo.WaterExpenseCategories (FarmId, Name, Description, IsActive)
        VALUES (@FarmId, N'Fuel',
                N'Auto-created for production-linked fuel expenses.', 1);

    IF NOT EXISTS (SELECT 1 FROM dbo.WaterExpenseCategories
                   WHERE FarmId = @FarmId AND Name = N'Labor')
        INSERT INTO dbo.WaterExpenseCategories (FarmId, Name, Description, IsActive)
        VALUES (@FarmId, N'Labor',
                N'Auto-created for production-linked labor expenses.', 1);

    IF NOT EXISTS (SELECT 1 FROM dbo.WaterExpenseCategories
                   WHERE FarmId = @FarmId AND Name = N'Production Other')
        INSERT INTO dbo.WaterExpenseCategories (FarmId, Name, Description, IsActive)
        VALUES (@FarmId, N'Production Other',
                N'Auto-created for production-linked miscellaneous expenses.', 1);
END
GO

-- =============================================================================
-- 4. spWaterProductionBatch_GetAll  — now returns GoodBags / AllInCost /
--    CostPerBag / MachineScope, plus the existing fields.
-- =============================================================================
CREATE OR ALTER PROCEDURE dbo.spWaterProductionBatch_GetAll
    @FarmId   NVARCHAR(450),
    @Status   NVARCHAR(20) = NULL,
    @FromDate DATE         = NULL,
    @ToDate   DATE         = NULL
AS
BEGIN
    SET NOCOUNT ON;

    SELECT  b.*,
            p.Name AS ProductName,
            m.MachineName,
            bh.BoreholeName,
            -- Derived columns the list page now relies on.
            (b.BagsProduced - ISNULL(b.DamagedBags, 0)) AS GoodBags,
            (b.TotalProductionCost + ISNULL(b.RawMaterialCost, 0)) AS AllInCost,
            CASE
                WHEN (b.BagsProduced - ISNULL(b.DamagedBags, 0)) > 0
                THEN (b.TotalProductionCost + ISNULL(b.RawMaterialCost, 0))
                     / (b.BagsProduced - ISNULL(b.DamagedBags, 0))
                ELSE 0
            END AS CostPerBag,
            CASE
                WHEN (b.BagsProduced * b.SachetsPerBag) > 0
                THEN CAST(((b.BagsProduced * b.SachetsPerBag) - ISNULL(b.RejectedSachets,0)) * 100.0
                          / (b.BagsProduced * b.SachetsPerBag) AS DECIMAL(6,2))
                ELSE 0
            END AS ProductionEfficiencyPercent
    FROM    dbo.WaterProductionBatches b
    INNER   JOIN dbo.WaterProducts p   ON p.WaterProductId = b.WaterProductId
    LEFT    JOIN dbo.WaterMachines m   ON m.WaterMachineId = b.WaterMachineId
    LEFT    JOIN dbo.WaterBoreholes bh ON bh.WaterBoreholeId = b.WaterBoreholeId
    WHERE   b.FarmId = @FarmId AND b.IsDeleted = 0
       AND  (@Status   IS NULL OR b.Status = @Status)
       AND  (@FromDate IS NULL OR b.ProductionDate >= @FromDate)
       AND  (@ToDate   IS NULL OR b.ProductionDate <= @ToDate)
    ORDER  BY b.ProductionDate DESC, b.WaterProductionBatchId DESC;
END
GO

