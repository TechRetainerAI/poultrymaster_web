CREATE OR ALTER PROCEDURE dbo.spWaterProductionLoss_GetAll
    @FarmId   NVARCHAR(450),
    @FromDate DATE = NULL,
    @ToDate   DATE = NULL,
    @Status   NVARCHAR(20) = NULL
AS
BEGIN
    SET NOCOUNT ON;
    SELECT  l.WaterProductionLossId, l.FarmId, l.LossDate, l.LossType,
            l.SourceType, l.SourceId,
            l.WaterProductId, p.Name AS ProductName,
            l.BagsLost, l.SachetsLost, l.SachetsPerBag,
            l.CostPerBag, l.BagsLossValue, l.SachetsLossValue, l.TotalValue,
            l.Reason, l.Status, l.Notes, l.CreatedBy, l.CreatedAt,
            b.BatchNumber
    FROM    dbo.WaterProductionLosses l
    LEFT    JOIN dbo.WaterProducts p ON p.WaterProductId = l.WaterProductId
    LEFT    JOIN dbo.WaterProductionBatches b
            ON b.WaterProductionBatchId = l.SourceId AND l.SourceType = 'ProductionBatch'
    WHERE   l.FarmId = @FarmId
      AND   l.IsDeleted = 0
      AND   (@FromDate IS NULL OR l.LossDate >= @FromDate)
      AND   (@ToDate   IS NULL OR l.LossDate <= @ToDate)
      AND   (@Status   IS NULL OR l.Status = @Status)
    ORDER  BY l.LossDate DESC, l.WaterProductionLossId DESC;
END
GO

CREATE OR ALTER PROCEDURE dbo.spWaterProductionLoss_GetByBatch
    @FarmId                 NVARCHAR(450),
    @WaterProductionBatchId INT
AS
BEGIN
    SET NOCOUNT ON;
    SELECT  l.WaterProductionLossId, l.FarmId, l.LossDate, l.LossType,
