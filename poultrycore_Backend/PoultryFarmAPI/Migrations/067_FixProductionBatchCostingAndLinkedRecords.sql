        WaterProductionLossId    INT IDENTITY(1,1) PRIMARY KEY,
        FarmId                   NVARCHAR(450) NOT NULL,
        LossDate                 DATE          NOT NULL,
        LossType                 NVARCHAR(40)  NOT NULL CONSTRAINT DF_WaterProductionLosses_Type DEFAULT ('ProductionDamage'),
        SourceType               NVARCHAR(40)  NOT NULL CONSTRAINT DF_WaterProductionLosses_SrcType DEFAULT ('ProductionBatch'),
        SourceId                 INT           NULL,
