/* =============================================================================
   067_FixProductionBatchCostingAndLinkedRecords.sql

   Prompt: "Production Batch Costing, Inventory, Loss, Expense, and UI Fixes".

   What this migration does
   ------------------------
   1. Cost per Bag + All-in Total Cost are now returned by the GetAll / GetById
      SPs so the list page can stop computing zero.  Formula:
        AllInCost  = TotalProductionCost + RawMaterialCost
                    (= Electricity+Fuel+Labor+Other + sum(rawMatUsage))
        GoodBags   = BagsProduced - DamagedBags
        CostPerBag = AllInCost / GoodBags   (0 when GoodBags = 0)

   2. WaterProductionBatches.MachineScope NVARCHAR(20).
      Values: 'SingleMachine' (default) or 'AllMachines'. When AllMachines
      the WaterMachineId stays NULL but the batch is clearly labelled as
      combined-production in the list and details views.

   3. New table dbo.WaterProductionLosses for damaged-bag / rejected-sachet
      loss records created automatically by the Approve SP. Each loss row
      points back to its production batch via SourceType+SourceId so the
      Loss page can list everything generated by production.

   4. Approve now creates linked records in one atomic transaction:
        - Finished-goods Restock row (existing — unchanged)
        - Raw material decrements (existing — unchanged)
        - WaterExpenses rows for Electricity/Fuel/Labor/Other > 0
          (auto-Approved, paid from a default cash account when one exists)
        - WaterProductionLosses rows for damaged bags / rejected sachets > 0

      The expense category lookup is forgiving: it tries the obvious name
      first ('Electricity / Utilities' for electricity, etc.) and falls
      back to a generic 'Production' category, which it auto-creates if
      missing. No new infrastructure required on the user side.

   5. Reopen now reverses everything Approve created — expenses are
      Cancelled (with reverse cash txn), production-loss rows for the
      batch are deleted, raw material is restored (existing), stock txn
      reversed (existing). So an approve/reopen/approve cycle is safe:
      the second approve recreates a fresh, single set of linked records.

   6. Approve uses `WHERE NOT EXISTS` checks before re-inserting, so even
      an out-of-band double-approve cannot create duplicate linked rows.

   Idempotent: COL_LENGTH / OBJECT_ID guards everywhere.
   ============================================================================= */

SET NOCOUNT ON;
SET QUOTED_IDENTIFIER ON;
SET ANSI_NULLS ON;
GO

