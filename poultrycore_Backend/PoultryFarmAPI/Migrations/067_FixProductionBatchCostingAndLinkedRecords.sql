-- Helper used by the details view to list the production-linked expenses for
-- a given batch in one call.
CREATE OR ALTER PROCEDURE dbo.spWaterProductionBatch_GetLinkedExpenses
    @FarmId                 NVARCHAR(450),
    @WaterProductionBatchId INT
AS
BEGIN
    SET NOCOUNT ON;
    SELECT  e.WaterExpenseId, e.FarmId, e.ExpenseDate,
            e.WaterExpenseCategoryId, c.Name AS CategoryName,
            e.Description, e.Amount, e.PaidTo, e.PaymentMethod,
            e.WaterCashAccountId, ca.AccountName AS CashAccountName,
            e.LinkedWaterProductionBatchId,
            e.Status, e.Notes, e.CreatedBy, e.ApprovedBy, e.ApprovedAt, e.CreatedAt
    FROM    dbo.WaterExpenses e
    INNER   JOIN dbo.WaterExpenseCategories c ON c.WaterExpenseCategoryId = e.WaterExpenseCategoryId
    LEFT    JOIN dbo.WaterCashAccounts ca     ON ca.WaterCashAccountId   = e.WaterCashAccountId
    WHERE   e.FarmId = @FarmId
      AND   e.LinkedWaterProductionBatchId = @WaterProductionBatchId
      AND   e.IsDeleted = 0
    ORDER  BY e.WaterExpenseId;
END
GO

CREATE OR ALTER PROCEDURE dbo.spWaterProductionBatch_GetLinkedStockTxns
    @FarmId                 NVARCHAR(450),
    @WaterProductionBatchId INT
AS
BEGIN
    SET NOCOUNT ON;
    DECLARE @BatchNo NVARCHAR(60);
    SELECT @BatchNo = BatchNumber
    FROM   dbo.WaterProductionBatches
    WHERE  WaterProductionBatchId = @WaterProductionBatchId AND FarmId = @FarmId;

    IF @BatchNo IS NULL RETURN;

    -- Finished goods movements written by Approve/Reopen.
    SELECT  s.StockTxnId AS WaterStockTransactionId,
            s.WaterProductId, p.Name AS ProductName,
            s.TxnType, s.Quantity, s.UnitCost, s.Note,
            s.CreatedDate AS CreatedAt
    FROM    dbo.WaterStockTransactions s
    INNER   JOIN dbo.WaterProducts p ON p.WaterProductId = s.WaterProductId
    WHERE   s.FarmId = @FarmId
      AND   (s.Note = CONCAT('Production batch ', @BatchNo)
             OR s.Note = CONCAT('Reopen production batch ', @BatchNo))
    ORDER  BY s.StockTxnId;
END
GO

